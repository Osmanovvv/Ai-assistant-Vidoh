-- Рассылка из панели (§15 ТЗ, задача 4.10).
--
-- §15 просит рассылку всем или сегменту с предпросмотром и
-- подтверждением, с ограничением частоты под глобальный лимит Telegram,
-- пропуском заблокировавших и возможностью остановить на середине.
--
-- **Две таблицы, а не счётчики в одной.** Счётчиков хватило бы, пока всё
-- идёт хорошо. Но рассылка на тысячу человек идёт минуту с лишним, и за
-- эту минуту бот может быть перезапущен выкладкой, потерять связь с
-- Telegram или упереться в 429. Со счётчиками «отправлено 412» нельзя
-- ответить на единственный вопрос, который тогда возникает: кому именно
-- уже ушло. Повторный заход разослал бы заново — то есть прислал бы
-- людям одно и то же дважды.
--
-- Строка на получателя отвечает на этот вопрос точно и делает повтор
-- безопасным: берётся только то, что ещё `pending`.
CREATE TABLE IF NOT EXISTS "broadcasts" (
  "id" uuid PRIMARY KEY DEFAULT gen_random_uuid(),

  -- Что рассылаем. Текст неизменен после старта: иначе половина людей
  -- получила бы одно, половина другое, и разобраться было бы нельзя.
  "text" text NOT NULL,

  -- Кому: 'all' или имя сегмента. Строкой, а не перечислением: сегменты
  -- будут появляться, а миграция ради каждого — дорого.
  "segment" text NOT NULL DEFAULT 'all',

  -- draft — составлена, но не подтверждена; running — идёт;
  -- stopped — остановлена человеком; done — дошла до конца;
  -- failed — сорвалась целиком (такого не должно случаться).
  "status" text NOT NULL DEFAULT 'draft',

  -- Кто завёл: логин из панели. Не ссылка на таблицу — администратор
  -- живёт в переменных окружения (см. журнал доступа, задача 4.11).
  "created_by" text NOT NULL,

  -- Просьба остановиться. Отдельным полем, а не статусом: воркер может
  -- быть в середине порции, и статус он поставит сам, когда остановится.
  -- Иначе «остановлено» показывалось бы раньше, чем отправка встала.
  "stop_requested_at" timestamp with time zone,

  "created_at" timestamp with time zone DEFAULT now() NOT NULL,
  "started_at" timestamp with time zone,
  "finished_at" timestamp with time zone
);

CREATE INDEX IF NOT EXISTS "broadcasts_created_idx" ON "broadcasts" ("created_at" DESC);

-- Кому и чем кончилось.
--
-- `user_id` с каскадом, в отличие от журнала доступа: здесь нет следа,
-- который надо сохранить вопреки удалению данных. Наоборот — человек,
-- попросивший удалить свои данные, не должен оставаться строкой в
-- списке рассылки (§16).
CREATE TABLE IF NOT EXISTS "broadcast_deliveries" (
  "id" uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  "broadcast_id" uuid NOT NULL REFERENCES "broadcasts"("id") ON DELETE CASCADE,
  "user_id" uuid NOT NULL REFERENCES "users"("id") ON DELETE CASCADE,

  -- Кому пишем. Копией, а не только ссылкой: получатель мог сменить
  -- аккаунт, а разбираться придётся с тем, куда ушло на самом деле.
  "tg_id" bigint NOT NULL,

  -- pending — ещё не отправляли; sent — ушло;
  -- skipped — пропущен (заблокировал бота или удалил чат);
  -- failed — отказ, который стоит показать в журнале ошибок.
  "status" text NOT NULL DEFAULT 'pending',
  "error" text,
  "at" timestamp with time zone
);

-- Один человек в одной рассылке ровно один раз. Не удобство, а защита:
-- повторный заход после перезапуска не должен прислать второе сообщение.
CREATE UNIQUE INDEX IF NOT EXISTS "broadcast_once_idx"
  ON "broadcast_deliveries" ("broadcast_id", "user_id");

-- Главный запрос воркера: «дай следующую порцию неотправленных».
CREATE INDEX IF NOT EXISTS "broadcast_pending_idx"
  ON "broadcast_deliveries" ("broadcast_id", "status");
