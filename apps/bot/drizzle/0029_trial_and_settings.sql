-- Пробный период и системные значения (§14 ТЗ, задача 4.3).
--
-- ── Системные значения ──────────────────────────────────────────────
--
-- §14 требует: «Пробный период ограничен количеством выгрузок, а не
-- днями. Значение настраивается в админ-панели без выкладки новой
-- версии». Механизма для этого не было вовсе: числа продукта живут в
-- переменных окружения и константами в коде, а и то и другое меняется
-- только выкладкой.
--
-- Таблица «ключ-значение», а не колонки на каждое число: список того,
-- что настраивается, по §15 будет расти (цены, лимиты, окно тишины,
-- пороги, частота напоминаний), и каждая новая настройка не должна
-- стоить миграции.
--
-- Значение строкой, а не числом: там будут не только числа, а разбор
-- по типу всё равно делает читатель — он один знает, чего ждёт.
--
-- `updated_by` заполнится в задаче 4.11, когда у админки появится вход:
-- §16 требует журналировать доступ к данным, а правка значения продукта
-- — тем более то, о чём потом спросят «кто это поменял».
CREATE TABLE IF NOT EXISTS "app_settings" (
  "key" text PRIMARY KEY,
  "value" text NOT NULL,
  "updated_at" timestamp with time zone DEFAULT now() NOT NULL,
  "updated_by" text
);

-- ── Признак траты пробного периода ─────────────────────────────────
--
-- §14 считает пробный период **выгрузками**, а план 4.3 уточняет:
-- «быстрые добавления не считаются — только выгрузки с разбором».
--
-- Признак на выгрузке, а не счётчик на человеке, по трём причинам.
-- Во-первых, счётчик нельзя проверить: если он разойдётся с правдой,
-- сверить его будет не с чем. Во-вторых, карточка человека в админке
-- (задача 4.6) должна показывать, какие именно выгрузки съели пробный
-- период — иначе спор «я столько не разбирала» не разрешить. В-третьих,
-- повторная обработка одной выгрузки не должна тратить период дважды, а
-- с признаком на строке это выходит само.
--
-- Пусто означает «не потратила». Поэтому все выгрузки, разобранные до
-- этой миграции, пробный период не тратят — и это не оплошность, а
-- решение: на боевом уже есть люди с разобранными выгрузками, и первая
-- же выкладка гейта закрыла бы им доступ за то, что они помогали нам
-- отлаживать бота. Задним числом отличить у них быстрое добавление от
-- разбора всё равно нечем.
ALTER TABLE "batches" ADD COLUMN IF NOT EXISTS "trial_counted_at" timestamp with time zone;

-- Гейт спрашивает «сколько выгрузок этот человек потратил» на каждом
-- входящем сообщении. Без индекса это чтение всей истории выгрузок.
CREATE INDEX IF NOT EXISTS "batches_trial_idx"
  ON "batches" ("user_id")
  WHERE "trial_counted_at" IS NOT NULL;
