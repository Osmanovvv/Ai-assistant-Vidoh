-- Число людей в ответе перестаёт быть догадкой (§16, ревизия этапа 4).
--
-- Столбец стоял `not null default 1`, а записывать в него было нечему:
-- `recordAccess` вызывался без `subjects`, и умолчание превращалось в
-- утверждение «в ответ попал один человек» — про каждую страницу списка
-- из двадцати, про предпросмотр рассылки и про журнал сбоев.
--
-- Это ровно тот случай, против которого написан инвариант проекта:
-- пустая клетка читается как ноль, то есть как факт. Здесь она читалась
-- как единица. Разбирающий инцидент увидел бы двадцать обращений «к
-- одному человеку» вместо «к странице из двадцати» — и вывод сделал бы
-- обратный правде.
--
-- Теперь `null` означает «сколько именно, не установлено», и панель
-- печатает это словом. Число ставится там, где оно **известно**: у
-- карточки — один, у списков — после ответа, по числу выданных строк.
ALTER TABLE "admin_access_log" ALTER COLUMN "subjects" DROP DEFAULT;
ALTER TABLE "admin_access_log" ALTER COLUMN "subjects" DROP NOT NULL;

-- Прежние записи не переписываются: их «1» была догадкой, но задним
-- числом установить настоящее число нечем, а стереть след — хуже.
COMMENT ON COLUMN "admin_access_log"."subjects" IS
  'Сколько человек попало в ответ. NULL — не установлено (не «один»).';
