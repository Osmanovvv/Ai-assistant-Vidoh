-- Индекс под поиск счёта по метке (§14, ревизия четвёртого этапа).
--
-- Комментарий в `pre_checkout_query` обещает «ровно одна проверка, по
-- индексу»: на подтверждение звёздного платежа Telegram даёт **десять
-- секунд**, не ответили — платёж не состоится вовсе, и человек увидит
-- отказ без объяснений. Обещание держалось ни на чём: индекса на
-- (provider, ref) не было ни одного, и поиск шёл перебором таблицы.
--
-- Пока счётов сотни, это незаметно. Заметно станет там, где всего
-- дороже: в момент оплаты, на тысячах строк, за десять секунд.
--
-- Тем же индексом обслуживаются оба обращения по метке при приёме
-- уведомления: подписка ищет счёт, чтобы понять, кому и что продлевать.
CREATE INDEX IF NOT EXISTS "billing_invoices_ref_idx"
  ON "billing_invoices" ("provider", "ref");
