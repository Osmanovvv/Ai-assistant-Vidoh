-- Когда выгрузку взяли в работу (§9.1 правило 4; ревизия этапов 1–2).
--
-- Досмотр возвращает в очередь выгрузки, застрявшие в `processing`, и
-- держит порог в три минуты, чтобы не трогать разбор, идущий прямо
-- сейчас. Порог этот отсчитывался от `closed_at` — от момента, когда
-- выгрузку закрыли, а не когда взяли в работу.
--
-- Для обычной выгрузки разница мала: разбор начинается сразу за
-- закрытием. Но выгрузка, пролежавшая в очереди час — так бывает, когда
-- у нас кончился доступ к модели и попытка нарочно не тратится, — уже в
-- первую же миллисекунду разбора выглядит «застрявшей на час». Досмотр
-- возвращал живой разбор в очередь и писал в журнал «Подобрал выгрузки,
-- о которых очередь забыла» — обвинение очереди в чужой ошибке. Ровно
-- это и случилось на боевом 04.09.2026; тогда завели порог, но мерил он
-- не то.
--
-- Задним числом не заполняется. Пусто — значит «взяли до этой правки»,
-- и порог считается по-прежнему от `closed_at`: придумать за прошлое
-- время начала разбора нельзя, а ноль читался бы как факт.
ALTER TABLE "batches"
  ADD COLUMN IF NOT EXISTS "processing_at" timestamptz;

COMMENT ON COLUMN "batches"."processing_at" IS
  'Когда выгрузку взяли в разбор. От неё, а не от закрытия, досмотр считает «застряла».';
