-- Момент конца пробного периода (§15 и §19 ТЗ, задача 4.4).
--
-- ── Зачем момент, если предел и так известен ──────────────────────────
--
-- Три шага воронки из четырёх уже лежат неизменными отметками:
-- регистрация в `users.created_at`, первая разобранная выгрузка в
-- `batches.processed_at`, оплата в `billing_invoices`. Невосстановим
-- ровно один факт: **при каком пределе пробный период кончился и когда
-- именно**.
--
-- Предел — настройка `trial.dumps`, её правят из панели без выкладки, и
-- истории у настроек нет. Посчитай мы «конец пробного» из нынешнего
-- предела — и каждая правка сдвигала бы третий шаг воронки у всех сразу,
-- задним числом. Отчёт о запуске у блогера менялся бы от настройки,
-- сделанной через месяц.
--
-- ── Почему на строке выгрузки, а не своей таблицей ────────────────────
--
-- План задачи говорил: «таблица `events` заводится здесь, потому что без
-- неё нечем закрыть §19 и воронку». Оба названных числа выводятся из
-- рабочих таблиц, а строка `events(kind='trial_over')` соответствовала
-- бы один к одному строке `batches`, которая уже есть, — то есть стала
-- бы второй правдой о выгрузках. В этом проекте второй источник тех же
-- чисел расходился с первым пять раз.
--
-- Здесь тот же приём, которым сделан `trial_counted_at`: признак на
-- строке, а не счётчик на человеке. И судьба при удалении данных
-- получается согласованной сама — шаги воронки живут на каскадных
-- строках и уходят вместе с человеком одинаково, а не вразнобой.
--
-- Названная цена: моменты ведутся с даты выкладки и задним числом не
-- досыпаются. Воронка обязана печатать дату начала ведения — ноль в этом
-- месте читается как факт «никто не дошёл».
alter table batches add column trial_over_at timestamptz;
alter table batches add column trial_limit integer;

comment on column batches.trial_over_at is
  'Момент, когда этой выгрузкой пробный период исчерпан. Один на человека.';
comment on column batches.trial_limit is
  'Предел, действовавший в ту секунду. Без него момент нем: предел правится из панели.';

-- Момент без предела нем, а предел без момента бессмыслен.
alter table batches add constraint batches_trial_over_pair
  check ((trial_over_at is null) = (trial_limit is null));

-- Один момент на человека — гарантией базы, а не осторожностью кода.
-- Иначе повторный проход или второй процесс записали бы второй «конец
-- пробного», и третий шаг воронки посчитал бы одного человека дважды.
create unique index batches_trial_over_once_idx
  on batches (user_id) where trial_over_at is not null;

-- По нему воронка отбирает моменты за окно когорты.
create index batches_trial_over_idx
  on batches (trial_over_at) where trial_over_at is not null;
