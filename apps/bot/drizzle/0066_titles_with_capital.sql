-- Названия дел — с заглавной и у записей, сохранённых до починки
-- (проверка 26.09.2026, вечер).
--
-- Заглавную ставит запись (задача 3.25, storedTitle), и все пути записи её
-- держат. Но правка, срезавшая час из начала названия, до 26.09 писала
-- остаток строчным — «зайти в аптеку», — и утренний разбор назвал бы дело
-- так же: «3. зайти в аптеку». На бою 26.09.2026 такая запись одна.
--
-- Правило — ровно withCapital: только если в первом слове нет ни одной
-- заглавной («iPhone починить», «ВБ заказы» не трогаются), только первая
-- буква. Локаль базы — C: upper() там кириллицы не знает, поэтому буква
-- переводится translate(), а «ё» названа отдельно — в [а-я] она не входит.
-- Черновики — слова человека как есть — не трогаются. updated_at не
-- сдвигается: по нему выбирается дело «последнего разговора».
UPDATE "items"
SET "text" = translate(
    left("text", 1),
    'абвгдеёжзийклмнопрстуфхцчшщъыьэюяabcdefghijklmnopqrstuvwxyz',
    'АБВГДЕЁЖЗИЙКЛМНОПРСТУФХЦЧШЩЪЫЬЭЮЯABCDEFGHIJKLMNOPQRSTUVWXYZ'
  ) || substr("text", 2)
WHERE "is_draft" = false
  AND "text" ~ '^[a-zа-яё]'
  AND substring("text" from '^\S+') !~ '[A-ZА-ЯЁ]';
