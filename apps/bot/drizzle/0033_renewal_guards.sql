-- Две защиты вокруг продления (§14 ТЗ, задача 4.2).
--
-- ── 1. Обещание автопродления живёт на счёте ──────────────────────────
--
-- Правду про продление знает только провайдер, и знает он её в момент
-- выставления счёта: у звёзд годовой тариф продлеваться не умеет вовсе,
-- а у Робокассы продление работает лишь после согласования услуги.
-- Догадка «месячный — значит продлевается» неверна на обоих рельсах и
-- врёт человеку в самом дорогом месте: подписка помечалась бы
-- продлеваемой, продление не приходило бы, а суточный работник каждый
-- день ходил бы списывать несписуемое.
--
-- Пусто = не обещали. Направление отказа выбрано так нарочно: не
-- продлить обещанное дешевле, чем списать необещанное.
alter table billing_invoices add column auto_renew boolean;

comment on column billing_invoices.auto_renew is
  'Обещал ли провайдер автопродление по этому счёту. NULL = не обещал.';

-- ── 2. Одно списание на период, и это запрещено базой ─────────────────
--
-- Дочернее списание Робокассы берёт деньги без участия человека, и
-- второе такое за тот же период — не «лишняя запись в журнале», а
-- дважды снятые деньги. Считать на это замок в Redis или флаг в памяти
-- нельзя: два процесса, перезапуск в середине прохода и потерянный
-- ответ Робокассы («не ответила» ≠ «не списала») ломают любой из них.
--
-- Поэтому запрет живёт там, где он выдерживает всё перечисленное: в
-- уникальном индексе. Ключ — конец периода, который продление
-- оплачивает; он у периода один, сколько бы раз мы ни просыпались.
alter table billing_invoices add column renews_period_end timestamptz;

comment on column billing_invoices.renews_period_end is
  'Конец периода, который оплачивает это продление. Ключ запрета второго списания.';

create unique index billing_renewal_once_idx
  on billing_invoices (provider, user_id, renews_period_end)
  where renews_period_end is not null;
