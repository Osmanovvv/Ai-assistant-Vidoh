-- Подробности дела отдельным полем (§7.4 ТЗ, задача 3.7).
--
-- «Если резолвер нашёл близкую активную запись и сегмент добавляет к ней
-- детали, а не заменяет их, содержимое уходит в поле контекста как
-- дополнение, а заголовок и срок не трогаются.»
--
-- Отдельным полем, а не дописыванием в заголовок: заголовок человек
-- читает в списке из десяти строк, и после третьей подробности этот
-- список перестанет читаться.
--
-- Колонка пустая у всех: до сегодняшнего дня подробностей было некуда
-- складывать, и переносить в неё нечего.
ALTER TABLE "items" ADD COLUMN "body" text;
