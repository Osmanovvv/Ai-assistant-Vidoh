-- Когда человек нажал «напишу своё» (задача 3.61; ревизия этапов 1–2,
-- дефект 28).
--
-- Ожидание ответа словами живёт четверть часа: нажал и отвлёкся на
-- день, а вернувшись сказал мысль — мысль уйдёт в разбор, а не в имя и
-- не в текст дела. Отсчёт шёл от `updated_at` строки настроек, а её
-- двигают все подряд: переключатели меню, шаги опроса, время
-- напоминаний. Нажал «Изменить» на карточке, через пятьдесят минут
-- выключил напоминания, ещё через пять сказал мысль — по `updated_at`
-- она сказана «через пять минут после нажатия», и запись переписана.
-- Отмена у человека есть, но обещание «окно в четверть часа» было
-- неправдой.
--
-- Задним числом не заполняется, как и `batches.processing_at`: момент
-- нажатия в прошлом восстановить нельзя, а `updated_at` — это верхняя
-- граница, то есть тот самый дефект. Пусто при заполненном
-- `awaiting_input` — значит «нажали до этой правки», и такое ожидание
-- считается просроченным: следующая реплика уйдёт в разбор. Это
-- безопасная сторона — мысль не теряется, — и живёт она ровно до
-- следующего нажатия, которое запишет момент.
ALTER TABLE "user_settings"
  ADD COLUMN IF NOT EXISTS "awaiting_since" timestamptz;

COMMENT ON COLUMN "user_settings"."awaiting_since" IS
  'Когда нажали «напишу своё». От него, а не от updated_at, считается окно ожидания.';
