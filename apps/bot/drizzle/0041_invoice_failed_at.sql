-- Время отказа у счёта (§15, ревизия панели).
--
-- Журнал сбоев отбирал неудачные платежи по `created_at` — по дате
-- счёта. Счёт же заведён в момент нажатия кнопки и живёт до
-- `expires_at`, а недоплата приходит уведомлением провайдера тогда,
-- когда человек соберётся заплатить. Счёт трёхдневной давности,
-- недоплаченный сегодня, при выборе «сутки» в журнале не появлялся
-- вовсе, а в колонке «Когда» стояла дата счёта — не время того
-- события, которое разбирают.
--
-- У оплаты и у возврата свои даты (`paid_at`, `refunded_at`), у отказа
-- не было никакой.
--
-- **Задним числом колонка не заполняется.** Времени отказа у прежних
-- счетов нет, и подставить им `created_at` значило бы записать догадку
-- в данные. Пусто здесь означает «неизвестно»; журнал у таких счетов
-- берёт дату счёта — то самое прежнее поведение.
ALTER TABLE "billing_invoices"
  ADD COLUMN IF NOT EXISTS "failed_at" timestamptz;

COMMENT ON COLUMN "billing_invoices"."failed_at" IS
  'Когда счёт стал неудачным. Пусто у помеченных до появления колонки.';
