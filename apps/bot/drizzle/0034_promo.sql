-- Промокоды на первый период (§14 ТЗ, задача 4.4).
--
-- §14 дословно: «Поддержка кода на первый период. Нужны для запуска
-- через блогеров».
--
-- ── Код называет ЦЕНУ, а не скидку ────────────────────────────────────
--
-- Не процент и не бесплатность, и оба отказа обоснованы кодом.
--
-- Бесплатность завести нельзя: `outSumOf` отвергает суммы меньше рубля,
-- звёздный счёт — суммы меньше одной звезды, а ноль в тарифах вообще
-- означает «цена не задана» и убирает кнопку оплаты. Счёт на нуль
-- физически не выставляется, значит «первый период бесплатно» — не
-- разновидность скидки, а отдельное устройство, и оно требует решения
-- заказчицы, а не догадки.
--
-- Процент отвергнут по другой причине: в панели заказчица называет
-- цену, а не долю. Фиксированная цена читается однозначно и не уползает
-- при смене цены тарифа.
--
-- Цены обе и обязательны: паритет правил Telegram — про товар, а не про
-- скидки, но скидка только на карту подталкивала бы людей мимо звёзд, то
-- есть делала бы ровно то, против чего правило написано.
create table promo_codes (
  code text primary key,

  -- Тариф, на который действует код. Один код — один тариф: применить
  -- «первый месяц за 99» к годовому значило бы подарить год.
  plan billing_plan not null,

  -- Цена первого периода. Копейки у рублей, штуки у звёзд.
  price_rub_minor integer not null,
  price_stars integer not null,

  -- До какого времени код живёт. Пусто — бессрочно.
  valid_until timestamptz,

  -- Сколько раз им можно заплатить. Пусто — без ограничения.
  -- Считаются ОПЛАЧЕННЫЕ счёта, а не выставленные: брошенный счёт квоту
  -- тратить не должен, а счета без оплаты — нормальное состояние.
  max_redemptions integer,

  -- Кому выдан код: имя блогера, канал, договорённость. Для панели.
  note text,

  created_at timestamptz not null default now(),
  -- Выключен вручную. Удалять код нельзя: по нему считается, сколько
  -- недополучено, и удаление стёрло бы этот счёт.
  disabled_at timestamptz,

  constraint promo_price_rub_positive check (price_rub_minor > 0),
  constraint promo_price_stars_positive check (price_stars > 0),
  constraint promo_max_positive check (max_redemptions is null or max_redemptions > 0)
);

comment on table promo_codes is
  'Промокоды на первый период (§14). Код называет цену, а не скидку.';

-- ── Применение — это строка счёта, а не своя таблица ──────────────────
--
-- Счёт заводится на каждую попытку оплаты и уже несёт всё нужное:
-- человека, рельс, тариф, сумму и состояние. Отдельная таблица
-- применений была бы вторым источником правды о том, кто заплатил по
-- коду, — и однажды разошлась бы со счётом: возврат обрывает период, но
-- строку счёта в «оплачено» не откатывает, а удаление данных счёт
-- обезличивает, а не удаляет.
alter table billing_invoices add column promo_code text references promo_codes(code) on delete set null;

-- Полная цена — та, что была бы без кода.
--
-- Нужна затем, что выручка в обзоре складывает суммы оплаченных счетов:
-- без полной цены скидка блогерам выглядела бы провалом продаж, а
-- посчитать «сколько недополучено по кодам» было бы нечем.
alter table billing_invoices add column amount_full_minor integer;

comment on column billing_invoices.promo_code is
  'Код, по которому выставлен счёт. Применение — это строка счёта, отдельной таблицы нет.';
comment on column billing_invoices.amount_full_minor is
  'Цена без скидки. Без неё скидка выглядела бы провалом продаж.';

-- Квота кода считается по оплаченным счетам — по этому индексу.
create index billing_invoices_promo_idx
  on billing_invoices (promo_code)
  where promo_code is not null;
