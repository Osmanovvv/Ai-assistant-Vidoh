-- Статусное сообщение занято ответом по существу (§9.2; ревизия этапа 1).
--
-- Статусное сообщение у выгрузки одно, и правит его `finishStatus`. Пока
-- в нём стоит «Секунду, слушаю запись», править его безопасно. Но как
-- только туда лёг ответ по существу — «Перенесла срок на пятницу» с
-- кнопкой «Отменить», — следующая правка стирает и текст, и кнопку.
--
-- Обработчик выгрузки это знал и держал признак у себя в памяти: первая
-- реплика забирает слот, каждая следующая уходит своим сообщением.
-- Докладчик о сбое живёт вне обработчика и признака не видел: он правил
-- слот напрямую, и подтверждение правки исчезало вместе с откатом. На
-- повторном заходе оно не возвращалось — вопрос уже закрыт.
--
-- Признак переезжает в строку выгрузки, потому что читает его другой
-- модуль. Ставится там же, где слот и занимают, — в `showStatus` при
-- финальной правке; второго места, где это решают, быть не должно.
ALTER TABLE "batches"
  ADD COLUMN IF NOT EXISTS "status_taken" boolean NOT NULL DEFAULT false;

COMMENT ON COLUMN "batches"."status_taken" IS
  'В статусном сообщении лежит ответ по существу: правит его только тот, кто занял.';
