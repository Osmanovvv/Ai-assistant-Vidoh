-- Журнал доступа к персональным данным (§16 ТЗ, задача 4.11).
--
-- §16 требует буквально: «доступ к персональным данным в админ-панели
-- журналируется». Требование не про удобство разбора инцидентов — про
-- то, что человек, доверивший боту сведения о здоровье детей и о
-- деньгах, вправе знать, что каждый взгляд на них оставляет след.
--
-- **Отдельная таблица, а не общий журнал приложения.** Журнал
-- приложения живёт в потоке вывода контейнера, ротируется и уезжает в
-- никуда через несколько дней. Здесь нужна запись, которую можно
-- предъявить: кто, когда и на чьи данные смотрел.
--
-- `subject_user_id` со `set null`, как у учёта расхода: удаление данных
-- человека не должно стирать след того, что к ним обращались, — иначе
-- удалением можно было бы прятать доступ. Кто именно смотрел и когда,
-- остаётся; связь с ушедшим человеком пропадает.
CREATE TABLE IF NOT EXISTS "admin_access_log" (
  "id" uuid PRIMARY KEY DEFAULT gen_random_uuid(),

  -- Кто смотрел: логин из панели. Не ссылка на таблицу: администратор
  -- живёт в переменных окружения, а не в базе.
  "login" text NOT NULL,

  -- Куда обращались: путь раздела панели.
  "route" text NOT NULL,

  -- На чьи данные смотрели. Пусто означает «на многих сразу» —
  -- например список людей с расходом; сколько именно, в "subjects".
  "subject_user_id" uuid REFERENCES "users"("id") ON DELETE SET NULL,

  -- Сколько человек попало в ответ. Для карточки один, для списка больше.
  "subjects" integer NOT NULL DEFAULT 1,

  "at" timestamp with time zone DEFAULT now() NOT NULL
);

-- Два вопроса, на которые журнал обязан отвечать быстро: «что смотрели
-- за последнее время» и «кто смотрел на этого человека».
CREATE INDEX IF NOT EXISTS "admin_access_at_idx" ON "admin_access_log" ("at" DESC);
CREATE INDEX IF NOT EXISTS "admin_access_subject_idx"
  ON "admin_access_log" ("subject_user_id");
