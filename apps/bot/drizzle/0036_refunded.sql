-- Возвращённый счёт — отдельное состояние (§14, ревизия четвёртого этапа).
--
-- Прежде возврат снимал доступ правильно, а счёт оставался «оплачен»:
-- выручка в панели продолжала считать вернувшиеся деньги, отличить
-- возврат было нечем, а человек навсегда числился платившим — то есть
-- терял право на промокод «первый период», не получив периода.
--
-- Отдельным состоянием, а не `failed`: неудача означает «денег не
-- было», возврат — «деньги были и ушли обратно». Первое разбирают как
-- поломку, второе как решение.
alter type billing_invoice_status add value if not exists 'refunded';

-- Дата возврата — отдельно от даты оплаты, а не вместо неё.
--
-- Чтобы в отчёте было видно и что заплатили, и что вернули: затирание
-- даты оплаты стёрло бы историю того месяца.
alter table billing_invoices add column refunded_at timestamptz;

comment on column billing_invoices.refunded_at is
  'Когда деньги вернулись. Отдельно от paid_at: обе даты нужны отчёту.';
