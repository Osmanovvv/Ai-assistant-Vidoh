-- Перенос: записи первой выгрузки остались без ссылки на тему.
--
-- §12.2 ТЗ ставит онбординг **после** первой выгрузки, а темы создаёт его
-- ответами. Значит первая выгрузка любого человека сохраняется, когда тем
-- ещё нет, и ссылку взять неоткуда. Код теперь проставляет её в момент
-- создания тем (см. createTopics), но у тех, кто прошёл онбординг раньше
-- этой правки, записи остались с названием и пустой ссылкой: на боевом
-- сервере 29.08.2026 таких было 37 из 38.
--
-- ТЗ держит тему записи именно ссылкой — текстового поля темы в составе
-- items там нет вовсе, название рядом стоит кэшем. Значит пустая ссылка —
-- это невыполненное требование схемы, а не задел на будущее.
--
-- Сравнение как в normalizeTopicName: пробелы по краям срезаны, регистр не
-- важен, «ё» равна «е». **Приведение регистра — через ICU, и это не украшение:**
-- база живёт в локали C, где lower() кириллицу не трогает вовсе, и обычный
-- lower(`Здоровье`) вернул бы `Здоровье`. Перенос 0018 сравнивал именно так и
-- потому молча не находил ничего, кроме уже строчных названий. Коды знаков
-- вместо букв — чтобы файл не зависел от кодировки. Записи, чьё название ни с чем не совпало,
-- остаются без ссылки: выдумывать им тему нельзя (§6.4 запрещает создавать
-- темы без спроса).
UPDATE "items" SET "topic_id" = t."id", "topic" = t."name"
FROM "topics" t
WHERE t."user_id" = "items"."user_id"
  AND "items"."topic_id" IS NULL
  AND "items"."topic" IS NOT NULL
  AND replace(lower(btrim(t."name") COLLATE "und-x-icu"), chr(1105), chr(1077))
      = replace(lower(btrim("items"."topic") COLLATE "und-x-icu"), chr(1105), chr(1077));
