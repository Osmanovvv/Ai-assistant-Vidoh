-- Один промо-счёт на человека — запретом базы (§14, ревизия этапа).
--
-- «Первый период» проверялся **только в момент выставления счёта**, а
-- счетов можно было завести сколько угодно, пока ни один не оплачен:
-- ссылки живут вечно, при оплате промокод не перепроверяется, а сроки
-- складываются. Двенадцать нажатий той же кнопки — год за 1188 ₽ вместо
-- 4788 ₽, и в панели «двенадцать применений».
--
-- Идемпотентность денежного действия обязана держаться индексом, а не
-- осторожностью кода: между проверкой и вставкой всегда есть щель, и два
-- нажатия подряд попадают в неё легко.
--
-- Неудачные и возвращённые счёта в запрет не входят: в первом случае
-- денег не было, во втором они ушли обратно — периода человек не
-- получил, значит право на первый период за ним осталось.
create unique index billing_promo_once_idx
  on billing_invoices (user_id)
  where promo_code is not null and user_id is not null and status not in ('failed', 'refunded');
