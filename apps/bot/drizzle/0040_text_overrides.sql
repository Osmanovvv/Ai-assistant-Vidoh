-- Правка реплик без выкладки (§13.9, задача 4.13).
--
-- §13.9 дословно: «Все тексты хранятся в отдельном словаре и меняются
-- без выкладки новой версии приложения». Словарь отдельный был с
-- задачи 2.11, а вот вторая половина требования не исполнялась: реплики
-- лежат в коде, и поменять слово можно было только выкладкой. План
-- обещал источник из базы «на четвёртом этапе» — вот он.
--
-- **Таблица переопределений, а не копия словаря.** Пусто означает «как в
-- коде», и это не экономия места, а решение: неправленые реплики
-- продолжают следовать за кодом. Скопируй мы словарь целиком — и любая
-- наша будущая починка формулировки обошла бы стороной все 232 строки,
-- потому что каждая была бы «уже правлена человеком».
create table if not exists text_overrides (
  -- Путь реплики в словаре: `answer.acknowledgement`, `limits.trialOver`.
  -- Он же ключ: одна реплика — одно переопределение.
  path text primary key,

  -- Что говорить вместо словарного. Подстановки — числами в фигурных
  -- скобках: `{1}` — первое значение, `{2}` — второе. Проверяется при
  -- записи: потерянная подстановка означает обрубок вместо названия дела.
  value text not null,

  updated_at timestamptz not null default now(),

  -- Кто поменял. §16 требует журналировать доступ к данным, а правку
  -- слов, которые бот скажет людям, — тем более: об этом спросят «кто».
  updated_by text
);

comment on table text_overrides is
  'Реплики, изменённые из панели. Пусто — реплика как в коде (§13.9).';

-- Порядок правок: панели нужно показать, что менялось последним.
create index if not exists text_overrides_updated_idx
  on text_overrides (updated_at desc);
