-- Чего бот ждёт от человека словами (задача 3.61).
--
-- Онбординг был целиком на кнопках, и причина записана в
-- `onboarding.service.ts`: свободный ответ приходит обычным сообщением и
-- попадает в буфер выгрузки, а угадывать «ответ это или новая мысль»
-- значит однажды угадать неверно и потерять мысль человека.
--
-- Явное нажатие «напишу своё» снимает догадку: человек сам сказал, что
-- следующая его реплика — ответ. Поэтому колонка почти всегда пуста, и
-- это её главное свойство: пока здесь NULL, путь входящего сообщения
-- ровно такой, каким был до задачи.
--
-- Значения: 'name', 'morning', 'evening', 'edit:<uuid записи>'.
-- Текстом, а не перечислением: у 'edit' внутри значения идёт
-- идентификатор, и перечислением это не выразить.
--
-- Индекса нет намеренно: колонка читается по первичному ключу таблицы.
ALTER TABLE "user_settings" ADD COLUMN "awaiting_input" text;--> statement-breakpoint

