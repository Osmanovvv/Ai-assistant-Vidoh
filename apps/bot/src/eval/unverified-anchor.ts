import type { ClassifiedItem } from '../modules/classifier/classifier.service.js';

/**
 * Правила повторения, стоящие на **непроверенном** якоре (находка
 * 10.09.2026).
 *
 * **Зачем считать.** Починка 10.09.2026 велела брать якорь правила из
 * проверенного срока. Там, где проверенного срока нет, якорем осталась
 * строка модели, и разведка предлагала выбрасывать правило целиком.
 * Скептик показал цену на «по будням», решение отложили до замера.
 *
 * Мерить тут нечего, кроме одного: **сколько записей за прогон вообще
 * попадают в это сочетание**. Ноль — и строгость ничего не стоит, спор
 * закрыт бесплатно. Не ноль — и видно поимённо, чем за неё платим.
 *
 * **Признак — снаружи разбора, по готовым записям.** Якорь при
 * отвергнутом сроке может прийти только из строки модели: значит «есть
 * правило и нет срока» — это тот случай целиком, без исключений. Считать
 * его здесь дешевле, чем протаскивать через разбор ещё одно поле, и
 * честнее: ради замера боевой путь не трогается вовсе.
 */
export interface UnverifiedAnchor {
  /** Текст записи — чтобы промах было видно поимённо, а не числом. */
  readonly text: string;
  readonly kind: string;
  /** Дата, на которой правило стоит: она пришла из строки модели. */
  readonly anchor: string;
  /** Слова человека о повторении: по ним видно, законное ли оно. */
  readonly said: string;
}

export function unverifiedAnchorsIn(items: readonly ClassifiedItem[]): readonly UnverifiedAnchor[] {
  const found: UnverifiedAnchor[] = [];

  for (const item of items) {
    const rule = item.recurrence?.rule;

    // Правило без срока — и есть опора на строку модели. Правило со
    // сроком опирается на проверенное, фраза без правила выбрасывать
    // нечего.
    if (rule === undefined || item.deadline !== undefined) continue;

    found.push({
      text: item.text,
      kind: rule.kind,
      anchor: rule.anchor,
      said: item.recurrence?.text ?? '',
    });
  }

  return found;
}

/**
 * Строка отчёта про одну такую запись.
 *
 * **Число печатается вместе со строкой, всегда.** Правило выучено дважды
 * за один день 05.09.2026: сперва счёт «точность срока» учитывал промах
 * по дате и не печатал строку — я прочёл молчание как «верно»; потом
 * счётчик проекта сказал «3 из 5», а какая цель не распознана, узнать
 * было нечем. Здесь то же самое: «правил на непроверенном якоре: 3» без
 * имён не отвечает на вопрос, ради которого счёт и заведён — какие
 * записи потеряют правило от предложенной строгости.
 */
export function anchorLine(caseId: string, anchor: UnverifiedAnchor): string {
  // Слова человека — в хвосте и только когда они есть: пустые кавычки
  // выглядят как «человек ничего не сказал», а это другая беда.
  const said = anchor.said === '' ? '' : ` (человек сказал «${anchor.said}»)`;

  return (
    `  якорь [${caseId}] «${anchor.text}»: правило ${anchor.kind} стоит на ${anchor.anchor} ` +
    `из строки модели, проверенного срока нет${said}`
  );
}
