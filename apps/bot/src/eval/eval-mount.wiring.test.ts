import { readFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

import { describe, expect, it } from 'vitest';

/**
 * Примонтированную папку отчётов нельзя сносить (ревизия этапов 1–2).
 *
 * `docker-compose.prod.yml` отдаёт боту `./eval:/eval:ro`, а Docker
 * привязывает том **по иноду**. Снесённую папку контейнер держит открытой
 * и читает дальше; новая на хозяине для него не существует. Отчёты
 * уезжали в никуда до следующей выкладки — только она пересоздаёт
 * контейнер, перезапуск оставляет тот же инод.
 *
 * Проект на этом уже обжигался с `Caddyfile`, и разбор записан рядом с
 * его томом в compose. Тем не менее заливка промптов сносила папку
 * `rm -rf` — то есть ловушка была известна и повторена.
 *
 * **Чего этот страж не умеет, сказано вслух.** Он читает текст скрипта,
 * значит снести точку монтирования всё ещё можно `mv`, `rsync --delete`
 * по родителю или `find` без `-mindepth`. Он ловит ровно тот приём,
 * который тут уже был, и напоминает про ловушку тому, кто придёт сюда
 * править. Поведенческой проверки быть не может: она потребовала бы
 * боевого сервера.
 */

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, '../../../..');

/** Скрипт без комментариев: ловушку тут принято описывать словами. */
function code(text: string): string {
  return text
    .split('\n')
    .map((line) => line.replace(/(^|\s)#.*$/u, ''))
    .join('\n');
}

describe('заливка отчётов не сносит точку монтирования', () => {
  it('папка eval чистится содержимым, а не удаляется целиком', async () => {
    const script = code(await readFile(resolve(root, 'ops/seed-prompts.sh'), 'utf8'));

    /**
     * Кавычки вокруг пути законны и даже рекомендуются shellcheck,
     * поэтому ищем и `rm -rf $REMOTE_DIR/eval`, и `rm -rf "$REMOTE_DIR/eval"`.
     * Прежний страж, написанный по слову `rm` до первой кавычки, кавыченный
     * вариант пропустил бы — то есть поощрял бы худшее написание.
     */
    const removals = [...script.matchAll(/\brm\s+-[a-z]*r[a-z]*\s+(\S+)/gu)].map((found) =>
      // Кавычки и экранирование срезаются, а не обрываются: снос,
      // написанный со сбережённой кавычкой, — это тот же снос. Прежний
      // страж читал только до первой кавычки и потому поощрял бы худшее
      // написание, к которому подталкивает shellcheck.
      (found[1] ?? '').replace(/["'\\]/gu, ''),
    );

    expect(
      removals.filter((path) => /\$REMOTE_DIR\/eval\/?$/u.test(path)),
      'папка отчётов сносится целиком: контейнер останется на старом иноде',
    ).toEqual([]);
  });

  it('очистка содержимого на месте, и её отказ назван словами', async () => {
    const script = code(await readFile(resolve(root, 'ops/seed-prompts.sh'), 'utf8'));

    // Именно `-mindepth 1`: без него `find -delete` сносит и саму папку.
    expect(script).toContain('find $REMOTE_DIR/eval -mindepth 1 -delete');

    /**
     * Отказ обязан быть слышен. Прежде эта строка молчала: `set -e` убивал
     * скрипт без единого слова о том, что именно не вышло, — а «не
     * удалось» без места читается как поломка заливки целиком.
     */
    expect(script).toContain('не удалось очистить папку отчётов на сервере');
  });

  it('том отчётов в compose и правда примонтирован — иначе стеречь нечего', async () => {
    // Пропади монтирование — вся эта проверка стала бы обрядом. Пусть
    // тогда краснеет она, а не человек через полгода.
    const compose = await readFile(resolve(root, 'docker-compose.prod.yml'), 'utf8');

    expect(compose).toContain('./eval:/eval:ro');
  });
});
