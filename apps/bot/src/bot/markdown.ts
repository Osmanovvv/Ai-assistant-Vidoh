/**
 * Экранирование для устаревшей разметки Telegram («Markdown»).
 *
 * Ревизия этапов 1–2, молчаливый отказ. Первый экран §13.1 уходит с
 * `parse_mode: 'Markdown'` — разметка там нужна ровно для одной ссылки на
 * политику, — и подставляет в него **имя из Telegram**, как есть. Имя
 * человек задаёт себе сам, и `Ann_a`, `*K*`, `[Ю` в нём — не редкость.
 *
 * Что происходило: Telegram отвечает «can't parse entities», отправка
 * падает, а повтор доставки глушится дедупликацией апдейтов — то есть
 * первый экран терялся **навсегда**, а не «до повтора». Человек на самое
 * первое `/start` получал ноль байт. Мониторинг молчал: один человек с
 * неудобным именем даёт долю ошибок много ниже порога.
 *
 * **Экранируется только то, что пришло извне.** Сами реплики пишем мы, и
 * разметка в них намеренная: экранируй их — и ссылка на политику
 * превратилась бы в текст со слешами.
 *
 * Набор знаков — тот, что называет Bot API для «Markdown»: подчёркивание,
 * звёздочка, обратная кавычка и открывающая квадратная скобка. Для
 * MarkdownV2 он шире, но V2 в проекте не используется, и расширять его
 * «на всякий случай» значило бы печатать слеши там, где они не нужны.
 */
const SPECIAL = /[_*[`]/gu;

export function escapeMarkdown(text: string): string {
  return text.replace(SPECIAL, (sign) => `\\${sign}`);
}
