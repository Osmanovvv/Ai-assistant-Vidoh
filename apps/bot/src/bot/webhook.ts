import type { RequestHandler } from 'express';
import { webhookCallback, type Bot } from 'grammy';

/**
 * Обработчик вебхука (задача 1.7).
 *
 * §16 ТЗ требует проверять подлинность вебхука. Telegram присылает секрет
 * в заголовке X-Telegram-Bot-Api-Secret-Token; grammY сверяет его сам и
 * отвечает 401 на чужие запросы, не доводя их до обработчиков.
 *
 * Тяжёлый разбор идёт в очереди, а не в обработчике: сюда попадает
 * только приём сообщения (§9.1 — сохранить раньше, чем думать).
 *
 * **Своего срока ответа здесь нет, и это решение ревизии первого этапа.**
 * Прежде стоял `timeoutMilliseconds: 8_000`. По срабатыванию срока grammY
 * делает два дела: отклоняет внешний промис — его ловит обработчик ошибок
 * express, отсюда честный пятисотый, — и **отдельной цепочкой** вешает
 * `finally` на всё ещё идущую обработку, без `catch`. Если обработка
 * потом отказывает, у этой второй цепочки приёмника нет, и Node выходит с
 * кодом 1: падение на одном апдейте убивало процесс целиком.
 *
 * Проверено замером на нашем Node, а не вычитано: «EXIT CODE = 1».
 * Достижимо двумя живыми путями — кнопка «это новое» зовёт классификатор
 * прямо в обработчике (срок вызова модели двести раз больше восьми
 * секунд), и удаление данных обходит ветки тем по одному вызову Telegram.
 * Второй хуже: данные уже удалены, а «Готово. Всё удалено.» человек не
 * увидит, и повтор апдейта отобьётся как дубль.
 *
 * Без своего срока цепочка одна: отказ обработки доходит до обработчика
 * ошибок express (express 5 доводит отклонённые промисы сам), человек
 * получает пятисотый, процесс живёт. Telegram при этом ждёт своим сроком
 * и при затянувшемся ответе просто пришлёт апдейт снова — а повтор у нас
 * отбивается по идентификатору апдейта, для того он и заведён.
 */
export function createWebhookHandler(bot: Bot, secretToken: string): RequestHandler {
  return webhookCallback(bot, 'express', { secretToken });
}
