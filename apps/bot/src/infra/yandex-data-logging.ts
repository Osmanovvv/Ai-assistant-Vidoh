/**
 * Отказ от сохранения содержания запросов на стороне Yandex Cloud.
 *
 * Заголовок `x-data-logging-enabled` понимают все сервисы Yandex Cloud,
 * к которым ходит бот: языковая модель и векторы (Foundation Models) и
 * распознавание речи (SpeechKit). У моделей по умолчанию **сохраняются
 * все данные запросов** — то есть слова людей; у SpeechKit по умолчанию
 * не сохраняются, но явное `false` делает обещание одинаковым на всех
 * трёх путях и не зависящим от умолчаний, которые Yandex вправе менять.
 *
 * Решение заказчицы 12.09.2026 (ответ на вопрос 16): «максимально
 * отключить логирование пользовательского контента на стороне Yandex».
 * Политика конфиденциальности (п. 9) обещает это словами — значит,
 * заголовок обязан стоять в каждом запросе, и у каждого провайдера есть
 * тест на него.
 *
 * Документация: aistudio.yandex.ru/docs/ru/ai-studio/operations/disable-logging
 * и aistudio.yandex.ru/docs/ru/speechkit/concepts/support-headers.
 */
export const YANDEX_NO_DATA_LOGGING = { 'x-data-logging-enabled': 'false' } as const;
