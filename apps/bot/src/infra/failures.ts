/**
 * Деление сбоев на временные и постоянные.
 *
 * Базовые классы живут здесь, а не в модуле речи, потому что различение
 * нужно всем внешним обращениям: распознаванию, языковой модели, Telegram.
 * От него зависит судьба выгрузки — повторить или похоронить, — и
 * заводить для каждого провайдера свою пару классов значило бы каждый раз
 * заново учить конвейер их различать.
 *
 * Правило простое: временное — это «у них не получилось сейчас»,
 * постоянное — «так не получится никогда». Неизвестное считается
 * постоянным: повтор не исправит ошибку в нашем коде, а бесконечный цикл
 * на ней сжигает чужие деньги и прячет причину.
 */

/** Сбой, который имеет смысл повторить: сеть, таймаут, перегрузка. */
export class TransientError extends Error {
  constructor(message: string, cause?: unknown) {
    // Штатный cause из ES2022: своё поле затенило бы его и сломало
    // вывод причины в логах и отладчиках.
    super(message, cause === undefined ? undefined : { cause });
    this.name = 'TransientError';
  }
}

/** Сбой, повторять который бессмысленно: битые данные, наша ошибка в запросе. */
export class PermanentError extends Error {
  constructor(message: string, cause?: unknown) {
    super(message, cause === undefined ? undefined : { cause });
    this.name = 'PermanentError';
  }
}

/**
 * Доступ к внешней службе закрыт: ключ отозван, папка недоступна, не
 * прошла оплата (задача 3.72).
 *
 * **Особый случай, и не из-за самого запроса.** Для запроса это отказ
 * навсегда: повтор с тем же ключом даст тот же 403. Но для человека это
 * простой на **нашей** стороне, а §17 требует прямо: «модель недоступна →
 * выгрузка сохраняется в очередь с повтором, пользователю честное
 * короткое сообщение о задержке». Похоронить его слова потому, что у нас
 * кончился доступ, — худшее из возможных решений.
 *
 * **Найдено 05.09.2026.** Yandex начал отвечать `403 Permission to
 * [folder, cloud, organization] denied` на любой запрос. Разбор считал
 * это постоянным сбоем: выгрузка помечалась `failed` и не
 * переподхватывалась никогда, а человек получал «попробуй ещё раз» —
 * совет, который не мог помочь. Слова оставались целы в `messages_raw`,
 * но разобрать их было уже нечему.
 *
 * **Класс временный, но повторы у него особые: попытки он не тратит**
 * (см. `pipeline.service.ts`). Пять повторов сгорают за пять минут, а
 * доступ возвращается через час — и слова пропали бы всё равно.
 */
export class AccessDeniedError extends TransientError {
  constructor(message: string, cause?: unknown) {
    super(message, cause);
    this.name = 'AccessDeniedError';
  }
}

/**
 * Ответы «доступа нет», одинаковые у всех служб Yandex.
 *
 * 401 — ключа не признали, 402 — не оплачено, 403 — прав нет. Ни один из
 * трёх не про содержимое запроса, все три про наш доступ.
 */
export const ACCESS_DENIED_STATUSES: ReadonlySet<number> = new Set([401, 402, 403]);

/**
 * Коды gRPC про доступ: `PERMISSION_DENIED` и `UNAUTHENTICATED`.
 *
 * SpeechKit отдаёт отказ операции кодом, а не статусом HTTP.
 */
export const ACCESS_DENIED_GRPC_CODES: ReadonlySet<number> = new Set([7, 16]);
