/**
 * Деление сбоев на временные и постоянные.
 *
 * Базовые классы живут здесь, а не в модуле речи, потому что различение
 * нужно всем внешним обращениям: распознаванию, языковой модели, Telegram.
 * От него зависит судьба выгрузки — повторить или похоронить, — и
 * заводить для каждого провайдера свою пару классов значило бы каждый раз
 * заново учить конвейер их различать.
 *
 * Правило простое: временное — это «у них не получилось сейчас»,
 * постоянное — «так не получится никогда». Неизвестное считается
 * постоянным: повтор не исправит ошибку в нашем коде, а бесконечный цикл
 * на ней сжигает чужие деньги и прячет причину.
 */

/** Сбой, который имеет смысл повторить: сеть, таймаут, перегрузка. */
export class TransientError extends Error {
  constructor(message: string, cause?: unknown) {
    // Штатный cause из ES2022: своё поле затенило бы его и сломало
    // вывод причины в логах и отладчиках.
    super(message, cause === undefined ? undefined : { cause });
    this.name = 'TransientError';
  }
}

/** Сбой, повторять который бессмысленно: битые данные, наша ошибка в запросе. */
export class PermanentError extends Error {
  constructor(message: string, cause?: unknown) {
    super(message, cause === undefined ? undefined : { cause });
    this.name = 'PermanentError';
  }
}

/**
 * Доступ к внешней службе закрыт: ключ отозван, папка недоступна, не
 * прошла оплата (задача 3.72).
 *
 * **Особый случай, и не из-за самого запроса.** Для запроса это отказ
 * навсегда: повтор с тем же ключом даст тот же 403. Но для человека это
 * простой на **нашей** стороне, а §17 требует прямо: «модель недоступна →
 * выгрузка сохраняется в очередь с повтором, пользователю честное
 * короткое сообщение о задержке». Похоронить его слова потому, что у нас
 * кончился доступ, — худшее из возможных решений.
 *
 * **Найдено 05.09.2026.** Yandex начал отвечать `403 Permission to
 * [folder, cloud, organization] denied` на любой запрос. Разбор считал
 * это постоянным сбоем: выгрузка помечалась `failed` и не
 * переподхватывалась никогда, а человек получал «попробуй ещё раз» —
 * совет, который не мог помочь. Слова оставались целы в `messages_raw`,
 * но разобрать их было уже нечему.
 *
 * **Класс временный, но повторы у него особые: попытки он не тратит**
 * (см. `pipeline.service.ts`). Пять повторов сгорают за пять минут, а
 * доступ возвращается через час — и слова пропали бы всё равно.
 */
export class AccessDeniedError extends TransientError {
  constructor(message: string, cause?: unknown) {
    super(message, cause);
    this.name = 'AccessDeniedError';
  }
}

/**
 * Перейдён потолок расхода, который мы сами себе поставили (задача 3.79).
 *
 * **Живёт рядом с отказом в доступе не случайно.** Для человека это одно
 * и то же: модель недоступна не по его вине, слова обязаны дождаться,
 * попытки на это тратить нечестно. Разница только в том, кто закрыл
 * доступ — провайдер или мы сами, — и она видна в тексте.
 *
 * Временная по построению: потолок поднимут, и та же выгрузка
 * разберётся. Постоянной делать нельзя — слова умрут из-за бюджета.
 */
export class SpendCeilingError extends TransientError {
  constructor(message: string) {
    super(message);
    this.name = 'SpendCeilingError';
  }
}

/**
 * Ответы «доступа нет», одинаковые у всех служб Yandex.
 *
 * 401 — ключа не признали, 402 — не оплачено, 403 — прав нет. Ни один из
 * трёх не про содержимое запроса, все три про наш доступ.
 */
export const ACCESS_DENIED_STATUSES: ReadonlySet<number> = new Set([401, 402, 403]);

/**
 * Коды gRPC про доступ: `PERMISSION_DENIED` и `UNAUTHENTICATED`.
 *
 * SpeechKit отдаёт отказ операции кодом, а не статусом HTTP.
 */
export const ACCESS_DENIED_GRPC_CODES: ReadonlySet<number> = new Set([7, 16]);

/**
 * Пометка «за это уже заплачено» (задача 3.82).
 *
 * **Зачем нужна.** Распознавание речи платное по секундам звука, и
 * платит его отправка, а не результат. Если звук отправлен и принят, а
 * сорвался опрос готовности или забор текста, повтор **всей** операции
 * оплачивает те же секунды второй раз. При трёх попытках `withRetry`
 * одна минута записи стоила три; вместе с повтором всей выгрузки —
 * до пятнадцати. В учёте при этом одна строка: у сорвавшегося вызова
 * расход пустой, и в отчёте эти деньги не видно вовсе.
 *
 * **Почему пометкой, а не `PermanentError`.** Для человека это отказ
 * временный: слова не потеряны, попробовать позже осмысленно, и
 * наверху он обязан читаться именно так. Меняется только одно — тесный
 * повтор вокруг платной отправки больше не крутится.
 *
 * Свойством, а не своим классом: пометить нужно любой отказ, от кого бы
 * он ни пришёл, не переписывая его тип.
 */
const ALREADY_PAID = Symbol.for('vydoh.alreadyPaid');

/**
 * Что именно оплачено.
 *
 * Пока это только секунды звука: у модели и векторов брошенный запрос
 * отменяется сигналом и денег не стоит, а распознавание платит отправкой.
 *
 * Своя узкая форма, а не тип из учёта: `infra` не должна зависеть от
 * модуля, который сама обслуживает.
 */
export interface PaidUsage {
  readonly audioSeconds: number;
}

function paidMark(error: unknown): true | PaidUsage | undefined {
  if (typeof error !== 'object' || error === null) return undefined;

  const mark = (error as Record<symbol, unknown>)[ALREADY_PAID];
  if (mark === true) return true;

  return typeof mark === 'object' && mark !== null ? (mark as PaidUsage) : undefined;
}

/**
 * Помечает отказ как оплаченный: повторять его отправкой нельзя.
 *
 * `paid` называет, **сколько** оплачено. Без числа учёт запишет
 * сорвавшемуся вызову пустой расход, а пустая колонка читается как ноль —
 * то есть как «денег не потратили», чего не было.
 *
 * `configurable: true` намеренно: один и тот же отказ помечается дважды —
 * своими силами внутри провайдера и снаружи, где известен наш таймаут.
 * Без этого вторая пометка падала бы `TypeError` и подменяла собой
 * настоящую причину отказа.
 */
export function markAlreadyPaid<E>(error: E, paid?: PaidUsage): E {
  if (typeof error === 'object' && error !== null) {
    Object.defineProperty(error, ALREADY_PAID, {
      value: paid ?? true,
      enumerable: false,
      configurable: true,
    });
  }

  return error;
}

/** Оплачен ли уже вызов, на котором случился этот отказ. */
export function isAlreadyPaid(error: unknown): boolean {
  return paidMark(error) !== undefined;
}

/** Сколько уже оплачено, если отказ это назвал. */
export function paidUsage(error: unknown): PaidUsage | undefined {
  const mark = paidMark(error);
  return mark === true || mark === undefined ? undefined : mark;
}
