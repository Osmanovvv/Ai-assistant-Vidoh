/**
 * Деление сбоев на временные и постоянные.
 *
 * Базовые классы живут здесь, а не в модуле речи, потому что различение
 * нужно всем внешним обращениям: распознаванию, языковой модели, Telegram.
 * От него зависит судьба выгрузки — повторить или похоронить, — и
 * заводить для каждого провайдера свою пару классов значило бы каждый раз
 * заново учить конвейер их различать.
 *
 * Правило простое: временное — это «у них не получилось сейчас»,
 * постоянное — «так не получится никогда». Неизвестное считается
 * постоянным: повтор не исправит ошибку в нашем коде, а бесконечный цикл
 * на ней сжигает чужие деньги и прячет причину.
 */

/** Сбой, который имеет смысл повторить: сеть, таймаут, перегрузка. */
export class TransientError extends Error {
  constructor(message: string, cause?: unknown) {
    // Штатный cause из ES2022: своё поле затенило бы его и сломало
    // вывод причины в логах и отладчиках.
    super(message, cause === undefined ? undefined : { cause });
    this.name = 'TransientError';
  }
}

/** Сбой, повторять который бессмысленно: битые данные, отказ в доступе. */
export class PermanentError extends Error {
  constructor(message: string, cause?: unknown) {
    super(message, cause === undefined ? undefined : { cause });
    this.name = 'PermanentError';
  }
}
