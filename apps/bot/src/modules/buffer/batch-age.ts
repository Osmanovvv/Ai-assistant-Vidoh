/**
 * Жёсткий потолок возраста открытой выгрузки: пять минут (задача 1.12).
 *
 * Выгрузка не может быть открыта вечно: по возрасту её закрывает либо
 * следующее сообщение (`attachMessageToBatch`), либо досмотр
 * (`recoverStuckBatches`). Настройкой не является — §15 его не просит.
 *
 * **Вывезен из `buffer.service.ts` ревизией этапов 1–2 (дефект 15).**
 * Прежде число жило только там, а предел окна тишины в реестре настроек
 * стоял свой — десять минут, вдвое шире. Панель принимала семь минут с
 * «Сохранено», а досмотр закрывал выгрузку по возрасту на пятой: окно от
 * пяти до десяти минут молча вырождалось в пятиминутное. Один потолок,
 * одно число — как у цены в звёздах, где реестр берёт предел у рельса.
 *
 * Отдельным модулем, а не рядом с `DEFAULT_LIMITS`, потому что
 * `buffer.service.ts` сам берёт умолчания из реестра: обратный импорт
 * замкнул бы круг, и чей-то верхний уровень читал бы ещё не созданную
 * константу.
 */
export const MAX_BATCH_AGE_MS = 5 * 60_000;
