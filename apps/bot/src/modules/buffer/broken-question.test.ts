import { describe, expect, it } from 'vitest';

import { rejoinBrokenQuestions } from './broken-question.js';

/**
 * Фраза, порванная вопросительным знаком распознавания (бой 29.09.2026,
 * заказчица): «Спросить рецепт? Рыбы у Анжелы, так ещё нужно…» — дело
 * «спросить рецепт рыбы у Анжелы», а разбор взял «Спросить рецепт» и
 * потерял «Рыбы у Анжелы». Склеивается только дело перед «?» и короткий
 * обрывок без глагола после; настоящие вопросы не трогаются.
 */
describe('rejoinBrokenQuestions — склеить', () => {
  it.each<[string, string]>([
    [
      'Так смотри, мне нужно выкопать собаку. Спросить рецепт? Рыбы у Анжелы, так еще нужно созвониться с Ириной Михайловной.',
      'Так смотри, мне нужно выкопать собаку. Спросить рецепт рыбы у Анжелы, так еще нужно созвониться с Ириной Михайловной.',
    ],
    ['Купить подарок? Маме на юбилей.', 'Купить подарок маме на юбилей.'],
    ['Записаться к стоматологу? Сыну.', 'Записаться к стоматологу сыну.'],
  ])('«%s»', (before, after) => {
    expect(rejoinBrokenQuestions(before)).toBe(after);
  });
});

describe('rejoinBrokenQuestions — не трогать', () => {
  it.each([
    // Все шесть мест «…? Слово» из записанных голосовых наборов (30.09.2026).
    'Так что так? У нас тут накопилось всякое',
    'в банк по карте, там что то с лимитом на? Следующей неделе записаться к стоматологу',
    'Кстати, что у меня там, на завтра? Надо позвонить в школу на счет экскурсии',
    'Что у меня завтра вообще? Кстати',
    // Настоящий вопрос — с вопросительным словом или «ли».
    'Что купить? Хлеб или булку',
    'Успею ли забрать? Посылку',
    // Начинается с глагола, но это вопрос: «узнать, когда…?» — и ответ после.
    'Узнать, когда приём? Завтра утром',
    // После «?» — ответ, поправка или новое дело с глаголом.
    'Позвонить маме? Нет, лучше написать.',
    'Записать сына к врачу? Наверное, в четверг.',
    'Купить хлеб? Надо ещё молоко.',
    'Купить хлеб? Забрать посылку.',
    // Перед «?» — не дело: нет глагола в начале.
    'Врач в четверг? Сыну',
    // Длинный хвост — это уже своя фраза.
    'Спросить рецепт? Рыбы у Анжелы из соседнего подъезда на третьем этаже',
    'Позвонить маме',
    '',
  ])('«%s»', (text) => {
    expect(rejoinBrokenQuestions(text)).toBe(text);
  });
});
