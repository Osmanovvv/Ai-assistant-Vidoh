/**
 * Одиночное сообщение-вопрос (прогон 17.09.2026, находка 20).
 *
 * Окно тишины склеивает серию мыслей в одну выгрузку (§9.1 ТЗ) — и на
 * вопрос оно действовало так же: «Что у меня на сегодня?» → «Слушаю.» →
 * полминуты → ответ. Заказчица дважды повторяла один и тот же вопрос, не
 * дождавшись. Вопрос — не серия: его можно разбирать сразу.
 *
 * Правило намеренно узкое: текст кончается на «?». Знак внутри («надо
 * ли? купить хлеб») — не вопрос, а речь; голосовое сюда не попадает —
 * его слов до разбора никто не знает. Ошибка правила дешёвая: вопрос, не
 * узнанный как вопрос, просто подождёт окно, как раньше.
 */
export function looksLikeQuestion(text: string | undefined): boolean {
  if (text === undefined) return false;

  const trimmed = text.trim();

  return trimmed.length > 1 && trimmed.endsWith('?');
}
