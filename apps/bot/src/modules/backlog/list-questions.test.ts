import { describe, expect, it } from 'vitest';

import { askedList } from './list-questions.js';

/**
 * Вопросы-списки по признаку (21.09.2026, список Никиты): просрочено,
 * на потом, без срока, сколько, с чего начать, что записала, что
 * сделала, желания/идеи/цели. Как и у отрезков: закрытые рамки, а всё,
 * что сверх рамки и признака, — предмет, и тогда это вопрос про предмет.
 */
describe('вопросы-списки по признаку', () => {
  it.each([
    ['что просрочено', { kind: 'overdue' }],
    ['что у меня просрочено', { kind: 'overdue' }],
    ['что я не успела', { kind: 'overdue' }],
    ['что горит', { kind: 'overdue' }],
    ['какие дела просрочены', { kind: 'overdue' }],
    ['что на потом', { kind: 'later' }],
    ['что я отложила', { kind: 'later' }],
    ['что у меня отложено', { kind: 'later' }],
    ['что без срока', { kind: 'undated' }],
    ['какие дела без даты', { kind: 'undated' }],
    ['сколько у меня дел', { kind: 'count' }],
    ['сколько всего задач', { kind: 'count' }],
    ['много ли накопилось', { kind: 'count' }],
    ['что важное', { kind: 'pick' }],
    ['что срочного', { kind: 'pick' }],
    ['с чего начать', { kind: 'pick' }],
    ['что в первую очередь', { kind: 'pick' }],
    ['что главное', { kind: 'pick' }],
    ['что мне делать в первую очередь', { kind: 'pick' }],
    ['с чего мне начать', { kind: 'pick' }],
    ['что я сегодня записала', { kind: 'recent', scope: 'today' }],
    ['что я записывала сегодня', { kind: 'recent', scope: 'today' }],
    ['что я последнее записала', { kind: 'recent', scope: 'last' }],
    ['что последнее записано', { kind: 'recent', scope: 'last' }],
    ['что я наговорила', { kind: 'recent', scope: 'last' }],
    ['что нового', { kind: 'recent', scope: 'last' }],
    ['что я сделала', { kind: 'done', period: 'week' }],
    ['что я сделала на неделе', { kind: 'done', period: 'week' }],
    ['что сделано за неделю', { kind: 'done', period: 'week' }],
    ['что я закрыла сегодня', { kind: 'done', period: 'today' }],
    ['что я сделала вчера', { kind: 'done', period: 'yesterday' }],
    ['что выполнено за месяц', { kind: 'done', period: 'month' }],
    ['что я успела за 3 дня', { kind: 'done', period: 'days:3' }],
    ['покажи желания', { kind: 'byType', type: 'DESIRE' }],
    ['какие у меня желания', { kind: 'byType', type: 'DESIRE' }],
    ['мои мечты', { kind: 'byType', type: 'DESIRE' }],
    ['покажи идеи', { kind: 'byType', type: 'IDEA' }],
    ['какие идеи у меня записаны', { kind: 'byType', type: 'IDEA' }],
    ['какие у меня цели', { kind: 'byType', type: 'goal' }],
    ['покажи большие цели', { kind: 'byType', type: 'goal' }],
  ])('«%s» → %o', (text, expected) => {
    expect(askedList(text)).toEqual(expected);
  });

  it('с предметом — вопрос про предмет, а не список', () => {
    for (const text of [
      'что просрочено по отчёту',
      'сколько дел по работе',
      'что я записала про стоматолога',
      'что я сделала с балконом',
      'какие идеи по ремонту',
      'что важное с машиной',
    ]) {
      expect(askedList(text), text).toBeUndefined();
    }
  });

  it('утверждения — не вопросы: «сделала отчёт», «отложила поездку»', () => {
    for (const text of ['сделала отчёт', 'отложила поездку', 'записала врача на вторник']) {
      expect(askedList(text), text).toBeUndefined();
    }
  });

  it('прежние рамки не перехватываются: отрезки и «всё»', () => {
    for (const text of [
      'что на завтра',
      'что у меня на 3 дня',
      'покажи все мои дела',
      'что там с котом',
    ]) {
      expect(askedList(text), text).toBeUndefined();
    }
  });
});

describe('«на сколько?» и «во сколько?» — не счёт дел (прогон Никиты 27.09.2026, 18:03)', () => {
  /**
   * После вопроса о часе куртки он спросил «На сколько ?» — бот ответил
   * счётом «Открыто 9 дел: …»: слово «сколько» узнавалось само по себе.
   * «На сколько» и «во сколько» спрашивают о времени, а не о числе дел.
   */
  it.each(['На сколько ?', 'на сколько', 'Во сколько ?', 'во сколько'])(
    '«%s» — не счёт',
    (text) => {
      expect(askedList(text)?.kind).not.toBe('count');
    },
  );

  it('«сколько у меня дел» — по-прежнему счёт', () => {
    expect(askedList('Сколько у меня дел?')).toEqual({ kind: 'count' });
  });
});
