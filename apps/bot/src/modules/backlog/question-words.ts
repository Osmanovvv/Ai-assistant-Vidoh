/**
 * Вводные слова — ни предмет, ни рамка: их в вопросе просто нет
 * (заказчица, бой 29.09.2026).
 *
 * «Слушай, а еще... Да выкати мне вообще все, что нужно сделать на этой
 * неделе.» — «слушай» и «да» код счёл предметом, вопрос о неделе ушёл в
 * поиск, и модель ответила по обзору с «Остальное подождёт». В рамку их
 * не кладём намеренно: рамка без предмета — вопрос обо всём, и «Слушай»
 * одно превратилось бы в полный список дел.
 */
const FILLER_WORDS: ReadonlySet<string> = new Set(['слушай', 'послушай', 'да', 'ну']);

/** Слова вопроса — без вводных (`FILLER_WORDS`). */
export function wordsOf(text: string): readonly string[] {
  return text
    .toLowerCase()
    .replace(/ё/gu, 'е')
    .split(/[^\p{L}]+/u)
    .filter((word) => word.length > 0 && !FILLER_WORDS.has(word));
}

/** Регистр не важен, «ё» равна «е». */
export function normalizeText(text: string): string {
  return text.toLowerCase().replace(/ё/gu, 'е');
}
