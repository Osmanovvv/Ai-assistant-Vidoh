import type { Item } from '../../db/schema.js';

/**
 * Реестр инструментов выполнения (§1.3 ТЗ, задача 3.11).
 *
 * **Реестр пустой, и это его нормальное состояние.** §1.3 прямо говорит:
 * интеграций с картами, календарями и доставкой в первой версии нет и не
 * будет. Но слой выполнения проектируется как отдельный интерфейс — это
 * десяток строк сейчас и переписанное ядро потом.
 *
 * Кнопка «Сделать сейчас» из §13.2 ходит именно через этот интерфейс.
 * Пока единственная её реализация — показать карточку записи, и это
 * тоже инструмент, просто встроенный.
 *
 * **Зачем это, если реестра всё равно нет.** Когда однажды появится
 * «позвонить» или «открыть карту», выбор инструмента окажется не новой
 * веткой в обработчике кнопки, а новой записью в списке. Разница между
 * этими двумя способами — недели работы и месяц ошибок.
 */

export interface ToolContext {
  readonly item: Item;
  readonly timeZone: string;
}

export interface Tool {
  /** Имя для журнала и для реестра. Уникально. */
  readonly name: string;
  /** Годится ли инструмент для этой записи. */
  readonly suits: (context: ToolContext) => boolean;
  /** Подпись на кнопке. Берётся из словаря вызывающим (инвариант 4). */
  readonly label: string;
}

export class ToolRegistry {
  private readonly tools = new Map<string, Tool>();

  /**
   * Второй инструмент с тем же именем — ошибка, а не замена.
   *
   * Молчаливая замена означала бы, что порядок регистрации решает
   * поведение продукта, а найти такое потом почти невозможно.
   */
  add(tool: Tool): void {
    if (this.tools.has(tool.name)) {
      throw new Error(`Инструмент «${tool.name}» уже зарегистрирован`);
    }

    this.tools.set(tool.name, tool);
  }

  /** Все инструменты, годные для записи. Пусто — значит показать карточку. */
  for(context: ToolContext): readonly Tool[] {
    return [...this.tools.values()].filter((tool) => tool.suits(context));
  }

  get size(): number {
    return this.tools.size;
  }
}

/**
 * Реестр продукта.
 *
 * Пуст намеренно. Добавление сюда — это продуктовое решение, а не
 * техническое: каждый инструмент обещает человеку, что бот умеет что-то
 * сделать за него, и обещание надо сдержать.
 */
export const tools = new ToolRegistry();
