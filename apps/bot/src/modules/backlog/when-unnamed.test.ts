import { describe, expect, it } from 'vitest';

import { asksWhenOfUnnamed } from './when-unnamed.js';

/**
 * «На когда» без названного дела (проверка Никиты 25.09.2026, 20:23): бот
 * только что ответил про стоматолога, человек переспросил «На когда» — и
 * получил «Про это у меня ничего не записано».
 */
describe('вопрос о сроке без названного дела', () => {
  it('рамка и слово о сроке — да', () => {
    for (const text of [
      'На когда',
      'На когда?',
      'Когда?',
      'А когда?',
      'Во сколько?',
      'Какого числа?',
      'А на когда это?',
      'Когда это у меня?',
    ]) {
      expect(asksWhenOfUnnamed(text), text).toBe(true);
    }
  });

  it('описка, поправленная в том же вопросе, — самоисправление: «На когад На когда» (бой)', () => {
    expect(asksWhenOfUnnamed('На когад На когда')).toBe(true);
    expect(asksWhenOfUnnamed('Во скольк во сколько?')).toBe(true);
  });

  it('названо дело — нет: его найдёт обычный поиск', () => {
    for (const text of [
      'На когда стоматолог?',
      'Когда к врачу?',
      'Во сколько забрать ребёнка?',
      'Когда день рождения у мамы?',
    ]) {
      expect(asksWhenOfUnnamed(text), text).toBe(false);
    }
  });

  it('без слова о сроке — нет: это не наш вопрос', () => {
    for (const text of ['что там с котом', 'как всё успеть', 'Что там?', 'Что делать?']) {
      expect(asksWhenOfUnnamed(text), text).toBe(false);
    }
  });

  it('описка без правильного слова рядом — не угадывается: «На когад» остаётся как есть', () => {
    expect(asksWhenOfUnnamed('На когад')).toBe(false);
  });
});
