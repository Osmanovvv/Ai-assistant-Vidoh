import { sql, type SQL } from 'drizzle-orm';

import { aiCalls } from '../../db/schema.js';

/**
 * «Вызовов без известной цены» — **одним условием на всех**.
 *
 * Число отвечает на один вопрос: сколько обращений к модели мы не смогли
 * оценить, то есть насколько показанная сумма ниже настоящей. Рядом с
 * ним панель печатает оговорку «расход не меньше показанного», и ровно
 * поэтому в него нельзя пускать **сорвавшиеся** вызовы: у отказа цены
 * нет и быть не может — 403, таймаут и обрыв не тарифицируются. Отказы
 * считаются своим числом (`failed`) в тех же запросах, так что без
 * фильтра один и тот же вызов попадал в оба разом.
 *
 * Цена ошибки не в лишней единице. Оговорка, которая горит после
 * **любого** сбоя модели, перестаёт значить что-либо, а настоящий
 * случай — модели нет в прайс-листе — от неё уже не отличить. Заказчица
 * читает «расход выше показанного» и не может узнать, правда это или
 * след вчерашнего таймаута; по этому же числу она решает про цену
 * подписки.
 *
 * **Условие живёт здесь, потому что его забывали дважды.** Первый раз —
 * в `account-spend.ts`, и там об этом написано своими словами: «сперва он
 * был забыт, и одно и то же число считалось двумя разными способами».
 * Починили одно место, а рядом остались пять: обзор, строка человека,
 * расход человека для §10.5 и два разреза раздела расходов. Значит дело
 * не в невнимательности, а в том, что условие было переписываемым. Теперь
 * оно одно, и его нельзя обойти незаметно — за этим стоит страж
 * `unpriced.test.ts`.
 */
export function unpricedSql(): SQL {
  return sql`(${aiCalls.costMicros} is null and ${aiCalls.ok})`;
}

/** То же число готовым счётчиком: `count(*) filter (...)` для select. */
export function unpricedCountSql(): SQL<number> {
  return sql<number>`count(*) filter (where ${unpricedSql()})::int`;
}
