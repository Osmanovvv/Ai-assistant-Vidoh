import { readFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

import { describe, expect, it } from 'vitest';

import { CODE_MAX, CODE_MIN } from '../billing/promo.service.js';
import { STARS_MAX_SUBSCRIPTION } from '../billing/providers/stars.js';
import { SETTINGS } from './settings.repo.js';

/**
 * У каждой настройки есть человеческое название в панели (задача 4.2).
 *
 * **Зачем страж.** Панель берёт название из своего словаря `TITLES`, а
 * при промахе показывает ключ из базы: `broadcast.per_second` вместо
 * «Темп рассылки». Отказ молчаливый — раздел работает, значение правится,
 * — и потому живёт долго: так и вышло с темпом рассылки (4.10) и с
 * четырьмя ценами (4.2), пока их не заметили глазами.
 *
 * Цена промаха у цен выше остальных: поле «price.monthly_rub_minor» без
 * подсказки не говорит ни про копейки, ни про то, что ноль выключает
 * продажу. Человек введёт «399» и продаст месяц за три рубля.
 *
 * Проверка идёт **по исходнику панели**, а не по собранному коду: словарь
 * живёт в другом пакете, импортировать `.tsx` в тесты бота незачем. Тот
 * же приём, что у стража путей админ-роутера.
 */

const panel = resolve(
  dirname(fileURLToPath(import.meta.url)),
  '../../../../admin/src/Settings.tsx',
);

/**
 * Исходник без пояснений.
 *
 * **Страж не должен держаться на комментарии.** Первая версия проверки
 * искала слово «истёк» в теле таблицы — и оставалась зелёной со снятой
 * пометкой, потому что то же слово стояло в пояснении рядом. Ровно та
 * порода отказа, за которой ревизия и пришла: страж выглядит охраной и
 * ничего не сторожит.
 */
function withoutComments(text: string): string {
  return text.replace(/\/\*[\s\S]*?\*\//gu, '').replace(/\/\/[^\n]*/gu, '');
}

/** Кусок исходника от одной опоры до другой. Обе обязаны быть. */
function regionOf(text: string, from: string, to: string): string {
  const start = text.indexOf(from);

  expect(start, `в панели настроек нет «${from}»`).toBeGreaterThan(-1);

  const end = text.indexOf(to, start);

  expect(end, `в панели настроек нет «${to}» после «${from}»`).toBeGreaterThan(start);

  return text.slice(start, end);
}

describe('названия настроек в панели', () => {
  it('ни одна настройка не показывается ключом из базы', () => {
    const source = readFileSync(panel, 'utf8');

    /**
     * Ищем объявление вида `имяНастройки: {` внутри словаря.
     *
     * Достаточно строго, чтобы не поймать случайное упоминание в
     * пояснении: имя должно стоять в начале строки как поле объекта.
     */
    const nameless = Object.keys(SETTINGS).filter(
      (name) => !new RegExp(`^\\s{2}${name}:\\s*\\{`, 'mu').test(source),
    );

    expect(
      nameless,
      `настройки без названия в панели (покажутся ключом из базы): ${nameless.join(', ')}`,
    ).toEqual([]);
  });
});

describe('отказ чтения настроек не уносит с экрана промокоды (находка 11)', () => {
  /**
   * **Зачем страж и почему по исходнику.** Отказ был молчаливым по сути:
   * панель работала, просто вместо раздела печатался один абзац — вместе
   * с блоком промокодов, который читается отдельным запросом и мог
   * ответить нормально. Цена: код утёк в публичный канал, выключить его
   * надо срочно, а на экране «Не удалось прочитать настройки».
   *
   * Браузерная половина живёт в `tests/admin/settings.spec.ts` и гоняется
   * отдельно; здесь держится связка «у раздела нет раннего возврата» —
   * то есть ни одно состояние не может унести PromoBlock с экрана.
   */
  it('у раздела настроек нет ни одного раннего возврата', () => {
    const source = readFileSync(panel, 'utf8');
    /**
     * До закрывающей скобки в нулевой колонке — то есть до конца самой
     * функции. Помощники, объявленные ниже, под запрет не попадают: у них
     * ранний возврат законен, а унести с экрана они ничего не могут.
     */
    const body = regionOf(source, 'export function SettingsPanel', '\n}\n');

    // Проверка не должна быть пустой: блок промокодов обязан стоять
    // внутри разбираемого куска, иначе сторожить нечего.
    expect(body, 'блок промокодов не найден внутри раздела настроек').toContain('<PromoBlock');

    const early = [...body.matchAll(/if \([^)]*\)\s*\{?\s*return/gu)].map((hit) => hit[0]);

    expect(
      early,
      [
        `в разделе настроек появился ранний возврат: ${early.join(' | ')}.`,
        'Ожидание и отказ не должны подменять собой страницу: блок промокодов',
        'читается своим запросом и от значений настроек не зависит вовсе.',
        'Печатайте отказ на месте таблицы, а не вместо раздела.',
      ].join('\n'),
    ).toEqual([]);
  });
});

describe('срок действия промокода достижим с экрана (находка 3)', () => {
  /**
   * Срок был на всём пути, кроме экрана: колонка в базе, разбор тела в
   * маршруте, соблюдение ботом («код истёк»). А форма поля не посылала, и
   * таблица колонки не печатала — значит код со сроком показывался живым,
   * с кнопкой «Выключить», пока бот уже отказывал человеку.
   */
  it('поле срока есть в форме и уходит в тело запроса', () => {
    const source = readFileSync(panel, 'utf8');

    expect(source, 'в форме промокода нет поля срока').toContain('name="promoUntil"');

    /**
     * Поле, не уходящее в тело запроса, — обманка хуже отсутствия: на
     * экране срок задан, в базе его нет, и бот кода не закроет.
     */
    expect(
      regionOf(source, 'void savePromoCode({', '.then('),
      'поле срока есть в форме, но в тело запроса не уходит',
    ).toContain('validUntil');
  });

  it('таблица кодов печатает срок и помечает истёкший', () => {
    const source = readFileSync(panel, 'utf8');
    const table = withoutComments(regionOf(source, '{rows.map((row)', '</table>'));

    expect(table, 'в таблице кодов не напечатан срок').toContain('row.validUntil');

    /**
     * Пометка рядом с кодом — так же явно, как «(выключен)». Без неё
     * панель показывает истёкший код живым: жалобу блогера «код не
     * работает» разобрать нечем, потому что на экране всё в порядке.
     *
     * Сверяется и слово, и то, чем оно посчитано: слово без вычисления —
     * подпись, вычисление без слова — молчание.
     */
    expect(table, 'истёкший код в таблице ничем не помечен').toContain('истёк');
    expect(table, 'пометка «истёк» ничем не посчитана').toContain('expired(row.validUntil');
  });
});

/**
 * Подсказка про код обещает то же правило, что держит проверка.
 *
 * Разбор «частично подтверждённых» нашёл здесь три текста одного экрана,
 * противоречащих друг другу: подсказка обещала «не короче шести знаков»,
 * шаблон пускал четыре, а отказ сервера называл третье. «SALE»
 * заводился молча — то есть панель отказывала в том, чего не запрещала,
 * или пропускала то, что запрещала подсказкой.
 *
 * Числа теперь названы один раз (`CODE_MIN`, `CODE_MAX`) и приезжают в
 * отказ сервера сами. В панель импортировать их нельзя — другой пакет,
 * — поэтому связку держит этот страж.
 */
describe('подсказка про код промокода не расходится с правилом', () => {
  function hint(): string {
    const text = readFileSync(panel, 'utf8');
    const at = text.indexOf('Код — латиница');

    expect(at, 'в панели нет подсказки про вид кода').toBeGreaterThan(-1);

    return text.slice(at, at + 200);
  }

  it('подсказка называет те же пределы длины, что и проверка', () => {
    const said = hint();

    expect(
      said.includes(String(CODE_MIN)) && said.includes(String(CODE_MAX)),
      `подсказка в панели обещает не те пределы: правило — от ${String(CODE_MIN)} до ` +
        `${String(CODE_MAX)} знаков, а сказано «${said.slice(0, 90)}…». Заказчица прочтёт ` +
        'подсказку и получит отказ на том, чего подсказка не запрещала.',
    ).toBe(true);
  });

  it('подсказка не обещает своего минимума помимо правила', () => {
    /**
     * Прежняя формулировка «не короче шести знаков» читалась правилом
     * поля, потому что стояла в списке правил. Совет остаться коротким
     * законен, но не в виде числа: число человек примет за границу.
     */
    expect(hint()).not.toContain('не короче шести');
  });
});

/**
 * Потолок звёзд назван на экране и держится записью.
 *
 * Разбор «частично подтверждённых»: подсказка обещала «потолок 10 000»
 * в том же списке, где остальные фразы описывают правила самого поля, а
 * предел в реестре стоял в сто раз шире. Заказчица вводила 12 000,
 * панель отвечала «Сохранено», и месяц перестал продаваться — отказ
 * приходил от рельса на счёте, то есть уже у человека.
 *
 * Число теперь одно (`STARS_MAX_SUBSCRIPTION`), и страж держит обе
 * связки: предел настройки равен пределу рельса, а подсказка называет
 * то же число.
 */
describe('потолок цены в звёздах — одно число на всех', () => {
  it('предел настройки равен пределу рельса', () => {
    expect(
      SETTINGS.priceMonthlyStars.max,
      'предел месячной цены в звёздах разошёлся с пределом рельса: панель примет число, ' +
        'на котором Telegram откажет уже у человека',
    ).toBe(STARS_MAX_SUBSCRIPTION);
  });

  it('подсказка в панели называет то же число', () => {
    const text = readFileSync(panel, 'utf8');
    const at = text.indexOf('Подписка в звёздах бывает только месячной');

    expect(at, 'в панели нет подсказки про цену в звёздах').toBeGreaterThan(-1);

    // Число печатается с пробелом-разделителем разрядов, как его читает
    // человек, поэтому сверяется по цифрам без разделителей.
    // `\s` в юникодном режиме покрывает и неразрывный пробел, которым
    // разделены разряды в подсказке.
    const said = text.slice(at, at + 160).replace(/\s/gu, '');

    expect(
      said.includes(String(STARS_MAX_SUBSCRIPTION)),
      `подсказка обещает не тот потолок: рельс держит ${String(STARS_MAX_SUBSCRIPTION)}, ` +
        `а сказано «${text.slice(at, at + 90)}…»`,
    ).toBe(true);
  });
});
