import { readFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

import { describe, expect, it } from 'vitest';

import { SETTINGS } from './settings.repo.js';

/**
 * У каждой настройки есть человеческое название в панели (задача 4.2).
 *
 * **Зачем страж.** Панель берёт название из своего словаря `TITLES`, а
 * при промахе показывает ключ из базы: `broadcast.per_second` вместо
 * «Темп рассылки». Отказ молчаливый — раздел работает, значение правится,
 * — и потому живёт долго: так и вышло с темпом рассылки (4.10) и с
 * четырьмя ценами (4.2), пока их не заметили глазами.
 *
 * Цена промаха у цен выше остальных: поле «price.monthly_rub_minor» без
 * подсказки не говорит ни про копейки, ни про то, что ноль выключает
 * продажу. Человек введёт «399» и продаст месяц за три рубля.
 *
 * Проверка идёт **по исходнику панели**, а не по собранному коду: словарь
 * живёт в другом пакете, импортировать `.tsx` в тесты бота незачем. Тот
 * же приём, что у стража путей админ-роутера.
 */

const panel = resolve(
  dirname(fileURLToPath(import.meta.url)),
  '../../../../admin/src/Settings.tsx',
);

describe('названия настроек в панели', () => {
  it('ни одна настройка не показывается ключом из базы', () => {
    const source = readFileSync(panel, 'utf8');

    /**
     * Ищем объявление вида `имяНастройки: {` внутри словаря.
     *
     * Достаточно строго, чтобы не поймать случайное упоминание в
     * пояснении: имя должно стоять в начале строки как поле объекта.
     */
    const nameless = Object.keys(SETTINGS).filter(
      (name) => !new RegExp(`^\\s{2}${name}:\\s*\\{`, 'mu').test(source),
    );

    expect(
      nameless,
      `настройки без названия в панели (покажутся ключом из базы): ${nameless.join(', ')}`,
    ).toEqual([]);
  });
});
