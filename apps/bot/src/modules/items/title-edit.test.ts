import { describe, expect, it } from 'vitest';

import { looksLikeNewTitle, newTitleFrom } from './title-edit.js';

/**
 * Новое название по «Изменить» (заказчица, 30.09.2026): она нажала
 * «Изменить» у «Купить молоко» и сказала голосом «Назови это молочко» —
 * название — «Молочко», а не «Назови это молочко».
 */
describe('newTitleFrom', () => {
  it.each([
    // Её слова, как их распознало голосовое.
    ['Назови это молочко.', 'Молочко'],
    ['назови молочко', 'Молочко'],
    ['Переименуй в «Молочко»', 'Молочко'],
    ['Переименуй это в купить молоко и хлеб', 'Купить молоко и хлеб'],
    ['Пусть будет купить молоко', 'Купить молоко'],
    ['Пусть называется молочко', 'Молочко'],
    ['Поменяй на записаться к стоматологу', 'Записаться к стоматологу'],
    ['Исправь название на Самвелику', 'Самвелику'],
    ['Название: молочко', 'Молочко'],
    ['Ну давай назови его молочко', 'Молочко'],
    // Просто новое название — как есть, с заглавной и без точки в конце.
    ['молочка', 'Молочка'],
    [
      'Записаться к стоматологу на следующую неделю',
      'Записаться к стоматологу на следующую неделю',
    ],
  ])('«%s» → «%s»', (spoken, title) => {
    expect(newTitleFrom(spoken)).toBe(title);
  });

  it.each(['Назови это', 'Переименуй в', '  ', '...'])(
    '«%s» — названия нет: не выдумывать',
    (spoken) => {
      expect(newTitleFrom(spoken)).toBeUndefined();
    },
  );

  it('слово-команда внутри названия не трогается: «Назвать сына Мишей — спросить маму»', () => {
    // «Назвать» — не «назови»: это дело, а не просьба переименовать.
    expect(newTitleFrom('Назвать сына Мишей — спросить маму')).toBe(
      'Назвать сына Мишей — спросить маму',
    );
  });
});

describe('looksLikeNewTitle — голосовое похоже на название, а не на выгрузку', () => {
  it.each(['Назови это молочко.', 'Молочко', 'Записаться к стоматологу на следующую неделю'])(
    '«%s» — название',
    (spoken) => {
      expect(looksLikeNewTitle(spoken)).toBe(true);
    },
  );

  it.each([
    // Несколько мыслей — это выгрузка: разобрать как обычно, ничего не потерять.
    'Назови это молочко. И ещё надо купить хлеб и позвонить маме в пятницу',
    'Купить молоко, забрать посылку, записаться к врачу, оплатить садик и позвонить маме вечером обязательно',
  ])('«%s» — не название', (spoken) => {
    expect(looksLikeNewTitle(spoken)).toBe(false);
  });
});
