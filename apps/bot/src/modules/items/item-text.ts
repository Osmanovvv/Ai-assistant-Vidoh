/**
 * Заглавная в начале, если первое слово написано строчными.
 *
 * **Условие про первое слово — не придирка.** «iPhone купить» от простого
 * `toUpperCase` на первом знаке превратилось бы в «IPhone купить», а
 * «ВБ заказы» трогать не нужно вовсе. Поэтому правится только то, где в
 * первом слове заглавных нет ни одной: там их отсутствие и есть небрежность.
 */
export function withCapital(text: string): string {
  const trimmed = text.trim();
  if (trimmed.length === 0) return trimmed;

  const [first = ''] = trimmed.split(/\s+/u);
  if (first !== first.toLowerCase()) return trimmed;

  const head = trimmed.slice(0, 1);
  const upper = head.toUpperCase();

  // Знак без регистра (цифра, кавычка, тире) заглавной не имеет — и
  // тогда трогать нечего: «5 сентября позвонить» так и остаётся.
  if (upper === head) return trimmed;

  return `${upper}${trimmed.slice(1)}`;
}
