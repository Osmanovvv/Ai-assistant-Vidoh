/**
 * Заголовок записи: как он хранится (задача 3.25).
 *
 * **Регистр плавал между выгрузками, и это видно человеку.** Ручной
 * прогон 01.09.2026: первая выгрузка дала все двенадцать записей с
 * большой буквы («Позвонить Ленке», «Дочитать книгу…»), вторая — все пять
 * с маленькой («сверить кассу», «договориться с няней…»). Внутри
 * выгрузки единообразно, между выгрузками нет — а в сводке ветки и в
 * выдаче они стоят рядом друг с другом.
 *
 * Это не тот дребезг, что чинили в 3.23: там один и тот же вход давал
 * разное, здесь вход разный, и модель просто по-разному решает про
 * регистр. Просить её об этом в промпте — значит платить прогоном набора
 * за то, что делается правилом без исключений.
 */

/**
 * Заглавная в начале, если первое слово написано строчными.
 *
 * **Условие про первое слово — не придирка.** «iPhone купить» от простого
 * `toUpperCase` на первом знаке превратилось бы в «IPhone купить», а
 * «ВБ заказы» трогать не нужно вовсе. Поэтому правится только то, где в
 * первом слове заглавных нет ни одной: там их отсутствие и есть небрежность.
 */
export function withCapital(text: string): string {
  const trimmed = text.trim();
  if (trimmed.length === 0) return trimmed;

  const [first = ''] = trimmed.split(/\s+/u);
  if (first !== first.toLowerCase()) return trimmed;

  const head = trimmed.slice(0, 1);
  const upper = head.toUpperCase();

  // Знак без регистра (цифра, кавычка, тире) заглавной не имеет — и
  // тогда трогать нечего: «5 сентября позвонить» так и остаётся.
  if (upper === head) return trimmed;

  return `${upper}${trimmed.slice(1)}`;
}

/**
 * Ярлыки карточки записи — те же слова, что печатает `card` в словаре.
 *
 * Список закрытый и держится рядом с проверкой, а не читается из словаря:
 * `saveItems` и классификация словаря не знают, а тащить его туда ради
 * четырёх слов значит менять подписи функций по всей цепочке. Расхождение
 * с словарём ловит тест — он сверяет этот список с `card` напрямую.
 */
export const CARD_LABELS = ['Срок', 'Статус', 'Сфера', 'Повторяется'] as const;

/**
 * Значения, которые карточка печатает у своих полей.
 *
 * Проверка **по значению, а не только по ярлыку** — и в этом весь смысл
 * узости. «Уточнить срок доставки» и «Спросить статус заявки» человек
 * говорит по-настоящему, и трогать их нельзя. А «Срок 07.09» и «Статус
 * ждет» — это буквально то, что бот рисует сам, и ничем другим быть не
 * может.
 */
const CARD_VALUE =
  /^(?:около\s+)?(?:\d{1,2}\.\d{1,2}(?:\.\d{2,4})?|без срока|ждет|ждёт|ждёт ответа|в работе|сделано|отложено|убрано|передано)$/u;

const LABEL = CARD_LABELS.join('|');

/**
 * Строка целиком — поле карточки: «Статус ждет», «Срок: 07.09».
 *
 * `String.raw`, а не обычная строка: без него обратные косые в выражении
 * пришлось бы удваивать, и `\s` молча стал бы буквой «s».
 */
const FIELD_LINE = new RegExp(String.raw`^(?:${LABEL})\s*:?\s*(.*)$`, 'u');

/**
 * Хвост первой строки: «Позвонить бабушке. Срок 07.09».
 *
 * **Точка в значении разрешена, и это не небрежность.** Первая версия
 * исключала её — и «Срок 07.09» не находился вовсе, потому что дата из
 * точек и состоит. Надёжность здесь держится не на классе знаков, а на
 * `CARD_VALUE`: что бы регулярное выражение ни выхватило, обрезается это
 * только если совпало со значением, которое печатает сама карточка.
 * «Срок уточнить. 07.09» под него не подходит и остаётся целым.
 */
const FIELD_TAIL = new RegExp(String.raw`[.,;]\s*(?:${LABEL})\s*:?\s*([^,;\n]{1,24})$`, 'u');

/**
 * Заголовок записи без полей карточки (задача 3.62).
 *
 * **Найдено живым прогоном 05.09.2026.** Заказчик переслал голосовое, и
 * одна запись из семнадцати вышла такой:
 *
 * ```
 * Позвонить бабушке. Срок 07.09
 * Статус ждет
 * ```
 *
 * Ни «Срок 07.09», ни «Статус ждет» человек не говорил — в расшифровке
 * этих слов нет вовсе. Формат протащила модель: в промпте классификации
 * есть раздел с заголовком «## Срок», и она вписала поля карточки внутрь
 * текста дела.
 *
 * **Почему правилом кода, а не промптом.** Утяжеление промпта в этом
 * проекте провалилось шесть раз из шести. А здесь и просить нечего: поля
 * карточки в заголовке — не спорное решение модели, а мусор, и убрать его
 * можно проверяемо.
 *
 * **Две узкие проверки, и обе по значению.**
 *
 * 1. Строка после первой, целиком состоящая из поля карточки с её же
 *    значением, — убирается. Заголовок дела одну строку и занимает.
 * 2. Хвост первой строки после точки или запятой: ярлык плюс значение,
 *    которое печатает карточка. «Уточнить срок доставки» под это не
 *    попадает: там ярлык не после точки и значение не карточное.
 *
 * Строка, не похожая на поле, **остаётся** — терять сказанное нельзя даже
 * ради опрятности. Если модель придумает третью форму, мы увидим её в
 * записи, а не потеряем.
 */
export function withoutCardFields(text: string): string {
  const lines = text.split(/\r?\n/u);

  const kept = lines.filter((line, index) => {
    if (index === 0) return true;

    const field = FIELD_LINE.exec(line.trim());
    return field === null || !CARD_VALUE.test((field[1] ?? '').trim());
  });

  const joined = kept.join('\n');
  const tail = FIELD_TAIL.exec(joined);
  if (tail === null || !CARD_VALUE.test((tail[1] ?? '').trim())) return joined;

  return joined.slice(0, tail.index).trimEnd();
}

/**
 * Заголовок для списка, в шапке которого назван день (задача 3.78).
 *
 * **Найдено прогоном выдачи на боевых записях 05.09.2026.** Утренняя
 * сводка проджекта читалась так:
 *
 * > На сегодня:
 * > — Вынести мусор
 * > — Позвонить стоматологу **завтра**
 *
 * Шапка говорит «сегодня», строка — «завтра», и человек читает это как
 * поломку. Причина простая: он сказал «завтра» **вчера**, срок встал на
 * сегодня, а слова в заголовке остались вчерашние.
 *
 * **Срезается только у дела, чей срок и есть названный в шапке день.**
 * Тогда дата в словах человека провабельно устарела, и убрать её значит
 * убрать противоречие, ничего не потеряв: настоящий день назван выше.
 *
 * **У дела без срока заголовок не трогается.** «Завтра» в его тексте —
 * единственное, что у человека есть про день: срок либо не назывался,
 * либо не прошёл проверку §2.7. Срезать это значило бы спрятать от него
 * то, чего больше нигде нет.
 */
export function titleUnderDayHeader(
  item: { readonly text: string; readonly deadlineAt: Date | null },
  params: { readonly now: Date; readonly timeZone: string },
): string {
  if (item.deadlineAt === null) return item.text;

  const day = isoDateIn(item.deadlineAt, params.timeZone);
  if (day !== isoDateIn(params.now, params.timeZone)) return item.text;

  /**
   * Заглавная после срезания — обязательна.
   *
   * «Завтра надо купить корм» даёт «надо купить корм», и в списке рядом с
   * «Вынести мусор» строчная буква читается как небрежность. То же
   * правило регистра, что при сохранении записи (задача 3.25).
   */
  return withCapital(titleWithoutDate(item.text));
}
