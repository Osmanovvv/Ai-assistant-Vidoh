import type { Item } from '../../db/schema.js';
import { withoutClockPhrase } from '../classifier/clock-time.js';
import { storedTitle } from './item-text.js';

/**
 * Повтор той же выгрузки (найдено на боевом 01.09.2026).
 *
 * **Человек отправил одно и то же голосовое три раза, и бот завёл
 * восемнадцать записей вместо шести.** Отправлял он повторно потому, что
 * ответ показывал не то, о чём он говорил, — то есть один дефект породил
 * второй. Первый починен порядком выдачи, но и второй надо закрыть: люди
 * повторяются и без наших ошибок — сеть отвалилась, показалось, что не
 * отправилось, вспомнил и сказал ещё раз.
 *
 * **Сверяется дословный текст, а не близость по смыслу.** Векторный
 * поиск в проекте есть, и соблазн применить его здесь велик — но цена
 * ошибки несимметрична. Пропущенный повтор даёт лишнюю строку в списке;
 * ложное совпадение **молча съедает сказанное**, а это ровно то, чего
 * продукт обещает не делать. «Позвонить маме» и «позвонить папе» по
 * вектору соседи.
 *
 * Дословное совпадение такой ошибки допустить не может: если строки
 * совпали до знака, это одно и то же дело, названное дважды.
 */

/**
 * Приводит текст к виду, в котором его можно сравнивать.
 *
 * **Сперва — тот вид, в каком текст хранится** (`storedTitle`). Сюда
 * приходят и сырой текст модели, и уже сохранённая запись, а в базу
 * текст уходит без полей карточки (задача 3.62). Сравнивать сырое с
 * обрезанным значило бы промахиваться ровно на тех записях, куда модель
 * вписала «Срок 07.09»: живой прогон 05.09.2026 дал такую одну из
 * семнадцати, и повтор заводил ей вторую копию. На уже сохранённом
 * тексте преобразование ничего не меняет.
 *
 * Регистр и «ё» — потому что расшифровка речи их не гарантирует: одно и
 * то же голосовое дважды может прийти как «Съездить в магазин» и
 * «съездить в магазин». Пробелы — потому что их число ничего не значит.
 * Хвостовая точка — потому что расшифровка ставит её через раз.
 */
export function sameTextKey(text: string): string {
  // Фраза о часе — не часть дела (живой прогон Никиты 23.09.2026): «Забрать
  // посылку без 15 6» и «Забрать посылку» — одно дело; у «без 15 6» два
  // чтения, час сроком не стал и остался в заголовке — и завёлся дубль.
  //
  // И день словом — тоже (проверка Никиты 24.09.2026, 19:00): «Поехать за
  // ребёнком завтра» при записанной «Поехать за ребёнком в 4 часа» завело
  // второе дело вместо переноса. Только «сегодня/завтра/послезавтра»:
  // «позвонить маме в четверг» и «в пятницу» могут быть разными делами.
  return storedTitle(withoutClockPhrase(text))
    .toLowerCase()
    .replace(/ё/gu, 'е')
    .replace(/(?<!\p{L})(?:на\s+)?(?:сегодня|завтра|послезавтра)(?!\p{L})/gu, ' ')
    .replace(/\s+/gu, ' ')
    .replace(/[.!]+$/u, '')
    .trim();
}

/**
 * День недели словом — «в понедельник», «до среды», «к пятнице».
 *
 * В общий ключ он не входит намеренно: «позвонить маме в четверг» и «в
 * пятницу» могут быть двумя делами. Но у записи **без срока** своего дня
 * нет, и спорить не с чем (прогон Никиты 27.09.2026, 15:22):
 * «Записать Мишу к ортодонту» легло без даты — распознавание прилепило
 * «в понедельник» к соседнему предложению, — а «Мишу записать к
 * ортодонту в понедельник» следом завело второе дело вместо того, чтобы
 * дать день первому. Закрытый список, целыми словами, по ключу — то есть
 * в нижнем регистре и с «е» вместо «ё».
 */
const WEEKDAY_PHRASE = new RegExp(
  String.raw`(?<!\p{L})(?:(?:в|во)\s+(?:(?:этот|эту|это|следующий|следующую|следующее|ближайший|ближайшую|ближайшее)\s+)?(?:понедельник|вторник|среду|четверг|пятницу|субботу|воскресенье)|до\s+(?:понедельника|вторника|среды|четверга|пятницы|субботы|воскресенья)|(?:к|ко)\s+(?:понедельнику|вторнику|среде|четвергу|пятнице|субботе|воскресенью))(?!\p{L})`,
  'gu',
);

/** Ключ без дня недели; запятые и пробелы по краям вырезанного — тоже. */
function withoutWeekday(key: string): string {
  return key
    .replace(WEEKDAY_PHRASE, ' ')
    .replace(/\s+/gu, ' ')
    .replace(/^[\s,;:—-]+|[\s,;:—-]+$/gu, '')
    .replace(/\s+,/gu, ',')
    .trim();
}

export interface KnownItems {
  /** Уже открытые записи с таким же текстом: ключ — `sameTextKey`. */
  readonly byText: ReadonlyMap<string, Item>;
  /**
   * Те же записи, но только без срока: к ним сказанное с днём недели —
   * повтор, а день — новый срок (27.09.2026).
   */
  readonly dateless: ReadonlyMap<string, Item>;
}

/**
 * Собирает указатель по открытым записям человека.
 *
 * Если одинаковый текст встретился дважды среди уже открытых (а он
 * встретился — дубли за 31.08 лежат в бою), берётся **самая ранняя**:
 * повтор присоединяется к первой записи, а не к последней копии.
 */
export function knownByText(open: readonly Item[]): KnownItems {
  const byText = new Map<string, Item>();
  const dateless = new Map<string, Item>();

  const earliest = (map: Map<string, Item>, key: string, item: Item): void => {
    const seen = map.get(key);
    if (seen === undefined || item.createdAt.getTime() < seen.createdAt.getTime()) {
      map.set(key, item);
    }
  };

  for (const item of open) {
    const key = sameTextKey(item.text);
    earliest(byText, key, item);
    if (item.deadlineAt === null) earliest(dateless, key, item);
  }

  return { byText, dateless };
}

/**
 * Повтор записи без срока с названным днём недели: «…в понедельник» при
 * записанном «…» без даты. Сказанное без дня сюда не доходит — его уже
 * нашло дословное сравнение.
 */
function datelessWithDay(key: string, known: KnownItems): Item | undefined {
  const bare = withoutWeekday(key);
  return bare === key || bare === '' ? undefined : known.dateless.get(bare);
}

/**
 * Двойник без срока внутри одной выгрузки (прогон Никиты 27.09.2026, 18:16).
 *
 * Два голосовых подряд — «Записать Мишу к стоматологу.» и «Записать Мишу к
 * стоматологу в среду.» — попали в одну выгрузку, и завелись два дела. Отсев
 * повтора внутри выгрузки (`splitKnown`) сравнивает дословно и оставляет
 * первое — а первым было то, что без дня. Здесь уступает запись без срока:
 * её слова — те же, что у записи с днём, без названного дня («в среду»,
 * «завтра»). Возвращает номера уступающих. Обе с днями — не трогаются: «в
 * четверг» и «в пятницу» могут быть двумя делами.
 */
export function datelessTwins(
  items: readonly { readonly text: string; readonly deadline?: unknown }[],
): ReadonlySet<number> {
  const withDay = new Set(
    items
      .filter((item) => item.deadline !== undefined)
      .map((item) => withoutWeekday(sameTextKey(item.text))),
  );

  const twins = new Set<number>();
  for (const [index, item] of items.entries()) {
    if (item.deadline === undefined && withDay.has(sameTextKey(item.text))) twins.add(index);
  }
  return twins;
}

export interface SplitResult<T> {
  /** Чего у человека ещё нет — это и надо завести. */
  readonly fresh: readonly T[];
  /** Что уже есть: заводить не надо, но человек об этом сейчас говорил. */
  readonly known: readonly Item[];
  /**
   * Повторы парой: что сказано сейчас и какая запись уже есть. Сказанное
   * может нести новый срок — «давай заберём посылку без 15 6» при уже
   * записанной посылке: это перенос, а не повтор (23.09.2026).
   */
  readonly repeats: readonly { readonly unit: T; readonly item: Item }[];
}

/**
 * Делит разобранные единицы на новые и уже имеющиеся.
 *
 * Повтор внутри одной выгрузки тоже считается повтором: если человек в
 * одной речи дважды сказал «купить хлеб», записей должно стать одна.
 */
export function splitKnown<T extends { readonly text: string }>(
  units: readonly T[],
  known: KnownItems,
): SplitResult<T> {
  const fresh: T[] = [];
  const found: Item[] = [];
  const repeats: { unit: T; item: Item }[] = [];
  const taken = new Set<string>();

  for (const unit of units) {
    const key = sameTextKey(unit.text);

    if (taken.has(key)) continue;
    taken.add(key);

    const existing = known.byText.get(key) ?? datelessWithDay(key, known);
    if (existing === undefined) {
      fresh.push(unit);
      continue;
    }

    found.push(existing);
    repeats.push({ unit, item: existing });
  }

  return { fresh, known: found, repeats };
}
