import { describe, expect, it } from 'vitest';

import { withCapital } from './item-text.js';

/**
 * Регистр заголовка (задача 3.25, найдено ручным прогоном 01.09.2026).
 *
 * Случаев «не трогать» здесь больше, чем «поправить», и так и надо:
 * пропущенная строчная буква — небрежность, а испорченное «iPhone» —
 * искажение слов человека.
 */

describe('поправляет строчное начало', () => {
  it.each([
    ['сверить кассу', 'Сверить кассу'],
    ['договориться с няней', 'Договориться с няней'],
    ['выспаться', 'Выспаться'],
    ['  съездить в магазин  ', 'Съездить в магазин'],
  ])('«%s» → «%s»', (before, after) => {
    expect(withCapital(before)).toBe(after);
  });
});

describe('не трогает то, что трогать нельзя', () => {
  it('уже с заглавной', () => {
    expect(withCapital('Позвонить Ленке')).toBe('Позвонить Ленке');
  });

  it('слово со внутренней заглавной остаётся как написано', () => {
    // Простой `toUpperCase` дал бы «IPhone купить» — это уже не слова
    // человека, а наша выдумка.
    expect(withCapital('iPhone купить')).toBe('iPhone купить');
    expect(withCapital('eSIM оформить')).toBe('eSIM оформить');
  });

  it('сокращение заглавными', () => {
    expect(withCapital('ВБ заказы сделать')).toBe('ВБ заказы сделать');
  });

  it('начало без регистра — цифра или знак', () => {
    expect(withCapital('5 сентября позвонить')).toBe('5 сентября позвонить');
    expect(withCapital('«Логика» дочитать')).toBe('«Логика» дочитать');
  });

  it('пустое остаётся пустым', () => {
    expect(withCapital('')).toBe('');
    expect(withCapital('   ')).toBe('');
  });
});

describe('правило устойчиво', () => {
  it('повторное применение ничего не меняет', () => {
    // Заголовок проходит через сохранение не один раз: правка перезаписывает
    // текст, и правило обязано быть неподвижной точкой.
    const once = withCapital('сверить кассу');

    expect(withCapital(once)).toBe(once);
  });
});
