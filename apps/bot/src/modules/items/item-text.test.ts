import { describe, expect, it } from 'vitest';

import { CARD_LABELS, withCapital, withoutCardFields } from './item-text.js';
import { defaultTexts } from '../../texts/index.js';

/**
 * Регистр заголовка (задача 3.25, найдено ручным прогоном 01.09.2026).
 *
 * Случаев «не трогать» здесь больше, чем «поправить», и так и надо:
 * пропущенная строчная буква — небрежность, а испорченное «iPhone» —
 * искажение слов человека.
 */

describe('поправляет строчное начало', () => {
  it.each([
    ['сверить кассу', 'Сверить кассу'],
    ['договориться с няней', 'Договориться с няней'],
    ['выспаться', 'Выспаться'],
    ['  съездить в магазин  ', 'Съездить в магазин'],
  ])('«%s» → «%s»', (before, after) => {
    expect(withCapital(before)).toBe(after);
  });
});

describe('не трогает то, что трогать нельзя', () => {
  it('уже с заглавной', () => {
    expect(withCapital('Позвонить Ленке')).toBe('Позвонить Ленке');
  });

  it('слово со внутренней заглавной остаётся как написано', () => {
    // Простой `toUpperCase` дал бы «IPhone купить» — это уже не слова
    // человека, а наша выдумка.
    expect(withCapital('iPhone купить')).toBe('iPhone купить');
    expect(withCapital('eSIM оформить')).toBe('eSIM оформить');
  });

  it('сокращение заглавными', () => {
    expect(withCapital('ВБ заказы сделать')).toBe('ВБ заказы сделать');
  });

  it('начало без регистра — цифра или знак', () => {
    expect(withCapital('5 сентября позвонить')).toBe('5 сентября позвонить');
    expect(withCapital('«Логика» дочитать')).toBe('«Логика» дочитать');
  });

  it('пустое остаётся пустым', () => {
    expect(withCapital('')).toBe('');
    expect(withCapital('   ')).toBe('');
  });
});

describe('правило устойчиво', () => {
  it('повторное применение ничего не меняет', () => {
    // Заголовок проходит через сохранение не один раз: правка перезаписывает
    // текст, и правило обязано быть неподвижной точкой.
    const once = withCapital('сверить кассу');

    expect(withCapital(once)).toBe(once);
  });
});

/**
 * Поля карточки в заголовке записи (задача 3.62).
 *
 * Найдено живым прогоном 05.09.2026. Заказчик переслал голосовое, и одна
 * запись из семнадцати вышла такой:
 *
 * ```
 * Позвонить бабушке. Срок 07.09
 * Статус ждет
 * ```
 *
 * Ни «Срок 07.09», ни «Статус ждет» человек не говорил — этих слов нет в
 * расшифровке вовсе. Формат протащила модель: в промпте классификации есть
 * раздел «## Срок».
 *
 * **Половина проверок ниже — про то, чего трогать нельзя.** Убрать лишнее
 * легко; трудно не съесть сказанное. «Уточнить срок доставки» — настоящее
 * дело, и оно обязано остаться целым.
 */
describe('поля карточки в заголовке', () => {
  it('боевой случай: убирает и хвост, и отдельную строку', () => {
    expect(withoutCardFields('Позвонить бабушке. Срок 07.09\nСтатус ждет')).toBe(
      'Позвонить бабушке',
    );
  });

  it('убирает поля с двоеточием, как их печатает карточка', () => {
    expect(withoutCardFields('Записаться к врачу\nСрок: 12.09\nСтатус: ждёт')).toBe(
      'Записаться к врачу',
    );
  });

  it('неточный срок карточки тоже узнаёт', () => {
    // «около 13.09» — это то, что карточка печатает при недельной точности.
    expect(withoutCardFields('Позвонить другу. Срок около 13.09')).toBe('Позвонить другу');
  });

  it('«без срока» — тоже значение карточки', () => {
    expect(withoutCardFields('Купить наушники. Срок без срока')).toBe('Купить наушники');
  });

  describe('чего трогать нельзя', () => {
    it('слово «срок» внутри дела остаётся', () => {
      for (const text of [
        'Уточнить срок доставки',
        'Спросить статус заявки',
        'Узнать Статус проекта',
        'Продлить срок аренды до конца года',
      ]) {
        expect(withoutCardFields(text), text).toBe(text);
      }
    });

    it('ярлык с не карточным значением остаётся', () => {
      /**
       * Надёжность держится на **значении**, а не на ярлыке: что бы
       * выражение ни выхватило, обрезается только совпавшее с тем, что
       * печатает карточка.
       */
      expect(withoutCardFields('Купить хлеб. Срок неизвестен')).toBe(
        'Купить хлеб. Срок неизвестен',
      );
      expect(withoutCardFields('Позвонить врачу. Срок уточнить. 07.09')).toBe(
        'Позвонить врачу. Срок уточнить. 07.09',
      );
    });

    it('вторая строка с настоящим содержанием остаётся', () => {
      // Терять сказанное нельзя даже ради опрятности.
      const text = 'Помыть машину\nи заодно пропылесосить';
      expect(withoutCardFields(text)).toBe(text);
    });

    it('обычный заголовок не меняется ничем', () => {
      for (const text of ['Позвонить бабушке', 'Вынести мусор', '']) {
        expect(withoutCardFields(text), text).toBe(text);
      }
    });
  });

  it('список ярлыков совпадает со словарём карточки', () => {
    /**
     * Список закрытый и живёт рядом с проверкой, а не читается из
     * словаря: `saveItems` словаря не знает. Расхождение ловит этот тест —
     * иначе переименованный ярлык молча перестал бы отсекаться.
     */
    const card = defaultTexts.card;
    expect([...CARD_LABELS].sort()).toEqual(
      [card.deadlineLabel, card.statusLabel, card.topicLabel, card.recurrenceLabel].sort(),
    );
  });
});
