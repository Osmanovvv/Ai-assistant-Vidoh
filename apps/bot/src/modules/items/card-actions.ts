/**
 * Действия карточки записи — данными, а не строками в обработчике.
 *
 * **Вынесено из `bot/handlers/card.ts` (задача 3.28).** Кнопку «Изменить»
 * предлагает теперь не только карточка: когда правка человека понята как
 * дополнение, а он говорил о замене, бот честно говорит, что заголовок
 * не менял, и даёт эту кнопку рядом с отменой. Обработчик у неё один и
 * тот же, значит и префикс должен быть один.
 *
 * Тот же приём, что у кнопок отката и уточняющего вопроса: «две копии
 * одной кнопки однажды разъехались бы префиксом, и половина нажатий
 * перестала бы находиться».
 *
 * **Строки менять нельзя.** Они лежат в переписке людей: сообщения с
 * кнопками остаются в чате навсегда, и нажатие по вчерашней кнопке
 * обязано находить свой обработчик. Тесты держат их дословно.
 */
export const CARD_ACTION = {
  done: 'i:done:',
  snooze: 'i:snz:',
  edit: 'i:edt:',
  /** «Не менять» под подсказкой «Изменить»: снимает ожидание заголовка. */
  editCancel: 'i:edx:',
  /** «Изменить время» / «Не менять» (ТЗ проджекта 17.09.2026, шаг 5). */
  retime: 'i:tm:',
  retimeCancel: 'i:tmx:',
  remove: 'i:rm:',
  /**
   * `i:mv:<код записи>` — открыть выбор сферы (§8.2, запрос на изменение №3).
   *
   * Нажатий два, потому что на первом сфера ещё не выбрана: одним
   * действием пришлось бы вести в `callback_data` и запись, и тему, а
   * темы там ещё нет.
   */
  move: 'i:mv:',
  /**
   * `i:to:<код записи>:<код сферы>` — переложить в выбранную сферу.
   *
   * Тема — коротким кодом, а не названием, по тому же доводу, что в меню
   * (`MENU_ACTION.topicPrefix`): колонка названия длину не ограничивает,
   * а кириллица весит по два байта на знак. Два кода и разделитель —
   * пятьдесят байт из шестидесяти четырёх, и предел не подвинется от
   * того, что кто-то заведёт длинное название.
   */
  moveTo: 'i:to:',
  /**
   * Похожее уже есть (заказчица, 30.09.2026): новое оставить —
   * `i:sk:<новое>`; то же — `i:ss:<новое>:<прежнее>` (новое убирается);
   * изменить прежнее — `i:se:<новое>:<прежнее>` (новое убирается,
   * открывается карточка прежнего). Два кода — 50 байт при пределе 64.
   */
  similarKeep: 'i:sk:',
  similarSame: 'i:ss:',
  similarEdit: 'i:se:',
} as const;
