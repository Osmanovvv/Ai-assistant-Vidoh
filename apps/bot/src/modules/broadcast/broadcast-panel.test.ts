import { readFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

import { describe, expect, it } from 'vitest';

/**
 * Что раздел «Рассылка» обязан показать и о чём сказать (ревизия панели).
 *
 * **Зачем страж и почему по исходнику.** Две находки ревизии молчаливые
 * и обе видны только в вёрстке: кнопка «Повторить неудачные», которую
 * сервер отвергает всегда, и список из двадцати рассылок без слов о том,
 * что показано не всё. Ни та, ни другая не роняют панель и ни одна не
 * видна в ответе сервера. Браузерная половина живёт в `tests/admin` и
 * гоняется отдельно и долго — тот же приём, что у стража журнала сбоев
 * (`admin/errors-panel.test.ts`) и у стража названий настроек.
 *
 * Страж грубый нарочно: он держит связку «условие панели совпадает с
 * условием сервера» и «обрезка названа словами», а не формулировки.
 */

const panel = resolve(
  dirname(fileURLToPath(import.meta.url)),
  '../../../../admin/src/Broadcast.tsx',
);

function source(): string {
  return readFileSync(panel, 'utf8');
}

describe('раздел рассылки не обещает того, чего сервер не сделает', () => {
  it('кнопка повтора спрашивает и про просьбу остановиться', () => {
    /**
     * Сервер требует три условия: неудачные есть, состояние законченное
     * и метка `stop_requested_at` пуста (`retryFailed`). Панель
     * спрашивала два — и у законченной рассылки с непустой меткой
     * кнопка висела активной, отвечая 409 на каждое нажатие. Кнопка,
     * которая отказывает, учит не верить панели.
     */
    const text = source();
    const at = text.indexOf('row.counts.failed > 0');

    expect(at, 'в панели нет условия показа кнопки повтора').toBeGreaterThan(-1);

    const condition = text.slice(at, text.indexOf('<button', at));

    expect(condition).toContain('row.stopRequestedAt === null');
    expect(condition).toContain("row.status === 'done'");
    expect(condition).toContain("row.status === 'failed'");
  });

  it('про обрезку списка сказано словами, и слова одни на две таблицы', () => {
    /**
     * Запрос отдаёт последние двадцать рассылок. Без числа и без слов об
     * обрезке двадцать строк читаются как полный список: после двадцать
     * первой рассылки предыдущие исчезают молча — вместе с единственным
     * путём к «Повторить неудачные».
     *
     * Слова берутся у «Ошибок», где эта строка уже написана для шести
     * журналов: второй способ сказать то же расходится молча — так и
     * вышло внутри самих «Ошибок», где строка досталась одному журналу
     * из шести.
     */
    const text = source();

    expect(text).toContain('page.total');
    expect(text).toMatch(/shown=\{page\.rows\.length\}\s*total=\{page\.total\}/u);
    expect(text).toContain("import { Trimmed } from './Errors.js'");

    // И своей копии тех же слов здесь нет.
    expect(text).not.toContain('Показаны последние');
  });
});
