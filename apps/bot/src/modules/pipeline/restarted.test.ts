import { describe, expect, it } from 'vitest';

import { restartedFragments } from './restarted.js';

/**
 * Обрывок, сказанный потом целиком («с нуля» Никиты 25.09.2026, 17:10):
 * голосовое «Перенеси стоматолога на после.» оборвалось, следом —
 * «Перенеси стоматолога на послезавтра в 7.». Бот разобрал обрывок
 * отдельной правкой и ответил «Там уже так — менять нечего».
 */
const resolved = (intent: string): boolean => ['PATCH', 'COMPLETE', 'CANCEL'].includes(intent);
const of = (...segments: [string, string][]) =>
  restartedFragments(
    segments.map(([intent, text]) => ({ intent, text })),
    resolved,
  );

describe('обрывок правки, сказанной потом целиком', () => {
  it('бой 25.09.2026: «на после.» и следом «на послезавтра в 7.» — первое обрывок', () => {
    expect(
      of(
        ['PATCH', 'Перенеси стоматолога на после.'],
        ['PATCH', 'Перенеси стоматолога на послезавтра в 7.'],
      ),
    ).toEqual(new Set([0]));
  });

  it('знаки и заглавные не мешают; обрыв посреди слова — тоже обрывок', () => {
    expect(
      of(
        ['PATCH', 'перенеси стоматолога, на пос…'],
        ['PATCH', 'Перенеси стоматолога на послезавтра.'],
      ),
    ).toEqual(new Set([0]));
    expect(of(['CANCEL', 'Удали.'], ['CANCEL', 'Удали хлеб из списка.'])).toEqual(new Set([0]));
  });

  it('то же самое дважды — повтор: первый не разбирается, второй разбирается', () => {
    expect(
      of(['PATCH', 'Перенеси хлеб на пятницу.'], ['PATCH', 'Перенеси хлеб на пятницу.']),
    ).toEqual(new Set([0]));
  });

  it('разные правки — не обрывки, обе разбираются', () => {
    expect(
      of(['PATCH', 'Перенеси стоматолога на пятницу.'], ['PATCH', 'Перенеси хлеб на субботу.']),
    ).toEqual(new Set());
    expect(
      of(['PATCH', 'Перенеси хлеб на пятницу.'], ['PATCH', 'Перенеси хлебницу на субботу.']),
    ).toEqual(new Set());
  });

  it('продолжение через «и», «а», «ещё» — добавка, а не обрывок: обе правки разбираются', () => {
    expect(of(['CANCEL', 'Удали хлеб.'], ['CANCEL', 'Удали хлеб и масло.'])).toEqual(new Set());
    expect(
      of(
        ['PATCH', 'Перенеси врача на пятницу.'],
        ['PATCH', 'Перенеси врача на пятницу, а маму на субботу.'],
      ),
    ).toEqual(new Set());
    expect(
      of(['PATCH', 'Перенеси врача.'], ['PATCH', 'Перенеси врача ещё и стоматолога на пятницу.']),
    ).toEqual(new Set());
    // Обрыв посреди слова — это не «и»: «и» — только целым словом.
    expect(
      of(
        ['PATCH', 'Перенеси стоматолога на послез.'],
        ['PATCH', 'Перенеси стоматолога на послезавтра и на 7.'],
      ),
    ).toEqual(new Set([0]));
    // Обрыв «н…» перед «на пятницу»: хвост «а пятницу» — не союз «а», а конец слова.
    expect(of(['PATCH', 'Перенеси врача н.'], ['PATCH', 'Перенеси врача на пятницу.'])).toEqual(
      new Set([0]),
    );
  });

  it('короткое после полного — не обрывок: человек не начинал заново', () => {
    expect(
      of(['PATCH', 'Перенеси стоматолога на пятницу в 7.'], ['PATCH', 'Перенеси стоматолога.']),
    ).toEqual(new Set());
  });

  it('обрывком бывает только правка; мысль и вопрос не трогаются', () => {
    expect(of(['DUMP', 'Купить хлеб.'], ['DUMP', 'Купить хлеб и молоко.'])).toEqual(new Set());
    expect(of(['QUERY', 'Что там с'], ['QUERY', 'Что там с посылкой?'])).toEqual(new Set());
    // Полная фраза может прийти и другим намерением — обрывок правки всё равно обрывок.
    expect(
      of(
        ['PATCH', 'Перенеси стоматолога на после.'],
        ['DUMP', 'Перенеси стоматолога на послезавтра.'],
      ),
    ).toEqual(new Set([0]));
  });

  it('пустое и знаки без букв — не обрывки', () => {
    expect(of(['PATCH', '…'], ['PATCH', 'Перенеси хлеб на пятницу.'])).toEqual(new Set());
  });
});
