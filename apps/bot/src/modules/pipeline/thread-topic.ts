import { normalizeTopicName } from '../topics/topics.repo.js';

/**
 * Тема ветки, в которую написал человек (§8.1 ТЗ).
 *
 * ТЗ говорит: «Если сообщение пришло внутри ветки, эта тема считается
 * контекстом по умолчанию». Задумано так: женщина, написавшая в ветку
 * «здоровье», не должна получать своё дело в «личном» только потому, что
 * не назвала сферу словами.
 *
 * **Задумано так, а работало иначе.** Тема ветки уезжала в классификацию
 * параметром `defaultTopic`, и код подставлял её единственным местом —
 * когда модель вернула тему, которой у человека нет. Живая модель всегда
 * называет тему из выданного ей списка, поэтому подстановка не
 * срабатывала никогда. Ветка на разбор не влияла вовсе.
 *
 * Найдено ручной проверкой на боевом боте 29.08.2026: «позвонить Марине
 * насчёт вторника», отправленное в ветку «здоровье», легло в «личное».
 * Проверка на это была зелёной, потому что подсовывала модели-заглушке
 * несуществующую тему и мерила ту единственную ветку кода, которая в бою
 * не исполняется.
 *
 * **Решение здесь, а не в промпте.** Промпт классификации можно было
 * научить теме ветки, но это правка промпта: §10.3 требует прогона
 * контрольного набора, а на кону 43 единицы разбора ради одного правила,
 * которое прекрасно выражается кодом.
 *
 * Правило: тема по умолчанию — та, куда модель складывает всё, чему не
 * нашла места. Если человек писал из ветки, «всё остальное» принадлежит
 * ветке, а не общей свалке.
 */

export interface ThreadTopicContext {
  /** Тема ветки, откуда пришла выгрузка. Пусто — писали в общую ветку. */
  readonly threadTopic: string | undefined;
  /**
   * Тема человека по умолчанию: та, что помечена `is_default`.
   *
   * Именно её модель называет и когда действительно считает дело личным,
   * и когда не отнесла его никуда: в списке тем она выглядит как «всё
   * остальное». Различить эти два случая по ответу модели нельзя — и не
   * нужно, потому что ответ в обоих один и тот же.
   */
  readonly catchAllTopic: string;
}

/**
 * Переносит в тему ветки то, что модель отправила в тему по умолчанию.
 *
 * Явно отнесённое не трогается: «купить корм коту» остаётся в покупках,
 * даже если сказано из ветки «здоровье». Ветка — контекст по умолчанию,
 * а не приказ.
 */
export function applyThreadTopic<T extends { readonly topic: string }>(
  items: readonly T[],
  context: ThreadTopicContext,
): T[] {
  const { threadTopic, catchAllTopic } = context;

  // Писали в общую ветку — умолчание и так общее, менять нечего.
  if (threadTopic === undefined) return [...items];

  const target = normalizeTopicName(threadTopic);
  const catchAll = normalizeTopicName(catchAllTopic);

  // Ветка и есть тема по умолчанию: подстановка была бы холостой.
  if (target === catchAll) return [...items];

  return items.map((item) =>
    normalizeTopicName(item.topic) === catchAll ? { ...item, topic: threadTopic } : item,
  );
}
