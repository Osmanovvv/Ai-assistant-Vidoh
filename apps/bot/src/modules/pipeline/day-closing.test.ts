import { describe, expect, it } from 'vitest';

import { looksLikeDayClosing } from './day-closing.js';

/**
 * Закрытие дня словами (ТЗ по визуалам, проджект 18.09.2026, карточка 06):
 * «на сегодня всё», «хватит» — точка завершения, без кнопок. Список
 * закрытый и сверяется со всей репликой целиком: фраза с делом внутри —
 * выгрузка, а не закрытие.
 */
describe('закрытие дня узнаётся', () => {
  it.each([
    'На сегодня всё.',
    'на сегодня всё 🤍',
    'Всё, хватит.',
    'Хватит на сегодня!',
    'Ладно, на сегодня хватит',
    'Ну всё, на сегодня достаточно',
    'На этом всё',
    'Закончим на сегодня',
  ])('«%s»', (text) => {
    expect(looksLikeDayClosing(text)).toBe(true);
  });
});

describe('что закрытием не считается', () => {
  it.each([
    // Дело внутри — выгрузка.
    'На сегодня всё: купить хлеб',
    'Хватит откладывать, надо позвонить маме',
    // Вопрос про сегодня — вопрос.
    'На сегодня что-нибудь есть?',
    // Одно «всё» — слишком мало, чтобы закрывать день.
    'всё',
    '',
    'Спасибо, ты очень помогаешь',
  ])('«%s»', (text) => {
    expect(looksLikeDayClosing(text)).toBe(false);
  });
});
