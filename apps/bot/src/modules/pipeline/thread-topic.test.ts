import { describe, expect, it } from 'vitest';

import { applyThreadTopic } from './thread-topic.js';

/**
 * Ветка как контекст по умолчанию (§8.1 ТЗ).
 *
 * **Прежняя проверка на это была зелёной и ничего не проверяла.** Она
 * подсовывала модели-заглушке тему «выдуманная» — несуществующую, — и
 * мерила ту единственную ветку кода, которая в бою не исполняется:
 * живая модель всегда называет тему из выданного списка. Ручная проверка
 * 29.08.2026 показала настоящее поведение: «позвонить Марине насчёт
 * вторника» из ветки «здоровье» легло в «личное».
 *
 * Поэтому здесь модель всегда отвечает как настоящая — реальным
 * названием темы человека.
 */

const CONTEXT = { threadTopic: 'здоровье', catchAllTopic: 'личное' } as const;

function item(
  topic: string,
  text = 'позвонить Марине насчёт вторника',
): { text: string; topic: string } {
  return { text, topic };
}

describe('тема ветки как умолчание', () => {
  it('дело без явной сферы уходит в тему ветки, а не в общую', () => {
    // Тот самый случай с боевого бота.
    const [moved] = applyThreadTopic([item('личное')], CONTEXT);

    expect(moved?.topic).toBe('здоровье');
  });

  it('явно отнесённое остаётся где было', () => {
    // Ветка — контекст, а не приказ: покупки остаются покупками, даже
    // если сказаны из ветки «здоровье».
    const [kept] = applyThreadTopic([item('покупки', 'купить корм коту')], CONTEXT);

    expect(kept?.topic).toBe('покупки');
  });

  it('в общей ветке ничего не двигается', () => {
    const [kept] = applyThreadTopic([item('личное')], {
      threadTopic: undefined,
      catchAllTopic: 'личное',
    });

    expect(kept?.topic).toBe('личное');
  });

  it('ветка совпала с темой по умолчанию — подстановка холостая', () => {
    const [kept] = applyThreadTopic([item('личное')], {
      threadTopic: 'Личное',
      catchAllTopic: 'личное',
    });

    expect(kept?.topic).toBe('личное');
  });

  it('регистр и «ё» сравнению не мешают', () => {
    // Название приходит от модели в том виде, в каком она его написала.
    const [moved] = applyThreadTopic([item('Личное')], {
      threadTopic: 'здоровьё',
      catchAllTopic: 'личное',
    });

    expect(moved?.topic).toBe('здоровьё');
  });

  it('в выгрузке несколько дел — двигаются только безадресные', () => {
    const moved = applyThreadTopic(
      [
        item('личное', 'позвонить Марине'),
        item('деньги', 'сверить кассу'),
        item('личное', 'купить хлеб'),
      ],
      CONTEXT,
    );

    expect(moved.map((one) => one.topic)).toEqual(['здоровье', 'деньги', 'здоровье']);
  });

  it('исходный список не портится', () => {
    // Функция чистая: разбор дальше по конвейеру опирается на тот же
    // массив, и правка на месте увела бы правки туда, где их не ждут.
    const source = [item('личное')];
    applyThreadTopic(source, CONTEXT);

    expect(source[0]?.topic).toBe('личное');
  });
});
