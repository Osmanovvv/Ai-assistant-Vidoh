import { describe, expect, it } from 'vitest';

import { looksLikeHelpRequest, looksLikeUndoRequest } from './bot-words.js';

/**
 * Слова к самому боту, а не о делах (21.09.2026, список Никиты, п. 11 и
 * 13): «помощь», «что ты умеешь», «отмени последнее», «верни как было».
 * Как и закрытие дня — закрытые списки, вся реплика целиком, до
 * обращения к модели.
 */
describe('просьба о помощи', () => {
  it.each([
    'помощь',
    'Помоги',
    'что ты умеешь?',
    'Что ты умеешь',
    'как тобой пользоваться',
    'как пользоваться',
    'как это работает',
    'инструкция',
    'что ты можешь',
    'кто ты',
    'ну, что ты умеешь?',
  ])('«%s» — помощь', (text) => {
    expect(looksLikeHelpRequest(text)).toBe(true);
  });

  it.each(['помоги мне с отчётом', 'что ты умеешь по деньгам', 'надо купить хлеб', ''])(
    '«%s» — не помощь',
    (text) => {
      expect(looksLikeHelpRequest(text)).toBe(false);
    },
  );
});

describe('просьба отменить последнее', () => {
  it.each([
    'отмени последнее',
    'Отмени последнее изменение',
    'отмени последнюю правку',
    'отмени изменение',
    'верни как было',
    'верни назад',
    'верни обратно',
    'отмени',
    'отмена',
    'ладно, верни как было',
  ])('«%s» — отмена последнего', (text) => {
    expect(looksLikeUndoRequest(text)).toBe(true);
  });

  it.each(['отмени встречу с врачом', 'верни книгу Лене', 'отмени последнее дело про кота', ''])(
    '«%s» — не отмена последнего, там предмет',
    (text) => {
      expect(looksLikeUndoRequest(text)).toBe(false);
    },
  );
});
