import { sentencesOf, sharesSignificantWord } from '../classifier/own-sentence.js';
import type { Segment } from '../router/router.service.js';

/**
 * Правка, вплетённая обратно в мысль, которую она правит (задача 3.57).
 *
 * **Что было не так.** Человек сказал одним дыханием: «Ещё в четверг хотел
 * заехать я на мойку. Хотя нет, давай мойку лучше в пятницу, вот в пятницу
 * тогда надо помыть машину, ещё позвонить стоматологу, записаться на
 * следующую неделю». Маршрутизатор отнёс второе предложение к намерению
 * `PATCH` — и правильно, это правка. Но в нём, кроме правки, названы **два
 * дела**, и до извлечения этот отрезок не доходит вовсе: разбор получает
 * только отрезки с намерением `DUMP`.
 *
 * Итог в бою 04.09.2026: дело «помыть машину» не появилось, а «позвонить
 * стоматологу, записаться на следующую неделю» собралось из соседнего
 * предложения-пояснения и вышло как «Записаться к стоматологу».
 *
 * **Почему не иначе.** Замерены четыре пути, и три оказались хуже:
 *
 * 1. Отдать разбору всю речь целиком. На нашем случае верно, но на речи
 *    «Купить продукты сегодня. Погулять с собакой. Вынести мусор. Позвонить
 *    бабушке. Хотя нет, за продуктами лучше завтра» разбор **теряет
 *    покупку продуктов совсем**. Потеря дела хуже неточного слова.
 * 2. Разбирать отрезок правки отдельно. Тогда «Нет, лучше в 10 30»
 *    становится делом «В 10:30» — ровно та «задача без задачи», которую
 *    §7.3 запрещает, — а «хлеб не надо, есть дома» превращается в дело.
 * 3. Отдельный вызов «что меняется, что нового». Двоит дело: «помыть
 *    машину» приходит и правкой, и новым делом, а стоматолог дробится на
 *    два обрывка. Слить двойника нечем: отсев повторов сверяет текст
 *    дословно, и это осознанное решение (`same-text.ts`).
 *
 * **Что делаем.** Возвращаем правку туда, где человек её и сказал: сразу за
 * своей мыслью. Разбор получает речь в её собственном порядке и дальше
 * справляется сам — проверено, из целой речи он даёт «Помыть машину в
 * пятницу» и «Позвонить стоматологу, записаться на следующую неделю», а
 * отменённого «заехать на мойку в четверг» не заводит вовсе.
 *
 * **Три условия, и все проверяются, а не предполагаются:**
 *
 * 1. **Общее значимое слово** с последним предложением правимой мысли.
 *    Без него правка относится к чему-то другому: «Позвонить бабушке. Хотя
 *    нет, за продуктами лучше завтра» не цепляется, и покупка продуктов
 *    остаётся целой в своём отрезке.
 * 2. **Это не отмена дела.** «Хотя нет, хлеб не надо, есть дома» разбор
 *    превратит в дело «хлеб не надо покупать». Отмену умеет путь правок,
 *    и он её и разбирает.
 * 3. **Правка называет дело, а не ссылается на запись** (задача 3.64,
 *    регрессия, найденная живым прогоном проджекта). «То дело с собакой,
 *    которое стоит на завтра, перенеси на понедельник» делит слово с
 *    мыслью и отменой не является — и всё же вплетать его нельзя: разбор
 *    заведёт из распоряжения дело. Признак — слова о записи, см.
 *    `ABOUT_RECORD`.
 *
 * **Путь правок при этом не отключается.** Вплетённая правка идёт к
 * резолверу как прежде: если разбор её учёл, резолверу менять нечего и он
 * молча паркует отрезок; если не учёл — резолвер поправит запись, как
 * делал до этой задачи. Страховка стоит одной невидимой строки в базе, а
 * снимает единственную настоящую опасность — что правка пропадёт совсем.
 */

/**
 * Слова отмены дела. Закрытый список, и это данные, а не поведение.
 *
 * Проверяется по всему отрезку: «хлеб не надо, есть дома» — отмена, где бы
 * «не надо» ни стояло.
 */
const CANCELS = ['не надо', 'не нужно', 'не буду', 'отмени', 'отменя', 'не пойду', 'не поеду'];

/**
 * Слова о **записи**, а не о деле (задача 3.64).
 *
 * **Найдено живым прогоном проджекта 04.09.2026, и это была регрессия от
 * самой задачи 3.57.** Он сказал: «Завтра надо купить собаке новый
 * ошейник. В воскресенье отвезти собаку к грумеру… А теперь вот то дело с
 * собакой, которое у меня стоит на завтра, перенеси на понедельник.
 * Поводок при этом оставь на завтра, его не переноси».
 *
 * Правка делит слово «собак» с мыслью и отменой не является — то есть
 * проходила по двум прежним условиям. Вплелась, и разбор завёл из неё две
 * записи: «Перенести на понедельник дело с собакой, которое стоит на
 * завтра» и «Поводок оставить на завтра, его не переносить». Человек
 * увидел свои распоряжения в списке дел.
 *
 * **Чем этот случай отличается от того, ради которого 3.57 и делалась.**
 * Там правка **заново называла дело**: «вот в пятницу тогда надо помыть
 * машину, ещё позвонить стоматологу, записаться». Здесь она **ссылается
 * на уже существующую запись**: «то дело, которое стоит на завтра»,
 * «перенеси», «его не переноси». Первое разбору нужно, второе — работа
 * пути правок, и вплетать его нельзя.
 *
 * Список закрытый, и это данные, а не поведение: «дело», «перенеси»,
 * «оставь как было» — слова о том, что уже записано.
 */
const RECORD_NOUNS = ['дело', 'дела', 'делу', 'запись', 'записи'];

/**
 * **Распоряжения** о записи — приказ сделать что-то с уже записанным.
 *
 * Отдельно от существительных, и это не придирка. «Надо доделать дело с
 * налогами» — настоящая мысль, в ней слово «дело» есть, а распоряжения
 * нет. Поэтому там, где цена ошибки — потерянная мысль (`dump.handler.ts`,
 * задача 3.67), проверяются только эти слова.
 */
export const RECORD_COMMANDS = [
  'перенеси',
  'перенести',
  'перенёс',
  'перенес',
  'переноси',
  'сдвинь',
  'сдвинуть',
  'оставь как',
  'оставить как',
  'оставь всё как',
  'не меняй',
  'ничего не меняй',
  'убери из планов',
  'закрой дело',
];

const ABOUT_RECORD = [...RECORD_NOUNS, ...RECORD_COMMANDS];

function normalize(text: string): string {
  return text.toLowerCase().replace(/ё/gu, 'е');
}

function cancels(text: string): boolean {
  const words = normalize(text);
  return CANCELS.some((mark) => words.includes(mark));
}

/** Правка говорит о записи, а не называет дело: вплетать нельзя. */
function aboutRecord(text: string): boolean {
  const words = normalize(text);
  return ABOUT_RECORD.some((mark) => words.includes(mark));
}

/**
 * Это распоряжение о записи, а не мысль (задача 3.67).
 *
 * **Найдено живым прогоном проджекта 04.09.2026.** Он прислал отдельным
 * сообщением «Перенеси дело с собакой на вторник». Резолвер цели не нашёл
 * — у человека три дела про собаку — и вернул «это новая мысль». А новая
 * мысль уходит в разбор, и его распоряжение стало **делом** «Перенеси
 * дело с собакой на вторник» со сроком на вторник.
 *
 * Проверяются **только приказы**, без существительного «дело»: «надо
 * доделать дело с налогами» — настоящая мысль, и терять её нельзя.
 */
export function isRecordCommand(text: string): boolean {
  const words = normalize(text);
  return RECORD_COMMANDS.some((mark) => words.includes(mark));
}

/** Последнее предложение мысли: именно к нему правка и относится. */
function lastSentenceOf(text: string): string {
  const sentences = sentencesOf(text);
  return sentences[sentences.length - 1] ?? '';
}

/**
 * Какие правки вплетаются и в какую мысль.
 *
 * Ключ — текст отрезка мысли, значение — текст правки, которую надо
 * приписать ему в конец. Разбирается по исходному порядку отрезков: он и
 * есть признак «правка сказана после этой мысли».
 *
 * Правка до первой мысли выгрузки сюда не попадает вовсе: она про то, что
 * человек говорил раньше, и её место — путь правок (задача 3.24).
 */
export function patchesToWeave(segments: readonly Segment[]): ReadonlyMap<string, string> {
  const weave = new Map<string, string>();
  let thought: Segment | undefined;

  for (const segment of segments) {
    if (segment.intent === 'DUMP') {
      thought = segment;
      continue;
    }

    if (segment.intent !== 'PATCH' || thought === undefined) continue;
    if (cancels(segment.text)) continue;
    // Правка про уже записанное — работа пути правок (задача 3.64).
    if (aboutRecord(segment.text)) continue;
    if (!sharesSignificantWord(lastSentenceOf(thought.text), segment.text)) continue;

    // Две правки к одной мысли приписываются подряд, в порядке речи.
    const already = weave.get(thought.text);
    weave.set(thought.text, already === undefined ? segment.text : `${already} ${segment.text}`);
  }

  return weave;
}

/**
 * Текст для извлечения: мысли, а в них — вплетённые правки.
 *
 * Отдельно от `dumpText`, который идёт в промпт классификации и в
 * презентацию. Менять его значило бы менять и то, что видит модель под
 * словами «человек сказал так», и это уже другая задача с другим замером.
 */
export function weaveForExtraction(
  parsed: readonly Segment[],
  segments: readonly Segment[],
): string {
  const weave = patchesToWeave(segments);
  if (weave.size === 0) return parsed.map((segment) => segment.text).join('\n');

  return parsed
    .map((segment) => {
      const patch = weave.get(segment.text);
      return patch === undefined ? segment.text : `${segment.text} ${patch}`;
    })
    .join('\n');
}
