/**
 * Закрытие дня словами (ТЗ по визуалам, проджект 18.09.2026, карточка 06).
 *
 * «На сегодня всё», «хватит» — точка завершения: карточка «На сегодня всё
 * 🤍» без кнопок, ни разбора, ни вопросов. Не слать каждый вечер
 * автоматически — только на её слова.
 *
 * Список закрытый и сверяется со **всей репликой целиком**, после снятия
 * знаков и вводных («ну», «ладно», «так»): фраза с делом внутри —
 * выгрузка, а не закрытие, и решать за человека, что «на сегодня всё:
 * купить хлеб» — это конец дня, нельзя. Считается до обращения к модели:
 * ничего не стоит.
 */

const OPENERS = new Set(['ну', 'ладно', 'так', 'ок', 'окей', 'все', 'всё', 'и']);

const CLOSINGS = new Set([
  'на сегодня все',
  'все на сегодня',
  'на сегодня хватит',
  'хватит на сегодня',
  'хватит',
  'на сегодня достаточно',
  'достаточно на сегодня',
  'на этом все',
  'на этом все на сегодня',
  'закончим на сегодня',
  'на сегодня закончим',
  'на сегодня закончили',
  'заканчиваем на сегодня',
  'на сегодня заканчиваем',
]);

function words(text: string): string[] {
  return text
    .toLowerCase()
    .replace(/ё/gu, 'е')
    .replace(/[^\p{L}\s]+/gu, ' ')
    .trim()
    .split(/\s+/u)
    .filter((word) => word.length > 0);
}

export function looksLikeDayClosing(text: string): boolean {
  const list = words(text);
  while (list.length > 1 && OPENERS.has(list[0] ?? '')) list.shift();

  return CLOSINGS.has(list.join(' '));
}
