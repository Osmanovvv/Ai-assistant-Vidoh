/**
 * Слова к самому боту, а не о делах (21.09.2026, список Никиты).
 *
 * «Помощь», «что ты умеешь», «отмени последнее», «верни как было» —
 * человек говорит с ботом о боте. Модель такое относила то к разговору
 * ни о чём (и бот молчал), то к вопросу (и отвечала «не поняла»), то к
 * отмене дела «последнее» (и говорила «такого дела не было»).
 *
 * Как у закрытия дня (`day-closing.ts`): закрытый список, сверяется вся
 * реплика целиком после снятия знаков и вводных. Фраза с делом внутри —
 * «помоги мне с отчётом», «отмени встречу» — сюда не попадает. Считается
 * до обращения к модели: ничего не стоит.
 */

const OPENERS = new Set(['ну', 'ладно', 'так', 'ок', 'окей', 'а', 'и', 'слушай', 'пожалуйста']);

const HELP = new Set([
  'помощь',
  'помоги',
  'справка',
  'инструкция',
  'что ты умеешь',
  'что умеешь',
  'что ты можешь',
  'что можешь',
  'как тобой пользоваться',
  'как пользоваться',
  'как это работает',
  'как ты работаешь',
  'как с тобой работать',
  'кто ты',
  'расскажи о себе',
]);

const UNDO = new Set([
  'отмени',
  'отмена',
  'отменить',
  'отмени последнее',
  'отмени последнее изменение',
  'отмени последнюю правку',
  'отмени последнее действие',
  'отмени изменение',
  'отмени правку',
  'отмени это',
  'верни как было',
  'верни все как было',
  'верни назад',
  'верни обратно',
  'верни',
  'откати',
  'откати последнее',
]);

function utterance(text: string): string {
  const list = text
    .toLowerCase()
    .replace(/ё/gu, 'е')
    .replace(/[^\p{L}\s]+/gu, ' ')
    .trim()
    .split(/\s+/u)
    .filter((word) => word.length > 0);

  while (list.length > 1 && OPENERS.has(list[0] ?? '')) list.shift();

  return list.join(' ');
}

/** Вся реплика — просьба о помощи. */
export function looksLikeHelpRequest(text: string): boolean {
  return HELP.has(utterance(text));
}

/** Вся реплика — просьба отменить последнее изменение. */
export function looksLikeUndoRequest(text: string): boolean {
  return UNDO.has(utterance(text));
}
