import { describe, expect, it } from 'vitest';

import type { Segment } from '../router/router.service.js';
import { patchesToWeave, weaveForExtraction } from './patch-in-place.js';

/**
 * Правка, вплетённая обратно в мысль (задача 3.57).
 *
 * Найдено живым прогоном 04.09.2026. Человек сказал одним дыханием: «Ещё в
 * четверг хотел заехать я на мойку. Хотя нет, давай мойку лучше в пятницу,
 * вот в пятницу тогда надо помыть машину, ещё позвонить стоматологу,
 * записаться на следующую неделю». Второе предложение маршрутизатор отнёс
 * к правкам — верно, это правка, — и до извлечения оно не дошло вовсе.
 * Вместе с ним не дошли два названных человеком дела.
 *
 * Здесь проверяется, что вплетение срабатывает **только** там, где связь
 * доказана, и молчит там, где прежний путь правок работает лучше.
 */

function dump(text: string): Segment {
  return { intent: 'DUMP', text };
}

function patch(text: string): Segment {
  return { intent: 'PATCH', text };
}

const THOUGHT = 'В четверг мне надо съездить к родителям. Ещё в четверг хотел заехать я на мойку.';
const CORRECTION =
  'Хотя нет, давай мойку лучше в пятницу, вот в пятницу тогда надо помыть машину, ещё позвонить стоматологу, записаться на следующую неделю.';

describe('правка вплетается в свою мысль', () => {
  it('боевой случай: правка приписана к мысли про мойку', () => {
    const weave = patchesToWeave([dump(THOUGHT), patch(CORRECTION)]);

    expect(weave.get(THOUGHT)).toBe(CORRECTION);
  });

  it('текст для разбора содержит речь в её порядке', () => {
    const input = weaveForExtraction([dump(THOUGHT)], [dump(THOUGHT), patch(CORRECTION)]);

    expect(input).toBe(`${THOUGHT} ${CORRECTION}`);
    // Порядок речи и есть смысл починки: «хотя нет» должно стоять сразу
    // за тем, что оно отменяет.
    expect(input.indexOf('заехать я на мойку')).toBeLessThan(input.indexOf('Хотя нет'));
  });

  it('две правки к одной мысли идут подряд', () => {
    const first = 'Хотя нет, мойку лучше в пятницу.';
    const second = 'Хотя нет, мойку лучше в субботу.';
    const weave = patchesToWeave([dump(THOUGHT), patch(first), patch(second)]);

    expect(weave.get(THOUGHT)).toBe(`${first} ${second}`);
  });
});

describe('вплетение молчит там, где прежний путь лучше', () => {
  it('без общего значимого слова правка не цепляется', () => {
    /**
     * «Купить продукты сегодня… Позвонить бабушке. Хотя нет, за продуктами
     * лучше завтра» — правка относится к продуктам, а не к бабушке. Если
     * вплести её к бабушке, разбор целой фразы **теряет покупку продуктов
     * совсем**: это замерено. Правку разбирает резолвер, как и раньше.
     */
    const thought = 'Вынести мусор. Позвонить бабушке.';
    const weave = patchesToWeave([
      dump('Купить продукты сегодня.'),
      dump(thought),
      patch('Хотя нет, за продуктами лучше завтра.'),
    ]);

    expect(weave.size).toBe(0);
  });

  it('отмена дела не вплетается', () => {
    // «Хотя нет, хлеб не надо, есть дома» разбор превратит в дело «хлеб не
    // надо покупать». Отмену умеет путь правок.
    const thought = 'Купить хлеб в пятницу.';
    const weave = patchesToWeave([dump(thought), patch('Хотя нет, хлеб не надо, есть дома.')]);

    expect(weave.size).toBe(0);
  });

  it('правка одного дня, без предмета, не цепляется', () => {
    // «Нет, лучше в 10 30» отдельно даёт дело «В 10:30» — задача без
    // задачи, которую §7.3 запрещает. Общего значимого слова здесь нет.
    const thought = 'Договориться с няней, чтобы приходила в 10.';
    const weave = patchesToWeave([dump(thought), patch('Нет, лучше в 10 30.')]);

    expect(weave.size).toBe(0);
  });

  it('правка предмета без общего слова не цепляется', () => {
    const weave = patchesToWeave([dump('Купить хлеб.'), patch('Хотя нет, лучше батон.')]);

    expect(weave.size).toBe(0);
  });

  it('правка до первой мысли выгрузки не вплетается', () => {
    /**
     * Такая правка про то, что человек говорил РАНЬШЕ, в прошлой выгрузке
     * (задача 3.24). Вплетать её в мысль, сказанную после, значило бы
     * испортить свежую запись вместо старой.
     */
    const weave = patchesToWeave([
      patch('Хотя нет, мойку лучше в пятницу.'),
      dump('Ещё надо заехать на мойку.'),
    ]);

    expect(weave.size).toBe(0);
  });

  it('без правок текст для разбора не меняется', () => {
    const one = dump('Купить хлеб.');
    const two = dump('Вынести мусор.');

    expect(weaveForExtraction([one, two], [one, two])).toBe('Купить хлеб.\nВынести мусор.');
  });

  it('ответ на вопрос бота не вплетается никогда', () => {
    // §7.3: ANSWER существует ровно для того, чтобы ответ не уходил в
    // разбор. Вплетение обязано его не касаться.
    const thought = 'Ещё надо заехать на мойку.';
    const weave = patchesToWeave([
      dump(thought),
      { intent: 'ANSWER', text: 'Да, мойку в пятницу.' },
    ]);

    expect(weave.size).toBe(0);
  });

  it('отмена и закрытие дела вплетению не подлежат', () => {
    const thought = 'Купить хлеб в пятницу.';

    for (const intent of ['CANCEL', 'COMPLETE', 'QUERY', 'SMALLTALK'] as const) {
      const weave = patchesToWeave([dump(thought), { intent, text: 'Хлеб уже купил в пятницу.' }]);
      expect(weave.size, intent).toBe(0);
    }
  });
});
