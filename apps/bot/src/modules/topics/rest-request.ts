/**
 * Просьба показать остальное — «Какие ещё 5» под сводкой ветки (живая
 * проверка Никиты 24.09.2026).
 *
 * Сводка ветки показывает пятнадцать дел и строку «И ещё N.». Спросить
 * «какие ещё» — самое естественное, что после неё можно сделать, а бот
 * отвечал «Я здесь. Расскажешь, что в голове?»: вопрос уходил модели
 * ответов, а она о сводке не знает. Узнаётся кодом, закрытым списком, и
 * только **целой короткой фразой**: «что ещё купить к празднику» или
 * «ещё купить молоко» — мысли, а не просьба о списке. «Покажи все дела» —
 * своя команда бота, её не перехватываем.
 */

const PATTERNS: readonly RegExp[] = [
  // «какие ещё 5», «а какие ещё», «что там ещё», «какие ещё 5 какие»
  /^(?:а )?(?:какие|что)(?: там)? еще(?: \d+)?(?: какие)?$/u,
  // «ещё какие», «а ещё 5 какие»
  /^(?:а )?еще(?: \d+)? какие$/u,
  // «а остальные», «остальные какие», «какие остальные»
  /^(?:а )?(?:какие )?остальные(?: какие)?$/u,
  // «покажи остальные», «покажи ещё», «покажи весь список», «покажи полностью»
  /^(?:а )?(?:покажи|показать|напиши|давай) (?:остальные|остальное|еще|весь список|список полностью|полностью)$/u,
];

function normalized(text: string): string {
  return text
    .toLowerCase()
    .replace(/ё/gu, 'е')
    .replace(/[?!.,…:;—-]+/gu, ' ')
    .replace(/\s+/gu, ' ')
    .trim();
}

export function asksForRest(text: string): boolean {
  const said = normalized(text);
  return said !== '' && PATTERNS.some((pattern) => pattern.test(said));
}
