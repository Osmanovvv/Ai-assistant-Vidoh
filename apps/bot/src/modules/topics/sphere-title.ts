import { withCapital } from '../items/item-text.js';

/**
 * Сфера для человека — с заглавной: «Личное», «Дом», «Покупки» (правка
 * заказчицы 30.09.2026: «Мне нравится, что это с большой буквы… Давайте
 * везде так поменяем»).
 *
 * Только показ. В базе имя темы остаётся как было: по нему сверяются
 * записи, ветки и ответы модели, и регистр там не нужен никому. Одной
 * функцией на все места — вкладка ветки, сводка, кнопки, реплики, —
 * чтобы следующий показ не остался строчным.
 */
export function sphereTitle(name: string): string {
  return withCapital(name);
}
