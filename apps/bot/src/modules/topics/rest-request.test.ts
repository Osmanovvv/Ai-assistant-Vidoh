import { describe, expect, it } from 'vitest';

import { asksForRest } from './rest-request.js';

/**
 * «Какие ещё 5» под сводкой ветки (живая проверка Никиты 24.09.2026).
 *
 * Сводка показывает пятнадцать дел и строку «И ещё 5.». Человек спросил
 * в ветке «Какие еще 5» — бот ответил «Я здесь. Расскажешь, что в
 * голове?»: вопрос ушёл модели ответов, а она о сводке не знает. Просьба
 * показать остальное узнаётся кодом, закрытым списком.
 */

describe('просьба показать остальное', () => {
  it.each([
    'Какие еще 5',
    'какие ещё 7?',
    'Какие ещё',
    'А какие ещё?',
    'что ещё',
    'Что там ещё?',
    'А остальные?',
    'остальные какие',
    'Какие остальные',
    'Покажи остальные',
    'покажи остальное',
    'Покажи ещё',
    'Ещё какие?',
    'а ещё 5 какие',
    'покажи весь список',
    'покажи полностью',
  ])('«%s» — да', (text) => {
    expect(asksForRest(text)).toBe(true);
  });

  it.each([
    // Новые мысли и правки со словом «ещё» — не просьба о списке.
    'ещё купить молоко',
    'И еще покрасить трубы',
    'что ещё купить к празднику — подумать',
    'надо ещё позвонить маме',
    // Своя команда у бота уже есть: её не перехватываем.
    'Покажи все дела',
    'Покажи все мои задачи',
    // Длинное — это мысль, даже если начинается похоже.
    'какие ещё дела нужно сделать до пятницы по работе и дома',
    '',
  ])('«%s» — нет', (text) => {
    expect(asksForRest(text)).toBe(false);
  });
});
