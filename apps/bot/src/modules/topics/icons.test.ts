import { describe, expect, it } from 'vitest';

import { TOPIC_ICONS } from './topics.service.js';

/**
 * Иконки веток — только из набора Telegram (правка заказчицы 30.09.2026).
 *
 * Произвольный эмодзи ветка не принимает: `getForumTopicIconStickers`
 * отдаёт 112 штук. Семья стояла 👨‍👩‍👧, личное 🤍 — обоих в наборе нет, и
 * эти ветки молча жили с кружком-буквой, пока заказчица не спросила.
 * Набор снят с боевого бота 30.09.2026; сменит Telegram набор — ветка
 * создастся без иконки, как раньше, а этот список надо будет снять заново.
 * Три составных знака набора (семья из четырёх, пиратский флаг,
 * полицейский) сюда не вписаны: сферам они не нужны, а невидимые
 * соединители в них легко потерять при переписывании.
 */
const TELEGRAM_ICONS_30_09_2026 =
  '📰 💡 ⚡ 🎙 🔝 🗣 🆒 ❗ 📝 📆 📁 🔎 📣 🔥 ❤ ❓ 📈 📉 💎 💰 💸 🪙 💱 ⁉ 🎮 💻 📱 🚗 🏠 💘 🎉 ‼ 🏆 🏁 🎬 🎵 🔞 📚 👑 ⚽ 🏀 📺 👀 🫦 🍓 💄 👠 ✈ 🧳 🏖 ⛅ 🦄 🛍 👜 🛒 🚂 🛥 🏔 🏕 🤖 🪩 🎟 🗳 🎓 🔭 🔬 🎶 🎤 🕺 💃 🪖 💼 🧪 👶 🤰 💅 🏛 🧮 🖨 🩺 💊 💉 🧼 🪪 🛃 🍽 🐟 🎨 🎭 🎩 🔮 🍹 🎂 ☕ 🍣 🍔 🍕 🦠 💬 🎄 🎃 ✍ ⭐ ✅ 🎖 🤡 🧠 🦮 🐈';

/** Знак начертания (U+FE0F) невидим и у Telegram то есть, то нет. */
const plain = (emoji: string): string => emoji.replace(/️/gu, '');

const ALLOWED = new Set(TELEGRAM_ICONS_30_09_2026.split(' ').map(plain));

describe('иконки веток — из набора Telegram', () => {
  it('семья — ❤️, личное — ⭐️ (выбор заказчицы 30.09.2026)', () => {
    expect(TOPIC_ICONS['семья']).toBe('❤️');
    expect(TOPIC_ICONS['личное']).toBe('⭐️');
  });

  it.each(
    // «Дети» — 🧸 в наборе нет; замена не выбрана, ветка пока без иконки.
    Object.entries(TOPIC_ICONS).filter(([name]) => name !== 'дети'),
  )('«%s» (%s) есть в наборе — ветка получит иконку', (_name, emoji) => {
    expect(ALLOWED.has(plain(emoji))).toBe(true);
  });
});
