import { describe, expect, it } from 'vitest';

import { sameTopicName } from './topic-key.js';

/**
 * Одна сфера под разными формами имени (бой 26.09.2026, 02:03): модель
 * назвала сферу машины «покупка», у человека своя «покупки» — код
 * сравнивал имена точно и завёл вторую сферу с веткой в чате.
 */
describe('формы одного имени — одна сфера', () => {
  it('формы одного слова совпадают', () => {
    for (const [one, other] of [
      ['покупка', 'покупки'],
      ['Покупки', 'покупка'],
      ['здоровье', 'здоровья'],
      ['семья', 'семьи'],
      ['работа', 'работы'],
      ['финансы', 'финансов'],
      ['дети', 'детей'],
      ['дом', 'дома'],
      ['личное', 'личная'],
      ['учёба', 'учеба'],
      // Существительное на «-ие»: окончание «-ие» у прилагательных его не путает.
      ['саморазвитие', 'саморазвития'],
      ['покупки', 'покупки'],
    ] as const) {
      expect(sameTopicName(one, other), `${one} ~ ${other}`).toBe(true);
    }
  });

  it('разные слова — разные сферы', () => {
    for (const [one, other] of [
      ['работа', 'рабочее'],
      ['дом', 'домашнее'],
      ['здоровье', 'здоровый'],
      ['личное', 'личность'],
      ['авто', 'автомобиль'],
      ['учёба', 'учёт'],
      ['покупки', 'покупатели'],
      ['семья', 'здоровье'],
    ] as const) {
      expect(sameTopicName(one, other), `${one} ≠ ${other}`).toBe(false);
    }
  });

  it('два слова — только точным совпадением: окончания там не угадываются', () => {
    expect(sameTopicName('здоровье и спорт', 'Здоровье  и спорт')).toBe(true);
    expect(sameTopicName('здоровье и спорт', 'здоровье и спорта')).toBe(false);
  });
});

describe('деньги под разными именами — одна сфера (прогон Никиты 27.09.2026)', () => {
  it('«финансы», «финансовое», «деньги» совпадают', () => {
    for (const [one, other] of [
      ['финансы', 'деньги'],
      ['финансовое', 'деньги'],
      ['Финансовые', 'финансы'],
      ['финансовая', 'финансовое'],
    ] as const) {
      expect(sameTopicName(one, other), `${one} ~ ${other}`).toBe(true);
    }
  });

  it('с другими сферами — нет', () => {
    for (const [one, other] of [
      ['деньги', 'покупки'],
      ['финансы', 'работа'],
    ] as const) {
      expect(sameTopicName(one, other), `${one} ≠ ${other}`).toBe(false);
    }
  });
});
