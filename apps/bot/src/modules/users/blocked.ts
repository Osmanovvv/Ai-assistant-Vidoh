import { GrammyError } from 'grammy';

/**
 * Распознавание блокировки бота пользователем (задача 1.19).
 *
 * В §17 ТЗ этого сценария нет, а это самый частый отказ у бота с
 * ежедневными напоминаниями. Признаков два, и нужны оба:
 *
 *   1. Апдейт my_chat_member со статусом kicked — приходит сразу, когда
 *      человек нажал «Заблокировать». Самый честный сигнал.
 *   2. Ошибка 403 при отправке — ловит случаи, когда апдейт мы пропустили:
 *      бот лежал, вебхук был отключён, пользователь удалил чат.
 *
 * Чистые функции без обращений к базе: решение «это блокировка или нет»
 * проверяется тестами без Postgres и без Telegram.
 */

/** Статусы участника, при которых бот больше не может писать. */
const BLOCKED_STATUSES = new Set(['kicked', 'left']);

export function isBlockingStatus(status: string): boolean {
  return BLOCKED_STATUSES.has(status);
}

/**
 * Тексты Telegram при блокировке. Код 403 бывает и по другим причинам —
 * например, бот выгнан из группы, — но для личного чата эти сообщения
 * означают именно блокировку или удаление аккаунта.
 */
const BLOCKED_DESCRIPTIONS = [
  'bot was blocked by the user',
  'user is deactivated',
  'chat not found',
  'bot was kicked',
];

/**
 * «Чат не найден» приходит с кодом 400, а не 403.
 *
 * Проверка ниже требовала 403, и эта ветка не срабатывала никогда:
 * человек, удаливший чат, давал ошибку уровня «сбой» вместо пометки
 * «недоступен». Найдено на выкладке этапа 2 — оповещение мониторинга
 * показало сто процентов ошибок, и все они были такими.
 *
 * Остальные 400 сюда не попадают намеренно: 400 — это обычно наша ошибка
 * в запросе, и она обязана остаться громкой.
 */
const GONE_AT_400 = 'chat not found';

export function isBlockedError(error: unknown): boolean {
  if (!(error instanceof GrammyError)) return false;

  const description = error.description.toLowerCase();

  if (error.error_code === 400) return description.includes(GONE_AT_400);
  if (error.error_code !== 403) return false;

  return BLOCKED_DESCRIPTIONS.some((known) => description.includes(known));
}

/**
 * `isRetryableSendError` убрана ревизией этапов 1–2.
 *
 * Она отвечала «стоит ли повторять отправку» и ждала напоминаний
 * третьего этапа: её комментарий обещал, что «вот там отправка будет
 * повторяться, и там же понадобится» знание о видах ошибок. Этап пришёл,
 * а повтор устроен без неё: отправитель на блокировке сам ставит
 * `is_blocked`, планировщик перед каждой отправкой смотрит на эту
 * пометку и снимает напоминание с причиной 'blocked' (§5 ТЗ, колонка
 * `attempts`); прочие сбои повторяются счётом, до `MAX_ATTEMPTS`, о виде
 * ошибки не спрашивая. Так условие 1.19 «после 403 повторных попыток
 * нет» выполнено, а функция осталась третьим местом с правдой про
 * доставку — с семью зелёными проверками и без единого вызывающего.
 *
 * Единственное знание, которое она хранила и которого нет у
 * `isBlockedError`, — «400 значит нашу ошибку в запросе, повтор её не
 * исправит». Оно живёт у `GONE_AT_400` выше, а решение «повторять ли
 * 400» планировщик сегодня не принимает нарочно: три попытки за три
 * минуты — конечная и дешёвая цена за то, чтобы не заводить второй
 * способ судить об ошибке отправки.
 */
