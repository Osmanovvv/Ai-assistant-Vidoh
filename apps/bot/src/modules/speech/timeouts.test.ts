import { describe, expect, it } from 'vitest';

import { DEFAULT_LIMITS } from '../buffer/buffer.service.js';
import { DEFAULT_MAX_POLL_MS } from './providers/yandex.js';
import { DEFAULT_TIMEOUT_MS } from './speech.service.js';

/**
 * Три потолка обязаны идти лесенкой (бой 17.09.2026).
 *
 * Провайдер ждёт операцию до своего потолка; снаружи стоит таймаут
 * расшифровки — он обязан быть длиннее, иначе в гонке побеждает он и
 * наверх уходит отказ без пометки об оплате, а повтор отправляет звук
 * заново. Ещё выше — досмотр очереди: выгрузку в обработке дольше
 * `maxProcessingMs` он считает забытой и возвращает в очередь. 17.09 в
 * 16:35 он так и сделал посреди живого распознавания (потолок был три
 * минуты при четырёх у провайдера); от двойного ответа спас только замок
 * на пользователя.
 */
describe('лесенка потолков расшифровки', () => {
  it('таймаут расшифровки длиннее ожидания операции хотя бы на минуту', () => {
    expect(DEFAULT_TIMEOUT_MS).toBeGreaterThanOrEqual(DEFAULT_MAX_POLL_MS + 60_000);
  });

  it('досмотр очереди терпит дольше, чем расшифровка с разбором', () => {
    // Разбор после расшифровки — три обращения к модели; под нагрузкой
    // 17.09 они заняли 34 секунды, запас — две минуты.
    expect(DEFAULT_LIMITS.maxProcessingMs).toBeGreaterThanOrEqual(DEFAULT_TIMEOUT_MS + 120_000);
  });
});
