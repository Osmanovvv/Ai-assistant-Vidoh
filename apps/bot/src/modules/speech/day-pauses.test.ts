import { describe, expect, it } from 'vitest';

import type { RecognizedUtterance } from './providers/types.js';
import { dayAfterPause, withDaysAfterPauses } from './day-pauses.js';

/**
 * День после паузы — следующему делу (прогон Никиты 27.09.2026).
 *
 * Паузы в случаях ниже — **с его двух голосовых**, распознанных заново:
 * «купить ‖650‖ в пятницу записать» и «купить ‖851‖ в понедельник
 * записать». Разметка `‖N‖` — пауза в миллисекундах перед словом; без
 * разметки слова идут подряд.
 */
function heard(text: string, marked: string): RecognizedUtterance {
  const words: { text: string; startMs: number; endMs: number }[] = [];
  let at = 0;
  let pause = 40;

  for (const token of marked.split(/\s+/u).filter((one) => one !== '')) {
    const gap = /^‖(\d+)‖$/u.exec(token);
    if (gap !== null) {
      pause = Number(gap[1]);
      continue;
    }
    const startMs = at + pause;
    words.push({ text: token, startMs, endMs: startMs + 300 });
    at = startMs + 300;
    pause = 40;
  }

  return { text, words };
}

describe('dayAfterPause — живые голосовые', () => {
  it('17:46: «купить ‖650‖ в пятницу записать» — пятница ортодонту', () => {
    const utterance = heard(
      'Так короче, пока не забыла завтра в 12 Машу отвезти на день рождения к подружке. Надо еще подарок ей купить в пятницу, записать Мишу к Ортодонту. А по оплатить кружок по рисованию до среды на работе отчет по продажам сдать до обеда в четверг?',
      'так короче ‖380‖ пока не забыла ‖589‖ завтра в двенадцать машу отвезти на день рождения к подружке ‖630‖ надо еще подарок ей купить ‖650‖ в пятницу записать мишу к ортодонту а по ‖1080‖ оплатить кружок по рисованию до среды ‖1309‖ на работе отчет по продажам сдать до обеда в четверг',
    );

    expect(dayAfterPause(utterance).text).toBe(
      'Так короче, пока не забыла завтра в 12 Машу отвезти на день рождения к подружке. Надо еще подарок ей купить. В пятницу записать Мишу к Ортодонту. А по оплатить кружок по рисованию до среды на работе отчет по продажам сдать до обеда в четверг?',
    );
  });

  it('15:13: «купить ‖851‖ в понедельник записать» — понедельник ортодонту', () => {
    const utterance = heard(
      'Так короче, пока не забыла сегодня в 6 вечера отвезти маме лекарства. Завтра в 12 Машу отвезти на день рождения к подружке. Надо еще подарок ей купить в понедельник, записать Мишу к Ортодонту.',
      'так короче пока не забыла ‖750‖ сегодня в шесть вечера отвезти маме лекарства ‖1150‖ завтра в двенадцать машу отвезти на день рождения к подружке ‖1349‖ надо еще подарок ей купить ‖851‖ в понедельник записать мишу к ортодонту',
    );

    // «сегодня» после паузы уже в своём предложении (знака после нет),
    // «Завтра» — после точки: трогать нечего.
    expect(dayAfterPause(utterance).text).toBe(
      'Так короче, пока не забыла сегодня в 6 вечера отвезти маме лекарства. Завтра в 12 Машу отвезти на день рождения к подружке. Надо еще подарок ей купить. В понедельник записать Мишу к Ортодонту.',
    );
  });
});

describe('dayAfterPause — чего не трогать', () => {
  const unchanged = (text: string, marked: string): void => {
    const utterance = heard(text, marked);
    expect(dayAfterPause(utterance)).toBe(utterance);
  };

  it('пауза после дня, а не перед ним: «купить подарок в пятницу, ‖700‖ записать» — пятница подарку', () => {
    unchanged(
      'Купить подарок в пятницу, записать Мишу к ортодонту.',
      'купить подарок в пятницу ‖700‖ записать мишу к ортодонту',
    );
  });

  it('паузы с обеих сторон — сомнение, текст как есть', () => {
    unchanged(
      'Купить подарок в пятницу, записать Мишу к ортодонту.',
      'купить подарок ‖700‖ в пятницу ‖700‖ записать мишу к ортодонту',
    );
  });

  it('пауза короче порога', () => {
    unchanged(
      'Купить подарок в пятницу, записать Мишу к ортодонту.',
      'купить подарок ‖400‖ в пятницу записать мишу к ортодонту',
    );
  });

  it('после дня знака нет — распознавание и так отдало его следующему', () => {
    unchanged(
      'Купить подарок в пятницу записать Мишу к ортодонту.',
      'купить подарок ‖700‖ в пятницу записать мишу к ортодонту',
    );
  });

  it('перед днём уже точка — всё и так на месте', () => {
    unchanged(
      'Купить подарок. В пятницу, записать Мишу к ортодонту.',
      'купить подарок ‖700‖ в пятницу записать мишу к ортодонту',
    );
  });

  it('день в конце фразы — отдавать некому', () => {
    unchanged('Купить подарок в пятницу.', 'купить подарок ‖700‖ в пятницу');
  });

  it('дней в тексте и в словах не поровну — какой из них какой, не сказать', () => {
    // В тексте «в пятницу» дважды, в словах — раз: первое по тексту
    // тоже прилеплено и с запятой — переставить можно не ту.
    unchanged(
      'Купить хлеб в пятницу, купить подарок в пятницу, записать Мишу.',
      'купить хлеб купить подарок ‖700‖ в пятницу записать мишу',
    );
  });
});

describe('dayAfterPause — два одинаковых дня', () => {
  it('переезжает только тот, что после паузы', () => {
    const utterance = heard(
      'В пятницу купить хлеб. Отнести куртку в пятницу, забрать посылку.',
      'в пятницу купить хлеб ‖900‖ отнести куртку ‖700‖ в пятницу забрать посылку',
    );

    expect(dayAfterPause(utterance).text).toBe(
      'В пятницу купить хлеб. Отнести куртку. В пятницу забрать посылку.',
    );
  });
});

describe('withDaysAfterPauses', () => {
  it('ничего не переехало — тот же результат', () => {
    const result = {
      text: 'Купить хлеб.',
      model: 'yandex:general',
      audioSeconds: 2,
      utterances: [heard('Купить хлеб.', 'купить хлеб')],
    };

    expect(withDaysAfterPauses(result)).toEqual({ result, moved: 0 });
    expect(withDaysAfterPauses(result).result).toBe(result);
  });

  it('без времён слов — как есть', () => {
    const result = { text: 'Купить хлеб.', model: 'openai', audioSeconds: 2 };

    expect(withDaysAfterPauses(result).result).toBe(result);
  });

  it('переехало — общий текст собран из фраз заново', () => {
    const first = heard('Купить хлеб.', 'купить хлеб');
    const second = heard(
      'Надо подарок купить в пятницу, записать Мишу к ортодонту.',
      'надо подарок купить ‖700‖ в пятницу записать мишу к ортодонту',
    );
    const result = {
      text: `${first.text} ${second.text}`,
      model: 'yandex:general',
      audioSeconds: 10,
      utterances: [first, second],
    };

    const { result: fixed, moved } = withDaysAfterPauses(result);

    expect(moved).toBe(1);
    expect(fixed.text).toBe(
      'Купить хлеб. Надо подарок купить. В пятницу записать Мишу к ортодонту.',
    );
  });
});
