import { readFile } from 'node:fs/promises';

import { describe, expect, it } from 'vitest';

import { normalizeCode } from './promo.service.js';

/**
 * Обещания промокодов не расходятся с тем, что код умеет (§14, задача 4.4).
 *
 * **Ревизия панели, находка 9.** В шапке `savePromo` стояло «Правится код
 * отдельным вызовом», и такого вызова не было ни в модуле, ни в маршруте:
 * `POST /api/promo` умеет только заводить и переключать. Опечатка в цене
 * уже опубликованного кода (99 вместо 9900) лечилась единственным
 * способом — выключить и завести новый, то есть попросить блогера
 * переписать пост. На экране это было сказано честно, в коде — нет.
 *
 * Обещание в комментарии дороже, чем кажется: следующий, кто будет
 * править цену «тем самым отдельным вызовом», сначала будет искать его
 * час, а потом решит, что сломал что-то сам.
 *
 * Проверка по исходнику, а не по экспортам: обещание — это текст, и
 * разойтись с кодом может только текст.
 */

const SERVICE = 'src/modules/billing/promo.service.ts';
const ROUTE = 'src/http/admin/index.ts';

/**
 * Обещание правки словами. Именно та формулировка, что стояла, и её
 * ближайшие родственники: «правится отдельным вызовом», «правится
 * особым вызовом».
 */
const PROMISE = /правится[^.]{0,60}вызовом/iu;

/** Путь правки: он назывался бы так и в службе, и в маршруте. */
const EDIT_PATH = /(?:export async function|async function) (?:update|edit|change)Promo/u;

describe('промокод: обещанное и сделанное', () => {
  it('шапка не обещает правки кода, которой нет ни в службе, ни в маршруте', async () => {
    const service = await readFile(SERVICE, 'utf8');
    const route = await readFile(ROUTE, 'utf8');

    const promised = PROMISE.test(service);
    const exists = EDIT_PATH.test(service) || EDIT_PATH.test(route);

    expect(
      promised && !exists,
      [
        'promo.service.ts обещает правку кода отдельным вызовом, а такого вызова нет.',
        'Обещание либо исполняется, либо снимается: искать несуществующий путь будет',
        'следующий, кто придёт править цену уже опубликованного кода.',
        'Появится путь — обещание станет правдой, и эта проверка снова позеленеет.',
      ].join('\n'),
    ).toBe(false);
  });

  it('проверка правда узнаёт то обещание, что стояло', () => {
    /**
     * Страж стража. Ослабь выражение — и проверка выше станет вечно
     * зелёной, не отличая починенное от сломанного: ровно тот случай,
     * из-за которого страж связки настроек спал на четырёх ценах.
     */
    expect(PROMISE.test('заметить это было бы нечем. Правится код отдельным вызовом.')).toBe(true);
    expect(PROMISE.test('Заведённый код не правится вовсе — ни здесь, ни где-то ещё.')).toBe(false);
    expect(EDIT_PATH.test('export async function updatePromo(')).toBe(true);
    expect(EDIT_PATH.test('export async function savePromo(')).toBe(false);
  });

  it('приведение кода к единому виду: заглавные, без пробелов, без кириллицы', () => {
    // Не про находку, а про то, чтобы файл проверял и поведение: блогер
    // напишет код как угодно, человек перепишет как увидел.
    expect(normalizeCode('  осень-2026  ')).toBeUndefined();
    expect(normalizeCode(' blogger7 ')).toBe('BLOGGER7');
    expect(normalizeCode('ой')).toBeUndefined();
  });
});
