/**
 * Провайдер оплаты за интерфейсом (§14 ТЗ, задача 4.1).
 *
 * **Почему интерфейс, а не сразу реализация.** §14 называет провайдером
 * ЮKassa, а правила платёжной платформы Telegram требуют продавать
 * цифровые услуги внутри бота только за Telegram Stars — расхождение
 * найдено на разборе ТЗ (находка Б1, `docs/01-analiz-tz.md`) и до сих
 * пор ждёт решения заказчицы. Само ТЗ выход и подсказывает: «архитектура
 * биллинга проектируется так, чтобы провайдер оплаты можно было
 * заменить, не трогая остальной код». Интерфейс верен при любом ответе,
 * поэтому он и написан первым: работа не простаивает, а решение не
 * предугадывается.
 *
 * **Форма выведена из двух настоящих API, а не придумана.**
 *  - Stars: `createInvoiceLink` (currency `XTR`, пустой `provider_token`,
 *    `subscription_period` — и он **только** 2 592 000 секунд),
 *    служебное сообщение `successful_payment`, апдейт `subscription`
 *    с состояниями canceled/active/failed, отмена через
 *    `editUserStarSubscription` по `telegram_payment_charge_id`.
 *  - ЮKassa по §14: первый платёж с сохранением способа оплаты, дальше
 *    автосписание; вебхуки со **проверкой подписи** и защитой от
 *    повторной обработки.
 *
 * Разница между ними съедена тремя решениями:
 *  1. Место оплаты — всегда ссылка. У Stars это ссылка на счёт, у
 *     ЮKassa — страница оплаты. Боту в обоих случаях нужна кнопка.
 *  2. Событие разбирает **провайдер**, наверх отдаёт наше. Там же живёт
 *     и проверка подписи (§16): она про формат провайдера, и знать о ней
 *     подписке незачем.
 *  3. Чем отменять — строка `subscriptionRef`, смысл которой знает
 *     только провайдер: у Stars это `telegram_payment_charge_id`, у
 *     ЮKassa — сохранённый способ оплаты.
 *
 * Операций ровно четыре, как просит план: создать счёт, разобрать
 * событие, отменить автопродление, получить состояние. Ни одной сверх:
 * возврат средств §14 не требует, а необратимое действие в интерфейсе —
 * приглашение однажды позвать его из кода.
 */

/** Тариф. Годовой в Stars автопродлением не бывает — см. `Checkout`. */
export type PlanKind = 'monthly' | 'yearly';

export interface CheckoutParams {
  /** Кому платить. Наш идентификатор, не телеграмный. */
  readonly userId: string;
  /** Идентификатор человека у провайдера: Stars шлёт счёт в чат. */
  readonly tgId: number;
  readonly plan: PlanKind;
  /** Цена в наименьших единицах: копейки у рублей, штуки у звёзд. */
  readonly amount: number;
  /** `RUB` у ЮKassa, `XTR` у звёзд. */
  readonly currency: string;
  /**
   * Наша метка счёта, которая вернётся в событии оплаты.
   *
   * Ею событие связывается с человеком и тарифом. У Stars это
   * `invoice_payload` — не более 128 байт и человеку не видна.
   */
  readonly ref: string;
  /** Название и описание в окне оплаты: их видит человек. */
  readonly title: string;
  readonly description: string;
  /**
   * Числовой номер счёта — тем провайдерам, которые его требуют.
   *
   * Робокассе он нужен и обязан быть **нашим**: по нему потом уходит
   * продление. Ноль или пустое значение означают у неё «назначу номер
   * сам», а повторный номер она отвергает ошибкой 40 — поэтому номер
   * выдаёт последовательность базы, а не провайдер.
   *
   * Звёзды его игнорируют: у них счёт опознаётся меткой.
   */
  readonly invoiceNumber?: number | undefined;
  /**
   * Просить ли автопродление. По умолчанию — да, где рельс это умеет.
   *
   * Заведено промокодами (задача 4.4): промо-счёт уходит без продления
   * на обоих рельсах. У звёзд продлевает Telegram сам и **по сумме
   * счёта** — подписочный промо-счёт означал бы скидку навсегда. У
   * Робокассы дочернее списание на сумму больше материнского официально
   * не выяснено, а формула подписи продления не подтверждена
   * документацией: ставить на это первое живое списание нельзя.
   *
   * Ложь означает «не проси», а не «не будет»: умеет ли рельс продление
   * вообще, по-прежнему отвечает `Checkout.autoRenews`.
   */
  readonly renewable?: boolean | undefined;
}

export interface Checkout {
  /** Куда отправить человека платить. */
  readonly url: string;
  /**
   * Будет ли продлеваться само.
   *
   * Не всякий счёт умеет автопродление: в Stars подписка бывает **только
   * тридцатидневной** (`subscription_period` в Bot API обязан быть
   * 2 592 000), поэтому годовой тариф там — разовый платёж без
   * автопродления. Провайдер обязан сказать это честно, чтобы бот не
   * обещал человеку продление, которого не будет.
   */
  readonly autoRenews: boolean;
}

/**
 * Событие провайдера, приведённое к нашему.
 *
 * Разделено на денежные и состояние: у денежных обязателен
 * `externalId` — ключ, которым база отбивает повторную доставку (§14
 * «защита от повторной обработки»). У изменения состояния такого ключа
 * нет и не нужно: выставить признак «продлевать не надо» дважды — то же
 * самое, что один раз.
 */
export type PaymentEvent =
  | {
      readonly kind: 'paid';
      /** Идентификатор платежа у провайдера. Уникален, в том числе у продлений. */
      readonly externalId: string;
      /** Наша метка из счёта. */
      readonly ref: string;
      readonly amount: number;
      readonly currency: string;
      /** Продление, а не первый платёж. */
      readonly renewal: boolean;
      /** До какого времени оплачено, если провайдер сказал. */
      readonly paidUntil?: Date | undefined;
      /** Чем потом отменять автопродление. */
      readonly subscriptionRef?: string | undefined;
    }
  | {
      readonly kind: 'refunded';
      readonly externalId: string;
      readonly ref: string;
      readonly amount: number;
      readonly currency: string;
    }
  | {
      /** Человек отключил автопродление сам, средствами провайдера. */
      readonly kind: 'renewalStopped';
      readonly ref: string;
    }
  | {
      /** Продление не прошло: денег не хватило или карта отвалилась. */
      readonly kind: 'renewalFailed';
      readonly ref: string;
    };

/**
 * Состояние подписки у провайдера — для сверки с нашим.
 *
 * **`autoRenews` необязателен, и это находка второй реализации.** Bot
 * API не отдаёт признака «продление отключено» ни одним методом: по
 * списку транзакций видно, когда и на сколько заплатили, но не то,
 * будет ли следующий платёж. Значит источник правды про автопродление —
 * наша таблица (мы сами его выключаем и сами получаем событие
 * `renewalStopped`), а ответ провайдера годится лишь на сверку там, где
 * он вообще есть.
 *
 * Первая версия требовала это поле от всех. Так и выглядит интерфейс,
 * выведенный из одного воображаемого провайдера: он врёт про второго.
 */
export interface ProviderStatus {
  readonly active: boolean;
  readonly autoRenews?: boolean | undefined;
  readonly paidUntil?: Date | undefined;
}

export interface PaymentProvider {
  /**
   * Имя для журнала и учёта. С двоеточием, как у моделей
   * (`yandex:yandexgpt/latest`): по нему в отчётах видно, чей платёж.
   */
  readonly name: string;

  /** Создать счёт и вернуть место, где человек заплатит. */
  createCheckout(params: CheckoutParams): Promise<Checkout>;

  /**
   * Разобрать событие провайдера.
   *
   * `undefined` означает «это не про оплату» — например любое другое
   * сообщение. Отказ означает, что событие пришло **испорченным**: не
   * сошлась подпись или не разобралось тело. Молча возвращать
   * `undefined` в этом случае нельзя: подделанное событие обязано быть
   * видно в журнале, а не выглядеть как посторонний апдейт (§16).
   */
  readEvent(raw: unknown): Promise<PaymentEvent | undefined>;

  /**
   * Отключить автопродление.
   *
   * Доступ при этом сохраняется до конца оплаченного периода — так
   * требует §14, и подписка следит за этим сама: провайдер отвечает
   * только за то, чтобы деньги больше не списывались.
   */
  stopRenewal(params: { readonly tgId: number; readonly subscriptionRef: string }): Promise<void>;

  /**
   * Что провайдер думает об этой подписке.
   *
   * `undefined` означает «провайдер не знает», и это не выдумка ради
   * удобства: у звёзд состояния подписки нет ни в одном методе Bot API.
   * Косвенно его можно поискать в списке транзакций, но старую подписку
   * там уже не найти — список конечен. Вернуть в таком случае
   * «неактивна» значило бы соврать и отобрать доступ у платящего.
   *
   * Источник правды про подписку — наша таблица; ответ провайдера
   * годится на сверку там, где он вообще есть.
   */
  statusOf(params: {
    readonly tgId: number;
    readonly subscriptionRef: string;
  }): Promise<ProviderStatus | undefined>;
}
