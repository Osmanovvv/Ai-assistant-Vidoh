import type { PlanKind } from './provider.js';
import type { SettingsRegistry } from '../settings/settings.repo.js';

/**
 * Тарифы (§14 ТЗ, задача 4.2).
 *
 * §14 дословно: «Тарифы месячный и годовой. Стоимость задается в
 * админ-панели». Значит цена — не константа кода, а настройка, и всё
 * здесь построено вокруг этого.
 *
 * **Ноль означает «цена не задана», а не «бесплатно».** Пока заказчица
 * не назвала цифру, продавать нечего: кнопка оплаты не показывается, счёт
 * не создаётся. Придуманная нами цена по умолчанию означала бы, что бот
 * однажды продаст подписку за выдуманные деньги, а заметить это можно
 * будет только по чужой жалобе.
 *
 * **Рельсов два, цены разные — и это нарочно.** Курс звезды к рублю
 * задаёт Telegram, он меняется, и пересчитывать его в коде значило бы
 * однажды продать год за две звезды. Паритет требует, чтобы **набор
 * тарифов** совпадал на обоих рельсах, а не чтобы совпадали цифры.
 */

/** Рельс оплаты. Имя с двоеточием — как у моделей в учёте расхода. */
export type Rail = 'robokassa:smz' | 'telegram:stars';

export const RAILS = ['robokassa:smz', 'telegram:stars'] as const;

/**
 * Кто снимает деньги за продление на рельсе — и, значит, чем оно
 * отменяется.
 *
 * У звёзд подписку держит Telegram: списывает сам, по своему ключу
 * (`subscriptionRef`), и без этого ключа отменить нечем. У Робокассы
 * дочернее списание уходит **от нас**, по строке `billing_subscriptions`
 * с включённым продлением: не списываем — продления нет, и удалённо
 * отменять нечего. Ключа отмены у неё поэтому нет и не бывает —
 * `readEvent` его не отдаёт.
 *
 * Запись исчерпывающая нарочно: третий рельс не соберётся, пока не
 * скажет, кто у него списывает. Иначе он молча унаследовал бы чужое —
 * ровно так робокассный подписчик после удаления данных читал
 * инструкцию про звёзды (дефект №20 ревизии).
 */
export const RENEWAL_CHARGED_BY: Readonly<Record<Rail, 'us' | 'provider'>> = {
  'robokassa:smz': 'us',
  'telegram:stars': 'provider',
};

export const PLANS = ['monthly', 'yearly'] as const;

export interface Price {
  /** Копейки у рублей, штуки у звёзд. */
  readonly amountMinor: number;
  readonly currency: 'RUB' | 'XTR';
}

/**
 * Сколько стоит тариф на этом рельсе. `undefined` — цена не задана.
 *
 * Возвращать ноль было бы хуже: ноль пришлось бы проверять в каждом
 * вызывающем месте, и однажды кто-нибудь не проверил бы.
 */
export async function priceOf(
  settings: SettingsRegistry,
  params: { readonly plan: PlanKind; readonly rail: Rail },
): Promise<Price | undefined> {
  if (params.rail === 'telegram:stars') {
    const stars = await settings.number(
      params.plan === 'monthly' ? 'priceMonthlyStars' : 'priceYearlyStars',
    );

    return stars > 0 ? { amountMinor: stars, currency: 'XTR' } : undefined;
  }

  const kopecks = await settings.number(
    params.plan === 'monthly' ? 'priceMonthlyRub' : 'priceYearlyRub',
  );

  return kopecks > 0 ? { amountMinor: kopecks, currency: 'RUB' } : undefined;
}

/*
  `tariffsOf` убрана ревизией четвёртого этапа.

  Она собирала заданные тарифы **одного** рельса, и вызывающих у неё не
  было ни одного вне проверок: экран подписки, гейт и реплики спрашивают
  `sellable` — та же сборка, но по всем рельсам и в порядке кнопок.

  Два способа ответить на вопрос «что мы продаём» — это два места, где
  живёт одна правда, и расходятся они молча: добавь рельс, и один из них
  о нём не узнает.
*/

/**
 * Конец оплаченного периода.
 *
 * **Месяц считается календарным, а не тридцатью днями.** Человек,
 * заплативший 31 января, ждёт списания в конце февраля, а не 2 марта;
 * «тридцать дней» дают тринадцать списаний в год вместо двенадцати, и
 * это заметят по счёту, а не по нашему коду.
 *
 * Переполнение короткого месяца решается в пользу человека: 31 января
 * плюс месяц — это 28 февраля, а не 3 марта. `Date` в JavaScript сам
 * перекидывает лишние дни вперёд, поэтому дата обрезается вручную.
 */
export function periodEndAfter(from: Date, plan: PlanKind): Date {
  const months = plan === 'monthly' ? 1 : 12;
  const end = new Date(from.getTime());
  const day = end.getUTCDate();

  // Первое число месяца — чтобы прибавление месяцев не перескочило.
  end.setUTCDate(1);
  end.setUTCMonth(end.getUTCMonth() + months);

  // Последний день целевого месяца: нулевой день следующего.
  const lastDay = new Date(Date.UTC(end.getUTCFullYear(), end.getUTCMonth() + 1, 0)).getUTCDate();
  end.setUTCDate(Math.min(day, lastDay));

  return end;
}

/**
 * Продление считается от конца оплаченного, пока он не наступил, — и от
 * «сейчас», если подписка уже закончилась.
 *
 * **Порога в семь дней здесь больше нет — это решение заказчицы
 * (12.09.2026).** Он был заведён под задержку автосписания: продление
 * приходит позже конца периода, и без порога человек терял бы эти дни.
 * Но правило одно на все оплаты, и на ручной оплате после окончания оно
 * било по человеку: заплатила на три дня позже — получила период на три
 * дня короче. «Нам не нужен спор с женщиной из-за трёх „съеденных“
 * дней» — и это верно.
 *
 * Что осталось от прежнего замысла, осталось честно: автосписание
 * уходит за сутки до конца периода (`RENEWAL_LEAD_MS`), поэтому в
 * обычном случае оно приходит **до** конца и продление идёт от конца —
 * годовщина не ползёт, оплаченные дни не теряются. Опоздавшее
 * уведомление считается от «сейчас» — то есть в пользу человека, а не
 * против него: доступа в те дни у неё не было, и платить за них не за
 * что. Ранняя ручная оплата — тоже от конца: заплатить за месяц вперёд
 * не значит потерять остаток нынешнего.
 */
export function renewFrom(currentPeriodEnd: Date, now: Date): Date {
  return currentPeriodEnd.getTime() > now.getTime() ? currentPeriodEnd : now;
}

/**
 * За сколько до конца периода уходит списание.
 *
 * Живёт здесь, а не в проходе продления, потому что нужна двоим: проходу
 * — чтобы списать, и экрану согласия — чтобы назвать человеку дату
 * первого автосписания **до** оплаты (оферта, п. 7.2–7.3). Одно число в
 * двух местах считалось бы двумя способами; здесь оно одно.
 *
 * Сутки — не для запаса скорости: неудачное списание оставляет человеку
 * день, чтобы заплатить руками и не потерять доступ ни на час.
 */
export const RENEWAL_LEAD_MS = 24 * 3_600_000;

/**
 * Когда уйдёт первое автосписание, если человек оплатит месяц сейчас.
 *
 * Считается тем же путём, каким приём оплаты назначит период
 * (`renewFrom` + `periodEndAfter`), и тем же отступом, каким проход
 * продления выберет день списания (`RENEWAL_LEAD_MS`). Экран согласия
 * обязан называть ту дату, в которую списание действительно случится —
 * иначе оферта обещала бы одно, а бот делал другое.
 *
 * `currentPeriodEnd` — конец нынешнего оплаченного периода, если он есть:
 * у платящего новый период начинается с конца прежнего, а не с сегодня.
 */
export function firstRenewalChargeAt(params: {
  readonly now: Date;
  readonly currentPeriodEnd?: Date | undefined;
}): Date {
  const from =
    params.currentPeriodEnd === undefined
      ? params.now
      : renewFrom(params.currentPeriodEnd, params.now);

  return new Date(periodEndAfter(from, 'monthly').getTime() - RENEWAL_LEAD_MS);
}
