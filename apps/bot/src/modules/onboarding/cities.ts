/** Слова, которыми город обрамляют: «я в Краснодаре», «город Сочи». */
const AROUND_CITY = new Set([
  'я',
  'мы',
  'в',
  'во',
  'из',
  'город',
  'городе',
  'живу',
  'нахожусь',
  'сейчас',
  'это',
]);

function normalize(text: string): string {
  return text.toLowerCase().replace(/ё/gu, 'е').trim();
}

/** Справочник с нормализованными ключами: сверять надо одинаково. */
const BY_NAME = new Map(Object.entries(CITIES).map(([name, zone]) => [normalize(name), zone]));

/**
 * Основа названия: без окончания, которое меняется по падежам.
 *
 * **Сверяются основы, а не окончания, и первая версия на этом и упала.**
 * Она отрезала окончание у сказанного и искала остаток в справочнике: «из
 * Москвы» давало «москв», а в справочнике стоит «москва» — не нашлось.
 * Основа снимается с **обеих** сторон, и тогда «москва» и «москвы»
 * встречаются в «москв».
 *
 * Догадок это не добавляет: справочник закрытый, и основа неизвестного
 * города ни с чем не совпадёт. А вот совпадение основ двух **разных**
 * городов было бы опасно — это проверяется тестом отдельно.
 */
function stemOf(word: string): string {
  /**
   * Длинные окончания стоят раньше коротких.
   *
   * Иначе «нижнего» потеряло бы только «о» и с «нижнем» не встретилось.
   * И прилагательные здесь обязательны: «Нижний Новгород», «Великий
   * Новгород», «Грозный» меняются как прилагательные, а не как
   * существительные, — на этом вторая версия и спотыкалась.
   */
  return word.replace(/(его|ого|ому|ами|ий|ый|ой|ем|ом|ах|ая|ое|ые|их|е|и|ы|а|у|я|ь)$/u, '');
}

/**
 * Основа многословного названия: по основе каждой части.
 *
 * Дефис здесь такой же разделитель, как пробел, и это важно: «в
 * Ростове-на-Дону» надо свести к тому же, что «Ростов-на-Дону». Если
 * стричь только целый токен, окончание снимется с «Дону», а «Ростове»
 * останется — и город не найдётся.
 */
function stemOfName(name: string): string {
  return name
    .split(/[\s-]+/u)
    .filter((part) => part !== '')
    .map((word) => stemOf(word))
    .join(' ');
}

/** Справочник по основам: им и сверяется сказанное. */
const BY_STEM = new Map(
  Object.entries(CITIES).map(([name, zone]) => [stemOfName(normalize(name)), zone]),
);

/**
 * Пояс города, названного словами. `undefined` — города нет в справочнике.
 *
 * **Ничего не угадывает.** Неизвестное название возвращает `undefined`, и
 * бот честно скажет, что не нашёл: молчание надёжнее догадки, потому что
 * неверный пояс ломает все сроки человека сразу.
 */
export function zoneOfCity(text: string): string | undefined {
  const words = normalize(text)
    .replace(/[^\p{L}\s-]+/gu, ' ')
    .split(/\s+/u)
    .filter((word) => word !== '' && !AROUND_CITY.has(word));

  if (words.length === 0 || words.length > 3) return undefined;

  const asked = words.join(' ');

  // Сперва как написано: «краснодар», «ростов-на-дону».
  const direct = BY_NAME.get(asked);
  if (direct !== undefined) return direct;

  // Потом по основе: «в Краснодаре», «из Москвы», «в Нижнем Новгороде».
  return BY_STEM.get(stemOfName(asked));
}

/**
 * Основы справочника **списком**, а не картой.
 *
 * Списком именно потому, что тест ищет совпадения: карта молча оставляет
 * последнее значение, и страж на ней сработать не мог бы вовсе. Проверка,
 * которая не в состоянии упасть, хуже отсутствующей.
 */
export function stemsOfDirectory(): readonly {
  readonly stem: string;
  readonly zone: string;
  readonly city: string;
}[] {
  return Object.entries(CITIES).map(([city, zone]) => ({
    city,
    zone,
    stem: stemOfName(normalize(city)),
  }));
}

/** Сколько городов знает справочник. Нужно тесту и отчёту о готовности. */
export const KNOWN_CITIES = BY_NAME.size;
