import { describe, expect, it } from 'vitest';

import { settingTime, spokenName } from './spoken-setting.js';

/**
 * Ответы на вопросы-настройки словами (план docs/28, шаг 6; набор
 * docs/eval-dialog/settings.md, 28.09.2026). Замер кодом: верно 44 из 107,
 * не так 18 — «в 9» на «Во сколько писать вечером?» ставило 09:00, «Меня
 * зовут Оля» становилось именем целиком.
 */
describe('время утром и вечером словами', () => {
  it.each<[string, string]>([
    ['7', '07:00'],
    ['в 7:30', '07:30'],
    ['в восемь', '08:00'],
    ['восемь утра', '08:00'],
    ['полвосьмого', '07:30'],
    ['в половине восьмого', '07:30'],
    ['около девяти', '09:00'],
    ['давай в 8', '08:00'],
    ['пусть в 7', '07:00'],
    ['ну в 8 наверное', '08:00'],
    ['без пятнадцати семь', '06:45'],
    ['7 утра пожалуйста', '07:00'],
    ['утром в 8', '08:00'],
  ])('утро: «%s» → %s', (text, expected) => {
    expect(settingTime(text, 'morning')).toBe(expected);
  });

  it.each<[string, string]>([
    ['21', '21:00'],
    ['в 9', '21:00'],
    ['9', '21:00'],
    ['в 8', '20:00'],
    ['часов в 10', '22:00'],
    ['в девять вечера', '21:00'],
    ['в девять', '21:00'],
    ['полдесятого', '21:30'],
    ['в половине десятого', '21:30'],
    ['давай в 9', '21:00'],
    // Утро названо прямо — как сказано.
    ['в 7 утра', '07:00'],
  ])('вечер: «%s» → %s', (text, expected) => {
    expect(settingTime(text, 'evening')).toBe(expected);
  });

  it.each(['не пиши вечером', 'вечером не надо', 'не надо', 'не пиши', 'не присылай'])(
    'вечер: «%s» — не писать',
    (text) => {
      expect(settingTime(text, 'evening')).toBe('off');
    },
  );

  it('утром «не надо» не выключает: утреннюю сводку так не отключают', () => {
    expect(settingTime('не надо', 'morning')).toBeUndefined();
  });

  it.each([
    'купить хлеб',
    'позвонить маме в 8',
    'что у меня на сегодня?',
    'как проснусь',
    'пораньше',
    'не знаю',
    'в смысле?',
  ])('«%s» — не время', (text) => {
    expect(settingTime(text, 'morning')).toBeUndefined();
    expect(settingTime(text, 'evening')).toBeUndefined();
  });
});

describe('имя словами', () => {
  it.each<[string, string]>([
    ['Оля', 'Оля'],
    ['Оля.', 'Оля'],
    ['Меня зовут Оля', 'Оля'],
    ['Зови меня Оля', 'Оля'],
    ['Можно просто Лена', 'Лена'],
    ['Я Маша', 'Маша'],
    ['Катя, спасибо', 'Катя'],
    ['Ольга Петровна', 'Ольга Петровна'],
    ['Мама', 'Мама'],
    ['Настя конечно', 'Настя'],
  ])('«%s» → %s', (text, expected) => {
    expect(spokenName(text)).toBe(expected);
  });

  it.each([
    'купить хлеб',
    'купить хлеб завтра',
    'позвонить маме',
    'что у меня на завтра',
    'устала',
    'спасибо',
    'не хочу говорить',
    'неважно',
    'зачем тебе?',
  ])('«%s» — не имя', (text) => {
    expect(spokenName(text)).toBeUndefined();
  });
});
