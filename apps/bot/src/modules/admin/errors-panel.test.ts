import { readFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

import { describe, expect, it } from 'vitest';

import { reminderKind } from '../../db/schema.js';

/**
 * Что журнал сбоев обязан сказать словами (§15, ревизия панели).
 *
 * **Зачем страж и почему по исходнику.** Три находки ревизии — молчаливые:
 * раздел, исчезающий вместе с заголовком; пятьдесят строк без слов об
 * обрезке; код `morning` в колонке «Какое». Ни одна из них не роняет
 * панель и ни одна не видна в ответе сервера — она видна только в вёрстке,
 * а вёрстку в этом наборе исполнить нечем: браузерные проверки живут в
 * `tests/admin`, гоняются отдельно и долго. Проверка идёт по тексту
 * `Errors.tsx` — тот же приём, что у стража названий настроек
 * (`settings/labels.test.ts`) и у стража путей админ-роутера: словарь
 * живёт в другом пакете, и импортировать `.tsx` в тесты бота незачем.
 *
 * Страж грубый нарочно: он держит связку «есть слова — есть разрез», а не
 * их формулировки. Формулировки читает браузерная половина.
 */

const panel = resolve(dirname(fileURLToPath(import.meta.url)), '../../../../admin/src/Errors.tsx');

/** Пять журналов от `/api/errors`. Шестой, доступа §16, — со своего пути. */
const LOGS = ['batches', 'calls', 'payments', 'sends', 'reminders'] as const;

function source(): string {
  return readFileSync(panel, 'utf8');
}

/** Клетки таблицы: от `page.<список>.map(` до конца тела таблицы. */
function bodyOf(text: string, log: string): string {
  const start = text.indexOf(`page.${log}.map(`);

  expect(start, `в панели нет таблицы для ${log}`).toBeGreaterThan(-1);

  return text.slice(start, text.indexOf('</tbody>', start));
}

describe('журнал сбоев говорит словами, а не пустотой', () => {
  it('у каждого из пяти разрезов пустота названа словами', () => {
    /**
     * Прежде три разреза из шести были обёрнуты в `length > 0`: при
     * пустом списке с экрана пропадал и заголовок. Проджект, разбирающий
     * «я заплатил, доступ не дали», не видел раздела платежей вовсе и не
     * мог отличить «неудачных платежей за сутки не было» от «журнал
     * платежей не показывает».
     */
    const text = source();

    const silent = LOGS.filter((log) => !text.includes(`page.${log}.length === 0`));

    expect(
      silent,
      `разрезы, исчезающие вместе с заголовком, вместо слов о пустоте: ${silent.join(', ')}`,
    ).toEqual([]);

    /** И это именно слова: пустая ветка каждого разреза их содержит. */
    const wordless = LOGS.filter((log) => {
      const at = text.indexOf(`page.${log}.length === 0`);

      return !text.slice(at, text.indexOf(') : (', at)).includes('за этот срок');
    });

    expect(wordless, `пустота без слов «за этот срок»: ${wordless.join(', ')}`).toEqual([]);
  });

  it('у каждого списка сказано, сколько строк скрыла обрезка', () => {
    /**
     * Сервер отдаёт последние пятьдесят строк и число за период рядом.
     * При заголовке «Сорвавшиеся разборы — всего 137» в таблице лежало
     * пятьдесят, и ничто не говорило, что это не всё: в сбое, породившем
     * сотни срывов, разбирающий решил бы, что перезапустил всех, а
     * перезапустил последних пятьдесят. Строка была написана — но
     * досталась одному журналу доступа из шести.
     */
    const text = source();

    const mute = LOGS.filter(
      (log) =>
        !new RegExp(
          `shown=\\{page\\.${log}\\.length\\}\\s*total=\\{page\\.${log}Total\\}`,
          'u',
        ).test(text),
    );

    expect(mute, `списки без слов об обрезке: ${mute.join(', ')}`).toEqual([]);

    // Журнал доступа §16 — шестой, и слова у всех одни и те же.
    expect(text).toMatch(/shown=\{seen\.rows\.length\}\s*total=\{seen\.total\}/u);
  });

  it('вид напоминания переведён для каждого значения из базы', () => {
    /**
     * В колонке «Какое» стоял код из базы — «morning» в русской панели, —
     * при том что соседние клетки того же журнала переводят и рельс
     * («звёзды», «карта»), и тариф («месяц», «год»). Отказ молчаливый:
     * раздел работает, и новое значение перечисления снова напечатается
     * кодом — поэтому словарь сверяется с `reminder_kind`, а не с
     * перечислением в чьём-то комментарии (в нём и было три значения из
     * пяти, одно из них несуществующее).
     */
    const text = source();

    const untranslated = reminderKind.enumValues.filter(
      (kind) => !new RegExp(`^\\s{2}${kind}: '`, 'mu').test(text),
    );

    expect(
      untranslated,
      `виды напоминания без слова в панели (напечатаются кодом): ${untranslated.join(', ')}`,
    ).toEqual([]);

    // И сама клетка кодом больше не печатается.
    expect(bodyOf(text, 'reminders')).not.toMatch(/<td>\{row\.kind\}<\/td>/u);
  });

  it('в строке не дошедшего письма названы рассылка и получатель', () => {
    /**
     * Подпись под таблицей велит идти к «нужной рассылке», а в строке не
     * было ни её времени, ни текста: `broadcastId` приезжал и не
     * рисовался нигде, раздел «Рассылка» идентификаторов не печатает.
     * И «Кому» было сырым телеграмным номером — по нему человека в
     * панели не найти, поиск в «Пользователях» идёт по имени и @имени.
     */
    const cells = bodyOf(source(), 'sends');

    expect(cells).toContain('row.broadcastAt');
    expect(cells).toContain('row.broadcastText');
    expect(cells).toContain('row.who');
  });

  it('совет про повтор назван вместе с условием, а не безусловно', () => {
    /**
     * **Панель не должна советовать того, чего выполнить нельзя.**
     * Кнопка «Повторить неудачные» есть только у законченной рассылки:
     * у идущей её нет, у остановленной нет нарочно — повтор досылал бы
     * всех оставшихся. Совет же был безусловным, то есть иногда обещал
     * несуществующую кнопку.
     */
    const text = source();
    const at = text.indexOf('Повторить неудачные');

    expect(at, 'в панели нет совета про повтор').toBeGreaterThan(-1);

    const advice = text.slice(at, text.indexOf('</p>', at));

    expect(advice).toContain('только у законченной');
    expect(advice).toContain('остановленной');
  });

  it('в строке неуспешного вызова видно, у кого он сорвался', () => {
    /**
     * Жалоба приходит от конкретного человека, а связать с ним строку
     * вызова было нечем: имя сервер не отдавал, а `batchId` довозился
     * двумя слоями типов и не рисовался нигде.
     */
    expect(bodyOf(source(), 'calls')).toContain('row.who');
  });
});
