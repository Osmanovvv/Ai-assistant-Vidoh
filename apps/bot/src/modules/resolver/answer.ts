/**
 * Чтение голосового ответа на уточняющий вопрос (§7.3 ТЗ, задача 3.6).
 *
 * Бот спросил «это про запись к врачу или отдельная история?» и дал две
 * кнопки. Человек с большой вероятностью ответит голосом — потому что
 * весь продукт про то, чтобы говорить, а не нажимать.
 *
 * **Словарём, а не моделью.** Обращение к модели ради того, чтобы понять
 * «да», стоило бы дороже самого разбора, который оно охраняет, и
 * добавило бы к ответу секунды ожидания. Словарь короткий и закрытый:
 * всё, чего в нём нет, честно считается непонятым.
 *
 * **Непонятое не толкуется в пользу правки.** Ошибочная правка стоит
 * доверия, лишняя запись — одного удаления; §7.3 выбирает второе прямо:
 * «дубли лучше потери данных».
 */

export type AnswerReading =
  /** «Добавить к прошлой». */
  | 'attach'
  /** «Это новое». */
  | 'separate'
  /**
   * Это не ответ, а новая мысль (задача 3.44).
   *
   * Маршрутизатор счёл реплику ответом на открытый вопрос, но в ней
   * есть содержание сверх слов ответа: «добавь ещё купить чехол для
   * зонта». Прочитать её как «добавь к прошлой» значило бы применить
   * отложенную правку и **выбросить** «купить чехол» — §9 запрещает.
   */
  | 'content'
  /** Ответ есть, но что он значит — непонятно. */
  | 'unclear';

/**
 * Сначала проверяется незнание.
 *
 * «Не знаю» начинается с «не», и без отдельной проверки ушло бы в
 * «отдельная история» как уверенный ответ. Человек при этом ничего не
 * решил, и делать вид, что решил, нельзя.
 */
const UNSURE = [
  'не знаю',
  'не помню',
  'не поняла',
  'не понял',
  'непонятно',
  'без понятия',
  'хз',
  'сложно сказать',
];

/** Явное «к прошлой»: человек назвал направление, а не только согласие. */
const ATTACH_PHRASES = [
  'к прошлой',
  'к прошлому',
  'к предыдущей',
  'к предыдущему',
  'к той',
  'к тому',
  'к этой',
  'туда же',
  'то же самое',
  'та же',
  'про ту',
  'про то',
  'про неё',
  'про нее',
  'про него',
  'это про',
];

/**
 * Глаголы, которые сами по себе значат «к прошлой» — но **только сами по
 * себе** (задача 3.44).
 *
 * «Добавь» в ответ на «это про запись к врачу или отдельная история?» —
 * согласие. А «добавь ещё купить чехол для зонта» — быстрое добавление
 * §13.3, которое случайно пришло, пока висел вопрос. Живой прогон
 * 03.09.2026: второе прочиталось как первое, правка применилась, а
 * «купить чехол» пропало без следа.
 */
const ATTACH_VERBS = ['добавь', 'добавить', 'поправь', 'исправь', 'перенеси'];

/** Связки, которые не несут содержания и не делают реплику мыслью. */
const FILLERS = [
  'и',
  'а',
  'ну',
  'вот',
  'тоже',
  'еще',
  'пожалуйста',
  'ладно',
  'ок',
  'окей',
  'хорошо',
  'давай',
  'это',
  'же',
];

/** Явное «это новое». */
const SEPARATE_PHRASES = [
  'новое',
  'новая',
  'новый',
  'отдельно',
  'отдельная',
  'отдельное',
  'другое',
  'другая',
  'не про',
  'не то',
  'не та',
  'не связано',
];

/** Короткое согласие без указания направления. */
const YES = ['да', 'ага', 'угу', 'верно', 'точно', 'именно', 'конечно'];

/** Короткий отказ. */
const NO = ['нет', 'неа', 'не'];

/**
 * Слова текста в нижнем регистре, без «ё» и без знаков.
 *
 * Границы слов ищутся разбиением, а не `\b`: `\b` определена через `\w`,
 * то есть латиницу, и кириллицу не видит. «Не» внутри «нести» иначе
 * прочиталось бы как отказ.
 */
function wordsOf(text: string): readonly string[] {
  return text
    .toLowerCase()
    .replace(/ё/gu, 'е')
    .split(/[^\p{L}]+/u)
    .filter((word) => word.length > 0);
}

/** Фраза целиком, по границам слов. */
function hasPhrase(words: readonly string[], phrase: string): boolean {
  const parts = phrase.split(' ');

  return words.some((_unused, index) =>
    parts.every((part, shift) => words[index + shift] === part),
  );
}

/**
 * Слова реплики, которые не относятся к ответу на вопрос.
 *
 * Из реплики вычитается весь словарь ответов и связки; что осталось —
 * содержание. Меньше двух слов содержанием не считается: «добавь
 * записи» — огрызок, а не мысль.
 */
export function answerRemainder(text: string): string {
  const words = wordsOf(text);
  const vocabulary = new Set<string>();

  for (const list of [UNSURE, ATTACH_PHRASES, SEPARATE_PHRASES]) {
    for (const phrase of list) for (const part of phrase.split(' ')) vocabulary.add(part);
  }
  for (const word of [...ATTACH_VERBS, ...YES, ...NO, ...FILLERS]) vocabulary.add(word);

  const rest = words.filter((word) => !vocabulary.has(word));
  return rest.length >= 2 ? rest.join(' ') : '';
}

export function readAnswer(text: string): AnswerReading {
  const words = wordsOf(text);
  if (words.length === 0) return 'unclear';

  if (UNSURE.some((phrase) => hasPhrase(words, phrase))) return 'unclear';

  /**
   * Направление важнее согласия.
   *
   * «Нет, к прошлой» — это «добавить к прошлой»: человек отрицает вторую
   * половину вопроса, а не первую. Проверь мы сначала «нет», ответ ушёл
   * бы в противоположную сторону.
   */
  if (ATTACH_PHRASES.some((phrase) => hasPhrase(words, phrase))) return 'attach';
  if (SEPARATE_PHRASES.some((phrase) => hasPhrase(words, phrase))) return 'separate';

  /**
   * Дальше — только если в реплике нет содержания сверх ответа (3.44).
   *
   * Направление названо явно — оно и решает, а остаток слов сохранится
   * отдельно (см. `answerRemainder`). А вот согласие, отказ и голый
   * глагол при содержании в два слова и больше — это мысль, которую
   * маршрутизатор принял за ответ. Её место в разборе, а не в правке.
   */
  if (answerRemainder(text) !== '') return 'content';

  if (ATTACH_VERBS.some((word) => words.includes(word))) return 'attach';
  if (YES.some((word) => words.includes(word))) return 'attach';
  if (NO.some((word) => words.includes(word))) return 'separate';

  return 'unclear';
}
