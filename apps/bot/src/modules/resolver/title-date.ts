/**
 * Устаревшая дата в цитируемом заголовке (задача 3.21 пункт 3).
 *
 * **Найдено ручным прогоном, дважды.** 31.08.2026 — в уточняющем вопросе:
 * «Это про „записать сына к врачу в четверг"…» при сроке в пятницу
 * читалось как потеря правки. 01.09.2026 — в подтверждении изменения, и
 * это оказалось куда чаще:
 *
 * > Перенесла «Запланировать поездку **на 5−7 сентября**» на **08.09**.
 *
 * Одна фраза называет две даты и читается так, будто бот не понял. А
 * подтверждение приходит после **каждой** правки, не только у
 * неоднозначных — поэтому отложенный дефект и вернулся.
 *
 * **Почему чиним в выводе, а не в извлечении.** Соблазн велик: не кладите
 * дату в заголовок, и проблемы нет. Но промпт извлечения намеренно хранит
 * слова человека — «первое слово фразы человека о его отношении к делу
 * дороже гладкости формулировки», — и ломать это правило ради вывода
 * нельзя. К тому же правка промпта означает обязательный прогон
 * контрольного набора и риск задеть разбор.
 *
 * В хранимом тексте дата остаётся. Убирается она только там, где рядом
 * уже названа настоящая — то есть только из **цитаты**.
 *
 * **Срезается лишь хвост, и это осознанная скупость.** «С 15 сентября
 * начать ходить 10 000 шагов» остаётся как есть: дата стоит в начале,
 * вырезать её из середины фразы значило бы калечить слова человека ради
 * аккуратности. Пропущенная дата — неаккуратность, изрезанная фраза —
 * потеря смысла.
 */

/** Дни недели во всех падежах, какие встречаются в речи. */
const WEEKDAYS = [
  'понедельник',
  'понедельника',
  'вторник',
  'вторника',
  'среду',
  'среда',
  'среды',
  'четверг',
  'четверга',
  'пятницу',
  'пятница',
  'пятницы',
  'субботу',
  'суббота',
  'субботы',
  'воскресенье',
  'воскресенья',
];

/** Месяцы в родительном — так их и произносят: «пятого сентября». */
const MONTHS = [
  'января',
  'февраля',
  'марта',
  'апреля',
  'мая',
  'июня',
  'июля',
  'августа',
  'сентября',
  'октября',
  'ноября',
  'декабря',
];

/** Слова, которые сами по себе называют день. */
const RELATIVE = ['завтра', 'послезавтра', 'сегодня'];

const PREPOSITIONS = new Set(['на', 'в', 'во', 'к', 'ко', 'до', 'по', 'с', 'со']);
const PREPOSITION = `(?:${[...PREPOSITIONS].join('|')})`;
/** Число или диапазон: «5», «5–7», «15 - 16». */
const DAY_NUMBER = '\\d{1,2}(?:\\s*[–—-]\\s*\\d{1,2})?';

/**
 * Хвостовая дата: предлог, число и месяц, день недели или «завтра».
 *
 * Собирается один раз: перебор вариантов в бою на каждой реплике —
 * лишняя работа, а список закрытый.
 */
const TAIL = new RegExp(
  '[\\s,]+' +
    `(?:${PREPOSITION}\\s+)?` +
    '(?:' +
    `${DAY_NUMBER}\\s+(?:${MONTHS.join('|')})` +
    `|(?:${MONTHS.join('|')})\\s+${DAY_NUMBER}` +
    `|${DAY_NUMBER}\\s*[.\\/]\\s*\\d{1,2}` +
    `|${WEEKDAYS.join('|')}` +
    `|${RELATIVE.join('|')}` +
    `|(?:следующей|этой|будущей|прошлой)\\s+недел[еюи]` +
    ')' +
    '\\s*[.!]?$',
  'iu',
);

/**
 * Заголовок без хвостовой даты — для цитирования рядом с настоящей датой.
 *
 * Если после срезания не остаётся ни слова, возвращается исходный
 * заголовок: «в четверг» само по себе — плохая цитата, но лучше пустой.
 */
export function titleWithoutDate(text: string): string {
  const trimmed = text.trim();
  const cut = trimmed.replace(TAIL, '').trim();

  if (cut.length === 0) return trimmed;

  /**
   * Мусорный хвост после срезания: «поездку на» без даты читается
   * оборванным. Предлог, оставшийся последним словом, убирается тоже.
   *
   * **По словам, а не регулярным выражением, и это не вкусовщина.**
   * Первая версия срезала хвост шаблоном — и «в» из списка предлогов
   * съело последнюю букву у «шагов»: получилось «нахаживать 10 000
   * шаго». Поймали тесты сразу же. Со словами такой ошибки не бывает.
   */
  const words = cut.replace(/,\s*$/u, '').split(/\s+/u);
  const last = words.at(-1)?.toLowerCase() ?? '';

  if (PREPOSITIONS.has(last)) words.pop();

  /**
   * Ничего не осталось — значит заголовок и был одной датой.
   *
   * Поймал собственный тест: «в четверг» превращалось в «в». Огрызок
   * хуже, чем нетронутый заголовок.
   */
  return words.length === 0 ? trimmed : words.join(' ');
}
