import { describe, expect, it } from 'vitest';

import { titleWithoutDate } from './title-date.js';

/**
 * Срезание хвостовой даты из цитаты (задача 3.21 пункт 3).
 *
 * Случаев «не трогать» здесь больше, чем «срезать», и это главное:
 * оставленная дата — неаккуратность, срезанное лишнее — искажение слов
 * человека. Оба примера ниже, из-за которых починка и делалась, взяты с
 * боевого дословно.
 */

describe('срезает хвостовую дату', () => {
  it.each([
    // Оба случая с боевого.
    ['Запланировать поездку на 5–7 сентября', 'Запланировать поездку'],
    ['записать сына к врачу в четверг', 'записать сына к врачу'],
    // Прочие живые формы.
    ['Записаться к врачу в пятницу', 'Записаться к врачу'],
    ['купить корм коту на завтра', 'купить корм коту'],
    ['сдать отчёт до пятницы', 'сдать отчёт'],
    ['оплатить садик 15 сентября', 'оплатить садик'],
    ['позвонить в налоговую на следующей неделе', 'позвонить в налоговую'],
    ['забрать посылку 05.09', 'забрать посылку'],
    ['разобрать шкаф в воскресенье.', 'разобрать шкаф'],
    ['сходить в зал, в среду', 'сходить в зал'],
  ])('«%s» → «%s»', (before, after) => {
    expect(titleWithoutDate(before)).toBe(after);
  });
});

/**
 * Дата первым словом (задача 3.77).
 *
 * **Два случая ниже переписаны по смыслу 05.09.2026.** Они охраняли
 * решение «срезаем только хвост» — и по боевым данным это решение
 * оказалось неверным: напоминание читалось «**Сегодня** срок: **Завтра**
 * надо купить собаке новый ошейник». Одна строка, одно дело, два разных
 * дня; человек читает это как поломку.
 *
 * Прежняя причина — «вырезать дату из середины значит калечить слова
 * человека» — осталась в силе и охраняется случаями ниже: середину не
 * трогаем. Речь про день говорит первым словом, и таких записей в базе
 * было три сразу.
 */
describe('срезает дату в начале', () => {
  it.each([
    // Все три с боевого, дословно.
    ['Завтра надо купить собаке новый ошейник', 'надо купить собаке новый ошейник'],
    ['Завтра нужно заехать в аптеку и купить витамины', 'нужно заехать в аптеку и купить витамины'],
    [
      'Завтра вечером сессия бросает структуру главной страницы',
      'вечером сессия бросает структуру главной страницы',
    ],
    // Прежде эти два охраняли обратное решение.
    ['С 15 сентября начать ходить 10 000 шагов', 'начать ходить 10 000 шагов'],
    ['в четверг записать сына к врачу', 'записать сына к врачу'],
    ['В воскресенье надо отвезти собаку к грумеру', 'надо отвезти собаку к грумеру'],
    ['5 сентября день рождения у мамы', 'день рождения у мамы'],
  ])('«%s» → «%s»', (before, after) => {
    expect(titleWithoutDate(before)).toBe(after);
  });

  describe('чего срезать нельзя', () => {
    it('союз после даты означает перечисление', () => {
      /**
       * «Сегодня и завтра нужно…» без первого слова читается оборванным,
       * а оборванная фраза хуже лишней даты. Ограда именно на это.
       */
      expect(titleWithoutDate('Сегодня и завтра нужно поливать рассаду')).toBe(
        'Сегодня и завтра нужно поливать рассаду',
      );
    });

    it('от заголовка должно остаться больше одного слова', () => {
      // «Завтра зал» дало бы «зал» — не фраза, а огрызок.
      expect(titleWithoutDate('Завтра зал')).toBe('Завтра зал');
      expect(titleWithoutDate('в пятницу баня')).toBe('в пятницу баня');
    });

    it('смягчающее слово не висит после срезанной даты', () => {
      /**
       * С боевого: «…посмотреть первый урок по сетям желательно в
       * субботу». Срезав «в субботу», «желательно» остаётся висеть
       * последним словом — то же, что оборванный предлог.
       */
      expect(titleWithoutDate('посмотреть первый урок по сетям желательно в субботу')).toBe(
        'посмотреть первый урок по сетям',
      );

      // В середине фразы такое слово значимо и остаётся.
      const middle = 'желательно позвонить врачу утром';
      expect(titleWithoutDate(middle)).toBe(middle);
    });

    it('дату из середины не трогает — прежнее решение в силе', () => {
      const middle = 'Купить в пятницу корм и заехать на мойку в город';
      expect(titleWithoutDate(middle)).toBe(middle);
    });
  });
});

describe('не трогает того, что датой не является', () => {
  it.each([
    // «День рождения» подразумевает дату, но не называет её. Ровно на
    // этом контрольный набор ловил выдуманные сроки.
    'купить подарок на день рождения',
    'поздравить Любу с днём рождения',
    'спланировать годовщину родителей',
    // Время — не дата. Срок хранится датой, и часам противоречить нечему.
    'договориться с няней, чтобы приходила не в 11, а в 9',
    'позвонить в 9 30',
    // Числа, которые не про календарь.
    'нахаживать 10 000 шагов',
    'дочитать книгу до 120 страницы',
  ])('«%s»', (text) => {
    expect(titleWithoutDate(text)).toBe(text);
  });
});

describe('края', () => {
  it('заголовок из одной даты остаётся как есть', () => {
    // Срезать всё — значит процитировать пустоту.
    expect(titleWithoutDate('в четверг')).toBe('в четверг');
    expect(titleWithoutDate('5 сентября')).toBe('5 сентября');
  });

  it('оборванный предлог убирается вместе с датой', () => {
    // «поездку на» читается как обрыв связи, а не как заголовок.
    expect(titleWithoutDate('перенести поездку на 8 сентября')).toBe('перенести поездку');
  });

  it('повторное применение ничего не меняет', () => {
    const once = titleWithoutDate('Запланировать поездку на 5–7 сентября');

    expect(titleWithoutDate(once)).toBe(once);
  });

  it('пустое и пробелы не ломают', () => {
    expect(titleWithoutDate('')).toBe('');
    expect(titleWithoutDate('   ')).toBe('');
  });
});
