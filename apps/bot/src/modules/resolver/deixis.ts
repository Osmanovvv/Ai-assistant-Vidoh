const TIME_STEMS =
  /^(?:понедельник|вторник|сред[ауе]|четверг|пятниц|суббот|воскресень|перв|втор|трет|четв[её]рт|пят|шест|седьм|восьм|девят|десят|одиннадцат|двенадцат)/u;

function tokens(text: string): readonly string[] {
  return text
    .toLowerCase()
    .replace(/ё/gu, 'е')
    .split(/[^\p{L}\d]+/u)
    .filter((word) => word.length > 0);
}

function known(word: string): boolean {
  return (
    POINTERS.has(word) ||
    CANCEL.has(word) ||
    COMPLETE.has(word) ||
    OTHER_COMMANDS.has(word) ||
    NOUNS.has(word) ||
    FILLERS.has(word) ||
    NEGATIONS.has(word) ||
    TIME.has(word) ||
    /^\d{1,4}$/u.test(word) ||
    TIME_STEMS.test(word)
  );
}

/** Реплика указывает на запись словом «это», не называя дела. */
export function pointsAtLast(text: string): boolean {
  const words = tokens(text);
  return words.some((word) => POINTERS.has(word)) && words.every(known);
}

/** Что сделать с указанным: убрать, отметить — или не ясно из слов. */
export function deicticAction(text: string): 'cancel' | 'complete' | undefined {
  const words = tokens(text);
  if (words.some((word) => CANCEL.has(word))) return 'cancel';
  if (words.some((word) => COMPLETE.has(word))) return 'complete';
  return undefined;
}

/**
 * Дело не названо (решение Никиты 23.09.2026): «Перенеси дело на пол 3»,
 * «перенеси на пол 3», «удали дело». Ни одного слова дела, но есть приказ,
 * «это» или само слово «дело» — речь о последнем обсуждённом, а не о том,
 * что покажется модели (на бою она выбрала «Купить хлеб» наугад).
 *
 * Самопоправки вроде «давай в 10 30», «нет, в пятницу» сюда не попадают:
 * приказа о записи в них нет, их разбирает модель по соседям в выгрузке.
 */
export function namesNoDeed(text: string): boolean {
  const words = tokens(text);
  const aboutRecord = words.some(
    (word) =>
      POINTERS.has(word) ||
      NOUNS.has(word) ||
      CANCEL.has(word) ||
      COMPLETE.has(word) ||
      OTHER_COMMANDS.has(word),
  );
  /**
   * Короткая поправка без дела (решение Никиты 23.09.2026): «а лучше в
   * 5», «нет, в пятницу» сразу после ответа бота — назван только новый
   * срок, дело не названо. Самопоправки внутри одной выгрузки сюда не
   * попадают: их отсекает вызывающий, там дело названо рядом.
   */
  const namesTime = words.some(
    (word) => TIME_CONTENT.has(word) || /^\d{1,4}(?::\d{2})?$/u.test(word) || TIME_STEMS.test(word),
  );
  return (aboutRecord || namesTime) && words.every(known);
}

/**
 * Приказ о записи без названия дела: «Перенеси дело на пол 3», «удали
 * это». В отличие от голой поправки («нет, в пятницу»), где назван только
 * срок, — здесь человек распоряжается записью, и перенос предлагается
 * вопросом (решение Никиты 23.09.2026).
 */
export function commandsRecord(text: string): boolean {
  return tokens(text).some(
    (word) =>
      POINTERS.has(word) ||
      NOUNS.has(word) ||
      CANCEL.has(word) ||
      COMPLETE.has(word) ||
      OTHER_COMMANDS.has(word),
  );
}
