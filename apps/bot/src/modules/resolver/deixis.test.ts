import { describe, expect, it } from 'vitest';

import { deicticAction, namesNoDeed, pointsAtLast } from './deixis.js';

/**
 * «Удали это дело» (живой прогон Никиты 23.09.2026, 03:16).
 *
 * Бот только что ответил про «Забрать посылку», человек сказал «удали
 * это дело» — и модель вернула номер записи вне списка: «это» ей не на
 * что опереть. Бот отложил слова и попросил сказать ещё раз.
 *
 * Указание без названия — работа кода: «это», «его» — та запись, которую
 * только что трогали, если она одна.
 */
describe('указание вместо названия', () => {
  it.each([
    'Удали это дело',
    'удали его',
    'отмени это',
    'Это сделала',
    'убери эту задачу',
    'удали, пожалуйста, это',
    'перенеси его на пятницу',
    'перенеси это на пол 1',
    'давай его на завтра в 10 утра',
  ])('«%s» — указание', (text) => {
    expect(pointsAtLast(text)).toBe(true);
  });

  it.each([
    'удали посылку',
    'надо это обдумать',
    'купить хлеб',
    'это важно для мамы',
    'перенеси врача на пятницу',
    'удали',
    '',
  ])('«%s» — не указание', (text) => {
    expect(pointsAtLast(text)).toBe(false);
  });
});

describe('что сделать с указанным', () => {
  it.each([
    ['Удали это дело', 'cancel'],
    ['убери его', 'cancel'],
    ['отмени это', 'cancel'],
    ['вычеркни это', 'cancel'],
    ['Это сделала', 'complete'],
    ['готово, это выполнила', 'complete'],
  ])('«%s» — %s', (text, action) => {
    expect(deicticAction(text)).toBe(action);
  });

  it('перенос — не отмена и не выполнение: срок разбирает модель', () => {
    expect(deicticAction('перенеси его на пятницу')).toBeUndefined();
  });
});

describe('дело не названо (решение Никиты 23.09.2026)', () => {
  /**
   * «Перенеси дело на пол 3» — модель выбрала наугад и спросила «Перенести
   * «Купить хлеб»?». Реплика, в которой нет ни одного слова дела, а есть
   * приказ, «это» или само слово «дело», — про последнее обсуждённое, а
   * не про то, что модели показалось.
   */
  it.each([
    'Перенеси дело на пол 3',
    'перенеси на пол 3',
    'удали дело',
    'Удали это дело',
    'сдвинь на завтра',
  ])('«%s» — дело не названо', (text) => {
    expect(namesNoDeed(text)).toBe(true);
  });

  it.each([
    // Дело названо.
    'перенеси врача на пятницу',
    'перенеси посылку на пол 1',
    'купить хлеб',
    // Ни дела, ни срока — не о чем говорить.
    'нет',
    'не надо',
    'ну давай',
    '',
  ])('«%s» — не то', (text) => {
    expect(namesNoDeed(text)).toBe(false);
  });
});

describe('короткая поправка без дела (решение Никиты 23.09.2026)', () => {
  /**
   * Бот ответил про посылку, человек тут же: «а лучше в 5». Дело не
   * названо, назван только новый срок — это про последнее обсуждённое.
   * Раньше модель выбирала наугад. Самопоправки внутри одной выгрузки
   * («к врачу в четверг, нет, в пятницу») это правило не трогает: их
   * отсекает вызывающий — в своей выгрузке дело названо рядом.
   */
  it.each([
    'а лучше в 5',
    'нет, в пятницу',
    'лучше в пятницу',
    'давай в 10 30',
    'давай на завтра',
    'не в пятницу, а в субботу',
    'на 17:00',
  ])('«%s» — дело не названо, назван срок', (text) => {
    expect(namesNoDeed(text)).toBe(true);
  });
});

describe('короткая поправка — и в новых формах времени (23.09.2026)', () => {
  it.each([
    'А лучше без 15 6.',
    'а лучше на час позже',
    'давай в пять вечера',
    'лучше через полчаса',
    'в четверть седьмого',
    'давай 15 минут седьмого',
    'на полчаса раньше',
    'в полночь',
  ])('«%s» — дело не названо, назван срок', (text) => {
    expect(namesNoDeed(text)).toBe(true);
  });
});
