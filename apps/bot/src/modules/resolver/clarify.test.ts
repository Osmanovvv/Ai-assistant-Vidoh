import { describe, expect, it } from 'vitest';

import { clarifiedCommand } from './clarify.js';

/**
 * Ответ на уточнение (живой прогон Никиты 23.09.2026, 12:50).
 *
 * «Перенеси дело на пол 4» — «Какое дело? Назови его — и сделаю.» —
 * «Забрать посылку» — и бот принял ответ за новое дело: о чём спрашивал,
 * он не помнил. Здесь только сборка команды из вопроса и ответа.
 */
describe('какое дело — ответ называет дело', () => {
  it('дело к команде: «Забрать посылку» после «Перенеси дело на пол 4»', () => {
    expect(clarifiedCommand('which', 'Перенеси дело на пол 4.', 'Забрать посылку')).toBe(
      'Перенеси дело на пол 4 — Забрать посылку',
    );
  });

  it.each([
    // Новая команда — не ответ, а своя правка.
    'перенеси врача на пятницу',
    'удали это',
    // Вопрос — не ответ.
    'а что у меня на завтра?',
    // Длинная реплика — уже новая мысль, а не название дела.
    'надо ещё купить хлеб молоко яйца и позвонить маме вечером',
    '',
  ])('«%s» — не ответ', (answer) => {
    expect(clarifiedCommand('which', 'Перенеси дело на пол 4.', answer)).toBeUndefined();
  });
});

describe('утро или вечер — ответ называет время', () => {
  it.each([
    ['утра', 'Перенеси посылку на пол 12 утра'],
    ['утром', 'Перенеси посылку на пол 12 утра'],
    ['днём', 'Перенеси посылку на пол 12 дня'],
    ['вечера', 'Перенеси посылку на пол 12 вечера'],
    ['в 11:30', 'Перенеси посылку в 11:30'],
    ['давай в 23:30', 'Перенеси посылку давай в 23:30'],
  ])('«%s»', (answer, command) => {
    expect(clarifiedCommand('time', 'Перенеси посылку на пол 12.', answer)).toBe(command);
  });

  it.each(['купить хлеб', 'в 9', 'не знаю'])('«%s» — не ответ', (answer) => {
    expect(clarifiedCommand('time', 'Перенеси посылку на пол 12.', answer)).toBeUndefined();
  });
});
