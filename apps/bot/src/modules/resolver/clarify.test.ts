import { describe, expect, it } from 'vitest';

import { clockTimesIn, hourWithoutDay } from '../classifier/clock-time.js';

import { clarifiedCommand, hourClarifyCommand, hourClarifyTitle } from './clarify.js';

/**
 * Ответ на уточнение (живой прогон Никиты 23.09.2026, 12:50).
 *
 * «Перенеси дело на пол 4» — «Какое дело? Назови его — и сделаю.» —
 * «Забрать посылку» — и бот принял ответ за новое дело: о чём спрашивал,
 * он не помнил. Здесь только сборка команды из вопроса и ответа.
 */
describe('какое дело — ответ называет дело', () => {
  it('дело к команде: «Забрать посылку» после «Перенеси дело на пол 4»', () => {
    expect(clarifiedCommand('which', 'Перенеси дело на пол 4.', 'Забрать посылку')).toBe(
      'Перенеси дело на пол 4 — Забрать посылку',
    );
  });

  it.each([
    // Новая команда — не ответ, а своя правка.
    'перенеси врача на пятницу',
    'удали это',
    // Вопрос — не ответ.
    'а что у меня на завтра?',
    // Длинная реплика — уже новая мысль, а не название дела.
    'надо ещё купить хлеб молоко яйца и позвонить маме вечером',
    '',
  ])('«%s» — не ответ', (answer) => {
    expect(clarifiedCommand('which', 'Перенеси дело на пол 4.', answer)).toBeUndefined();
  });
});

describe('утро или вечер — ответ называет время', () => {
  it.each([
    ['утра', 'Перенеси посылку на пол 12 утра'],
    ['утром', 'Перенеси посылку на пол 12 утра'],
    ['днём', 'Перенеси посылку на пол 12 дня'],
    ['вечера', 'Перенеси посылку на пол 12 вечера'],
    ['в 11:30', 'Перенеси посылку в 11:30'],
    ['давай в 23:30', 'Перенеси посылку давай в 23:30'],
  ])('«%s»', (answer, command) => {
    expect(clarifiedCommand('time', 'Перенеси посылку на пол 12.', answer)).toBe(command);
  });

  it.each(['купить хлеб', 'в 9', 'не знаю'])('«%s» — не ответ', (answer) => {
    expect(clarifiedCommand('time', 'Перенеси посылку на пол 12.', answer)).toBeUndefined();
  });
});

/**
 * Переспрос о часе нового дела (вариант Б, решение Никиты 24.09.2026):
 * «Забрать ребёнка в 7» — «Во сколько — 07:00 или 19:00?». Команда,
 * которую доделает ответ, — перенос этого дела на час без части суток.
 */
describe('утро или вечер у нового дела — команда для ответа', () => {
  it.each<[string, number, string, number]>([
    ['Забрать ребёнка в 7', 7 * 60, 'Вечером', 19 * 60],
    ['Забрать ребёнка в 7', 7 * 60, 'утром', 7 * 60],
    ['Забрать ребёнка в 7', 7 * 60, 'в 19:30', 19 * 60 + 30],
    ['Позвонить маме в половине десятого', 9 * 60 + 30, 'вечером', 21 * 60 + 30],
    ['Позвонить маме', 10 * 60 + 15, 'вечером', 22 * 60 + 15],
  ])('«%s» (%i мин), ответ «%s»', (title, morning, answer, expected) => {
    const command = hourClarifyCommand(title, morning);
    const done = clarifiedCommand('time', command, answer);

    expect(done).toBeDefined();
    expect(clockTimesIn(done ?? '')).toEqual([[expected]]);
    // Дня в команде нет — перенос меняет только час.
    expect(hourWithoutDay(done ?? '')).toBe(true);
  });

  it('название из команды переспроса — для ответа прямо к делу; своя команда человека — не она', () => {
    expect(hourClarifyTitle('Перенеси «Забрать ребенка» в 7')).toBe('Забрать ребенка');
    expect(hourClarifyTitle(hourClarifyCommand('Позвонить маме', 9 * 60 + 30))).toBe(
      'Позвонить маме',
    );
    expect(hourClarifyTitle('Перенеси посылку на пол 12')).toBeUndefined();
  });

  it('название — без часа: «Перенеси «Забрать ребёнка» в 7»', () => {
    expect(hourClarifyCommand('Забрать ребёнка в 7', 7 * 60)).toBe(
      'Перенеси «Забрать ребёнка» в 7',
    );
  });
});

/**
 * Разговорные ответы на «утро или вечер?» (проверка Никиты 24.09.2026):
 * «вечерком», «с утра», «к вечеру» бот не понимал — реплика шла мыслью,
 * вопрос терялся. «Утром в 8» — час называет человек, а не вопрос.
 */
describe('утро или вечер — разговорные ответы', () => {
  const command = hourClarifyCommand('Забрать ребенка в 7', 7 * 60);

  it.each<[string, number]>([
    ['вечерком', 19 * 60],
    ['Ну давай вечерком', 19 * 60],
    ['утречком', 7 * 60],
    ['с утра', 7 * 60],
    ['к вечеру', 19 * 60],
    ['под вечер', 19 * 60],
    ['рано утром', 7 * 60],
    ['поздно вечером', 19 * 60],
    ['семь вечера', 19 * 60],
    ['восемь утра', 8 * 60],
    ['утром в 8', 8 * 60],
    ['вечером в 8', 20 * 60],
    ['в 8 вечера', 20 * 60],
  ])('«%s»', (answer, expected) => {
    const done = clarifiedCommand('time', command, answer);

    expect(done).toBeDefined();
    expect(clockTimesIn(done ?? '')).toEqual([[expected]]);
    expect(hourWithoutDay(done ?? '')).toBe(true);
  });

  it.each(['вечерком купить хлеб', 'в обед', 'вечером в пятницу', 'в 8'])(
    '«%s» — не ответ',
    (answer) => {
      expect(clarifiedCommand('time', command, answer)).toBeUndefined();
    },
  );
});
