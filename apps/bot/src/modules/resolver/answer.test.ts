import { describe, expect, it } from 'vitest';

import { answerRemainder, readAnswer } from './answer.js';

/**
 * Чтение голосового ответа на уточняющий вопрос (§7.3 ТЗ, задача 3.6).
 *
 * План называет формулировки, на которых это обязано работать: «да»,
 * «нет», «к прошлой», «это новое», «не знаю». Все пять здесь, и вокруг
 * них — то, обо что словарь легко разбивается: живая речь с «нет» в
 * начале и направлением в конце, и слова, внутри которых спрятались
 * короткие «да» и «не».
 */

describe('пять формулировок из плана', () => {
  it('«да» — добавить к прошлой', () => {
    expect(readAnswer('да')).toBe('attach');
  });

  it('«нет» — это новое', () => {
    expect(readAnswer('нет')).toBe('separate');
  });

  it('«к прошлой» — добавить', () => {
    expect(readAnswer('к прошлой')).toBe('attach');
  });

  it('«это новое» — отдельно', () => {
    expect(readAnswer('это новое')).toBe('separate');
  });

  it('«не знаю» — непонятно, и толковать нельзя', () => {
    // Человек ничего не решил. Делать вид, что решил, — значит решить
    // за него, а §7.3 запрещает боту угадывать.
    expect(readAnswer('не знаю')).toBe('unclear');
  });
});

describe('живая речь', () => {
  it('согласие в разных видах', () => {
    for (const text of ['ага', 'угу', 'да, верно', 'точно, про неё', 'конечно']) {
      expect(readAnswer(text), text).toBe('attach');
    }
  });

  it('отказ в разных видах', () => {
    for (const text of ['неа', 'нет, отдельная история', 'это другое', 'не связано']) {
      expect(readAnswer(text), text).toBe('separate');
    }
  });

  it('направление важнее согласия', () => {
    // «Нет, к прошлой» — человек отрицает вторую половину вопроса, а не
    // первую. Проверь мы сначала «нет», ответ ушёл бы наоборот.
    expect(readAnswer('нет, к прошлой')).toBe('attach');
    expect(readAnswer('нет, добавь к той')).toBe('attach');
  });

  it('незнание сильнее отказа', () => {
    // «Не знаю» начинается с «не» и без отдельной проверки читалось бы
    // как уверенное «это новое».
    for (const text of ['не знаю', 'да не знаю я', 'нет, не помню', 'без понятия']) {
      expect(readAnswer(text), text).toBe('unclear');
    }
  });
});

describe('чего словарь не должен путать', () => {
  it('короткие слова внутри длинных не считаются', () => {
    // «Нести», «неделя», «дать» содержат «не» и «да» подстрокой.
    // Границы слова через `\b` кириллицу не видят, отсюда разбиение.
    for (const text of ['нести продукты', 'неделя', 'дать ответ']) {
      expect(readAnswer(text), text).not.toBe('separate');
      expect(readAnswer(text), text).not.toBe('attach');
    }

    // Одно слово — непонятно; два слова содержания — мысль (3.44),
    // и она уйдёт в разбор, а не пропадёт.
    expect(readAnswer('неделя')).toBe('unclear');
    expect(readAnswer('нести продукты')).toBe('content');
    expect(readAnswer('дать ответ')).toBe('content');
  });

  it('пустой и бессмысленный ответ — непонятно', () => {
    for (const text of ['', '   ', '???', 'ммм']) {
      expect(readAnswer(text), text).toBe('unclear');
    }
  });

  it('«ё» и регистр не мешают', () => {
    expect(readAnswer('Да, про неё')).toBe('attach');
  });
});

describe('содержание — не ответ (задача 3.44)', () => {
  /**
   * Живой прогон 03.09.2026: бот спросил «это про „Купить зонт" или
   * отдельная история?», человек сказал «добавь ещё купить чехол для
   * зонта». Голый глагол «добавь» прочитался как «к прошлой»: правка
   * применилась, а «купить чехол» пропало без следа. §9 запрещает.
   */
  it('глагол с содержанием — мысль, а не согласие', () => {
    expect(readAnswer('добавь ещё купить чехол для зонта')).toBe('content');
    expect(readAnswer('запиши купить хлеб и молоко')).toBe('content');
    expect(readAnswer('перенеси встречу с бухгалтером')).toBe('content');
  });

  it('согласие или отказ с содержанием — тоже мысль', () => {
    expect(readAnswer('да, купить хлеб')).toBe('content');
    expect(readAnswer('нет, позвонить маме вечером')).toBe('content');
  });

  it('голый глагол и короткое согласие остаются ответом', () => {
    expect(readAnswer('добавь')).toBe('attach');
    expect(readAnswer('перенеси')).toBe('attach');
    expect(readAnswer('да')).toBe('attach');
    expect(readAnswer('нет')).toBe('separate');
    // Одно слово содержания — не мысль: «добавь записи» огрызок.
    expect(readAnswer('добавь туда')).toBe('attach');
  });

  it('названное направление решает, даже если дальше есть слова', () => {
    // Человек сказал, куда, — это ответ. Остаток сохранится отдельно.
    expect(readAnswer('да, к прошлой, и ещё купить чехол')).toBe('attach');
    expect(readAnswer('нет, это новое, и купить хлеб')).toBe('separate');
  });

  it('остаток ответа — слова сверх словаря, не меньше двух', () => {
    expect(answerRemainder('да, к прошлой, и ещё купить чехол')).toBe('купить чехол');
    expect(answerRemainder('добавь ещё купить чехол для зонта')).toBe('купить чехол для зонта');
    expect(answerRemainder('да, к прошлой')).toBe('');
    expect(answerRemainder('добавь туда')).toBe('');
    expect(answerRemainder('')).toBe('');
  });
});

/**
 * Разговорные ответы (проверка Никиты 24.09.2026). На «Перенести «X»?»
 * «давай», «ок», «хорошо» читались непонятым ответом — «Не разобрала
 * ответ, ничего не меняла». На «Это про «X» или отдельная история?» они
 * ничего не выбирают и остаются непонятыми.
 */
describe('«Перенести «X»?» — разговорное согласие', () => {
  it.each([
    'давай',
    'ок',
    'окей',
    'хорошо',
    'ладно',
    'можно',
    'согласна',
    'пойдёт',
    'давай, переноси',
  ])('«%s» — да', (text) => {
    expect(readAnswer(text, { move: true })).toBe('attach');
  });

  it('на «Это про «X» или отдельная история?» «давай» и «ок» — по-прежнему не ответ', () => {
    expect(readAnswer('давай')).toBe('unclear');
    expect(readAnswer('ок')).toBe('unclear');
    expect(readAnswer('хорошо')).toBe('unclear');
  });

  it('прежние ответы на перенос не изменились', () => {
    expect(readAnswer('да', { move: true })).toBe('attach');
    expect(readAnswer('нет', { move: true })).toBe('separate');
    expect(readAnswer('не знаю', { move: true })).toBe('unclear');
    expect(readAnswer('да, купить хлеб', { move: true })).toBe('content');
  });
});

describe('«да нет» — это нет', () => {
  it.each([
    'да нет',
    'конечно нет',
    'не надо',
    'давай не надо',
    'не нужно',
    'не стоит',
    'не переноси',
    'не трогай',
  ])('«%s»', (text) => {
    expect(readAnswer(text, { move: true })).toBe('separate');
    expect(readAnswer(text)).toBe('separate');
  });
});

/**
 * Замер docs/eval-dialog (28.09.2026): на «Это про «X» или отдельная
 * история?» «Не про то» читалось «к прошлой» («про то» внутри), а вопрос
 * «Что значит отдельная?» — ответом «отдельно».
 */
describe('«не так» из замера: отрицание и встречный вопрос', () => {
  it.each(['Не про то', 'не про неё', 'Это не то'])('«%s» — отдельно', (text) => {
    expect(readAnswer(text)).toBe('separate');
  });

  it.each(['Что значит отдельная?', 'Добавить к прошлой — это как?', 'Какую посылку?', 'Да?'])(
    '«%s» — вопрос, а не ответ: ни направления, ни согласия',
    (text) => {
      expect(['content', 'unclear']).toContain(readAnswer(text, { move: true }));
    },
  );

  it('«Нет, к прошлой» — по-прежнему к прошлой', () => {
    expect(readAnswer('Нет, к прошлой')).toBe('attach');
  });
});
