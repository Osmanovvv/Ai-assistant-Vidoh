import { describe, expect, it } from 'vitest';

import { restoreUncovered } from './coverage.js';
import type { Segment } from './router.service.js';

/**
 * Обрезанный ответ маршрутизатора (бой 21.09.2026, выгрузка Никиты;
 * воспроизведено на стенде 21.09, след `docs/eval-live-21-09/runs/…14-34-22`).
 *
 * Восемь дел одним голосовым на 447 знаков. Модель вернула три отрезка
 * `DUMP`, и третий оборвала на «Её в клинику ветеринарную,» — хвоста
 * «потом надо будет позвонить маме… сделать в университете задания» в
 * её ответе нет вовсе. Четыре дела пропали молча: конвейер разбирает
 * только то, что в отрезках. Промпт не трогаем; страж в коде: кусок
 * текста, не покрытый ни одним отрезком, в котором есть слово долга или
 * глагол дела, возвращается в разбор мыслью на своём месте.
 */

const seg = (intent: Segment['intent'], text: string): Segment => ({ intent, text });

const INPUT =
  'В общем, смотри, мне сегодня надо будет сходить к стоматологу в 13 0 0 вот также. В 9 0 0 мне надо отнести компьютер на чистку, замена термопасты. Потом надо будет погулять с собакой, также завтра вечером надо будет отвезти. Ее в клинику ветеринарную, потом надо будет позвонить маме сегодня либо завтра. Вот также сходить купить еды, продукты, посмотреть уроки по изучению моего направления, сделать в университете задания, вот в общем вроде все.';

const ROUTED: readonly Segment[] = [
  seg('DUMP', 'В общем, смотри, мне сегодня надо будет сходить к стоматологу в 13 0 0 вот также.'),
  seg('DUMP', 'В 9 0 0 мне надо отнести компьютер на чистку, замена термопасты.'),
  seg(
    'DUMP',
    'Потом надо будет погулять с собакой, также завтра вечером надо будет отвезти. Её в клинику ветеринарную,',
  ),
];

describe('непокрытый отрезками кусок с делами возвращается в разбор', () => {
  it('обрезанный хвост с боя 21.09.2026 — четвёртый отрезок, мыслью, на своём месте', () => {
    const restored = restoreUncovered(INPUT, ROUTED);

    expect(restored).toHaveLength(4);
    expect(restored.slice(0, 3)).toEqual(ROUTED);
    expect(restored[3]?.intent).toBe('DUMP');
    expect(restored[3]?.text).toBe(
      'потом надо будет позвонить маме сегодня либо завтра. Вот также сходить купить еды, продукты, посмотреть уроки по изучению моего направления, сделать в университете задания, вот в общем вроде все.',
    );
  });

  it('пропуск посередине — тоже, между соседями', () => {
    const input = 'Надо купить хлеб. Ещё надо позвонить маме и записаться к врачу. Что у меня на завтра?';
    const restored = restoreUncovered(input, [
      seg('DUMP', 'Надо купить хлеб.'),
      seg('QUERY', 'Что у меня на завтра?'),
    ]);

    expect(restored).toEqual([
      seg('DUMP', 'Надо купить хлеб.'),
      seg('DUMP', 'Ещё надо позвонить маме и записаться к врачу.'),
      seg('QUERY', 'Что у меня на завтра?'),
    ]);
  });

  it('пересказ моделью — не пропуск: отрезки покрывают текст с точностью до слов', () => {
    const input = 'Надо купить хлеб, молоко и еще позвонить маме насчет выходных.';
    const routed = [seg('DUMP', 'Надо купить хлеб, молоко и ещё позвонить маме насчёт выходных')];

    expect(restoreUncovered(input, routed)).toEqual(routed);
  });

  it('непокрытый кусок без дел — приветствие, заполнители — не возвращается', () => {
    const input =
      'Выдох привет. Давай с тобой запишем планы на сегодня. Отдать ковер в химчистку. Вроде бы пока все из срочного.';
    const routed = [seg('DUMP', 'Отдать ковер в химчистку.')];

    expect(restoreUncovered(input, routed)).toEqual(routed);
  });

  it('короткий непокрытый кусок — меньше четырёх слов — не считается', () => {
    const input = 'Так, надо купить хлеб. Ну всё.';
    const routed = [seg('DUMP', 'надо купить хлеб.')];

    expect(restoreUncovered(input, routed)).toEqual(routed);
  });

  it('отрезок, которого в тексте нет, — сравнивать нечем: всё как есть', () => {
    const routed = [seg('DUMP', 'Совсем другой пересказ всего, что было сказано человеком.')];

    expect(restoreUncovered(INPUT, routed)).toEqual(routed);
  });

  it('пустой список отрезков не трогается: замена на одну мысль — дело маршрутизатора', () => {
    expect(restoreUncovered(INPUT, [])).toEqual([]);
  });
});
