/** Слова текста без знаков, «ё» приравнена к «е». */
function wordsOf(text: string): readonly string[] {
  return text
    .toLowerCase()
    .replace(/ё/gu, 'е')
    .split(/[^\p{L}]+/u)
    .filter((word) => word.length > 0);
}

function hasPhrase(words: readonly string[], phrase: string): boolean {
  const parts = phrase.replace(/ё/gu, 'е').split(' ');
  return words.some((_unused, index) =>
    parts.every((part, shift) => words[index + shift] === part),
  );
}

/** Отрезок, названный разговором, на самом деле несёт дело. */
export function looksLikeThought(text: string): boolean {
  const words = wordsOf(text);
  if (words.length === 0) return false;

  return (
    OBLIGATION.some((phrase) => hasPhrase(words, phrase)) ||
    ACTIONS.some((verb) => hasPhrase(words, verb))
  );
}

