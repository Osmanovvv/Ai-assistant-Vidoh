import { describe, expect, it } from 'vitest';

import { looksLikeThought } from './thought-words.js';

/**
 * Разговор с делами внутри (бой 21.09.2026, выгрузка Никиты).
 *
 * Восемь дел одним голосовым; маршрутизатор отдал три отрезка, и в
 * извлечение дошло на треть меньше текста, чем в маршрутизатор
 * (по токенам журнала: 98 против 62). Четыре дела — «позвонить маме»,
 * «купить продукты», «посмотреть уроки», «сделать задания» — пропали
 * молча: отрезок, названный моделью разговором, конвейер не разбирает.
 * Промпт маршрутизатора не трогаем; страж в коде: разговор, в котором
 * есть слово долга или глагол дела, — мысль.
 */
describe('разговор с делами внутри — мысль', () => {
  it('«надо», «нужно», «не забыть» — слова долга', () => {
    for (const text of [
      'потом надо будет позвонить маме сегодня либо завтра',
      'нужно ещё в аптеку зайти',
      'не забыть про садик',
      'мне обязательно к врачу',
    ]) {
      expect(looksLikeThought(text), text).toBe(true);
    }
  });

  it('глагол дела в перечислении — тоже мысль', () => {
    for (const text of [
      'Вот также сходить купить еды, продукты, посмотреть уроки по изучению моего направления, сделать в университете задания, вот в общем вроде все.',
      'ну и позвонить в банк',
      'забрать посылку',
    ]) {
      expect(looksLikeThought(text), text).toBe(true);
    }
  });

  it('разговор без дел остаётся разговором', () => {
    for (const text of [
      'вот в общем вроде все',
      'привет, как дела',
      'спасибо большое',
      'ну ладно, пока',
      'рада тебя видеть',
      'давай запишем планы на сегодня',
      'Выдох привет',
      'всё, устала',
      '',
    ]) {
      expect(looksLikeThought(text), text).toBe(false);
    }
  });

  it('слова правок и отмен мыслью не считаются: их разбирает резолвер', () => {
    for (const text of ['отменить стоматолога', 'перенести врача на пятницу']) {
      expect(looksLikeThought(text), text).toBe(false);
    }
  });
});
