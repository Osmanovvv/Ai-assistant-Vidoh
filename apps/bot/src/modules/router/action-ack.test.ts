import { describe, expect, it } from 'vitest';

import { onlyActionAck, onlyConversationAck, splitConversationAcks } from './action-ack.js';
import type { Segment } from './router.service.js';

describe('«Пошла делать» — подтверждение без нового дела', () => {
  it.each([
    'Супер. Пошла делать',
    'Пошла делать!',
    'Хорошо, я пошла делать.',
    'Ну всё, пойду делать',
    'Ок. Пошёл делать 👍',
    'СУПЕР!\nПОШЛА ДЕЛАТЬ',
    'Пойду сделаю',
    'Приступаю',
    'Начинаю',
    'Сейчас займусь',
    'Берусь за дело',
    'Займусь этим',
    'Спасибо, поняла, я приступаю',
  ])('«%s» — только подтверждение', (text) => {
    expect(onlyActionAck(text)).toBe(true);
  });

  it.each([
    'Пошла делать отчёт',
    'Супер. Пошла делать ужин',
    'Пойду делать маникюр завтра',
    'Надо пойти делать паспорт',
    'Пошла делать. Ещё купить хлеб',
    'Супер. Пошла делать. Позвонить маме',
    'Пошла делать?',
    'Не пошла делать',
    'Запиши «пошла делать»',
    'Пошла делать в 15:00',
    'Пошла делать 2',
    'Супер',
    'Приступаю к отчёту',
    'Начинаю новый курс',
    'Сейчас займусь отчётом',
    'Берусь за дело завтра',
    'Займусь этим вечером',
    'Завтра приступаю',
    'Не начинаю',
    'Готово',
    'Сделала',
    'Сделаю завтра',
    '',
  ])('«%s» — прежний разбор: есть дополнительные слова или вопрос', (text) => {
    expect(onlyActionAck(text)).toBe(false);
  });

  it('выделяет подтверждение, сохраняя настоящее дело после него', () => {
    expect(
      splitConversationAcks([
        { intent: 'DUMP', text: 'Супер. Пошла делать. Ещё надо купить хлеб.' },
      ]),
    ).toEqual([
      { intent: 'SMALLTALK', text: 'Супер. Пошла делать.' },
      { intent: 'DUMP', text: 'Ещё надо купить хлеб.' },
    ]);
  });

  it('настоящие дела с обеих сторон остаются на месте', () => {
    expect(
      splitConversationAcks([
        { intent: 'DUMP', text: 'Купить хлеб. Супер. Пошла делать. Позвонить маме.' },
      ]),
    ).toEqual([
      { intent: 'DUMP', text: 'Купить хлеб.' },
      { intent: 'SMALLTALK', text: 'Супер. Пошла делать.' },
      { intent: 'DUMP', text: 'Позвонить маме.' },
    ]);
  });

  it('текст с конкретным делом и переносы строк без подтверждения не меняются', () => {
    const segments: readonly Segment[] = [
      { intent: 'DUMP', text: 'Пошла делать отчёт.\nКупить хлеб.' },
    ];
    expect(splitConversationAcks(segments)).toEqual(segments);
  });

  it('ответы, правки, вопросы и отметки о выполнении не переопределяются', () => {
    const segments: readonly Segment[] = (
      ['ANSWER', 'PATCH', 'QUERY', 'COMPLETE', 'CANCEL'] as const
    ).map((intent) => ({ intent, text: 'Пошла делать' }));
    expect(splitConversationAcks(segments)).toEqual(segments);
  });
});

describe('подтверждение рядом с настоящим содержанием', () => {
  it.each(['Да, поняла', 'Спасибо, поняла', 'Супер, спасибо', 'Сейчас займусь'])(
    '«%s» — подтверждение',
    (text) => {
      expect(onlyConversationAck(text)).toBe(true);
    },
  );
  it.each(['Готово', 'Сделала', 'Сделаю завтра', 'На сегодня всё', 'Давай', 'Согласна'])(
    '«%s» остаётся своему сценарию',
    (text) => {
      expect(onlyConversationAck(text)).toBe(false);
    },
  );
  it.each([
    ['Спасибо, поняла, ещё надо позвонить маме', 'Спасибо, поняла,', 'ещё надо позвонить маме'],
    ['Приступаю, купить хлеб', 'Приступаю,', 'купить хлеб'],
    ['Супер!\n\nПошла делать.\nПозвонить маме', 'Супер!\n\nПошла делать.', 'Позвонить маме'],
    ['Спасибо; надо купить хлеб', 'Спасибо;', 'надо купить хлеб'],
  ])('«%s»: выделяет подтверждение, сохраняя дело дословно', (text, ack, deed) => {
    expect(splitConversationAcks([{ intent: 'DUMP', text }])).toEqual([
      { intent: 'SMALLTALK', text: ack },
      { intent: 'DUMP', text: deed },
    ]);
  });
  it.each([
    'Пойду делать, отчёт',
    'Приступаю, к отчёту',
    'Начинаю, новый курс',
    'Купить книгу «Спасибо, поняла. Пошла делать»',
    'Купить книгу "Супер. Приступаю"',
    "Купить книгу 'Супер. Приступаю'",
    'Купить книгу ‘Супер. Приступаю’',
    'Купить открытку, спасибо',
    'Купить книгу (название: Спасибо, поняла)',
    'Купить книгу «Супер. Приступаю',
  ])('«%s» не теряет продолжение или название', (text) => {
    const segments: readonly Segment[] = [{ intent: 'DUMP', text }];
    expect(splitConversationAcks(segments)).toEqual(segments);
  });
  it('разговорная разметка модели тоже сохраняет предмет после запятой', () => {
    const segments: readonly Segment[] = [
      { intent: 'SMALLTALK', text: 'Купить открытку, спасибо' },
    ];
    expect(splitConversationAcks(segments)).toEqual(segments);
  });
  it('цитата после подтверждения сохраняется дословно', () => {
    const deed = 'Купить книгу «Спасибо, поняла. Пошла делать»';
    expect(splitConversationAcks([{ intent: 'DUMP', text: `Отлично. ${deed}` }])).toEqual([
      { intent: 'SMALLTALK', text: 'Отлично.' },
      { intent: 'DUMP', text: deed },
    ]);
  });
});
