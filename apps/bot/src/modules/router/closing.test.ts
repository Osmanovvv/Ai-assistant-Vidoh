import { describe, expect, it } from 'vitest';

import { saidAsDone, splitClosings } from './closing.js';
import type { Segment } from './router.service.js';

/**
 * Два закрытия одним отрезком (серия голосовых 18.09.2026, голос 5).
 *
 * «Продукты купила уже, а в школу звонить не надо. Всё решилось» —
 * модель маршрутизатора отдала это одним `COMPLETE`. Резолвер получил
 * одну реплику про два разных дела, выбрать не смог, сказал «новая
 * мысль» — и школа осталась открытой, а слова легли черновиком. Промпт
 * не трогаем: отметка и отмена — по одному делу на отрезок, режем кодом.
 */

const seg = (intent: Segment['intent'], text: string): Segment => ({ intent, text });

describe('закрытия режутся по одному делу', () => {
  it('отметка и отмена через «а» — два отрезка, каждый со своим намерением', () => {
    const result = splitClosings([
      seg('COMPLETE', 'Продукты купила уже, а в школу звонить не надо. Все решилось,'),
    ]);

    expect(result).toEqual([
      seg('COMPLETE', 'Продукты купила уже'),
      seg('CANCEL', 'а в школу звонить не надо. Все решилось'),
    ]);
  });

  it('в обратном порядке: отмена, потом отметка', () => {
    const result = splitClosings([seg('CANCEL', 'В школу звонить не надо, а продукты я купила.')]);

    expect(result).toEqual([
      seg('CANCEL', 'В школу звонить не надо'),
      seg('COMPLETE', 'а продукты я купила.'),
    ]);
  });

  it('две отметки по предложениям — два отрезка', () => {
    const result = splitClosings([seg('COMPLETE', 'Продукты купила. К врачу сходила.')]);

    expect(result).toEqual([
      seg('COMPLETE', 'Продукты купила.'),
      seg('COMPLETE', 'К врачу сходила.'),
    ]);
  });

  it('часть без своего сказуемого — продолжение предыдущей: «Всё решилось» остаётся при отмене', () => {
    const result = splitClosings([
      seg('CANCEL', 'В школу звонить не надо. Все решилось. А продукты купила.'),
    ]);

    expect(result).toEqual([
      seg('CANCEL', 'В школу звонить не надо. Все решилось.'),
      seg('COMPLETE', 'А продукты купила.'),
    ]);
  });
});

describe('обрывок дня — начало следующей части, а не отдельная правка (стенд 27.09.2026, voice-27-02)', () => {
  /**
   * «И в пятницу. Забрать документы из МФЦ, они уже готовы.» маршрутизатор
   * отдал закрытием; резка сделала из «И в пятницу.» отдельный отрезок, и
   * резолвер, получив одну эту фразу, по правилу «короткая поправка — про
   * последнее обсуждённое» перенёс на пятницу шиномонтаж — чужое дело.
   */
  it('первая часть — один день: приклеена к следующей, отрезок остаётся целым', () => {
    const whole = seg('COMPLETE', 'И в пятницу. Забрать документы из МФЦ, они уже готовы.');

    expect(splitClosings([whole])).toEqual([whole]);
  });

  it('день между двумя частями уходит вперёд, к своему делу', () => {
    const result = splitClosings([
      seg('COMPLETE', 'Продукты купила. И в пятницу. К врачу сходила.'),
    ]);

    expect(result).toEqual([
      seg('COMPLETE', 'Продукты купила.'),
      seg('COMPLETE', 'И в пятницу. К врачу сходила.'),
    ]);
  });

  it('день в самом конце — хвост последней части: вперёд идти некуда', () => {
    const result = splitClosings([seg('COMPLETE', 'Продукты купила. К врачу сходила. В пятницу.')]);

    expect(result).toEqual([
      seg('COMPLETE', 'Продукты купила.'),
      seg('COMPLETE', 'К врачу сходила. В пятницу.'),
    ]);
  });
});

describe('что не трогается', () => {
  it.each([
    // Перечисление внутри одной отметки: у «и хлеб» своего сказуемого нет.
    ['COMPLETE', 'Купила продукты и хлеб.'],
    // Одно дело — один отрезок.
    ['COMPLETE', 'Мусор вынесла.'],
    ['CANCEL', 'С альбомом я передумала.'],
    // Запятая без союза не режет: «как ты просила» — не второе дело.
    ['COMPLETE', 'Записала сына к врачу, как ты просила.'],
    // Отрицание — не отметка: «не купила» не делает второй отрезок отметкой.
    ['COMPLETE', 'Продукты не купила и хлеб тоже.'],
  ] as const)('%s «%s» — тот же один сегмент', (intent, text) => {
    const input = [seg(intent, text)];

    expect(splitClosings(input)).toEqual(input);
  });

  it('мысли, вопросы, правки и ответы не разбираются', () => {
    const input = [
      seg('DUMP', 'Продукты купить, а в школу позвонить.'),
      seg('PATCH', 'не в среду, а в четверг'),
      seg('QUERY', 'что купила, а что нет?'),
      seg('ANSWER', 'да, а вторую не надо'),
    ];

    expect(splitClosings(input)).toEqual(input);
  });

  it('пустой список не ломает', () => {
    expect(splitClosings([])).toEqual([]);
  });
});

describe('сказано как о сделанном — любым родом (стенд 27.09.2026)', () => {
  it.each([
    'Позвонить маме, уже позвонил',
    'Мусор я уже вынес',
    'Посылку привез',
    'Продукты купила',
    'Все сделано',
    'К врачу больше не надо',
  ])('«%s» — сделано или отменено', (text) => {
    expect(saidAsDone(text)).toBe(true);
  });

  it.each(['Забрать документы из МФЦ, они уже готовы', 'Позвонить маме', 'Не позвонил маме'])(
    '«%s» — нет',
    (text) => {
      expect(saidAsDone(text)).toBe(false);
    },
  );
});
