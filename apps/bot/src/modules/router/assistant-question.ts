/**
 * Вопрос о самом ВЫДОХе, а не о сохранённых делах.
 *
 * Модель маршрутизатора иногда слышит в «расскажи, для чего ты нужна и
 * какая у тебя добавочная ценность» обычный вопрос к бэклогу из-за слов
 * «расскажи» и «можешь». Если такой сегмент оставить `QUERY`, пустой поиск
 * попадёт в журнал `backlog.nothing`. Здесь достаточно устойчивых признаков
 * самого помощника: они не затрагивают вопросы про дела пользователя.
 */
const ASSISTANT_VALUE =
  /(?<!\p{L})(?:добавочн\p{L}*\s+ценност\p{L}*|польз\p{L}*|ценност\p{L}*|возможност\p{L}*)(?!\p{L})/iu;
const ASSISTANT_ACTION =
  /(?<!\p{L})(?:расскаж\p{L}*|объясн\p{L}*|можеш\p{L}*|умееш\p{L}*|помож\p{L}*|помога\p{L}*|нужн\p{L}*|зачем|для\s+чего)(?!\p{L})/iu;
const ASSISTANT_SUBJECT = /(?<!\p{L})(?:ты|тебе|тебя|себе|сво\p{L}*)(?!\p{L})/iu;

export function looksLikeAssistantQuestion(text: string): boolean {
  return ASSISTANT_VALUE.test(text) && ASSISTANT_ACTION.test(text) && ASSISTANT_SUBJECT.test(text);
}
