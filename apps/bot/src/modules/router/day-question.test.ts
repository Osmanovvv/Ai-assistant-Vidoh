import { describe, expect, it } from 'vitest';

import { splitDayQuestions, withoutDayQuestions } from './day-question.js';
import type { Segment } from './router.service.js';

/**
 * Вопрос о дне внутри мысли (серия голосовых 18.09.2026, голос 3).
 *
 * «Надо позвонить в школу насчёт экскурсии. Кстати, что у меня там на
 * завтра и ещё платить интернет?» — расшифровка склеила вопрос и
 * следующую мысль в одно предложение со знаком вопроса. Модель
 * маршрутизатора либо оставила всё мыслью — и из вопроса вышло дело
 * «Проверить, что запланировано на завтра» со сроком, — либо назвала
 * вопросом вместе с «платить интернет», и мысль пропала бы в ответе.
 * Промпт не трогаем: вопрос о дне узнаётся кодом теми же словами, что
 * и при ответе на него.
 */

const seg = (intent: Segment['intent'], text: string): Segment => ({ intent, text });

describe('вопрос о дне внутри мысли выделяется', () => {
  it('из мысли: до вопроса — мысль, вопрос — вопрос, «и ещё …» после него — мысль', () => {
    const result = splitDayQuestions([
      seg(
        'DUMP',
        'Надо позвонить в школу на счет экскурсии. Кстати, что у меня там на завтра и еще платить интернет?',
      ),
    ]);

    expect(result).toEqual([
      seg('DUMP', 'Надо позвонить в школу на счет экскурсии.'),
      seg('QUERY', 'Кстати, что у меня там на завтра'),
      seg('DUMP', 'и еще платить интернет?'),
    ]);
  });

  it('из вопроса: «и ещё платить интернет» после вопроса о дне — мысль, а не часть вопроса', () => {
    const result = splitDayQuestions([
      seg('QUERY', 'Кстати, что у меня там на завтра и еще платить интернет?'),
    ]);

    expect(result).toEqual([
      seg('QUERY', 'Кстати, что у меня там на завтра'),
      seg('DUMP', 'и еще платить интернет?'),
    ]);
  });

  it('второй раз тот же вопрос о том же дне не задаётся: голосовое наговорили дважды', () => {
    const result = splitDayQuestions([
      seg('DUMP', 'Надо позвонить в школу насчет экскурсии.'),
      seg('QUERY', 'Кстати, что у меня там, на завтра?'),
      seg(
        'DUMP',
        'Надо позвонить в школу на счет экскурсии. Кстати, что у меня там на завтра и еще платить интернет?',
      ),
    ]);

    expect(result).toEqual([
      seg('DUMP', 'Надо позвонить в школу насчет экскурсии.'),
      seg('QUERY', 'Кстати, что у меня там, на завтра?'),
      seg('DUMP', 'Надо позвонить в школу на счет экскурсии.'),
      seg('DUMP', 'и еще платить интернет?'),
    ]);
  });

  it('вопрос о дне, названный моделью мыслью, становится вопросом целиком', () => {
    const result = splitDayQuestions([seg('DUMP', 'Что у меня на завтра?')]);

    expect(result).toEqual([seg('QUERY', 'Что у меня на завтра?')]);
  });

  it('предложения вокруг вопроса остаются по одной мысли с каждой стороны', () => {
    const result = splitDayQuestions([
      seg(
        'DUMP',
        'Купить хлеб. Позвонить маме. Что там на неделе? Оплатить садик. Забрать посылку.',
      ),
    ]);

    expect(result).toEqual([
      seg('DUMP', 'Купить хлеб. Позвонить маме.'),
      seg('QUERY', 'Что там на неделе?'),
      seg('DUMP', 'Оплатить садик. Забрать посылку.'),
    ]);
  });
});

describe('вопрос после «кстати» посреди предложения (голос 10, 18.09.2026)', () => {
  it('«…нет сил ни на что, кстати, что у меня на выходных и ещё надо разобрать балкон» — вопрос выделяется', () => {
    // Бой: расшифровка приклеила вопрос к предыдущей фразе запятой, и
    // вопрос лёг сведением «Что у меня запланировано на выходных?».
    const result = splitDayQuestions([
      seg(
        'DUMP',
        'И и вообще, я так устала за эту неделю. Просто нет сил ни на что, кстати, что у меня на выходных и еще и еще надо разобрать балкон.',
      ),
    ]);

    expect(result).toEqual([
      seg('DUMP', 'И и вообще, я так устала за эту неделю. Просто нет сил ни на что'),
      seg('QUERY', 'кстати, что у меня на выходных'),
      seg('DUMP', 'и еще и еще надо разобрать балкон.'),
    ]);
  });
});

describe('что не трогается', () => {
  it.each([
    // Обрывок про день без вопроса — продолжение мысли, а не вопрос.
    ['Купить хлеб. Надо на завтра.'],
    // День внутри дела: есть предмет — «готовить», «ужин».
    ['Надо решить, что завтра готовить на ужин.'],
    // «И ещё» после мысли, а не после вопроса, — обычное перечисление.
    ['Записать сына к врачу в четверг, и ещё купить корм.'],
    // Вопрос про предмет, а не про день.
    ['Что у меня по банку?'],
    // Мысль без единого вопроса.
    ['Позвонить в школу насчёт экскурсии. Оплатить интернет.'],
    // «Кстати» без вопроса о дне — обычная мысль, режь не режь.
    ['Купить хлеб, кстати, молоко тоже кончилось.'],
  ])('«%s» — тот же один сегмент', (text) => {
    const input = [seg('DUMP', text)];

    expect(splitDayQuestions(input)).toEqual(input);
  });

  it('вопрос про предмет с «и ещё» не режется: без вопроса о дне резать нечего', () => {
    const input = [seg('QUERY', 'Что у меня по банку и ещё надо ли платить?')];

    expect(splitDayQuestions(input)).toEqual(input);
  });

  it('«и ещё» без повеления после вопроса о дне — часть вопроса', () => {
    const input = [seg('QUERY', 'Что у меня на завтра и ещё на выходных?')];

    expect(splitDayQuestions(input)).toEqual(input);
  });

  it('правки, отметки и ответы не разбираются', () => {
    const input = [
      seg('PATCH', 'нет, что на завтра — перенеси'),
      seg('COMPLETE', 'что на сегодня — сделала'),
      seg('ANSWER', 'на завтра'),
    ];

    expect(splitDayQuestions(input)).toEqual(input);
  });

  it('пустой список не ломает', () => {
    expect(splitDayQuestions([])).toEqual([]);
  });
});

describe('речь без вопросов о дне — для правил дня классификации', () => {
  /**
   * Голос 10 Никиты, 18.09.2026: «…кстати, что у меня на выходных и ещё
   * надо разобрать балкон». Вопрос маршрутизатор из разбора убрал, но
   * правила дня читают речь целиком — и «на выходных» из вопроса стало
   * сроком балкона: выдуманный срок. Вопрос о дне из речи для правил
   * вырезается; сама мысль остаётся.
   */
  it('вырезает вопрос о дне, оставляя мысль за «и ещё»', () => {
    expect(
      withoutDayQuestions(
        'Просто нет сил ни на что, кстати, что у меня на выходных и еще и еще надо разобрать балкон.',
      ),
    ).toBe('Просто нет сил ни на что и еще и еще надо разобрать балкон.');
  });

  it('вопрос отдельным предложением — тоже вырезается', () => {
    expect(
      withoutDayQuestions(
        'Надо позвонить в школу. Кстати, что у меня там на завтра? И оплатить интернет.',
      ),
    ).toBe('Надо позвонить в школу. И оплатить интернет.');
  });

  it('речь без вопроса возвращается как есть', () => {
    const speech = 'Вот на выходных надо бы разобрать балкон, там коробки разобрать.';
    expect(withoutDayQuestions(speech)).toBe(speech);
  });
});

describe('вопросы-списки по признаку внутри мысли — тоже вопросы (21.09.2026)', () => {
  /**
   * «Что просрочено», «сколько у меня дел», «что я сделала» — те же
   * вопросы к бэклогу, что и «что на завтра»: модель, отдав их мыслью,
   * сделала бы из «что просрочено» запись. Правило одно: вопрос без
   * предмета с вопросительным словом или знаком — вопрос.
   */
  it('«что у меня просрочено?» в мысли выделяется вопросом', () => {
    const result = splitDayQuestions([seg('DUMP', 'Надо позвонить маме. Что у меня просрочено?')]);

    expect(result).toEqual([
      seg('DUMP', 'Надо позвонить маме.'),
      seg('QUERY', 'Что у меня просрочено?'),
    ]);
  });

  it('«сколько у меня дел» без знака вопроса — вопрос по слову «сколько»', () => {
    expect(splitDayQuestions([seg('DUMP', 'сколько у меня дел')])).toEqual([
      seg('QUERY', 'сколько у меня дел'),
    ]);
  });

  it('утверждение «сделала отчёт» вопросом не становится', () => {
    expect(splitDayQuestions([seg('DUMP', 'сделала отчёт')])).toEqual([
      seg('DUMP', 'сделала отчёт'),
    ]);
  });
});
