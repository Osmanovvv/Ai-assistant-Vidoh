import { describe, expect, it } from 'vitest';

import { looksLikeAppend, looksLikeCorrection, startsWithReplacement } from './append.js';

/**
 * Признак дополнения (§7.4, дефект найден ручным прогоном 31.08.2026).
 *
 * Таблица случаев, и случаев «это не дополнение» здесь больше, чем
 * «дополнение». Так и должно быть: ложное срабатывание уводит новое дело
 * в резолвер, и если тот назовёт цель с низкой уверенностью, дело осядет
 * черновиком вместо задачи. Пропущенное дополнение всего лишь создаёт
 * вторую запись — неприятно, но не потеря.
 */

describe('это дополнение', () => {
  it.each([
    'а ещё туда надо взять карту прививок',
    'а ещё к этому надо приложить справку',
    'и ещё туда же документы',
    'а ещё заодно спросить про прививки',
    'кстати к нему ещё полис нужен',
    'а также по дороге забрать рецепт',
  ])('«%s»', (text) => {
    expect(looksLikeAppend(text)).toBe(true);
  });

  it('регистр и «ё» не мешают', () => {
    expect(looksLikeAppend('А ЕЩЁ ТУДА надо взять карту')).toBe(true);
    expect(looksLikeAppend('а еще туда надо взять карту')).toBe(true);
  });
});

describe('это не дополнение', () => {
  it.each([
    // Связка есть, отсылки назад нет — обычное перечисление.
    'а ещё надо забрать вещи из химчистки',
    'и ещё купить продукты',
    'а ещё записаться к врачу',
    'кстати надо оплатить садик',
    // Отсылка есть, связки нет — это обычная мысль.
    'туда надо взять карту прививок',
    'заодно купить хлеб',
    // Ни того, ни другого.
    'надо записать сына к врачу в четверг',
    'перенеси на пятницу',
    'кассу сверила',
  ])('«%s»', (text) => {
    expect(looksLikeAppend(text)).toBe(false);
  });

  it('слово внутри другого слова не считается отсылкой', () => {
    // «затуманился» содержит «туда»? нет — но «тамада» содержит «там».
    expect(looksLikeAppend('а ещё позвать тамаду')).toBe(false);
  });

  it('пустая строка — не дополнение', () => {
    expect(looksLikeAppend('')).toBe(false);
    expect(looksLikeAppend('   ')).toBe(false);
  });
});

describe('замена по §7.1 не может стать дополнением', () => {
  /**
   * Найдено ручным прогоном на боевом 02.09.2026: «нет, няня пусть
   * приходит в 9 30» резолвер разобрал дополнением — время ушло в
   * подробности, а заголовок остался врать «в 9».
   */
  it.each([
    'нет, няня пусть приходит в 9 30',
    'Нет, лучше в 10 30',
    'лучше в пятницу',
    'вместо среды давай четверг',
    'перенеси на 8 сентября',
    'нет',
  ])('«%s» — замена', (text) => {
    expect(startsWithReplacement(text)).toBe(true);
  });

  it.each([
    // Дополнение §7.4 — с него всё и началось.
    'а ещё туда надо взять карту прививок',
    'и ещё туда же документы',
    // Признак должен стоять в начале, а не где придётся.
    'купить хлеб, а лучше два',
    'позвонить, если нет ответа — написать',
    // Слова, которые лишь начинаются так же.
    'нетворкинг на конференции',
    'лучшее враг хорошего',
    'переносить коробки в гараж',
  ])('«%s» — не замена', (text) => {
    expect(startsWithReplacement(text)).toBe(false);
  });

  it('пустое не считается заменой', () => {
    expect(startsWithReplacement('')).toBe(false);
    expect(startsWithReplacement('   ')).toBe(false);
  });
});

/**
 * Явная поправка к сказанному (задача 3.68).
 *
 * Живой прогон проджекта 04.09.2026: выгрузка **только из правок**, а
 * маршрутизатор отнёс две из них к мыслям, и из них вышли записи.
 *
 * Половина проверок ниже — про то, чего трогать нельзя. Признак работает
 * поверх решения модели, и лишнее слово здесь отправляет настоящую мысль
 * в путь правок.
 */
describe('явная поправка', () => {
  it('боевые случаи проджекта узнаются', () => {
    for (const text of [
      'Стоматологу всё-таки позвоню завтра, а не в пятницу. Сам приём пока не назначай',
      'И с балконом пока ничего не меняй, оставь всё как было',
    ]) {
      expect(looksLikeCorrection(text), text).toBe(true);
    }
  });

  it('отказ от изменения узнаётся одной приметой', () => {
    /**
     * Одной здесь достаточно, и это не поблажка: новая мысль так не
     * звучит никогда. Человек, называющий дело, не просит его не менять.
     */
    for (const text of [
      'С этим ничего не меняй',
      'Оставь как было',
      'Давай оставим как было',
      'Пусть остаётся как было',
      'Оставь как есть',
    ]) {
      expect(looksLikeCorrection(text), text).toBe(true);
    }
  });

  it('«всё-таки» без отрицания прежнего — не поправка', () => {
    // «Я всё-таки хочу отдохнуть» — это мысль, а не правка.
    for (const text of [
      'Я всё-таки хочу отдохнуть',
      'Всё-таки надо купить хлеб',
      'Всё-таки съезжу к родителям',
    ]) {
      expect(looksLikeCorrection(text), text).toBe(false);
    }
  });

  it('обычная мысль поправкой не считается', () => {
    for (const text of [
      'Надо сходить в магазин и купить продукты',
      'Завтра нужно заехать в аптеку и купить витамины',
      'В воскресенье надо отвезти собаку к грумеру',
      'Хочу начать бегать по утрам',
      'Мне нужен отдых, а не работа',
    ]) {
      expect(looksLikeCorrection(text), text).toBe(false);
    }
  });

  it('регистр и «ё» не мешают', () => {
    expect(looksLikeCorrection('ВСЕ-ТАКИ ЗАВТРА, А НЕ В ПЯТНИЦУ')).toBe(true);
    expect(looksLikeCorrection('Ничего Не Меняй')).toBe(true);
  });
});
