import { describe, expect, it } from 'vitest';

import { onlyDoneWords, patchesKnownItem } from './known-patch.js';

/**
 * Реплики без вопроса бота (набор docs/eval-dialog/commands.md, 28.09.2026):
 * маршрутизатор счёл мыслью «посылку на 10 утра», «давай хлеб на вечер»,
 * «у торта срок до пятницы» — а это перенос записанного: завелось бы второе
 * дело. «Готово» он счёл болтовнёй.
 */
const open = ['Забрать посылку', 'Купить хлеб', 'Купить торт', 'Позвонить маме'];

describe('перенос записанного дела без глагола', () => {
  it.each([
    'посылку на 10 утра',
    'давай хлеб на вечер',
    'у торта срок до пятницы',
    'маму на субботу',
    'посылку на завтра',
    'хлеб на час позже',
  ])('«%s» — правка', (text) => {
    expect(patchesKnownItem(text, open)).toBe(true);
  });

  it.each([
    // Глагол — своя мысль (повтор с новым сроком ловит отсев).
    'купить хлеб на завтра',
    'забрать посылку в 10',
    // Срока нет.
    'посылку',
    'хлеб',
    // Просьба завести новое — не перенос (пересчёт замера 28.09.2026).
    'запиши к врачу в пятницу',
    'напомни про хлеб вечером',
    // Такого дела нет.
    'молоко на завтра',
    'стоматолог в пятницу',
    // Длинная реплика — уже рассказ.
    'посылку на завтра а ещё надо записать Диму к логопеду и купить краски',
  ])('«%s» — не правка', (text) => {
    expect(patchesKnownItem(text, open)).toBe(false);
  });
});

describe('«готово» — сделано', () => {
  it.each(['готово', 'Готово!', 'всё, готово', 'сделано', 'уже сделала', 'выполнено'])(
    '«%s»',
    (text) => {
      expect(onlyDoneWords(text)).toBe(true);
    },
  );

  it.each(['готово тесто', 'готова к поездке?', 'привет', 'сделала посылку'])(
    '«%s» — не только «сделано»',
    (text) => {
      expect(onlyDoneWords(text)).toBe(false);
    },
  );
});
