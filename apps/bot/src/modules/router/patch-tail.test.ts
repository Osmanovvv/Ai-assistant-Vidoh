import { describe, expect, it } from 'vitest';

import { splitPatchTails } from './patch-tail.js';
import type { Segment } from './router.service.js';

/**
 * Мысль, приклеенная к правке (серия голосовых 18.09.2026, голос 10).
 *
 * «Во вторник отвести дочку к врачу, хотя нет к врачу лучше в пятницу
 * ещё оплатить садик до 20 купить подарок сестре» — без точек модель
 * маршрутизатора отдала правкой всё до точки. Резолвер увидел в одной
 * «правке» три дела и сказал «новая мысль»: садик и подарок код спас как
 * поздние мысли, а перенос врача пропал. «Ещё + повеление» внутри правки
 * — граница новой мысли, как и после вопроса о дне.
 */

const seg = (intent: Segment['intent'], text: string): Segment => ({ intent, text });

describe('мысль после правки отделяется', () => {
  it('«ещё оплатить…» после «хотя нет, лучше в пятницу» — мысль, правка остаётся короткой', () => {
    const result = splitPatchTails([
      seg(
        'PATCH',
        'хотя нет к врачу лучше в пятницу еще оплатить садик до 20 купить подарок сестре.',
      ),
    ]);

    expect(result).toEqual([
      seg('PATCH', 'хотя нет к врачу лучше в пятницу'),
      seg('DUMP', 'еще оплатить садик до 20 купить подарок сестре.'),
    ]);
  });

  it('через «и ещё» и «а ещё» — так же', () => {
    expect(splitPatchTails([seg('PATCH', 'нет, лучше в пятницу, и ещё купить корм')])).toEqual([
      seg('PATCH', 'нет, лучше в пятницу'),
      seg('DUMP', 'и ещё купить корм'),
    ]);
  });
});

describe('что не трогается', () => {
  it.each([
    // Правка без «ещё».
    ['нет, лучше в пятницу'],
    // «Ещё» без повеления — часть правки: срок «ещё на неделю».
    ['перенеси врача ещё на неделю'],
    // Явное дополнение: «ещё позвонить менеджеру» — это и есть содержание.
    ['К банку добавь: ещё позвонить менеджеру'],
    ['Допиши к стоматологу ещё взять полис'],
    // Дополнение по §7.4 — «а ещё туда …» целиком и есть правка.
    ['а ещё туда надо взять карту прививок'],
    // До «ещё» нет слова о времени — на правку не похоже, резать нечего.
    ['нет, не так, ещё купить корм'],
  ])('PATCH «%s» — тот же один сегмент', (text) => {
    const input = [seg('PATCH', text)];

    expect(splitPatchTails(input)).toEqual(input);
  });

  it('мысли, вопросы и закрытия не разбираются здесь', () => {
    const input = [
      seg('DUMP', 'купить хлеб, ещё оплатить садик'),
      seg('QUERY', 'что у меня на завтра и ещё оплатить садик?'),
      seg('COMPLETE', 'продукты купила, ещё надо забрать заказ'),
    ];

    expect(splitPatchTails(input)).toEqual(input);
  });
});
