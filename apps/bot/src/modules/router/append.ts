/**
 * Дополнение к уже сказанному (§7.4 ТЗ, задача 3.7).
 *
 * **Правило живёт в коде, а не в промпте, и это решение.** Маршрутизатор
 * работает на лёгкой модели и теряет единицы от любого утяжеления
 * промпта — проверено на контрольном наборе. Признаки правки в §7.1
 * перечислены закрытым списком («нет», «перенеси», «вместо», «лучше»), и
 * «а ещё» в него не входит: маршрутизатор ведёт себя по спецификации.
 * Дыра между §7.1 и §7.4 закрывается здесь.
 *
 * **Найдено ручным прогоном 31.08.2026.** Дословный пример из условия
 * готовности 3.7 — «а ещё туда надо взять карту прививок» — уходил в
 * обычный разбор и создавал вторую запись вместо подробности к первой.
 * Механизм дополнения был цел и покрыт тестами на двух уровнях, но обоим
 * сегмент приходил уже размеченным.
 *
 * **Одного «а ещё» мало, и в этом вся тонкость.** Эта связка чаще вводит
 * новое дело: «надо продукты, а ещё забрать вещи из химчистки». Отличает
 * дополнение **отсылка назад** — «туда», «к этому», «заодно»: слово,
 * которое само по себе ничего не значит и требует прошлого предложения.
 * Без такой отсылки сегмент остаётся новой мыслью.
 */

/** Связки, с которых начинается дополнение. */
const CONTINUATIONS = ['а ещё', 'и ещё', 'ещё', 'а также', 'к тому же', 'кстати'];

/**
 * Отсылки к ранее сказанному.
 *
 * Каждое слово здесь бессмысленно без прошлого предложения: «туда» — это
 * куда? «к этому» — к чему? Именно поэтому они и годятся в признак.
 */
const BACK_REFERENCES = [
  'туда',
  'там же',
  'к этому',
  'к нему',
  'к ней',
  'к ним',
  'заодно',
  'вместе с этим',
  'по дороге',
];

function normalize(text: string): string {
  return text.toLowerCase().replace(/ё/gu, 'е').trim();
}

/**
 * Списки нормализуются один раз, здесь.
 *
 * Первая версия сравнивала нормализованный текст с ненормализованными
 * словами: «а ещё» в списке против «а еще» в тексте — и правило молчало
 * на самом своём примере. Поймали тесты сразу.
 */
const STARTS = CONTINUATIONS.map(normalize);
const REFERENCES = BACK_REFERENCES.map(normalize);

function words(text: string): readonly string[] {
  return normalize(text)
    .split(/[^\p{L}]+/u)
    .filter((word) => word.length > 0);
}

/**
 * Похож ли сегмент на дополнение к ранее сказанному.
 *
 * Нужны **оба** признака: связка продолжения и отсылка назад. Одна связка
 * без отсылки — это перечисление, а перечисление разбирается как обычно.
 */
export function looksLikeAppend(text: string): boolean {
  const flat = normalize(text);
  const parts = words(text);

  if (!STARTS.some((mark) => flat.startsWith(`${mark} `))) return false;

  /**
   * Односложные отсылки ищутся среди слов, а не подстрокой: «там» внутри
   * «тамады» отсылкой не является.
   */
  return REFERENCES.some((mark) =>
    mark.includes(' ') ? flat.includes(mark) : parts.includes(mark),
  );
}

/**
 * Признаки замены из §7.1 — закрытый список самого ТЗ.
 *
 * «нет», «перенеси», «вместо», «лучше». Больше сюда добавлять нельзя без
 * согласования: список закрыт спецификацией, а не нашим вкусом.
 */
const REPLACEMENTS = ['нет', 'перенеси', 'перенести', 'вместо', 'лучше'];

/**
 * Начинается ли реплика с признака замены.
 *
 * **Зачем.** Ручной прогон на боевом 02.09.2026: «нет, няня пусть
 * приходит в 9 30» резолвер разобрал как **дополнение** — время ушло в
 * подробности, а в заголовке осталось прежнее «в 9». Человек увидел
 * «Добавила подробность», а запись при этом врёт.
 *
 * Та же модель на «Нет, лучше в 10 30» в другой реплике выбрала замену.
 * То есть решает она непоследовательно, а признак в §7.1 назван прямо и
 * закрытым списком — значит это правило, а не догадка, и место ему в
 * коде. Промпт резолвера при этом не трогается.
 *
 * Дополнением такая реплика быть не может: §7.4 требует связки
 * продолжения в начале («а ещё», «и ещё»), а не отрицания.
 */
export function startsWithReplacement(text: string): boolean {
  const flat = normalize(text);

  return REPLACEMENTS.some(
    (mark) => flat === mark || flat.startsWith(`${mark} `) || flat.startsWith(`${mark},`),
  );
}

/**
 * Явная поправка к сказанному ранее (задача 3.68).
 *
 * **Найдено живым прогоном проджекта 04.09.2026.** Он прислал выгрузку, в
 * которой были **только правки**, и маршрутизатор отнёс две из них к
 * мыслям:
 *
 * > «Стоматологу всё-таки позвоню завтра, **а не** в пятницу»
 * > «И с балконом пока **ничего не меняй**, оставь всё как было»
 *
 * Из первой вышла новая запись «Позвонить стоматологу завтра» рядом с уже
 * существующей, из второй — запись «Оставить всё на балконе как было».
 * Просьба ничего не менять сама стала изменением.
 *
 * **Промпт маршрутизатора не трогаем** — он теряет единицы от любого
 * утяжеления, проверено многократно. Приём тот же, что у дополнения выше:
 * закрытый список в коде.
 *
 * **Цена ошибки ограничена ровно так же.** Если сегмент всё-таки новая
 * мысль, резолвер не найдёт цели и вернёт его в обычный разбор — запись
 * появится, потеряется один вызов модели. Поэтому список узкий.
 */

/**
 * Отказ от изменения: «ничего не меняй», «оставь как было».
 *
 * Одной приметы здесь достаточно, и это не поблажка: новая мысль так не
 * звучит **никогда**. Человек, называющий дело, не просит его не менять.
 */
const KEEP_AS_IS = [
  'ничего не меняй',
  'ничего не меняем',
  'оставь как было',
  'оставь всё как было',
  'оставь все как было',
  'оставим как было',
  'оставь как есть',
  'пусть остаётся как было',
  'пусть остается как было',
];

/**
 * Приметы поправки: передумал и называет новое вместо прежнего.
 *
 * Нужны **обе** — «всё-таки» и отрицание прежнего. Одного «всё-таки»
 * мало: «я всё-таки хочу отдохнуть» — это мысль, а не правка.
 */
const RECONSIDERED = ['всё-таки', 'все-таки', 'всетаки'];
const INSTEAD_OF = ['а не ', 'а не,', 'вместо ', 'не в ', 'не на '];

export function looksLikeCorrection(text: string): boolean {
  const flat = normalize(text);

  if (KEEP_AS_IS.some((mark) => flat.includes(normalize(mark)))) return true;

  return (
    RECONSIDERED.some((mark) => flat.includes(normalize(mark))) &&
    INSTEAD_OF.some((mark) => flat.includes(normalize(mark)))
  );
}
