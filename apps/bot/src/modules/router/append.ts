/**
 * Дополнение к уже сказанному (§7.4 ТЗ, задача 3.7).
 *
 * **Правило живёт в коде, а не в промпте, и это решение.** Маршрутизатор
 * работает на лёгкой модели и теряет единицы от любого утяжеления
 * промпта — проверено на контрольном наборе. Признаки правки в §7.1
 * перечислены закрытым списком («нет», «перенеси», «вместо», «лучше»), и
 * «а ещё» в него не входит: маршрутизатор ведёт себя по спецификации.
 * Дыра между §7.1 и §7.4 закрывается здесь.
 *
 * **Найдено ручным прогоном 31.08.2026.** Дословный пример из условия
 * готовности 3.7 — «а ещё туда надо взять карту прививок» — уходил в
 * обычный разбор и создавал вторую запись вместо подробности к первой.
 * Механизм дополнения был цел и покрыт тестами на двух уровнях, но обоим
 * сегмент приходил уже размеченным.
 *
 * **Одного «а ещё» мало, и в этом вся тонкость.** Эта связка чаще вводит
 * новое дело: «надо продукты, а ещё забрать вещи из химчистки». Отличает
 * дополнение **отсылка назад** — «туда», «к этому», «заодно»: слово,
 * которое само по себе ничего не значит и требует прошлого предложения.
 * Без такой отсылки сегмент остаётся новой мыслью.
 */

/** Связки, с которых начинается дополнение. */
const CONTINUATIONS = ['а ещё', 'и ещё', 'ещё', 'а также', 'к тому же', 'кстати'];

/**
 * Отсылки к ранее сказанному.
 *
 * Каждое слово здесь бессмысленно без прошлого предложения: «туда» — это
 * куда? «к этому» — к чему? Именно поэтому они и годятся в признак.
 */
const BACK_REFERENCES = [
  'туда',
  'там же',
  'к этому',
  'к нему',
  'к ней',
  'к ним',
  'заодно',
  'вместе с этим',
  'по дороге',
];

function normalize(text: string): string {
  return text.toLowerCase().replace(/ё/gu, 'е').trim();
}

/**
 * Списки нормализуются один раз, здесь.
 *
 * Первая версия сравнивала нормализованный текст с ненормализованными
 * словами: «а ещё» в списке против «а еще» в тексте — и правило молчало
 * на самом своём примере. Поймали тесты сразу.
 */
const STARTS = CONTINUATIONS.map(normalize);
const REFERENCES = BACK_REFERENCES.map(normalize);

function words(text: string): readonly string[] {
  return normalize(text)
    .split(/[^\p{L}]+/u)
    .filter((word) => word.length > 0);
}

/**
 * Похож ли сегмент на дополнение к ранее сказанному.
 *
 * Нужны **оба** признака: связка продолжения и отсылка назад. Одна связка
 * без отсылки — это перечисление, а перечисление разбирается как обычно.
 */
export function looksLikeAppend(text: string): boolean {
  const flat = normalize(text);
  const parts = words(text);

  if (!STARTS.some((mark) => flat.startsWith(`${mark} `))) return false;

  /**
   * Односложные отсылки ищутся среди слов, а не подстрокой: «там» внутри
   * «тамады» отсылкой не является.
   */
  return REFERENCES.some((mark) =>
    mark.includes(' ') ? flat.includes(mark) : parts.includes(mark),
  );
}
