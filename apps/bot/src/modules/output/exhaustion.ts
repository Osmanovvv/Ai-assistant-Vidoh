/**
 * «Сил нет вовсе» — единственное состояние, урезающее выдачу до одного
 * дела (задача 3.47).
 *
 * **Зачем понадобилось различать.** До 03.09.2026 выдачу до одного дела
 * урезала **любая** эмоция в выгрузке. Человек говорил «задолбался всё
 * это в голове держать» и на двадцать дел получал одну строку. Заказчик
 * попросил показывать в таком случае три самых важных.
 *
 * ТЗ это различие делает само, в таблице сигналов §13.7:
 *
 * - «Я сегодня вообще без сил» → «Признание в одну строку, **одно
 *   действие**, предложение сказать, если появятся силы»;
 * - «Я чувствую, что ничего не успеваю» → «Признание в одну строку,
 *   **сокращённая выдача**. Список не показывается целиком».
 *
 * «Сокращённая» — это не «одна»: главный эталон ответа на выгрузку
 * (§13.2) сам называет усталость («и просто усталость от того, что все
 * это висит в голове») и показывает при ней **три** дела.
 *
 * Короткая форма §13.7 остаётся в силе при любой эмоции: признание одной
 * строкой, никакой морали, закрытие без вопроса. Меняется только число.
 *
 * **Список закрытый и узкий** — как у слов о времени и у кризисных
 * маркеров. Ошибка в сторону трёх дел стоит человеку одного взгляда,
 * ошибка в сторону одного — спора с ним: он сказал, что не может, а бот
 * выкатил список.
 */

/**
 * Прямые заявления «сил нет».
 *
 * Чего здесь намеренно нет: «устала», «тяжело», «задолбался», «ничего не
 * успеваю», «всё навалилось». Это усталость и досада, а не «не могу
 * вовсе», и по таблице §13.7 им положена сокращённая выдача, а не одно
 * дело.
 *
 * «Ничего не могу» тоже не входит: слишком широко — «ничего не могу
 * найти в этом бардаке» про состояние не говорит.
 */
const NO_STRENGTH = [
  'на нуле',
  'без сил',
  'нет сил',
  'сил нет',
  'сил не осталось',
  'не осталось сил',
  'не могу больше',
  'больше не могу',
  'вымотана',
  'вымотан',
  'выжата',
  'выжат',
  'еле живая',
  'еле живой',
  'падаю с ног',
  'с ног валюсь',
  'валюсь с ног',
] as const;

/**
 * Слова текста без знаков, «ё» приравнена к «е».
 *
 * Разбиением, а не поиском подстроки: границы `\b` определены через
 * латиницу и кириллицу не видят, а «выжат» внутри «выжатый» — то же
 * состояние, зато «нет сил» внутри «нет силикона» — нет.
 */
function wordsOf(text: string): readonly string[] {
  return text
    .toLowerCase()
    .replace(/ё/gu, 'е')
    .split(/[^\p{L}]+/u)
    .filter((word) => word.length > 0);
}

function hasPhrase(words: readonly string[], phrase: string): boolean {
  const parts = phrase.split(' ');

  return words.some((_unused, index) =>
    parts.every((part, shift) => words[index + shift] === part),
  );
}

/** Сказал ли человек, что сил нет вовсе. */
export function saysNoStrength(text: string): boolean {
  const words = wordsOf(text);
  return NO_STRENGTH.some((phrase) => hasPhrase(words, phrase));
}
