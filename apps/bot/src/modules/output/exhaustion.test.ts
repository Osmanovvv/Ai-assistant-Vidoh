import { describe, expect, it } from 'vitest';

import { saysNoStrength } from './exhaustion.js';

/**
 * Различие, которое ТЗ делает в таблице сигналов §13.7 (задача 3.47):
 * «вообще без сил» — одно действие, «ничего не успеваю» — сокращённая
 * выдача. До 03.09.2026 продукт этого различия не знал и урезал выдачу
 * до одного дела на **любую** эмоцию.
 */

describe('«сил нет вовсе» узнаётся', () => {
  const exhausted = [
    'Я на нуле совсем',
    'Я сегодня вообще без сил',
    'Сил нет',
    'Нет сил ни на что',
    'Сил не осталось',
    'Больше не могу',
    'Не могу больше',
    'Совсем вымотана',
    'Я выжат как лимон',
    'Еле живая',
    'Падаю с ног',
    'Валюсь с ног',
  ];

  for (const text of exhausted) {
    it(`видит «сил нет» в «${text}»`, () => {
      expect(saysNoStrength(text)).toBe(true);
    });
  }

  it('регистр и «ё» не мешают', () => {
    expect(saysNoStrength('Я НА НУЛЕ')).toBe(true);
    expect(saysNoStrength('силёнок нет')).toBe(false);
  });
});

describe('усталость и досада — это не «сил нет»', () => {
  const tired = [
    'Я уже задолбался всё это держать в голове',
    'Такое ощущение, что я ничего не успеваю',
    'Всё навалилось',
    'Устала',
    'Я так устала от всего этого',
    'Тяжело',
    'Хочу выдохнуть',
    'В голове бардак',
    'Ничего не могу найти в этом бардаке',
    'Голова кругом',
  ];

  for (const text of tired) {
    it(`не видит «сил нет» в «${text}»`, () => {
      expect(saysNoStrength(text)).toBe(false);
    });
  }
});

describe('чего словарь не должен путать', () => {
  it('слова внутри других слов не считаются', () => {
    expect(saysNoStrength('купить силикон')).toBe(false);
    expect(saysNoStrength('записаться в силовые')).toBe(false);
    // «Выжать сок» — про сок, а не про состояние.
    expect(saysNoStrength('выжать сок из апельсинов')).toBe(false);
  });

  it('пустой текст — не состояние', () => {
    expect(saysNoStrength('')).toBe(false);
    expect(saysNoStrength('   ')).toBe(false);
  });
});
