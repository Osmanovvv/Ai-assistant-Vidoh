import type { StatusButton } from '../presenter/status.service.js';
import { toShortId } from '../shared/short-id.js';
import type { TextProfile } from '../../texts/types.js';
import type { ProjectStep } from '../../db/schema.js';

/**
 * Кнопка «Шаг сделан» под ответом о проекте (§21 п.6, задача 3.82).
 *
 * **Почему её не было и почему это дефект.** Разложение на шаги, ответ
 * контекстом, ближайший шаг, три реплики про закрытие шага — всё было
 * написано и покрыто тестами. А закрыть шаг было нельзя ничем:
 * единственный, кто пишет `projectSteps.doneAt`, — `completeStep`, и его
 * не звала ни одна кнопка бота. `doneAt` оставался пустым всегда, а
 * значит «ближайший шаг» был вечно первым: человек, вернувшийся через
 * неделю, видел «Ближайший шаг: позвонить в кафе» и после звонка, и
 * через месяц. §21 п.6 обещает показать, **что уже решено** — а раздел
 * «Сделано» не мог наполниться никогда.
 *
 * Кнопка, а не речь: речью шаг закрыть тоже можно будет (резолвер видит
 * записи, не шаги), но это отдельная задача с моделью. Кнопка стоит ноль
 * и закрывает пункт ТЗ.
 *
 * **Строку менять нельзя.** Она лежит в переписке людей: сообщения с
 * кнопками остаются в чате навсегда, и нажатие по вчерашней кнопке
 * обязано находить свой обработчик.
 */
export const PROJECT_ACTION = {
  stepDone: 'p:sd:',
} as const;

/**
 * Кнопка под ближайшим шагом. Шага нет — кнопки нет: нажимать нечего.
 *
 * Код шага, а не проекта: пока человек читает ответ, ближайшим может
 * стать другой шаг (закрыл со второго устройства), и нажатие обязано
 * закрыть тот шаг, который человек видел, а не тот, который стал первым.
 */
export function stepButtons(
  next: ProjectStep | undefined,
  texts: TextProfile,
): readonly StatusButton[] {
  if (next === undefined) return [];

  return [
    {
      label: texts.project.buttonStepDone,
      action: `${PROJECT_ACTION.stepDone}${toShortId(next.id)}`,
    },
  ];
}
