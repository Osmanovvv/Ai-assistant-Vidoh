import { describe, expect, it } from 'vitest';

import { shortTitleFrom } from './project-title.js';

/**
 * Короткое название цели от модели раскладки (заказчица 30.09.2026):
 * «Разобраться с днём рождения ребёнка, место, гости, торт» — части ушли в
 * шаги, в названии осталась цель. Модели верим, только если она укоротила
 * её слова, а не переписала, и ничего не потеряла.
 */
describe('короткое название цели', () => {
  const birthday = 'Разобраться с днём рождения ребёнка, место, гости, торт, украшения ведущей';
  const birthdaySteps = [
    'Выбрать место',
    'Составить список гостей',
    'Заказать торт',
    'Продумать украшения',
    'Найти ведущего',
  ];

  it('части ушли в шаги — в названии остаётся цель, её же словами', () => {
    expect(shortTitleFrom(birthday, 'Разобраться с днём рождения ребёнка', birthdaySteps)).toBe(
      'Разобраться с днём рождения ребёнка',
    );
  });

  it('«е» вместо «ё» и точка в конце у модели — название всё равно её, с «ё»', () => {
    expect(shortTitleFrom(birthday, 'разобраться с днем рождения ребенка.', birthdaySteps)).toBe(
      'Разобраться с днём рождения ребёнка',
    );
  });

  it('модель переписала название своими словами — не принимается', () => {
    expect(
      shortTitleFrom(birthday, 'Организовать день рождения ребёнка', birthdaySteps),
    ).toBeUndefined();
  });

  it('другие слова той же длины, что её цель до запятой, — не принимается', () => {
    expect(
      shortTitleFrom(birthday, 'Устроить праздник для любимого ребёнка', birthdaySteps),
    ).toBeUndefined();
  });

  it('обрезано посреди фразы, а не по перечислению — не принимается', () => {
    expect(shortTitleFrom(birthday, 'Разобраться с днём', birthdaySteps)).toBeUndefined();
    // Отрезанное при этом есть в шагах — и всё равно нет: «в ванной» —
    // часть цели, а не перечисления.
    expect(
      shortTitleFrom('Сделать ремонт в ванной, плитка, свет', 'Сделать ремонт', [
        'Выбрать плитку для ванной',
        'Поменять свет',
      ]),
    ).toBeUndefined();
  });

  it('убранной части нет в шагах — не принимается: она бы потерялась', () => {
    const withoutCake = birthdaySteps.filter((step) => step !== 'Заказать торт');
    expect(
      shortTitleFrom(birthday, 'Разобраться с днём рождения ребёнка', withoutCake),
    ).toBeUndefined();
  });

  it('перечисление — продолжение самой цели: шаги повторяют её действие — не принимается', () => {
    expect(
      shortTitleFrom('Разобрать шкаф, балкон, гараж', 'Разобрать шкаф', [
        'Разобрать шкаф',
        'Разобрать балкон',
        'Разобрать гараж',
      ]),
    ).toBeUndefined();
    expect(
      shortTitleFrom('Сделать ремонт в ванной, спальне, кухне', 'Сделать ремонт в ванной', [
        'Выбрать плитку',
        'Сделать ремонт в спальне',
        'Сделать ремонт на кухне',
      ]),
    ).toBeUndefined();
  });

  it('слово цели в шаге не по её действию — не повтор (проба decomposer@2, 30.09.2026)', () => {
    // «школьную» — не «подготовить»: цель делают по частям, а не повторяют.
    expect(
      shortTitleFrom(
        'Подготовить сына к школе, форма, рюкзак, канцелярия, медосмотр',
        'Подготовить сына к школе',
        [
          'Купить школьную форму',
          'Выбрать и купить рюкзак',
          'Купить канцелярские принадлежности',
          'Пройти медосмотр',
        ],
      ),
    ).toBe('Подготовить сына к школе');
    expect(
      shortTitleFrom('Сделать фотосессию семьи, фотограф платья', 'Сделать фотосессию семьи', [
        'Выбрать фотографа',
        'Подобрать платья для фотосессии',
        'Провести фотосессию',
      ]),
    ).toBe('Сделать фотосессию семьи');
  });

  it('после запятой — продолжение мысли, а не части: название не трогается (стенд 01.10.2026)', () => {
    // voice-27-08: «День рождения у Иры, подарок ещё не купила» — раскладка
    // дала «День рождения у Иры», и «подарок» пропал из списка дел.
    expect(
      shortTitleFrom('День рождения у Иры, подарок ещё не купила', 'День рождения у Иры', [
        'Выбрать подарок',
        'Купить подарок',
      ]),
    ).toBeUndefined();
    expect(
      shortTitleFrom('Ремонт в детской, обои купила', 'Ремонт в детской', [
        'Поклеить обои',
        'Купить краску',
      ]),
    ).toBeUndefined();
  });

  it('название не укорочено или его нет — менять нечего', () => {
    expect(shortTitleFrom(birthday, birthday, birthdaySteps)).toBeUndefined();
    expect(shortTitleFrom(birthday, undefined, birthdaySteps)).toBeUndefined();
    expect(shortTitleFrom(birthday, '  ', birthdaySteps)).toBeUndefined();
  });

  it('после двоеточия или тире — тоже граница перечисления', () => {
    const steps = ['Купить билеты', 'Забронировать отель', 'Оформить страховку'];
    expect(
      shortTitleFrom(
        'Подготовиться к поездке: билеты, отель, страховка',
        'Подготовиться к поездке',
        steps,
      ),
    ).toBe('Подготовиться к поездке');
    expect(
      shortTitleFrom(
        'Подготовиться к поездке — билеты, отель, страховка',
        'Подготовиться к поездке',
        steps,
      ),
    ).toBe('Подготовиться к поездке');
  });
});
