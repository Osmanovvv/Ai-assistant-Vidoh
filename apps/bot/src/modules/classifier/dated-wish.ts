/**
 * Желание с рамкой срока — дело (блок B 17.09.2026, решение Никиты).
 *
 * «Хочу за осень сделать ремонт в спальне: обои, потолок, шторы» —
 * модель отдаёт желание: слово «хочу» для неё сильнее всего остального.
 * По смыслу это дело-цель с сезонным сроком: человек назвал, **что**
 * сделать и **к какому времени**. На живом наборе 20.09.2026 и бой, и
 * стенд ошиблись одинаково; промпт классификатора не трогаем (правки
 * промпта — только с замером), правило живёт кодом.
 *
 * Правило узкое, из трёх обязательных примет в одной единице:
 *
 * 1. «хочу» или «хотим» — своё слово, не «хотелось бы» (мягче, спорно);
 * 2. рамка срока: «за <сезон|месяц|год|неделю>», «до <конца …|месяца|
 *    даты>», «к <месяцу|дате|празднику>»; длительность («на недельку»,
 *    «хотя бы неделю») рамкой не считается;
 * 3. глагол действия в неопределённой форме рядом.
 *
 * Без любой из трёх — желание остаётся желанием: превратить мечту в
 * дело — самая частая ошибка разбора (§6.2), и правило не должно её
 * добавлять.
 */

const WISH = /(?<!\p{L})хо(?:чу|тим)(?!\p{L})/iu;

const SEASONS = 'осень|зиму|весну|лето|месяц|год|неделю|полгода|квартал|выходные|праздники';
const MONTHS = 'январ|феврал|март|апрел|ма[йя]|июн|июл|август|сентябр|октябр|ноябр|декабр';

/** Рамка срока: предлог и слово о времени за ним. */
const FRAME = new RegExp(
  String.raw`(?<!\p{L})(?:за\s+(?:${SEASONS})(?!\p{L})` +
    // «До Нового года», «до лета» (прогон Никиты 27.09.2026, 18:17).
    String.raw`|до\s+(?:конца|нового\s+года|лета|зимы|осени|весны|праздников|отпуска|(?:${MONTHS})\p{L}*|\d{1,2}(?:\s|\.|$))` +
    String.raw`|к\s+(?:(?:${MONTHS})\p{L}*|новому\s+году|\d{1,2}(?:\s|\.|$)|дню\s+рождения|отпуску|празднику|лету|зиме|осени|весне))`,
  'iu',
);

/** Глагол действия в неопределённой форме. */
const ACTION =
  /(?<!\p{L})(?:с|до|пере|за|раз|по|от|о|вы|при|у|на)?(?:делать|строить|ремонтировать|чинить|учить|выучить|читать|писать|дописать|бираться|браться|разобраться|готовить|купить|продать|съездить|сдать|пройти|закончить|завершить|запустить|открыть|собрать|найти|оформить|решить|заняться|навести|выбрать|записаться|похудеть|накопить|освоить|выйти)(?:ся)?(?!\p{L})/iu;

function normalize(text: string): string {
  return text.toLowerCase().replace(/ё/gu, 'е');
}

/**
 * «Хочу» + рамка срока + глагол действия.
 *
 * Рамка и глагол — в самой единице. «Хочу» — в ней же или в **том
 * предложении речи, где стоит эта рамка**: извлечение опускает «хочу»
 * («Хочу за осень сделать ремонт» → «за осень сделать ремонт», блок B
 * 17.09.2026), а слово человека при этом никуда не делось. Предложение
 * ищется по рамке, а не по всей единице, — модель единицу перефразирует.
 */
export function looksLikeDatedWish(text: string, speech?: string): boolean {
  const normalized = normalize(text);
  const frame = FRAME.exec(normalized);

  if (frame === null || !ACTION.test(normalized)) return false;
  if (WISH.test(normalized)) return true;
  if (speech === undefined) return false;

  const phrase = frame[0].trim();

  return normalize(speech)
    .split(/[.!?\n]+/u)
    .some((sentence) => sentence.includes(phrase) && WISH.test(sentence));
}
