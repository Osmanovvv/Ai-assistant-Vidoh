describe('обозначение дня, занятое соседней записью (прогон 17.09.2026)', () => {
  const thursday = { now: new Date('2026-09-16T23:24:42.000Z'), timeZone: 'Europe/Moscow' };

  it('«в четверг» из слов врача молоку не достаётся', () => {
    // Полный прогон после хвоста со сроком показал: «записать сына к врачу
    // в четверг, купить молоко» — молоко получало четверг. Слово стоит в
    // словах соседа, значит принадлежит ему.
    const day = dayFromOwnSentence({
      ...thursday,
      itemText: 'купить молоко',
      spoken: 'записать сына к врачу в четверг, купить молоко',
      siblings: ['записать сына к врачу в четверг'],
    });

    expect(day).toBeUndefined();
  });

  it('из двух обозначений одно занято соседом — остаётся одно, и оно берётся', () => {
    // Живая расшифровка: неделя — стоматолога, месяц свободен и стоит в том
    // же предложении, что и диспансеризация.
    const day = dayFromOwnSentence({
      ...thursday,
      itemText: 'пройти диспансеризацию',
      spoken:
        'Следующей неделе записаться к стоматологу давно уже откладываю в октябре пройти диспансеризацию.',
      siblings: ['на следующей неделе записаться к стоматологу'],
    });

    expect(day?.accuracy).toBe('month');
    expect(day?.at.toISOString()).toBe('2026-09-30T21:00:00.000Z');
  });

  it('без соседей поведение прежнее', () => {
    const day = dayFromOwnSentence({
      ...thursday,
      itemText: 'купить молоко',
      spoken: 'в четверг купить молоко',
      siblings: [],
    });

    expect(day?.accuracy).toBe('day');
  });
});

describe('слово о времени суток берёт день у слова о дне перед ним (голос 8, 18.09.2026)', () => {
  /**
   * Бой: «Завтра утром позвонить в поликлинику, вечером забрать заказ в
   * пункте выдачи и в субботу днём поехать на дачу» — «забрать заказ»
   * получило сегодня: своего дня у него нет, а «вечером» — слово о
   * времени, и дату модели страж пропустил. Но день в этом предложении
   * назван — «завтра», и стоит он перед «вечером», в той же цепочке
   * через запятую. Человек называет день один раз на всю фразу.
   */
  const FRIDAY = new Date('2026-09-18T13:59:37.000Z');
  const speech =
    'Завтра утром позвонить в поликлинику, вечером забрать заказ в пункте выдачи и в субботу днем поехать на дачу.';

  function found(itemText: string, spoken = speech): string {
    const day = dayBeforeDaypart({ itemText, spoken, now: FRIDAY, timeZone: ZONE });
    if (!day) return 'нет';

    return `${new Intl.DateTimeFormat('sv-SE', { timeZone: ZONE }).format(day.at)} ${day.accuracy}`;
  }

  it('«вечером забрать заказ» после «завтра утром …» — завтра', () => {
    expect(found('вечером забрать заказ в пункте выдачи')).toBe('2026-09-19 day');
  });

  it('у записи со своим днём правило молчит: «в субботу днём поехать на дачу»', () => {
    expect(found('в субботу днем поехать на дачу')).toBe('нет');
  });

  it('без слова о времени суток правило молчит', () => {
    expect(found('забрать заказ в пункте выдачи')).toBe('нет');
  });

  it('день назван после, а не до, — не берётся', () => {
    expect(
      found(
        'вечером забрать заказ',
        'Вечером забрать заказ, а завтра утром позвонить в поликлинику.',
      ),
    ).toBe('нет');
  });

  it('день в другом предложении не берётся', () => {
    expect(
      found('вечером забрать заказ', 'Завтра позвонить в поликлинику. Вечером забрать заказ.'),
    ).toBe('нет');
  });

  it('через «а» — противопоставление, день не переносится', () => {
    expect(
      found('вечером забрать заказ', 'Завтра позвонить в поликлинику, а вечером забрать заказ.'),
    ).toBe('нет');
  });

  it('день недели перед словом о времени суток — тот день', () => {
    expect(
      found('вечером забрать заказ', 'В понедельник сходить в банк, вечером забрать заказ.'),
    ).toBe('2026-09-21 day');
  });
});

describe('день, сказанный обрывком перед делом (заказчица, бой 21.09.2026)', () => {
  /**
   * Бой, 09:46 по Москве: «…Записаться в Краснодаре на Хайдру на среду,
   * так? Так завтра. С 9 до 10 не забыть позвонить. Елене Михайловне в
   * бухгалтерию.» Расшифровка поставила точку после «завтра», и день
   * оказался в предложении из двух слов, где дела нет. Обрывок из
   * слов-заполнителей и одного определённого дня — начало следующего
   * предложения: так люди и говорят, «так, завтра — позвонить».
   */
  const MONDAY = new Date('2026-09-21T06:46:00.000Z');
  const speech =
    'Записаться в Краснодаре на Хайдру на среду, так? Так завтра. С 9 до 10 не забыть позвонить. Елене Михайловне в бухгалтерию. Вроде бы пока все из срочного.';

  function found(itemText: string, spoken = speech): string {
    const day = dayFromOwnSentence({ itemText, spoken, now: MONDAY, timeZone: ZONE });
    if (!day) return 'нет';

    return `${new Intl.DateTimeFormat('sv-SE', { timeZone: ZONE }).format(day.at)} ${day.accuracy}`;
  }

  it('«Так завтра. С 9 до 10 не забыть позвонить…» — завтра', () => {
    expect(found('С 9 до 10 не забыть позвонить Елене Михайловне в бухгалтерию')).toBe(
      '2026-09-22 day',
    );
  });

  it('обрывок с двумя днями не приклеивается', () => {
    expect(
      found('Позвонить в бухгалтерию', 'Так завтра или в среду. Позвонить в бухгалтерию.'),
    ).toBe('нет');
  });

  it('предложение с делом и днём — не обрывок: сосед его день не берёт', () => {
    expect(found('Позвонить маме', 'Купить хлеб завтра. Позвонить маме.')).toBe('нет');
  });

  it('у Хайдры остаётся её среда', () => {
    expect(found('Записаться в Краснодаре на Хайдру на среду')).toBe('2026-09-23 day');
  });
});
