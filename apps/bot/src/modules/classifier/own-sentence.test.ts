import { describe, expect, it } from 'vitest';

import { dayFromOwnSentence } from './own-sentence.js';

/**
 * День из своего предложения речи (задача 3.49).
 *
 * Живая выгрузка проджекта 03.09.2026: «Ещё сегодня хотел позвонить
 * бабушке» и «Вот на выходных надо бы разобрать балкон» — модель не дала
 * этим делам срока вовсе, а слово о дне стоит рядом, в том же
 * предложении.
 */

/** Четверг, 3 сентября 2026, вечер по Москве. */
const NOW = new Date('2026-09-03T17:00:00.000Z');
const ZONE = 'Europe/Moscow';

const SPEECH = [
  'Вот сегодня мне надо сходить в магазин, купить продукты домой, молоко, хлеб, яйца, сыр и воду.',
  'Вот ещё сегодня вечером обязательно надо погулять с собакой, потом надо вынести мусор.',
  'Ещё сегодня хотел позвонить бабушке.',
  'Желательно вечером.',
  'Завтра надо отнести ноутбук в сервис на проверку, потому что он в последнее время тормозит.',
  'А ещё корм собаки заканчивается.',
  'Его тоже надо купить завтра.',
  'В четверг мне надо съездить к родителям, завести им вещи.',
  'Ещё в четверг хотел заехать я на мойку.',
  'Хотя нет, давай мойку лучше в пятницу, вот в пятницу тогда надо помыть машину, ещё позвонить стоматологу, записаться на следующую неделю.',
  'Вот на выходных надо бы разобрать балкон, там коробки разобрать, ненужное выкинуть.',
  'И в воскресенье вечером надо позвонить другу, я обещал.',
].join(' ');

function dayOf(itemText: string): string {
  const found = dayFromOwnSentence({ itemText, spoken: SPEECH, now: NOW, timeZone: ZONE });
  if (!found) return 'нет';

  const date = new Intl.DateTimeFormat('sv-SE', { timeZone: ZONE }).format(found.at);
  return `${date} ${found.accuracy}`;
}

describe('день берётся из предложения, где мысль и сказана', () => {
  it('«сегодня» у бабушки', () => {
    expect(dayOf('Позвонить бабушке')).toBe('2026-09-03 day');
  });

  it('«на выходных» у балкона — точность недели, дата на субботу', () => {
    expect(dayOf('Разобрать балкон: выкинуть коробки, купить стеллаж и пуфики')).toBe(
      '2026-09-05 week',
    );
  });

  it('цепочка не перескакивает через точку', () => {
    /**
     * Живой прогон 04.09.2026: цепочка искалась по всей речи разом и
     * захватывала слова из следующего предложения — «коробки разобрать
     * ненужное выкинуть **посмотреть сколько**», хотя речь там разделена
     * точкой. Ни одно предложение такой цепочки не содержало, и правило
     * молча выходило ни с чем: «на выходных» терялось.
     */
    expect(
      dayOf(
        'Разобрать балкон: коробки разобрать, ненужное выкинуть, посмотреть, сколько свободного места останется',
      ),
    ).toBe('2026-09-05 week');
  });

  it('«в четверг» у родителей — ближайший четверг, то есть сегодня', () => {
    expect(dayOf('Съездить к родителям, завезти им вещи')).toBe('2026-09-03 day');
  });

  it('«в воскресенье» у друга', () => {
    expect(dayOf('Позвонить другу')).toBe('2026-09-06 day');
  });
});

describe('чего запасной путь делать не должен', () => {
  it('два обозначения дня в предложении — выходим', () => {
    // «в пятницу… ещё позвонить стоматологу, записаться на следующую
    // неделю»: какой из двух дней его — догадка.
    expect(dayOf('Позвонить стоматологу, записаться на следующую неделю')).toBe('нет');
  });

  it('слова мысли встречаются в двух предложениях — выходим', () => {
    // Связь неоднозначна: в каком из двух дней дело — неизвестно.
    const twice = 'Завтра надо позвонить маме. И в пятницу позвонить маме ещё раз.';
    expect(
      dayFromOwnSentence({ itemText: 'Позвонить маме', spoken: twice, now: NOW, timeZone: ZONE }),
    ).toBeUndefined();
  });

  it('в предложении дня нет вовсе — выходим', () => {
    const plain = 'Надо разобрать шкаф. И протереть пыль.';
    expect(
      dayFromOwnSentence({ itemText: 'Протереть пыль', spoken: plain, now: NOW, timeZone: ZONE }),
    ).toBeUndefined();
  });

  it('мусор назван в том же предложении, что «сегодня» — и это верно', () => {
    // «Вот ещё сегодня вечером обязательно надо погулять с собакой,
    // потом надо вынести мусор» — одно предложение, один день.
    expect(dayOf('Вынести мусор')).toBe('2026-09-03 day');
  });

  it('«на следующую неделю» дня не даёт и рядом стоящий день не пускает', () => {
    // «Вот в пятницу тогда надо помыть машину, ещё позвонить
    // стоматологу, записаться на следующую неделю» — два срока, чей
    // какой, отсюда не видно.
    expect(dayOf('Записаться на следующую неделю')).toBe('нет');
  });

  it('пересказ вместо слов человека не подходит', () => {
    // Связь не доказана: дословной цепочки в речи нет.
    expect(dayOf('Приобрести провизию в супермаркете')).toBe('нет');
  });

  it('одного слова мало, даже если оно в речи есть', () => {
    expect(dayOf('Собака')).toBe('нет');
    expect(dayOf('Мусор')).toBe('нет');
  });

  it('пустая мысль и пустая речь ничего не дают', () => {
    expect(
      dayFromOwnSentence({ itemText: '', spoken: SPEECH, now: NOW, timeZone: ZONE }),
    ).toBeUndefined();
    expect(
      dayFromOwnSentence({ itemText: 'Позвонить бабушке', spoken: '', now: NOW, timeZone: ZONE }),
    ).toBeUndefined();
  });
});

describe('мысль, собранная из двух предложений (задача 3.55)', () => {
  /**
   * Живой прогон 04.09.2026: у мысли «Разобрать балкон, коробки, выкинуть
   * ненужное, посмотреть, сколько свободного места останется» самая
   * длинная дословная цепочка — «свободного места останется» — сидит в
   * соседнем предложении, где дня нет. Правило брало только её и молча
   * выходило ни с чем, теряя «на выходных».
   */

  const TWO = [
    'Вот на выходных надо бы разобрать балкон, там коробки разобрать, ненужное выкинуть.',
    'Посмотреть, сколько вообще свободного места останется.',
  ].join(' ');

  it('день берётся, даже если мысль дотянулась до двух предложений', () => {
    const found = dayFromOwnSentence({
      itemText:
        'Разобрать балкон, коробки, выкинуть ненужное, посмотреть, сколько свободного места останется',
      spoken: TWO,
      now: NOW,
      timeZone: ZONE,
    });

    expect(found?.accuracy).toBe('week');
    // Ближайшая суббота от четверга 3 сентября — 5-е; начало дня по Москве.
    expect(found?.at.toISOString().slice(0, 10)).toBe('2026-09-04');
  });

  it('два разных дня в затронутых предложениях — выходим', () => {
    // Однозначность проверяется по дню, а не по числу предложений.
    const conflicting = [
      'Завтра надо разобрать балкон.',
      'А в пятницу коробки разобрать и ненужное выкинуть.',
    ].join(' ');

    expect(
      dayFromOwnSentence({
        itemText: 'Разобрать балкон, коробки разобрать, ненужное выкинуть',
        spoken: conflicting,
        now: NOW,
        timeZone: ZONE,
      }),
    ).toBeUndefined();
  });

  it('один и тот же день в двух предложениях — не спор', () => {
    const same = ['Завтра надо разобрать балкон.', 'И завтра же ненужное выкинуть.'].join(' ');

    const found = dayFromOwnSentence({
      itemText: 'Разобрать балкон, ненужное выкинуть',
      spoken: same,
      now: NOW,
      timeZone: ZONE,
    });

    expect(found?.at.toISOString().slice(0, 10)).toBe('2026-09-03');
  });

  it('цепочка из двух предложений связь не доказывает', () => {
    /**
     * «Купить корм» встречается дважды, поэтому это предложение в набор
     * не попадает; а «для собаки» встречается один раз — и попадает.
     */
    const twice = ['Завтра купить корм для собаки.', 'И ещё купить корм коту.'].join(' ');

    const found = dayFromOwnSentence({
      itemText: 'Купить корм для собаки',
      spoken: twice,
      now: NOW,
      timeZone: ZONE,
    });

    expect(found?.at.toISOString().slice(0, 10)).toBe('2026-09-03');
  });
});
