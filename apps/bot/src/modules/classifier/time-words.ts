/** Цифры в тексте: «на 5 7 сентября», «в 9 30», «к 15-му». */
const DIGITS = /\d/u;

function normalize(text: string): string {
  return text.toLowerCase().replace(/ё/gu, 'е');
}

/**
 * Есть ли в тексте хоть одно слово о времени.
 *
 * Цифры считаются словом о времени: человек, назвавший число, скорее
 * всего назвал дату или час, а лишний сохранённый срок дешевле
 * потерянного.
 */
export function hasTimeWord(text: string): boolean {
  const normalized = normalize(text);

  if (DIGITS.test(normalized)) return true;

  return TIME_WORDS.some((word) => normalized.includes(normalize(word)));
}

/**
 * Дни недели по-русски: для проверки, что дата действительно тот день,
 * который назвал человек.
 *
 * Замер 27.08.2026: на «записаться к стоматологу в четверг» модель
 * вернула среду, 2 сентября. Ни сегодня-четверг, ни следующий четверг —
 * просто не тот день. Считать день недели — работа кода, а не модели.
 */
const WEEKDAYS: readonly { readonly roots: readonly string[]; readonly index: number }[] = [
  { roots: ['понедельник'], index: 1 },
  { roots: ['вторник'], index: 2 },
  { roots: ['среду', 'среда', 'среды'], index: 3 },
  { roots: ['четверг'], index: 4 },
  { roots: ['пятницу', 'пятница', 'пятницы'], index: 5 },
  { roots: ['субботу', 'суббота', 'субботы'], index: 6 },
  { roots: ['воскресенье', 'воскресенья'], index: 0 },
];

/**
 * Дни недели, названные в тексте.
 *
 * Их может быть несколько: «каждый вторник и четверг». Раньше проверка в
 * таком случае отказывалась работать — и модель спокойно ставила
 * понедельник, а поймать это было нечем. Выбирать за человека один из
 * двух нельзя, но требовать, чтобы дата была **одним из названных**,
 * можно и нужно.
 */
export function weekdaysIn(text: string): readonly number[] {
  const normalized = normalize(text);

  return WEEKDAYS.filter((day) =>
    day.roots.some((root) => normalized.includes(normalize(root))),
  ).map((day) => day.index);
}

/** Какой день недели назван в тексте, если назван ровно один. */
export function weekdayIn(text: string): number | undefined {
  const found = weekdaysIn(text);
  return found.length === 1 ? found[0] : undefined;
}
