/**
 * Слова о времени в речи человека (задача 2.7).
 *
 * **Зачем это в коде, а не в промпте.** Промпт уже говорит «не выдумывай
 * сроки». Замер 27.08.2026 на контрольном наборе показал десять
 * выдуманных сроков из сорока трёх дел: семи покупкам подряд модель
 * поставила «на этой неделе», хотя человек не назвал ни одной даты.
 * Просьба не помогла, значит нужна проверка.
 *
 * Цена ошибки не в самом сроке. Фильтр выдачи (2.10) ставит дела «на
 * сегодня» впереди всех, поэтому мелочь с придуманной датой вытесняет из
 * выдачи важное дело без срока. На живой выгрузке 27.08.2026 так и
 * вышло: в ответе оказались пуфики, капсулы и кофе, а ортопед,
 * стоматолог и витамины — нет.
 *
 * **Правило.** Срок принимается, только если в словах человека есть хоть
 * одно слово о времени. Ищем сначала в тексте самой единицы, потом во
 * всей выгрузке: «на 5 7 сентября» может стоять в соседней фразе, а
 * разбор склеивает единицы по-своему. Нет нигде — значит срока человек не
 * называл, и придуманная дата отбрасывается.
 *
 * То же решение, что с регулярностью на 2.18а: не выдумывать, а
 * признаваться. Разница лишь в том, что там правило хранит текст
 * человека, а здесь — проверяет его.
 */

/**
 * Корни слов, которыми по-русски называют **момент или период времени**.
 *
 * Список закрытый и намеренно узкий. Первая версия была широкой, и живая
 * выгрузка 27.08.2026 показала, чем это кончается: в списке стояли
 * «годовщина», «день рождения», «праздник», «отпуск», «каникулы» — и
 * модель спокойно выдумала «спланировать годовщину родителей» на 26
 * сентября и «поздравить с днём рождения» на 12 сентября. Человек не
 * называл ни одной из этих дат.
 *
 * **Событие — не время.** «День рождения» подразумевает дату, но не
 * называет её; для проверки это то же самое, что её нет. Убраны и слова
 * вроде «успеть», «пора», «скоро», «потом», «уже»: ни одно не называет
 * момент, а вместе они пропускали почти всё.
 *
 * Проверка отсекает случай «о времени не было сказано вообще ничего» —
 * самый частый и самый вредный.
 */
const TIME_WORDS = [
  // Дни относительно сегодня
  'сегодня',
  'завтра',
  'послезавтра',
  'вчера',
  'ночью',
  'утром',
  'днём',
  'днем',
  'вечером',

  // Дни недели
  'понедельник',
  'вторник',
  'сред',
  'четверг',
  'пятниц',
  'суббот',
  'воскресен',
  'будни',
  'выходны',

  // Периоды
  'недел',
  'месяц',
  'год',
  'квартал',
  'полугод',
  'выходные',

  // Месяцы
  'январ',
  'феврал',
  'март',
  'апрел',
  'мая',
  'май',
  'июн',
  'июл',
  'август',
  'сентябр',
  'октябр',
  'ноябр',
  'декабр',

  // Указания на срок словами
  'срок',
  'дедлайн',
  'к числу',
  'числа',
  'через',
  'до конца',
  'полугод',
] as const;

/**
 * События, которые подразумевают дату, но не называют её.
 *
 * Вырезаются из текста **до** поиска слов о времени, потому что внутри
 * них эти слова и сидят: «годовщину» содержит «год», «днём рождения» —
 * «днём». Без вырезания проверка пропускала оба, и живая выгрузка
 * 27.08.2026 это показала: годовщина уехала на 26 сентября, день
 * рождения — на 12-е, хотя человек не называл ни одной даты.
 */
const EVENT_PHRASES = [
  'годовщин',
  'день рождения',
  'дня рождения',
  'дню рождения',
  'днем рождения',
  'днями рождения',
  'дни рождения',
  'праздник',
  'каникул',
  'отпуск',
  'новый год',
  'нового года',
] as const;

/** Цифры в тексте: «на 5 7 сентября», «в 9 30», «к 15-му». */
const DIGITS = /\d/u;

function normalize(text: string): string {
  return text.toLowerCase().replace(/ё/gu, 'е');
}

/** Событие — не время: вырезается вместе со своими же словами. */
function withoutEvents(normalized: string): string {
  let text = normalized;
  for (const phrase of EVENT_PHRASES) {
    text = text.split(normalize(phrase)).join(' ');
  }
  return text;
}

function hasTimeRoot(normalized: string): boolean {
  return TIME_WORDS.some((word) => normalized.includes(normalize(word)));
}

/**
 * Части суток и часы в тех формах, в которых их произносят **после
 * числа**: «до 6 вечера», «к 9 утра», «часов в 11».
 *
 * Зачем отдельным списком, а не добавить их в основной. Основной список
 * держит наречия — «вечером», «утром», — и его узость измерена: каждое
 * добавление туда ослабляет **главную** проверку, ту, что отсекает
 * выдуманные сроки. «Утра» в основном списке поймало бы и «утрату».
 *
 * Здесь другая цена ошибки: эти слова нужны, только чтобы признать
 * цитату, которая **и так обязана дословно найтись в речи**. Ослабить
 * главную проверку они не могут.
 */
const CLOCK_WORDS = ['вечера', 'утра', 'ночи', 'дня', 'часов', 'часа', 'полудня'] as const;

function namesTime(text: string): boolean {
  const normalized = withoutEvents(normalize(text));

  return (
    hasTimeRoot(normalized) || CLOCK_WORDS.some((word) => normalized.includes(normalize(word)))
  );
}

/**
 * Есть ли в тексте хоть одно слово о времени.
 *
 * Цифры считаются словом о времени: человек, назвавший число, скорее
 * всего назвал дату или час, а лишний сохранённый срок дешевле
 * потерянного.
 */
export function hasTimeWord(text: string): boolean {
  const normalized = withoutEvents(normalize(text));

  if (DIGITS.test(normalized)) return true;

  return hasTimeRoot(normalized);
}

/**
 * Текст словами: только буквы и цифры, разделённые одиночными пробелами,
 * с пробелами по краям.
 *
 * Пробелы по краям — не украшение: по ним поиск цитаты попадает **на
 * границы слов**. Без них цитата «год» нашлась бы внутри «годовщины», а
 * «мая» — внутри «замаячило».
 */
function words(text: string): string {
  const bare = normalize(text)
    .replace(/[^\p{L}\p{N}]+/gu, ' ')
    .trim();

  return bare === '' ? '' : ` ${bare} `;
}

/**
 * Цитата о времени, **подтверждённая речью человека** (задача 3.37).
 *
 * Проверка `hasTimeWord` смотрит в слова человека об этом деле — и это
 * заслуженная строгость: когда она смотрела во всю выгрузку, одного
 * «успеть» хватало, чтобы пропустить выдуманные сроки у двадцати дел.
 * Но извлечение ведущее слово о времени выбрасывает («сегодня вечером
 * надо погулять с собакой» → «Погулять с собакой»), и тогда проверка
 * отбрасывает **верную** дату: за сутки 02.09.2026 таких шесть, все на
 * днях, которые человек назвал.
 *
 * Связи мысли с предложением речи у кода нет, и **догадываться о ней
 * нельзя** — цена догадки это выдуманный срок. Но догадываться и не
 * надо: связь называет сама модель, а код её проверяет.
 *
 * Три условия, все обязательны:
 *
 * 1. в цитате есть слово о времени — и **не просто цифра**: цифра есть
 *    почти в любой речи, «5 заказов» не срок;
 * 2. цитата встречается в речи **дословно, по границам слов**;
 * 3. в ней есть что проверять — меньше трёх знаков не цитата.
 *
 * Выдумать срок после этого значит выдумать цитату, которая дословно
 * есть в речи. А если модель перескажет вместо цитаты, проверка не
 * пройдёт и получится прежнее поведение: **худший случай равен тому, что
 * было, лучший возвращает потерянные дни.**
 */
export function timeQuoteInSpeech(quote: string, speech: string): boolean {
  const needle = words(quote);
  if (needle.trim().length < 3) return false;

  // Цифра сама по себе не считается: см. условие 1.
  if (!namesTime(quote)) return false;

  if (words(speech).includes(needle)) return true;

  /**
   * Цитата не нашлась целиком — сверяем **день** из неё (задача 3.49).
   *
   * Живой прогон 03.09.2026: человек сказал «а ещё корм собаки
   * заканчивается, его тоже надо купить **завтра**», модель привела
   * цитату «завтра вечером». Такой пары слов рядом в речи нет, и верная
   * дата отбрасывалась. А «завтра» в речи есть, и дата из него считается
   * однозначно.
   *
   * Правило: слова, **называющие день** («сегодня», «завтра»,
   * «послезавтра», дни недели, «выходные», месяцы), обязаны найтись в
   * речи все до одного. Слова о часе («вечером», «до шести») дню не
   * противоречат и здесь не проверяются — они и не решают дату.
   *
   * Выдумать срок это не помогает: назвать день, которого человек не
   * называл, по-прежнему нельзя.
   */
  const spoken = words(speech);
  const named = dayWordsIn(quote);

  return named.length > 0 && named.every((word) => spoken.includes(` ${word} `));
}

/**
 * Слова цитаты, называющие **день**.
 *
 * Только они решают дату. Отдельным списком, а не через `TIME_WORDS`:
 * там лежат и «вечером», и «через», и «срок» — слова о времени, но не о
 * дне, и требовать их присутствия в речи значило бы отбрасывать верные
 * даты (см. `timeQuoteInSpeech`).
 */
const DAY_WORDS = [
  'сегодня',
  'завтра',
  'послезавтра',
  'понедельник',
  'вторник',
  'среда',
  'среду',
  'среды',
  'четверг',
  'пятница',
  'пятницу',
  'пятницы',
  'суббота',
  'субботу',
  'субботы',
  'воскресенье',
  'воскресенья',
  'выходные',
  'выходных',
  'января',
  'февраля',
  'марта',
  'апреля',
  'мая',
  'июня',
  'июля',
  'августа',
  'сентября',
  'октября',
  'ноября',
  'декабря',
] as const;

export function dayWordsIn(text: string): readonly string[] {
  const found = new Set<string>();
  const normalized = normalize(text)
    .replace(/[^\p{L}\p{N}]+/gu, ' ')
    .trim()
    .split(' ');

  for (const word of normalized) {
    if (DAY_WORDS.some((day) => normalize(day) === word)) found.add(word);
  }

  return [...found];
}

/**
 * Дни, названные словом: их дата считается **точно**, без модели.
 *
 * «Позавчера» и «вчера» сюда не входят: срок в прошлом отбрасывается
 * раньше, и подтягивать к нему нечего.
 */
const RELATIVE_DAYS: readonly (readonly [string, number])[] = [
  ['послезавтра', 2],
  ['сегодня', 0],
  ['завтра', 1],
];

/**
 * Смещения в днях, названные в тексте словом (задача 3.41).
 *
 * Порядок важен: «послезавтра» содержит «завтра», поэтому длинное слово
 * ищется первым и вырезается, иначе «послезавтра» дало бы и +2, и +1.
 *
 * Найдено на живой выгрузке проджекта 03.09.2026: «ещё **сегодня** хотел
 * позвонить бабушке» модель датировала завтрашним днём. Слово названо
 * прямо, дата из него считается однозначно — значит это работа кода.
 */
export function relativeDaysIn(text: string): readonly number[] {
  let rest = normalize(text);
  const found: number[] = [];

  for (const [word, offset] of RELATIVE_DAYS) {
    const parts = rest.split(word);
    if (parts.length > 1) {
      found.push(offset);
      rest = parts.join(' ');
    }
  }

  return found;
}

/**
 * Дни недели по-русски: для проверки, что дата действительно тот день,
 * который назвал человек.
 *
 * Замер 27.08.2026: на «записаться к стоматологу в четверг» модель
 * вернула среду, 2 сентября. Ни сегодня-четверг, ни следующий четверг —
 * просто не тот день. Считать день недели — работа кода, а не модели.
 */
const WEEKDAYS: readonly { readonly roots: readonly string[]; readonly index: number }[] = [
  { roots: ['понедельник'], index: 1 },
  { roots: ['вторник'], index: 2 },
  { roots: ['среду', 'среда', 'среды'], index: 3 },
  { roots: ['четверг'], index: 4 },
  { roots: ['пятницу', 'пятница', 'пятницы'], index: 5 },
  { roots: ['субботу', 'суббота', 'субботы'], index: 6 },
  { roots: ['воскресенье', 'воскресенья'], index: 0 },
];

/**
 * Дни недели, названные в тексте.
 *
 * Их может быть несколько: «каждый вторник и четверг». Раньше проверка в
 * таком случае отказывалась работать — и модель спокойно ставила
 * понедельник, а поймать это было нечем. Выбирать за человека один из
 * двух нельзя, но требовать, чтобы дата была **одним из названных**,
 * можно и нужно.
 */
export function weekdaysIn(text: string): readonly number[] {
  const normalized = normalize(text);

  return WEEKDAYS.filter((day) =>
    day.roots.some((root) => normalized.includes(normalize(root))),
  ).map((day) => day.index);
}

/** Какой день недели назван в тексте, если назван ровно один. */
export function weekdayIn(text: string): number | undefined {
  const found = weekdaysIn(text);
  return found.length === 1 ? found[0] : undefined;
}
