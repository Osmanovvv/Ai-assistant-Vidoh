import type { ItemType } from '../ai/schemas/classifier.js';
import { withoutClockPhrase } from './clock-time.js';

/**
 * Заголовок дела — чистое повеление (видео заказчицы 15.09.2026).
 *
 * Извлечение обязано переписывать мысль в повеление и выбрасывать
 * ведущее слово о времени — так устроены промпт и проверки сроков. Но
 * на бою из шести дел два пришли как сказано: «Хочу завтра съездить в
 * офис распечатать документы», «Надо отправить заявление на продление
 * декретного». Так они легли в карточки, в список ветки и в вечернее
 * напоминание — «Завтра срок: Хочу завтра съездить…».
 *
 * Срез — кодом, по закрытому списку и целыми словами: «надолго» и
 * «нужные» не трогаются. Слово о дне срезается только когда день уже
 * стал сроком записи — иначе «завтра» единственный след дня, и терять
 * его нельзя. Только у дел: у желания «хочу» — смысл, у состояния —
 * слова человека.
 *
 * Прогон 17.09.2026 (находка 24) добавил к дню неделю, месяц и день
 * недели («В пятницу надо забрать справку», «На следующей неделе
 * записаться к стоматологу», «В октябре пройти диспансеризацию»),
 * повторение («Каждый вторник…» — когда стало правилом и стоит в
 * карточке своей строкой) и «не забыть» / «когда-нибудь» — первое
 * модальное, второе уже стало важностью.
 */
const LEADING_MODAL =
  /^(?:(?:мне|нам)\s+)?(?:надо|нужно|необходимо|хочу|хотела|хотел|хочется|хотелось|не\s+забыть|не\s+забудь|когда-нибудь|когда\s+нибудь)(?:\s+бы)?(?:\s+(?:ещё|еще))?(?=\s)\s+/iu;

const WEEKDAYS = 'понедельник|вторник|среду|четверг|пятницу|субботу|воскресенье';
const MONTHS = 'январе|феврале|марте|апреле|мае|июне|июле|августе|сентябре|октябре|ноябре|декабре';

/**
 * Ведущее слово о дне, которое уже стало сроком: день, день недели с
 * предлогом, неделя, выходные, месяц.
 */
const LEADING_DAY = new RegExp(
  String.raw`^(?:сегодня|завтра|послезавтра|(?:в|во)\s+(?:${WEEKDAYS})|на\s+(?:этой|следующей|той)\s+неделе|на\s+неделе|на\s+выходных|в\s+(?:${MONTHS}))(?=\s)\s+`,
  'iu',
);

/** Дни в правиле повторения: «вторник», «вторникам». */
const RULE_DAYS = `${WEEKDAYS}|понедельникам|вторникам|средам|четвергам|пятницам|субботам|воскресеньям`;

/**
 * Ведущее правило повторения, когда оно уже поле записи. Дни — списком
 * (Р4, стенд 27.09.2026): «Каждый вторник и четверг у Сони бассейн» иначе
 * теряло только «Каждый вторник», и в названии оставалось «И четверг…».
 */
const LEADING_RULE = new RegExp(
  String.raw`^(?:каждый|каждую|каждое|по)\s+(?:(?:${RULE_DAYS})(?:(?:\s*,\s*|\s+и\s+)(?:${RULE_DAYS}))*|день|неделю|месяц|утро|вечер|будни|выходные)(?=\s)\s+`,
  'iu',
);

/**
 * То же правило повторения в конце названия (прогон Никиты 27.09.2026,
 * 16:44): «Каждую среду и пятницу у Димы футбол в 5» модель переписала в
 * «У Димы футбол каждую среду и пятницу», и срез с начала его не видел.
 * Только целой фразой в самом конце, после пробела или запятой.
 */
const TRAILING_RULE = new RegExp(
  String.raw`(?:\s*,\s*|\s+)(?:каждый|каждую|каждое|по)\s+(?:(?:${RULE_DAYS})(?:(?:\s*,\s*|\s+и\s+)(?:${RULE_DAYS}))*|день|неделю|месяц|утро|вечер|будни|выходные)[.!]?$`,
  'iu',
);

/** Остаток, который делом не является: одно слово о времени. */
const ONLY_TIME = new RegExp(
  String.raw`^(?:сегодня|завтра|послезавтра|(?:в|во)\s+(?:${WEEKDAYS})|в\s+(?:${MONTHS}))$`,
  'iu',
);

export function cleanTitle(
  text: string,
  item: {
    readonly type: ItemType;
    readonly hasDeadline: boolean;
    readonly hasRule?: boolean;
    /** Час стал сроком (`deadline.time`): в заголовке он дубль карточки. */
    readonly hasHour?: boolean;
  },
): string {
  if (item.type !== 'TASK') return text;

  /**
   * Срезы по кругу, пока есть что срезать: «Надо в пятницу забрать» —
   * модальное, потом день; «В пятницу надо забрать» — день, потом
   * модальное. Круг ограничен: каждое правило снимает только начало.
   */
  let rest = text.trim();
  // Час — где угодно во фразе, с предлогом: «Позвонить сестре в 3:10 сегодня».
  if (item.hasHour === true) rest = withoutClockPhrase(rest);
  for (let round = 0; round < 4; round += 1) {
    const before = rest;
    rest = rest.replace(LEADING_MODAL, '');
    if (item.hasDeadline) rest = rest.replace(LEADING_DAY, '');
    if (item.hasRule === true) rest = rest.replace(LEADING_RULE, '').replace(TRAILING_RULE, '');
    if (rest === before) break;
  }

  // После среза должно остаться дело, а не обрывок или одно слово о дне.
  if (rest === text.trim() || !/\p{L}{2,}/u.test(rest) || ONLY_TIME.test(rest)) {
    return text;
  }

  return rest.charAt(0).toUpperCase() + rest.slice(1);
}
