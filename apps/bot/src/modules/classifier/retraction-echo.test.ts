import { describe, expect, it } from 'vitest';

import { retractionEchoes } from './retraction-echo.js';

/**
 * Эхо самопоправки — не запись (стенд 21.09.2026, живой набор `live-14`).
 *
 * «Так, во вторник надо отвезти дочку к врачу, хотя нет к врачу лучше в
 * пятницу» — извлечение сделало две единицы: «Во вторник надо отвезти
 * дочку к врачу» и «К врачу лучше в пятницу». День у первой перенесён
 * верно (правило отмены вслух), а вторая — те же слова поправки — легла
 * второй записью про врача. Поправка меняет соседа, а сама записью не
 * бывает.
 */
describe('эхо самопоправки среди единиц', () => {
  const speech =
    'Так, во вторник надо отвезти дочку к врачу, хотя нет к врачу лучше в пятницу. Ещё оплатить садик до 20, купить подарок сестре.';

  it('«К врачу лучше в пятницу» рядом с «отвезти дочку к врачу» — эхо', () => {
    const units = [
      'Во вторник надо отвезти дочку к врачу',
      'К врачу лучше в пятницу',
      'оплатить садик до 20',
      'купить подарок сестре',
    ];

    expect(retractionEchoes(units, speech)).toEqual(new Set([1]));
  });

  it('в отменяющем предложении есть свои дела — они остаются: «помыть машину», «позвонить стоматологу»', () => {
    const spoken =
      'Ещё в четверг хотел заехать я на мойку. Хотя нет, давай мойку лучше в пятницу, вот в пятницу тогда надо помыть машину, ещё позвонить стоматологу, записаться на следующую неделю.';
    const units = [
      'Заехать на мойку',
      'Помыть машину в пятницу',
      'Позвонить стоматологу',
      'Записаться на следующую неделю',
    ];

    expect(retractionEchoes(units, spoken)).toEqual(new Set());
  });

  it('без соседа с общим значимым словом — не эхо: поправка сама по себе', () => {
    expect(retractionEchoes(['К врачу лучше в пятницу', 'Купить хлеб'], speech)).toEqual(new Set());
  });

  it('единица с глаголом дела — не эхо, даже внутри отменяющей фразы', () => {
    const spoken = 'Во вторник к врачу, хотя нет, лучше в пятницу записаться к врачу.';

    expect(
      retractionEchoes(['Во вторник к врачу', 'Записаться к врачу в пятницу'], spoken),
    ).toEqual(new Set());
  });

  it('речь без отмены — эха нет', () => {
    expect(
      retractionEchoes(
        ['Отвезти дочку к врачу', 'К врачу в пятницу'],
        'Во вторник отвезти дочку к врачу. К врачу в пятницу.',
      ),
    ).toEqual(new Set());
  });

  it('пустые входы ничего не ломают', () => {
    expect(retractionEchoes([], speech)).toEqual(new Set());
    expect(retractionEchoes(['К врачу лучше в пятницу'], '')).toEqual(new Set());
  });
});
