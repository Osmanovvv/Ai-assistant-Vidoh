import { describe, expect, it } from 'vitest';

import { notShopping } from './shopping-topic.js';

/**
 * «Покупки» — то, что покупают (заказчица, 30.09.2026: «Отправить посылку в
 * Калининград почему-то в покупках оказался»). Модель кладёт туда любые
 * поручения вне дома; дело, которое начинается с действия, точно не
 * покупки, уходит в сферу по умолчанию.
 */
describe('не покупка, хоть модель и сказала «покупки»', () => {
  it.each([
    'Отправить посылку в Калининград',
    'Позвонить в банк насчёт карты',
    'Завтра позвонить в банк по карте',
    'Оплатить квартплату до десятого',
    'Оплатить садик до 20',
    'Забрать документы из МФЦ в пятницу',
    'Забрать ботинки из ремонта',
    'Отвезти машину на шиномонтаж',
    'Отнести пальто в химчистку',
    'Сдать пальто в химчистку',
    'Продлить документы на машину, страховку',
    'Записаться на маникюр',
  ])('уходит: %s', (title) => {
    expect(notShopping(title)).toBe(true);
  });

  it.each([
    'Купить хлеб, молоко и яйца',
    'Заказать шампунь',
    'Сходить на Вайлдберриз',
    'Заехать в аптеку за витаминами',
    'Забрать заказ в пункте выдачи',
    'Забрать посылку с Вайлдберриз',
    'Забрать посылку с почты',
    'Оплатить заказ на Озоне',
    'Позвонить в магазин насчёт заказа',
    'Молочка',
    'Нужна химчистка',
    'В субботу купить подарок свекрови',
  ])('остаётся: %s', (title) => {
    expect(notShopping(title)).toBe(false);
  });
});
