import { openingAction } from '../router/thought-words.js';

/**
 * «Покупки» — то, что покупают (заказчица, 30.09.2026).
 *
 * «Отправить посылку в Калининград почему-то в покупках оказался». Модель
 * понимает «Покупки» как любые поручения вне дома: на стенде туда легли
 * МФЦ, банк, квартплата, шиномонтаж, химчистка. В промпте у сфер
 * определений нет, и спор с моделью ведётся здесь, узко: дело, которое
 * **начинается** с действия, точно не покупки, уходит в сферу по умолчанию
 * (решение Никиты 01.10.2026 — «Личное», и оплата тоже).
 *
 * Получение купленного — покупка: «Забрать заказ», «Забрать посылку с
 * Вайлдберриз». И любое действие о заказе — тоже: «Оплатить заказ на
 * Озоне», «Позвонить в магазин насчёт заказа». Всё, что начинается не с
 * глагола из списка («Сходить на Вайлдберриз», «Нужна химчистка»,
 * «Молочка»), остаётся, как решила модель.
 */

/** Действия, которые покупкой не бывают. */
const NOT_SHOPPING = new Set([
  'отправить',
  'позвонить',
  'созвониться',
  'написать',
  'записаться',
  'записать',
  'отвезти',
  'отвести',
  'отнести',
  'отдать',
  'оплатить',
  'заплатить',
  'продлить',
  'оформить',
  'подать',
  'сдать',
  'починить',
  'проверить',
  'узнать',
  'спросить',
  'уточнить',
  'договориться',
  'встретиться',
  'обсудить',
  'забрать',
]);

/** О заказе — это покупка при любом действии. */
const ORDER = /заказ|покупк|товар|вайлдбер|озон|маркетплейс/iu;
/** Забрать посылку или из пункта выдачи — получить купленное. */
const RECEIVED = /посылк|пункт\S*\s+выдачи/iu;

export function notShopping(title: string): boolean {
  const verb = openingAction(title);
  if (verb === undefined || !NOT_SHOPPING.has(verb)) return false;
  if (ORDER.test(title)) return false;
  if (verb === 'забрать' && RECEIVED.test(title)) return false;
  return true;
}
