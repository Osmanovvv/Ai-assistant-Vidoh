import { describe, expect, it } from 'vitest';

import { isStrictInfinitive, splitActions, splitItems } from './split-actions.js';

/**
 * Два действия через запятую — два дела (правка заказчицы 29.09.2026):
 * «Созвониться с Ириной Михайловной, проверить документы по кассе» —
 * «прописать как отдельные 2 задачи, не через запятую». Через «и» не
 * делится: «пойти на борьбу и позаниматься» — одно дело.
 *
 * Лучше не разделить, чем разделить неправильно: не разделённое остаётся
 * как было, а неверное деление портит запись. Поэтому глагол узнаётся
 * строго, а сомнительное — не делится.
 */
describe('splitActions — делить', () => {
  it.each<[string, readonly string[]]>([
    [
      'Созвониться с Ириной Михайловной, проверить документы по кассе',
      ['Созвониться с Ириной Михайловной', 'Проверить документы по кассе'],
    ],
    ['Помыть окна, постирать шторы', ['Помыть окна', 'Постирать шторы']],
    [
      'Позвонить маме, записаться к врачу, забрать справку',
      ['Позвонить маме', 'Записаться к врачу', 'Забрать справку'],
    ],
    ['Отвезти дочку в садик, забрать посылку', ['Отвезти дочку в садик', 'Забрать посылку']],
    ['Приготовить ужин, помочь сыну с уроками', ['Приготовить ужин', 'Помочь сыну с уроками']],
    [
      'Созвониться с бухгалтером, разобраться с налогами',
      ['Созвониться с бухгалтером', 'Разобраться с налогами'],
    ],
    [
      'Купить хлеб, забрать посылку и отвезти маме',
      ['Купить хлеб', 'Забрать посылку и отвезти маме'],
    ],
    ['Попросить маму забрать детей, купить хлеб', ['Попросить маму забрать детей', 'Купить хлеб']],
    [
      'Написать мужу список продуктов, позвонить маме',
      ['Написать мужу список продуктов', 'Позвонить маме'],
    ],
    ['Не забыть взять зонт, позвонить маме', ['Не забыть взять зонт', 'Позвонить маме']],
    ['Сделать уроки с сыном, погулять', ['Сделать уроки с сыном', 'Погулять']],
  ])('«%s»', (text, parts) => {
    expect(splitActions(text)).toEqual(parts);
  });
});

describe('splitActions — не делить', () => {
  it.each([
    // Список покупок — одно действие (решение о покупках — отдельно).
    'Купить овощи, мясо и специи',
    // «кровать», «дочь» — не глаголы, хоть и на -ть/-чь.
    'Купить подушку, кровать и шкаф',
    'Забрать сына, дочь',
    'Купить подарок маме, папе и бабушке',
    // Через «и» — одно дело.
    'Пойти на борьбу и позаниматься',
    'Позвонить маме',
    // Обёртка, а не дело: «не забыть», «успеть».
    'Не забыть, купить хлеб',
    'Успеть, забрать ребёнка в 5',
    'Купить хлеб, не забыть молоко',
    'Купить хлеб, успеть до закрытия',
    // Косвенный вопрос: «прийти ли».
    'Спросить у мамы, прийти ли ей в субботу',
    'Узнать, записаться ли к врачу',
    'Позвонить маме, приехать ли ей в субботу',
    // Один глагол перед запятой — вопрос или раздумье, а не дело.
    'Решить, поехать на дачу или нет',
    // Что сказать — не второе дело.
    'Сказать мужу, купить хлеб',
    'Сказать Ирине Михайловне, проверить документы',
    // До запятой нет действия.
    'Вечером, позвонить маме',
    // Внутри кавычек и скобок — название, а не дела.
    'Посмотреть фильм «Любить, верить»',
    'Купить продукты (молоко, хлеб)',
    // Второе действие — цель первого: без собеседника из первой части
    // оно теряет смысл (наборы eval-live, 30.09.2026: «Спросить про
    // дачу» — у кого?, «Поздравить её» — кого?).
    'Позвонить маме завтра, спросить про дачу',
    'Ещё раз маме позвонить, напомнить про лекарства',
    'Позвонить свекрови, поздравить её',
    'Позвонить в банк, спросить про кредит',
    'Написать Ире, узнать про встречу',
    'Попросить Лену забрать документы из офиса мужу, напомнить про счетчики',
    // Отсылка назад: «её», «туда», «это».
    'Купить торт маме, отвезти его вечером',
    'Записаться в сервис, съездить туда в субботу',
    // Что делается там, куда едешь, — одна поездка.
    'Заехать в сервис, поменять масло',
    'Сходить в магазин, купить продукты домой, молоко, хлеб',
    'Зайти к маме, забрать документы',
  ])('«%s»', (text) => {
    expect(splitActions(text)).toEqual([text]);
  });
});

describe('isStrictInfinitive — глагол узнаётся строго', () => {
  it.each([
    'купить',
    'проверить',
    'созвониться',
    'отвезти',
    'помочь',
    'сесть',
    'пройтись',
    'погулять',
    'вернуть',
    'мыть',
  ])('«%s» — глагол', (word) => {
    expect(isStrictInfinitive(word)).toBe(true);
  });

  it.each([
    'кровать',
    'дочь',
    'печать',
    'путь',
    'смерть',
    'новость',
    'радость',
    'тетрадь',
    'пять',
    'двадцать',
    'ночь',
    'есть',
    'быть',
    'гости',
    'части',
    'ртуть',
    'нефть',
    'память',
    'зять',
  ])('«%s» — не глагол', (word) => {
    expect(isStrictInfinitive(word)).toBe(false);
  });
});

describe('splitItems — какие записи делятся', () => {
  const task = (text: string, extra: Record<string, unknown> = {}) => ({
    text,
    type: 'TASK' as const,
    isProject: false,
    topic: 'работа',
    ...extra,
  });
  const TWO = 'Созвониться с Ириной Михайловной, проверить документы по кассе';

  it('дело — на части, у каждой те же поля', () => {
    expect(splitItems([task(TWO, { deadline: 'd' })])).toEqual([
      task('Созвониться с Ириной Михайловной', { deadline: 'd' }),
      task('Проверить документы по кассе', { deadline: 'd' }),
    ]);
  });

  it('проект, не-дело и дело с вопросом «утро или вечер» — как были', () => {
    const kept = [
      task(TWO, { isProject: true }),
      task(TWO, { type: 'IDEA' }),
      task(TWO, { unclearTime: [480, 1200] }),
    ];
    expect(splitItems(kept)).toEqual(kept);
  });
});
