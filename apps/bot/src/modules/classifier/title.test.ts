import { describe, expect, it } from 'vitest';

import { cleanTitle } from './title.js';

/**
 * Заголовок дела — чистое повеление (видео заказчицы 15.09.2026).
 *
 * Извлечение обязано переписывать мысль в повеление, но модель это
 * делает не всегда: на бою «Хочу завтра съездить в офис…» и «Надо
 * отправить заявление…» ушли в карточки и в вечернее напоминание как
 * есть. Срез — кодом, по закрытому списку слов, только у дел.
 */
describe('cleanTitle', () => {
  const task = { type: 'TASK', hasDeadline: false } as const;
  const dated = { type: 'TASK', hasDeadline: true } as const;

  it('срезает ведущее «надо / нужно / хочу» и поднимает первую букву', () => {
    expect(cleanTitle('Надо отправить заявление', task)).toBe('Отправить заявление');
    expect(cleanTitle('нужно позвонить маме', task)).toBe('Позвонить маме');
    expect(cleanTitle('Хочу съездить в офис', task)).toBe('Съездить в офис');
    expect(cleanTitle('Мне надо к врачу', task)).toBe('К врачу');
    expect(cleanTitle('Надо бы ещё купить хлеб', task)).toBe('Купить хлеб');
    expect(cleanTitle('Хотелось бы разобрать балкон', task)).toBe('Разобрать балкон');
  });

  it('слово о дне срезает только когда день уже стал сроком', () => {
    expect(cleanTitle('Хочу завтра съездить в офис', dated)).toBe('Съездить в офис');
    expect(cleanTitle('Завтра позвонить в банк', dated)).toBe('Позвонить в банк');
    expect(cleanTitle('Завтра позвонить в банк', task)).toBe('Завтра позвонить в банк');
    expect(cleanTitle('Сегодня вечером погулять с собакой', dated)).toBe(
      'Вечером погулять с собакой',
    );
  });

  it('целые слова: «надолго», «нужные» и «хочется» внутри не трогает', () => {
    expect(cleanTitle('Надолго уехать к маме', task)).toBe('Надолго уехать к маме');
    expect(cleanTitle('Нужные документы собрать', task)).toBe('Нужные документы собрать');
    expect(cleanTitle('Купить то, что хочется', task)).toBe('Купить то, что хочется');
  });

  it('не у дела — как есть: у желания «хочу» это смысл', () => {
    expect(
      cleanTitle('Хочу научиться играть на гитаре', { type: 'DESIRE', hasDeadline: false }),
    ).toBe('Хочу научиться играть на гитаре');
    expect(cleanTitle('Надо бы отдохнуть', { type: 'EMOTION', hasDeadline: false })).toBe(
      'Надо бы отдохнуть',
    );
  });

  it('день недели, неделя и месяц срезаются, когда стали сроком (прогон 17.09.2026, находка 24)', () => {
    /**
     * Бой 17.09.2026: «В пятницу надо забрать справку из поликлиники» при
     * сроке 18.09, «На следующей неделе записаться к стоматологу» при
     * сроке «на неделе с 21.09», «В октябре пройти диспансеризацию» при
     * сроке «в октябре» — день в заголовке дублирует срок и читается как
     * не разобранное.
     */
    expect(cleanTitle('В пятницу надо забрать справку из поликлиники', dated)).toBe(
      'Забрать справку из поликлиники',
    );
    expect(cleanTitle('На следующей неделе записаться к стоматологу', dated)).toBe(
      'Записаться к стоматологу',
    );
    expect(cleanTitle('В октябре пройти диспансеризацию', dated)).toBe('Пройти диспансеризацию');
    expect(cleanTitle('Во вторник отвезти машину на сервис', dated)).toBe(
      'Отвезти машину на сервис',
    );
    expect(cleanTitle('На выходных разобрать балкон', dated)).toBe('Разобрать балкон');
    // Модальное слово может стоять и до, и после дня.
    expect(cleanTitle('Надо в пятницу забрать справку', dated)).toBe('Забрать справку');
    // Без срока день остаётся: он часть смысла, а не дубль.
    expect(cleanTitle('В пятницу забрать справку', task)).toBe('В пятницу забрать справку');
  });

  it('«каждый вторник» срезается, когда стало правилом повторения; «не забыть» и «когда-нибудь» — всегда', () => {
    const recurring = { type: 'TASK', hasDeadline: true, hasRule: true } as const;

    // «Повторяется: каждый вторник» стоит в карточке отдельной строкой.
    expect(cleanTitle('Каждый вторник не забыть отвести дочку на танцы', recurring)).toBe(
      'Отвести дочку на танцы',
    );
    // Правила нет — «каждый вторник» единственный след повторения, остаётся
    // вместе со всем, что за ним: срезы только с начала.
    expect(cleanTitle('Каждый вторник не забыть отвести дочку на танцы', dated)).toBe(
      'Каждый вторник не забыть отвести дочку на танцы',
    );
    expect(cleanTitle('Не забыть купить корм коту', task)).toBe('Купить корм коту');
    // «Когда-нибудь» — это важность «когда-нибудь», не часть дела.
    expect(cleanTitle('Когда-нибудь разобрать фотографии на телефоне', task)).toBe(
      'Разобрать фотографии на телефоне',
    );
  });

  it('час срезается, когда стал сроком: он в карточке и в напоминании, в заголовке — дубль (бой 22.09.2026)', () => {
    // «Позвонить сестре в 3:10 сегодня» ушло в список как есть, а рядом
    // стоял «Срок: 03:10». Час — где угодно во фразе, с предлогом.
    const timed = { type: 'TASK', hasDeadline: true, hasHour: true } as const;

    expect(cleanTitle('Позвонить сестре в 3:10 сегодня', timed)).toBe('Позвонить сестре сегодня');
    expect(cleanTitle('Сходить к стоматологу в 13:00', timed)).toBe('Сходить к стоматологу');
    expect(cleanTitle('В 9 0 0 отнести компьютер', timed)).toBe('Отнести компьютер');
    expect(cleanTitle('Отнести компьютер на чистку, замена термопасты в 9:00', timed)).toBe(
      'Отнести компьютер на чистку, замена термопасты',
    );
    expect(cleanTitle('До 6 вечера забрать заказ', timed)).toBe('Забрать заказ');
    expect(cleanTitle('Позвонить маме в 15 часов', timed)).toBe('Позвонить маме');
    expect(cleanTitle('Встреча с 9 до 10', timed)).toBe('Встреча');
  });

  it('разговорный час срезается целиком, вместе со словом о дне рядом (живой прогон Никиты 22.09.2026)', () => {
    /**
     * На бою «В пол 11 вечера забрать посылку» стало «В пол забрать
     * посылку», а «Полить цветы сегодня без четверти 11 вечера» —
     * «Полить цветы сегодня без четверти»: срезка знала только «11
     * вечера». Час и день уже в сроке — в заголовке им делать нечего.
     */
    const timed = { type: 'TASK', hasDeadline: true, hasHour: true } as const;

    expect(cleanTitle('В пол 11 вечера забрать посылку', timed)).toBe('Забрать посылку');
    expect(cleanTitle('Полить цветы сегодня без четверти 11 вечера', timed)).toBe('Полить цветы');
    expect(cleanTitle('Позвонить маме завтра в половине десятого утра', timed)).toBe(
      'Позвонить маме',
    );
    expect(cleanTitle('Без пятнадцати семь быть в школе', timed)).toBe('Быть в школе');
    expect(cleanTitle('Забрать посылку сегодня в 18:00', timed)).toBe('Забрать посылку');
  });

  it('без часа в сроке цифры во фразе не трогаются', () => {
    expect(cleanTitle('Зайти в 3 магазина', dated)).toBe('Зайти в 3 магазина');
    expect(cleanTitle('Сходить к стоматологу в 13:00', dated)).toBe(
      'Сходить к стоматологу в 13:00',
    );
  });

  it('если после среза не остаётся дела — оставляет как было', () => {
    expect(cleanTitle('Надо', task)).toBe('Надо');
    expect(cleanTitle('Хочу завтра', dated)).toBe('Хочу завтра');
    expect(cleanTitle('  надо  ', task)).toBe('  надо  ');
    expect(cleanTitle('В 13:00', { type: 'TASK', hasDeadline: true, hasHour: true })).toBe(
      'В 13:00',
    );
  });
});
