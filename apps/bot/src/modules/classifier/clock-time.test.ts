/**
 * Названное время уже прошло — срок не сегодня (проджект, бой 21.09.2026).
 *
 * Выгрузка Никиты в 15:01 по Омску: «…мне сегодня надо будет сходить к
 * стоматологу в 13 0 0. В 9 0 0 мне надо отнести компьютер на чистку…».
 * Компьютер получил срок «сегодня», и проджект спросил: «как он на 9:00
 * записал на сегодня, если уже это время прошло???». Модель не знает,
 * который час: в промпте только дата (минуты в нём давали разный
 * разбор одного текста). Значит это работа кода: время названо, оно
 * позади, дня своего у дела нет — ближайшее такое время завтра.
 * Сказанное «сегодня» решает: стоматолог остаётся на сегодня.
 */
describe('часы в словах', () => {
  it('«в 13:00», «в 9 0 0» (расшифровка), «до 6 вечера», «к 9 утра», «в 15 часов» — одно чтение', () => {
    expect(clockTimesIn('сходить к стоматологу в 13:00')).toEqual([[13 * 60]]);
    expect(clockTimesIn('В 9 0 0 мне надо отнести компьютер')).toEqual([[9 * 60]]);
    expect(clockTimesIn('забрать посылку до 6 вечера')).toEqual([[18 * 60]]);
    expect(clockTimesIn('к 9 утра быть в школе')).toEqual([[9 * 60]]);
    expect(clockTimesIn('в 15 часов созвон')).toEqual([[15 * 60]]);
    expect(clockTimesIn('в 9.30 к врачу')).toEqual([[9 * 60 + 30]]);
    expect(clockTimesIn('созвон в 3 дня')).toEqual([[15 * 60]]);
    expect(clockTimesIn('в 12 обед')).toEqual([[12 * 60]]);
  });

  it('голое «в 9», «в 9 часов», «с 9 до 10» — два чтения: утро и вечер (решение Никиты 21.09.2026)', () => {
    /**
     * Утро это или вечер, из текста не видно, и угадывать нельзя. Оба
     * чтения возвращаются, а правило переноса требует, чтобы прошли оба.
     */
    expect(clockTimesIn('в 9 к врачу')).toEqual([[9 * 60, 21 * 60]]);
    expect(clockTimesIn('в 9 часов созвон')).toEqual([[9 * 60, 21 * 60]]);
    expect(clockTimesIn('с 9 до 10 позвонить Елене Михайловне')).toEqual([
      [9 * 60, 21 * 60],
      [10 * 60, 22 * 60],
    ]);
  });

  it('разговорные формы: «в половине десятого», «без пятнадцати семь», «в пол шестого» (22.09.2026)', () => {
    /**
     * Так говорят вслух чаще, чем «в 21:30». Половина — это половина
     * **следующего** часа: «половина десятого» — 9:30. «Без пятнадцати
     * семь» — 6:45. Двусмысленность утро/вечер та же, что у голого
     * «в 9»: два чтения, и перенос только когда прошли оба.
     */
    expect(clockTimesIn('созвон в половине десятого')).toEqual([[9 * 60 + 30, 21 * 60 + 30]]);
    expect(clockTimesIn('в пол шестого забрать ребёнка')).toEqual([[5 * 60 + 30, 17 * 60 + 30]]);
    expect(clockTimesIn('быть там без пятнадцати семь')).toEqual([[6 * 60 + 45, 18 * 60 + 45]]);
    expect(clockTimesIn('без двадцати восемь выходить')).toEqual([[7 * 60 + 40, 19 * 60 + 40]]);
    expect(clockTimesIn('в половине первого обед')).toEqual([[0 * 60 + 30, 12 * 60 + 30]]);
  });

  it('половина с цифрой: «в пол 11», «в пол 6» (живой прогон Никиты 22.09.2026)', () => {
    // На бою «В пол 11 забрать посылку» осталось без часа: правило ждало
    // слово («одиннадцатого»), а человек сказал цифру.
    expect(clockTimesIn('в пол 11 забрать посылку')).toEqual([[10 * 60 + 30, 22 * 60 + 30]]);
    expect(clockTimesIn('в пол 6 забрать ребёнка')).toEqual([[5 * 60 + 30, 17 * 60 + 30]]);
    expect(clockTimesIn('в пол 11 вечера')).toEqual([[22 * 60 + 30]]);
    expect(clockTimesIn('без пятнадцати 7 быть там')).toEqual([[6 * 60 + 45, 18 * 60 + 45]]);
  });

  it('часть суток снимает двусмысленность и у разговорных форм', () => {
    expect(clockTimesIn('в половине десятого вечера')).toEqual([[21 * 60 + 30]]);
    expect(clockTimesIn('без пятнадцати семь утра')).toEqual([[6 * 60 + 45]]);
  });

  it('число без часа — не время: «15 сентября», «5 7 сентября», «1968 года», «10 000 шагов», «в 3 магазина»', () => {
    for (const text of [
      'купить подарок к 15 сентября',
      'поездка на 5 7 сентября',
      'родился в 1968 году',
      'нахаживать 10 000 шагов',
      'на 3 дня',
      'через 2 дня',
      'зайти в 3 магазина',
      'сходить в 2 места',
      'позвонить в 5 раз',
      '',
    ]) {
      expect(clockTimesIn(text), text).toEqual([]);
    }
  });
});

describe('названное время уже прошло — срок завтра', () => {
  /** Понедельник 21.09.2026, 15:01 по Омску (UTC+6). */
  const NOW = new Date('2026-09-21T09:01:00.000Z');
  const ZONE = 'Asia/Omsk';
  const SPEECH =
    'В общем, смотри, мне сегодня надо будет сходить к стоматологу в 13 0 0 вот также. В 9 0 0 мне надо отнести компьютер на чистку, замена термопасты. Потом надо будет погулять с собакой.';

  function moved(itemText: string, spoken = SPEECH, now = NOW): string {
    const day = dayAfterPassedClock({ itemText, spoken, now, timeZone: ZONE });
    if (!day) return 'нет';

    return `${new Intl.DateTimeFormat('sv-SE', { timeZone: ZONE }).format(day.at)} ${day.accuracy}`;
  }

  it('«отнести компьютер в 9:00», сказанное в 15:01 без «сегодня», — завтра', () => {
    expect(moved('Отнести компьютер на чистку, замена термопасты в 9:00')).toBe('2026-09-22 day');
  });

  it('«сходить к стоматологу в 13:00» — в его предложении сказано «сегодня»: правило молчит', () => {
    expect(moved('Сходить к стоматологу в 13:00')).toBe('нет');
  });

  it('время ещё не прошло — правило молчит', () => {
    expect(
      moved('Отнести компьютер на чистку в 9:00', SPEECH, new Date('2026-09-21T02:30:00.000Z')),
    ).toBe('нет');
  });

  it('ровно названное время — ещё не прошло', () => {
    expect(
      moved('Отнести компьютер на чистку в 9:00', SPEECH, new Date('2026-09-21T03:00:00.000Z')),
    ).toBe('нет');
  });

  it('без часов в словах дела правило молчит', () => {
    expect(moved('Погулять с собакой')).toBe('нет');
  });

  it('у дела со своим днём правило молчит: «завтра в 9:00»', () => {
    expect(moved('Завтра в 9:00 отнести компьютер', 'Завтра в 9 0 0 отнести компьютер.')).toBe(
      'нет',
    );
  });

  it('«сегодня» в самих словах дела — правило молчит', () => {
    expect(moved('Сегодня в 9:00 отнести компьютер', 'Сегодня в 9 0 0 отнести компьютер.')).toBe(
      'нет',
    );
  });

  it('голое «в 9» переносится, только когда прошли оба чтения — и 9:00, и 21:00', () => {
    /**
     * Решение Никиты 21.09.2026: «в 9» в 15:01 — могло быть 21:00, перенос
     * отнял бы сегодняшнее дело; в 22:30 прошли оба чтения — ошибиться
     * нельзя, и это завтра.
     */
    const speech = 'В 9 мне надо отнести компьютер на чистку.';
    const item = 'Отнести компьютер на чистку в 9';

    // 15:01 по Омску — 9:00 прошло, 21:00 нет.
    expect(moved(item, speech, NOW)).toBe('нет');
    // 22:30 — прошли оба.
    expect(moved(item, speech, new Date('2026-09-21T16:30:00.000Z'))).toBe('2026-09-22 day');
    // 21:00 ровно — вечернее чтение ещё не прошло.
    expect(moved(item, speech, new Date('2026-09-21T15:00:00.000Z'))).toBe('нет');
  });

  it('промежуток «с 9 до 10» прошёл только после конца обоих чтений', () => {
    const speech = 'С 9 до 10 не забыть позвонить Елене Михайловне в бухгалтерию.';
    const item = 'С 9 до 10 не забыть позвонить Елене Михайловне в бухгалтерию';

    // 09:46 по Омску — ещё идёт.
    expect(moved(item, speech, new Date('2026-09-21T03:46:00.000Z'))).toBe('нет');
    // 10:30 — утреннее чтение прошло, вечернее (21–22) нет.
    expect(moved(item, speech, new Date('2026-09-21T04:30:00.000Z'))).toBe('нет');
    // 22:30 — прошли оба.
    expect(moved(item, speech, new Date('2026-09-21T16:30:00.000Z'))).toBe('2026-09-22 day');
  });
});

