describe('двусмысленный час нового дела — вопрос при записи (вариант Б, 24.09.2026)', () => {
  it('unclearClockOf: «в 7» — оба чтения; «в 4», «в 13» и без часа — не вопрос', () => {
    expect(unclearClockOf('Забрать ребёнка в 7', 'Забрать ребёнка в 7.')).toEqual([H(7), H(19)]);
    expect(unclearClockOf('Позвонить маме', 'В половине восьмого позвонить маме.')).toEqual([
      H(7, 30),
      H(19, 30),
    ]);
    expect(unclearClockOf('Поехать за ребёнком в 4 часа', 'Поехать за ребёнком в 4 часа.')).toBe(
      undefined,
    );
    expect(unclearClockOf('Сходить к врачу в 13:00', 'Сходить к врачу в 13:00.')).toBe(undefined);
    expect(unclearClockOf('Купить хлеб', 'Купить хлеб.')).toBe(undefined);
  });

  /**
   * Фраза о часе для переспроса: к ней дописывается ответ человека
   * («вечером» → «вечера»), и разбор обязан прочитать одно чтение.
   */
  it.each([H(7), H(11), H(7, 30), H(7, 15), H(10, 5), H(9, 45), H(0, 30)])(
    'clockPhraseOf(%i): без части суток — два чтения, с ней — одно, и срезается целиком',
    (morning) => {
      const phrase = clockPhraseOf(morning);
      const command = `Перенеси «Забрать ребёнка» ${phrase}`;

      expect(clockTimesIn(command)[0]).toEqual([morning, morning + H(12)]);
      expect(clockTimesIn(`${command} вечера`)[0]).toEqual([morning + H(12)]);
      // «11 ночи», «10:05 ночи», «9:45 ночи» — поздний вечер (28.09.2026).
      expect(clockTimesIn(`${command} ночи`)[0]).toEqual([
        morning >= H(9) ? morning + H(12) : morning,
      ]);
      expect(withoutClockPhrase(command)).toBe('Перенеси «Забрать ребёнка»');
      expect(hourWithoutDay(`${command} вечера`)).toBe(true);
    },
  );
});

