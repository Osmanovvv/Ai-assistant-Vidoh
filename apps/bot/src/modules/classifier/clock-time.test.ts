import { describe, expect, it } from 'vitest';

import {
  clockTimeOf,
  clockTimesIn,
  dayAfterPassedClock,
  fromNowIn,
  hourWithoutDay,
  timeShiftIn,
} from './clock-time.js';

/**
 * Названное время уже прошло — срок не сегодня (проджект, бой 21.09.2026).
 *
 * Выгрузка Никиты в 15:01 по Омску: «…мне сегодня надо будет сходить к
 * стоматологу в 13 0 0. В 9 0 0 мне надо отнести компьютер на чистку…».
 * Компьютер получил срок «сегодня», и проджект спросил: «как он на 9:00
 * записал на сегодня, если уже это время прошло???». Модель не знает,
 * который час: в промпте только дата (минуты в нём давали разный
 * разбор одного текста). Значит это работа кода: время названо, оно
 * позади, дня своего у дела нет — ближайшее такое время завтра.
 * Сказанное «сегодня» решает: стоматолог остаётся на сегодня.
 */
describe('часы в словах', () => {
  it('«в 13:00», «в 9 0 0» (расшифровка), «до 6 вечера», «к 9 утра», «в 15 часов» — одно чтение', () => {
    expect(clockTimesIn('сходить к стоматологу в 13:00')).toEqual([[13 * 60]]);
    expect(clockTimesIn('В 9 0 0 мне надо отнести компьютер')).toEqual([[9 * 60]]);
    expect(clockTimesIn('забрать посылку до 6 вечера')).toEqual([[18 * 60]]);
    expect(clockTimesIn('к 9 утра быть в школе')).toEqual([[9 * 60]]);
    expect(clockTimesIn('в 15 часов созвон')).toEqual([[15 * 60]]);
    expect(clockTimesIn('в 9.30 к врачу')).toEqual([[9 * 60 + 30]]);
    expect(clockTimesIn('созвон в 3 дня')).toEqual([[15 * 60]]);
    expect(clockTimesIn('в 12 обед')).toEqual([[12 * 60]]);
  });

  it('голое «в 9», «в 9 часов», «с 9 до 10» — два чтения: утро и вечер (решение Никиты 21.09.2026)', () => {
    /**
     * Утро это или вечер, из текста не видно, и угадывать нельзя. Оба
     * чтения возвращаются, а правило переноса требует, чтобы прошли оба.
     */
    expect(clockTimesIn('в 9 к врачу')).toEqual([[9 * 60, 21 * 60]]);
    expect(clockTimesIn('в 9 часов созвон')).toEqual([[9 * 60, 21 * 60]]);
    expect(clockTimesIn('с 9 до 10 позвонить Елене Михайловне')).toEqual([
      [9 * 60, 21 * 60],
      [10 * 60, 22 * 60],
    ]);
  });

  it('разговорные формы: «в половине десятого», «без пятнадцати семь», «в пол шестого» (22.09.2026)', () => {
    /**
     * Так говорят вслух чаще, чем «в 21:30». Половина — это половина
     * **следующего** часа: «половина десятого» — 9:30. «Без пятнадцати
     * семь» — 6:45. Двусмысленность утро/вечер та же, что у голого
     * «в 9»: два чтения, и перенос только когда прошли оба.
     */
    expect(clockTimesIn('созвон в половине десятого')).toEqual([[9 * 60 + 30, 21 * 60 + 30]]);
    expect(clockTimesIn('в пол шестого забрать ребёнка')).toEqual([[5 * 60 + 30, 17 * 60 + 30]]);
    expect(clockTimesIn('быть там без пятнадцати семь')).toEqual([[6 * 60 + 45, 18 * 60 + 45]]);
    expect(clockTimesIn('без двадцати восемь выходить')).toEqual([[7 * 60 + 40, 19 * 60 + 40]]);
    expect(clockTimesIn('в половине первого обед')).toEqual([[0 * 60 + 30, 12 * 60 + 30]]);
  });

  it('половина с цифрой: «в пол 11», «в пол 6» (живой прогон Никиты 22.09.2026)', () => {
    // На бою «В пол 11 забрать посылку» осталось без часа: правило ждало
    // слово («одиннадцатого»), а человек сказал цифру.
    expect(clockTimesIn('в пол 11 забрать посылку')).toEqual([[10 * 60 + 30, 22 * 60 + 30]]);
    expect(clockTimesIn('в пол 6 забрать ребёнка')).toEqual([[5 * 60 + 30, 17 * 60 + 30]]);
    expect(clockTimesIn('в пол 11 вечера')).toEqual([[22 * 60 + 30]]);
    expect(clockTimesIn('без пятнадцати 7 быть там')).toEqual([[6 * 60 + 45, 18 * 60 + 45]]);
  });

  it('часть суток снимает двусмысленность и у разговорных форм', () => {
    expect(clockTimesIn('в половине десятого вечера')).toEqual([[21 * 60 + 30]]);
    expect(clockTimesIn('без пятнадцати семь утра')).toEqual([[6 * 60 + 45]]);
  });

  it('число без часа — не время: «15 сентября», «5 7 сентября», «1968 года», «10 000 шагов», «в 3 магазина»', () => {
    for (const text of [
      'купить подарок к 15 сентября',
      'поездка на 5 7 сентября',
      'родился в 1968 году',
      'нахаживать 10 000 шагов',
      'на 3 дня',
      'через 2 дня',
      'зайти в 3 магазина',
      'сходить в 2 места',
      'позвонить в 5 раз',
      '',
    ]) {
      expect(clockTimesIn(text), text).toEqual([]);
    }
  });
});

describe('названное время уже прошло — срок завтра', () => {
  /** Понедельник 21.09.2026, 15:01 по Омску (UTC+6). */
  const NOW = new Date('2026-09-21T09:01:00.000Z');
  const ZONE = 'Asia/Omsk';
  const SPEECH =
    'В общем, смотри, мне сегодня надо будет сходить к стоматологу в 13 0 0 вот также. В 9 0 0 мне надо отнести компьютер на чистку, замена термопасты. Потом надо будет погулять с собакой.';

  function moved(itemText: string, spoken = SPEECH, now = NOW): string {
    const day = dayAfterPassedClock({ itemText, spoken, now, timeZone: ZONE });
    if (!day) return 'нет';

    return `${new Intl.DateTimeFormat('sv-SE', { timeZone: ZONE }).format(day.at)} ${day.accuracy}`;
  }

  it('«отнести компьютер в 9:00», сказанное в 15:01 без «сегодня», — завтра', () => {
    expect(moved('Отнести компьютер на чистку, замена термопасты в 9:00')).toBe('2026-09-22 day');
  });

  it('«сходить к стоматологу в 13:00» — в его предложении сказано «сегодня»: правило молчит', () => {
    expect(moved('Сходить к стоматологу в 13:00')).toBe('нет');
  });

  it('время ещё не прошло — правило молчит', () => {
    expect(
      moved('Отнести компьютер на чистку в 9:00', SPEECH, new Date('2026-09-21T02:30:00.000Z')),
    ).toBe('нет');
  });

  it('ровно названное время — ещё не прошло', () => {
    expect(
      moved('Отнести компьютер на чистку в 9:00', SPEECH, new Date('2026-09-21T03:00:00.000Z')),
    ).toBe('нет');
  });

  it('без часов в словах дела правило молчит', () => {
    expect(moved('Погулять с собакой')).toBe('нет');
  });

  it('у дела со своим днём правило молчит: «завтра в 9:00»', () => {
    expect(moved('Завтра в 9:00 отнести компьютер', 'Завтра в 9 0 0 отнести компьютер.')).toBe(
      'нет',
    );
  });

  it('«сегодня» в самих словах дела — правило молчит', () => {
    expect(moved('Сегодня в 9:00 отнести компьютер', 'Сегодня в 9 0 0 отнести компьютер.')).toBe(
      'нет',
    );
  });

  it('голое «в 9» переносится, только когда прошли оба чтения — и 9:00, и 21:00', () => {
    /**
     * Решение Никиты 21.09.2026: «в 9» в 15:01 — могло быть 21:00, перенос
     * отнял бы сегодняшнее дело; в 22:30 прошли оба чтения — ошибиться
     * нельзя, и это завтра.
     */
    const speech = 'В 9 мне надо отнести компьютер на чистку.';
    const item = 'Отнести компьютер на чистку в 9';

    // 15:01 по Омску — 9:00 прошло, 21:00 нет.
    expect(moved(item, speech, NOW)).toBe('нет');
    // 22:30 — прошли оба.
    expect(moved(item, speech, new Date('2026-09-21T16:30:00.000Z'))).toBe('2026-09-22 day');
    // 21:00 ровно — вечернее чтение ещё не прошло.
    expect(moved(item, speech, new Date('2026-09-21T15:00:00.000Z'))).toBe('нет');
  });

  it('промежуток «с 9 до 10» прошёл только после конца обоих чтений', () => {
    const speech = 'С 9 до 10 не забыть позвонить Елене Михайловне в бухгалтерию.';
    const item = 'С 9 до 10 не забыть позвонить Елене Михайловне в бухгалтерию';

    // 09:46 по Омску — ещё идёт.
    expect(moved(item, speech, new Date('2026-09-21T03:46:00.000Z'))).toBe('нет');
    // 10:30 — утреннее чтение прошло, вечернее (21–22) нет.
    expect(moved(item, speech, new Date('2026-09-21T04:30:00.000Z'))).toBe('нет');
    // 22:30 — прошли оба.
    expect(moved(item, speech, new Date('2026-09-21T16:30:00.000Z'))).toBe('2026-09-22 day');
  });
});

describe('час дела — для напоминания в указанный час (ТЗ проджекта 17.09.2026, шаг 5)', () => {
  const speech =
    'Мне сегодня надо будет сходить к стоматологу в 13 0 0. В 9 0 0 отнести компьютер. Потом погулять с собакой. В 9 позвонить маме.';

  it('однозначный час из слов дела — минуты от полуночи', () => {
    expect(clockTimeOf('Сходить к стоматологу в 13:00', speech)).toBe(13 * 60);
    expect(clockTimeOf('Забрать посылку до 6 вечера', 'Забрать посылку до 6 вечера.')).toBe(
      18 * 60,
    );
  });

  it('час остался только в речи — из своего предложения, если оно одно', () => {
    expect(clockTimeOf('Отнести компьютер', speech)).toBe(9 * 60);
  });

  it('двусмысленное «в 9» — часа нет: утро это или вечер, не угадываем', () => {
    expect(clockTimeOf('Позвонить маме в 9', speech)).toBeUndefined();
    expect(clockTimeOf('Позвонить маме', speech)).toBeUndefined();
  });

  it('без часа — ничего', () => {
    expect(clockTimeOf('Погулять с собакой', speech)).toBeUndefined();
  });

  it('час соседа из общего предложения не берётся: «к стоматологу в 13:00 и погулять с собакой»', () => {
    const shared = 'Завтра надо сходить к стоматологу в 13 0 0 и погулять с собакой.';

    expect(clockTimeOf('Сходить к стоматологу в 13:00', shared, ['Погулять с собакой'])).toBe(
      13 * 60,
    );
    expect(
      clockTimeOf('Погулять с собакой', shared, ['Сходить к стоматологу в 13:00']),
    ).toBeUndefined();
    // Без соседей предложение своё — час берётся, как у компьютера.
    expect(clockTimeOf('Погулять с собакой', shared)).toBe(13 * 60);
  });

  it('промежуток «с 9 до 10» — начало, если он однозначен: «с 14 до 16»', () => {
    expect(clockTimeOf('Созвон с 14 до 16', 'Созвон с 14 до 16.')).toBe(14 * 60);
    expect(clockTimeOf('Позвонить с 9 до 10', 'Позвонить с 9 до 10.')).toBeUndefined();
  });
});

describe('час после «на» (живой прогон Никиты 23.09.2026)', () => {
  /**
   * «Перенеси посылку на завтра на 12 часов» — час не прочитался: формы
   * «N часов» и «H MM» знали предлоги «в, к, до, около, после», а «на» —
   * нет. Бот честно ответил «на 24.09, 11:00» — старым часом.
   *
   * Голое «на 12» без «часов» так и остаётся не часом: «перенеси на 12»
   * — это ещё и двенадцатое число, и угадывать тут нельзя.
   */
  it('«на 12 часов», «на 9 30», «на 12:00» — час', () => {
    expect(clockTimesIn('перенеси посылку на завтра на 12 часов')).toEqual([[12 * 60]]);
    expect(clockTimesIn('перенеси на 9 30')).toEqual([[9 * 60 + 30]]);
    expect(clockTimesIn('давай на 12:00')).toEqual([[12 * 60]]);
    expect(clockTimesIn('перенеси на 15 часов')).toEqual([[15 * 60]]);
  });

  it('голое «на 12» — не час: может быть и число месяца', () => {
    expect(clockTimesIn('перенеси на 12')).toEqual([]);
    expect(clockTimesIn('купить торт на 12 человек')).toEqual([]);
    expect(clockTimesIn('уехать на 3 дня')).toEqual([]);
  });

  it('«в полдень» — 12:00, одно чтение', () => {
    expect(clockTimesIn('перенеси на полдень')).toEqual([[12 * 60]]);
    expect(clockTimesIn('созвон в полдень')).toEqual([[12 * 60]]);
  });
});

describe('час без дня — дата модели не сказана (решение Никиты 23.09.2026)', () => {
  /**
   * «Перенеси посылку на пол 1» — модель вернула 01.10 (число из часа);
   * «Перенеси дело на пол 3» — модель вернула «сегодня», и посылка уехала
   * с 24.09 на 23.09. Правило Никиты: час без дня меняет только час.
   * Значит, если в словах есть час и нет ни одного дня (ни словом, ни
   * числом вне часа), любая дата от модели — не сказанная.
   */
  it.each([
    'Перенеси посылку на пол 1.',
    'Перенеси дело на пол 3.',
    'перенеси на 12 часов',
    'давай в 9 30',
  ])('«%s» — час без дня', (text) => {
    expect(hourWithoutDay(text)).toBe(true);
  });

  it.each([
    // День назван — числом или словом.
    'перенеси на 1 сентября на пол 1',
    'на 12 число в 12 часов',
    'перенеси на завтра на пол 1',
    'в пятницу в 9 30',
    // Часа нет — правило молчит: «на 12» может быть и числом.
    'перенеси на 12',
    'перенеси на пятницу',
  ])('«%s» — не то', (text) => {
    expect(hourWithoutDay(text)).toBe(false);
  });
});

/**
 * Все способы назвать время — одной таблицей (живой прогон Никиты
 * 23.09.2026: «А лучше без 15 6» — «Там уже так — менять нечего»).
 *
 * Формы взяты из расшифровок его голосовых: распознавание пишет числа
 * цифрами («без 15 6», «на пол 1», «в 3 10»), а слова — где говорят
 * словами («без четверти», «в половине»). Два чтения — утро и вечер —
 * там, где часть суток не названа и час меньше полудня: так решено для
 * голого «в 9» (21.09.2026), и разговорные формы ведут себя так же.
 */
const H = (hour: number, minute = 0): number => hour * 60 + minute;

describe('таблица форм времени (23.09.2026)', () => {
  it.each<[string, readonly number[]]>([
    // «Без» — с цифрами и с «минут».
    ['без 15 6', [H(5, 45), H(17, 45)]],
    ['а лучше без 15 6', [H(5, 45), H(17, 45)]],
    ['без 15 минут 6', [H(5, 45), H(17, 45)]],
    ['без пятнадцати минут шесть', [H(5, 45), H(17, 45)]],
    ['без 5 7', [H(6, 55), H(18, 55)]],
    ['без 20 8', [H(7, 40), H(19, 40)]],
    ['без 10 минут 12', [H(11, 50), H(23, 50)]],
    ['без 15 6 вечера', [H(17, 45)]],
    ['без четверти 11 вечера', [H(22, 45)]],
    // Четверть и «N минут M-го» — про следующий час.
    ['четверть седьмого', [H(6, 15), H(18, 15)]],
    ['в четверть 7', [H(6, 15), H(18, 15)]],
    ['15 минут седьмого', [H(6, 15), H(18, 15)]],
    ['20 минут восьмого', [H(7, 20), H(19, 20)]],
    ['пять минут десятого', [H(9, 5), H(21, 5)]],
    // Часы и минуты словами «часов … минут».
    ['в 6 часов 15 минут', [H(6, 15)]],
    ['в 18 часов 30 минут', [H(18, 30)]],
    // Час словом.
    ['в пять вечера', [H(17)]],
    ['в шесть утра', [H(6)]],
    ['в двенадцать дня', [H(12)]],
    ['в час дня', [H(13)]],
    ['в пять', [H(5), H(17)]],
    ['в пять часов', [H(5), H(17)]],
    ['к шести', [H(6), H(18)]],
    ['до пяти', [H(5), H(17)]],
    ['в двенадцать', [H(12)]],
    ['на пять часов', [H(5), H(17)]],
    // Полночь и полдень.
    ['в полночь', [H(0)]],
    ['в полдень', [H(12)]],
    // Уже знакомые формы — не сломаны.
    ['на пол 1', [H(0, 30), H(12, 30)]],
    ['в половине 10', [H(9, 30), H(21, 30)]],
    ['в пол 11 вечера', [H(22, 30)]],
    ['в 3 10', [H(3, 10)]],
    ['на 12 часов', [H(12)]],
    ['на 10 утра', [H(10)]],
    ['в 17:30', [H(17, 30)]],
  ])('«%s»', (text, readings) => {
    expect(clockTimesIn(text)[0]).toEqual(readings);
  });

  it.each([
    'в два раза больше',
    'уехать на два дня',
    'до двух недель',
    'на пять человек',
    'в семь лет',
    '15 минут назад',
    'через 15 минут',
    'в пятницу',
    'купить 5 яблок',
  ])('«%s» — не время', (text) => {
    expect(clockTimesIn(text)).toEqual([]);
  });
});

describe('сдвиг времени (23.09.2026)', () => {
  it.each<[string, number]>([
    ['на час позже', 60],
    ['перенеси на час позже', 60],
    ['на полчаса позже', 30],
    ['на 30 минут позже', 30],
    ['на 2 часа раньше', -120],
    ['позже на час', 60],
    ['на час вперёд', 60],
    ['на полчаса назад', -30],
    ['сдвинь на 15 минут позже', 15],
    ['на полтора часа позже', 90],
  ])('«%s» — %i мин', (text, minutes) => {
    expect(timeShiftIn(text)).toBe(minutes);
  });

  it.each(['на час', 'в час дня', 'позже', 'на пятницу'])('«%s» — не сдвиг', (text) => {
    expect(timeShiftIn(text)).toBeUndefined();
  });

  it.each<[string, number]>([
    ['через час', 60],
    ['через полчаса', 30],
    ['через 2 часа', 120],
    ['через 45 минут', 45],
    ['перенеси через полтора часа', 90],
  ])('«%s» — от сейчас %i мин', (text, minutes) => {
    expect(fromNowIn(text)).toBe(minutes);
  });

  it.each(['через неделю', 'через 2 дня', 'в 5'])('«%s» — не «через время»', (text) => {
    expect(fromNowIn(text)).toBeUndefined();
  });
});

describe('сдвиг — не час на циферблате (23.09.2026)', () => {
  it.each(['на 2 часа позже', 'на 3 часа раньше', 'на 1 час вперёд'])('«%s»', (text) => {
    expect(clockTimesIn(text)).toEqual([]);
  });
});

describe('точка после фразы о часе не мешает (23.09.2026)', () => {
  it.each<[string, readonly number[]]>([
    ['Перенеси посылку на 12 часов.', [H(12)]],
    ['Перенеси посылку на завтра на 12 часов.', [H(12)]],
    ['А лучше без 15 6.', [H(5, 45), H(17, 45)]],
    ['В пять вечера.', [H(17)]],
    ['Перенеси на пол 1.', [H(0, 30), H(12, 30)]],
  ])('«%s»', (text, readings) => {
    expect(clockTimesIn(text)[0]).toEqual(readings);
  });
});
