import { describe, expect, it } from 'vitest';

import { looksLikeDatedWish } from './dated-wish.js';

/**
 * «Хочу за осень сделать ремонт в спальне» — дело, а не мечта (блок B
 * 17.09.2026, решение Никиты; живой набор 20.09.2026: и бой, и стенд
 * отдают желание).
 *
 * Правило узкое и закрытое: «хочу» **и** рамка срока («за осень», «до
 * конца месяца», «к Новому году») **и** глагол действия. Одного «хочу»
 * мало — «хочу съездить в отпуск на море хотя бы на недельку» остаётся
 * желанием: «на недельку» — длительность, не срок.
 */
describe('желание с рамкой срока — дело', () => {
  it.each([
    'Хочу за осень сделать ремонт в спальне: обои, потолок, шторы',
    'за осень хочу сделать ремонт в спальне',
    'хочу до конца месяца доделать сайт',
    'хочу к Новому году закончить курс',
    'хотим за лето переделать балкон',
    'хочу до октября разобраться с документами на машину',
  ])('«%s» — дело', (text) => {
    expect(looksLikeDatedWish(text)).toBe(true);
  });

  it.each([
    // Длительность — не срок.
    'Хочу наконец съездить в отпуск на море хотя бы на недельку',
    // Ни рамки, ни срока.
    'давно хочу научиться играть на гитаре',
    'хочу больше гулять',
    // Рамка есть, «хочу» нет — это и так дело, правило ни при чём.
    'за осень сделать ремонт',
    // «Хотелось бы» — мягче, чем «хочу»; в закрытый список не входит.
    'хотелось бы за зиму выучить английский',
    // Рамка без глагола действия.
    'хочу за лето на море',
    '',
  ])('«%s» — не дело по этому правилу', (text) => {
    expect(looksLikeDatedWish(text)).toBe(false);
  });

  it('«хочу» ищется в предложении речи с той же рамкой: извлечение его опускает', () => {
    // dump-6 17.09.2026: единица «за осень сделать ремонт в спальне», а
    // «Хочу» осталось в речи. Предложение находится по рамке «за осень».
    const speech =
      'Попросить мужа забрать посылку с почты. Хочу за осень сделать ремонт в спальне обои, потолок, шторы. Давно хочу научиться играть на гитаре.';

    expect(
      looksLikeDatedWish('за осень сделать ремонт в спальне: обои, потолок, шторы', speech),
    ).toBe(true);
    // Рамки в речи нет — «хочу» из другого предложения не считается.
    expect(looksLikeDatedWish('за зиму выучить английский', speech)).toBe(false);
    // Без речи и без своего «хочу» — не дело по этому правилу.
    expect(looksLikeDatedWish('за осень сделать ремонт в спальне')).toBe(false);
  });
});
