/**
 * «Когда-нибудь разобрать фотографии» — дело на потом, а не желание
 * (живой набор, известный промах 17.09.2026; починено 22.09.2026).
 *
 * Модель отдаёт такое желанием: «когда-нибудь» для неё сильнее
 * названного действия. Для женщины разница не безобидная: желания в
 * списки дел не попадают («Мои дела» показывают дела, в том числе из
 * «⏳ Позже», а желания — нет), и названное ею действие пропадает из
 * виду до тех пор, пока она сама о нём не спросит.
 *
 * Правило узкое, по образцу желания с рамкой срока (`dated-wish.ts`):
 * нужны **и** слово об откладывании, **и** глагол действия сразу за
 * ним, **и** отсутствие слова желания. «Хочу когда-нибудь съездить на
 * море» остаётся желанием — её правило «желание не превращается в
 * задачу» здесь главнее.
 */

/** Слова желания: при них запись остаётся желанием, что бы ни стояло рядом. */
const WISH =
  /(?<!\p{L})(?:хочу|хочется|хотим|хотелось|мечта|мечтаю|было\s+бы\s+(?:здорово|хорошо|неплохо)|давно\s+хочу)(?!\p{L})/iu;

/** Откладывание словами: «когда-нибудь», «как-нибудь», «на досуге». */
const SOMEDAY =
  /(?<!\p{L})(?:когда[\s-]*нибудь|как[\s-]*нибудь|на\s+досуге|при\s+случае|в\s+свободное\s+время)(?!\p{L})/iu;

/**
 * Глагол действия в неопределённой форме — тот же список, что у желания
 * с рамкой срока, плюс бытовые глаголы живых выгрузок.
 */
const ACTION =
  /(?<!\p{L})(?:с|до|пере|за|раз|по|от|о|вы|при|у|на)?(?:делать|смотреть|строить|ремонтировать|чинить|учить|выучить|читать|писать|дописать|бирать|брать|браться|бираться|разобрать|разобраться|готовить|купить|продать|съездить|сдать|пройти|закончить|завершить|запустить|открыть|собрать|найти|оформить|решить|заняться|навести|выбрать|записаться|похудеть|накопить|освоить|выйти|звонить|позвонить|вернуть|отдать|отвезти|привести|убрать|почистить|постирать|повесить|поменять)(?:ся)?(?!\p{L})/iu;

function normalize(text: string): string {
  return text.toLowerCase().replace(/ё/gu, 'е');
}

/**
 * Дело, отложенное словами? Действие обязано стоять **после**
 * откладывания: в «позвонить маме, когда-нибудь освободится» речь о
 * чужом обстоятельстве, а не об откладывании своего дела.
 */
export function looksLikeSomedayTask(text: string): boolean {
  const normalized = normalize(text);
  if (WISH.test(normalized)) return false;

  const someday = SOMEDAY.exec(normalized);
  if (someday === null) return false;

  const after = normalized.slice(someday.index + someday[0].length);
  return ACTION.test(after);
}
