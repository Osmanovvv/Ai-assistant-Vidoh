/** Короткое «сказать кому» — не длиннее трёх слов — пересказ, а не дело. */
const SPEECH_ADDRESS_WORDS = 3;

function wordsOf(text: string): readonly string[] {
  return (text.match(/[\p{L}-]+/gu) ?? []).map((word) => word.toLowerCase().replace(/ё/gu, 'е'));
}

/** Запятые вне «кавычек» и (скобок). */
function commasOutside(text: string): readonly number[] {
  const at: number[] = [];
  let quotes = 0;
  let brackets = 0;
  // Знаки, по которым идёт счёт, — одиночные: индексы строки годятся.
  for (let index = 0; index < text.length; index += 1) {
    const char = text[index];
    if (char === '«') quotes += 1;
    else if (char === '»') quotes = Math.max(0, quotes - 1);
    else if (char === '(') brackets += 1;
    else if (char === ')') brackets = Math.max(0, brackets - 1);
    else if (char === ',' && quotes === 0 && brackets === 0) at.push(index);
  }
  return at;
}

/** Действие перед запятой: не короче двух слов, последний глагол — не обёртка и не пересказ. */
function actionBefore(part: string): boolean {
  const words = wordsOf(part);
  if (words.length < 2) return false;
  const verbs = words.filter((word) => isStrictInfinitive(word));
  const last = verbs.at(-1);
  if (last === undefined || WRAPPERS.has(last) || TRIP_VERBS.has(last)) return false;
  return !(SPEECH.has(last) && words.length <= SPEECH_ADDRESS_WORDS);
}

/**
 * После запятой — новое дело: сразу глагол, не обёртка и не «…ли», не
 * разговор с тем, кто назван раньше, и без отсылки назад.
 */
function actionAfter(part: string): boolean {
  const words = wordsOf(part);
  const [first, second] = words;
  if (first === undefined || !isStrictInfinitive(first) || WRAPPERS.has(first)) return false;
  if (second === 'ли' || ADDRESSEE_VERBS.has(first)) return false;
  return !words.some((word) => BACK_REFERENCES.has(word));
}

/**
 * Части дела — или само дело целиком, если делить нечего или сомнительно.
 * Части — с заглавной, без хвостовых знаков.
 */
export function splitActions(text: string): readonly string[] {
  const parts: string[] = [];
  let start = 0;
  for (const comma of commasOutside(text)) {
    const before = text.slice(start, comma);
    const after = text.slice(comma + 1);
    if (actionBefore(before) && actionAfter(after)) {
      parts.push(before);
      start = comma + 1;
    }
  }
  if (parts.length === 0) return [text];
  parts.push(text.slice(start));
  return parts.map((part) => withCapital(part.trim().replace(/[\s,;]+$/u, '')));
}

interface Splittable {
  readonly text: string;
  readonly type: string;
  readonly isProject: boolean;
  readonly unclearTime?: readonly [number, number] | undefined;
}

/**
 * Записи после классификации, где два действия через запятую — две
 * записи с теми же полями. Не делятся: проект (у него свой разбор на
 * шаги), не-дело и дело, о часе которого бот сейчас спросит «утро или
 * вечер», — вопрос привязан к одной записи.
 */
export function splitItems<T extends Splittable>(items: readonly T[]): T[] {
  return items.flatMap((item) => {
    if (item.type !== 'TASK' || item.isProject || item.unclearTime !== undefined) return [item];
    const parts = splitActions(item.text);
    return parts.length < 2 ? [item] : parts.map((text) => ({ ...item, text }));
  });
}
