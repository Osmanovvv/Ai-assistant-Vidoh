/**
 * Два действия через запятую — два дела (правка заказчицы 29.09.2026).
 *
 * «Созвониться с Ириной Михайловной, проверить документы по кассе · 30.09»
 * — «прописать как отдельные 2 задачи, не через запятую». Извлечение
 * должно было разделить разные действия само (extractor@6: «дроби только
 * разные действия»), но сказанное одной фразой оставляет вместе. Делит
 * код, по названию после классификации: у частей тот же срок и сфера.
 *
 * **Лучше не разделить, чем разделить неправильно.** Не разделённое
 * остаётся как было; неверное деление портит запись («Купить подушку» и
 * «Кровать»). Поэтому:
 * - делится только по запятой, за которой сразу глагол в неопределённой
 *   форме — узнанный строго (`isStrictInfinitive`); через «и» — нет:
 *   «пойти на борьбу и позаниматься» — одно дело;
 * - до запятой — действие не короче двух слов: одно слово перед запятой —
 *   вопрос или раздумье («Узнать, записаться ли…», «Решить, поехать…»);
 * - обёртки не делятся: «не забыть, …», «успеть, …», «…, не забыть …»;
 * - косвенный вопрос — «…, прийти ли …» — не дело;
 * - что сказать — не второе дело: «Сказать мужу, купить хлеб»;
 * - второе действие — цель первого: «Позвонить маме, спросить про
 *   дачу», «Позвонить свекрови, поздравить её», «Заехать в сервис,
 *   поменять масло» — без первой части оно теряет смысл (наборы
 *   eval-live, 30.09.2026: «Спросить про дачу» — у кого?). Узнаётся по
 *   глаголу, которому нужен собеседник, по отсылке назад («её», «туда»)
 *   и по поездке в первой части — что делается там, одна поездка;
 * - внутри «кавычек» и (скобок) — название, а не дела.
 */

