/** Глагол в неопределённой форме — строго: сомнительное глаголом не считается. */
export function isStrictInfinitive(raw: string): boolean {
  const word = raw.toLowerCase().replace(/ё/gu, 'е');
  if (NOT_VERBS.has(word) || NUMBER.test(word)) return false;
  if (/(?:ти|тись)$/u.test(word)) return TI_VERBS.has(word);
  if (/(?:чь|чься)$/u.test(word)) return CH_VERBS.has(word);
  if (word.endsWith('сть')) return STJ_VERBS.has(word);
  if (word.endsWith('ться')) return word.length >= 6;
  return /[аяеиоуы]ть$/u.test(word) && word.length >= 4;
}

