import { describe, expect, it } from 'vitest';

import { detectRhythm, MAX_SPREAD, MIN_OCCURRENCES } from './detector.js';

/**
 * Определитель повторяемости (задача 3.8в).
 *
 * План просит таблицу случаев: ровные промежутки, разброс, две точки,
 * разные формулировки одного дела. Формулировки сюда не входят — их
 * различает смысловой поиск, а здесь только даты.
 *
 * Главное, что здесь проверяется, — **молчание**. Ложное «это у тебя
 * каждую неделю?» на разовом деле раздражает, а раздражение копится
 * быстрее доверия. Поэтому случаев «ритма нет» больше, чем «ритм есть».
 */

const days = (...values: readonly string[]): Date[] =>
  values.map((value) => new Date(`${value}T09:00:00.000Z`));

describe('ритм есть', () => {
  it('ровно каждую неделю', () => {
    const rhythm = detectRhythm(days('2026-08-05', '2026-08-12', '2026-08-19'));

    expect(rhythm?.kind).toBe('weekly');
    expect(rhythm?.interval).toBe(1);
  });

  it('примерно каждый месяц — тоже ритм', () => {
    // Человек живёт не по календарю: 28 и 33 дня — это «каждый месяц».
    const rhythm = detectRhythm(days('2026-06-03', '2026-07-01', '2026-08-03'));

    expect(rhythm?.kind).toBe('monthly');
    expect(rhythm?.interval).toBe(1);
  });

  it('раз в две недели', () => {
    const rhythm = detectRhythm(days('2026-08-03', '2026-08-17', '2026-08-31'));

    expect(rhythm?.kind).toBe('weekly');
    expect(rhythm?.interval).toBe(2);
  });

  it('порядок дат неважен', () => {
    // Записи приходят из базы в каком угодно порядке.
    expect(detectRhythm(days('2026-08-19', '2026-08-05', '2026-08-12'))?.kind).toBe('weekly');
  });
});

describe('ритма нет, и молчание тут — правильный ответ', () => {
  it('двух точек мало', () => {
    // Через две точки проходит прямая любой периодичности: месяц между
    // ними одинаково хорошо объясняется и правилом, и совпадением.
    expect(detectRhythm(days('2026-08-05', '2026-08-12'))).toBeUndefined();
  });

  it('«месяц, три дня, полгода» — не регулярность', () => {
    expect(detectRhythm(days('2026-01-05', '2026-02-05', '2026-02-08'))).toBeUndefined();
  });

  it('разброс больше четверти медианы не проходит', () => {
    // 7 и 12 дней: медиана 9,5, отклонение 2,5 — это 26%.
    expect(detectRhythm(days('2026-08-01', '2026-08-08', '2026-08-20'))).toBeUndefined();
  });

  it('ритм есть, но названия ему нет', () => {
    // Каждые четыре дня — это ритм, но не «каждую неделю» и не «каждый
    // месяц». Предлагать человеку «каждые 4 дня» продукт не станет:
    // такого правила в §5.1 нет.
    expect(detectRhythm(days('2026-08-01', '2026-08-05', '2026-08-09'))).toBeUndefined();
  });

  it('две записи в один день ритмом не считаются', () => {
    expect(detectRhythm(days('2026-08-01', '2026-08-01', '2026-08-08'))).toBeUndefined();
  });

  it('пустой список и одна дата', () => {
    expect(detectRhythm([])).toBeUndefined();
    expect(detectRhythm(days('2026-08-01'))).toBeUndefined();
  });
});

describe('пороги названы там, где их видно', () => {
  it('три повторения, а не два', () => {
    expect(MIN_OCCURRENCES).toBe(3);
  });

  it('разброс — четверть медианы', () => {
    expect(MAX_SPREAD).toBe(0.25);
  });
});
