import { describe, expect, it } from 'vitest';

import { askedToRemember, sourceOf } from './asked.js';

/**
 * Просьба запомнить (задача 3.8б).
 *
 * Четыре способа появления регулярности — это четыре разных уровня
 * права бота на инициативу. Правило, о котором попросили, менять без
 * спроса нельзя; правило, которое бот заметил сам, — можно предложить
 * убрать. Задним числом источник не восстановить, поэтому различать
 * надо в момент разбора.
 */

describe('просьбу слышно', () => {
  it('прямые формы', () => {
    for (const text of [
      'запомни, садик оплачивается пятого числа',
      'Запомни: это каждый месяц',
      'запиши себе, я хожу к врачу по вторникам',
      'напоминай мне про витамины',
    ]) {
      expect(askedToRemember(text), text).toBe(true);
    }
  });

  it('регулярность без просьбы просьбой не считается', () => {
    // «Каждый месяц оплачиваю садик» — человек назвал факт, а не
    // попросил бота его держать. Разница в праве бота на инициативу.
    for (const text of [
      'каждый месяц оплачиваю садик',
      'по вторникам хожу к врачу',
      'надо оплатить садик',
    ]) {
      expect(askedToRemember(text), text).toBe(false);
    }
  });

  it('слово внутри другого слова не считается', () => {
    // «Запомнилось» содержит «запомни» подстрокой, а границы `\b`
    // кириллицу не видят — отсюда разбиение по словам.
    for (const text of ['мне это запомнилось', 'запоминание дат']) {
      expect(askedToRemember(text), text).toBe(false);
    }
  });
});

describe('источник регулярности', () => {
  it('просьба поднимает источник до asked', () => {
    expect(sourceOf('запомни, это каждый месяц')).toBe('asked');
  });

  it('без просьбы остаётся тем, что решил разбор', () => {
    expect(sourceOf('каждый месяц')).toBe('stated');
    expect(sourceOf('каждый месяц', 'noticed')).toBe('noticed');
  });

  it('просьба сильнее того, что решил разбор', () => {
    // Бот мог заметить регулярность сам, но если человек её ещё и
    // попросил запомнить — это его правило, а не наблюдение бота.
    expect(sourceOf('запомни, каждый месяц', 'noticed')).toBe('asked');
  });
});
