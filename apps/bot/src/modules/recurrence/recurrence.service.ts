import type { Item } from '../../db/schema.js';
import { nextOccurrence, parseStoredRule, type RecurrenceRule } from './recurrence.js';

/**
 * Регулярное дело — одна запись, у которой движется срок (задача 3.8а).
 *
 * **Главное решение этапа, и оно продуктовое, а не техническое.**
 * Материализовать повторения проще в коде и катастрофично в продукте.
 * Женщина, пропустившая три недели, открыла бы «Все задачи» и увидела
 * стену одинаковых просроченных дел — то есть ровно ту вину, которую
 * продукт существует, чтобы снимать. §13.6 прямо запрещает подавать
 * просроченное как провал и запрещает считать пропущенные дни. Список
 * из двенадцати «оплатить садик» считает их за нас, молча и убедительно.
 *
 * Отсюда три следствия:
 *
 * 1. отметка выполнения **переносит срок** на следующее повторение, а
 *    не закрывает запись;
 * 2. **пропуски не накапливаются**: две пропущенные недели дают одну
 *    запись со сроком впереди, а не две просроченные;
 * 3. факт каждого выполнения не теряется — он ложится в `item_revisions`
 *    по инварианту 7, откуда его видно.
 *
 * **Чего это стоит, честно.** Статистика «выполнено 3 раза из 5» без
 * дополнительной работы становится невозможна. Это не потеря, а
 * граница: считать выполнения и показывать серии — это трекер привычек,
 * а он в §1.3 списка «не входит».
 */

/** Правило записи, если оно есть и рабочее. */
export function ruleOf(item: Pick<Item, 'recurrenceRule'>): RecurrenceRule | undefined {
  return parseStoredRule(item.recurrenceRule);
}

export interface MoveParams {
  readonly timeZone: string;
  readonly now: Date;
}

/**
 * Куда переехать сроку регулярного дела после отметки выполнения.
 *
 * Отсчёт идёт от **позднейшего из двух**: сегодня или нынешний срок. Оба
 * края нужны, и каждый закрывает свой случай.
 *
 * **Сегодня** закрывает пропуск. Считай мы только от прежнего срока, три
 * пропущенные недели дали бы три шага вперёд по одному — а человеку нужен
 * один ближайший вторник, а не догоняющая очередь.
 *
 * **Нынешний срок** закрывает обратное, и это нашлось ручным прогоном
 * 31.08.2026. Дело сделано **раньше** срока — «отвёл сына на плавание» в
 * понедельник, когда стоит вторник, — и следующее повторение после
 * сегодня совпадает с нынешним сроком. Изменение выходит пустым: запись
 * остаётся на месте, человек получает «не разобрала», хотя он всё сделал.
 * Случай не редкий: садик оплачивают до дедлайна.
 *
 * `undefined` означает «дело не регулярное»: его надо закрывать обычным
 * образом.
 */
export function nextDeadlineAfterDone(
  item: Pick<Item, 'recurrenceRule' | 'deadlineAt'>,
  params: MoveParams,
): Date | undefined {
  const rule = ruleOf(item);
  if (rule === undefined) return undefined;

  const deadline = item.deadlineAt;
  const after =
    deadline !== null && deadline.getTime() > params.now.getTime() ? deadline : params.now;

  return nextOccurrence(rule, { after, timeZone: params.timeZone });
}

/**
 * Отмена регулярного дела снимает правило, а не отменяет запись.
 *
 * «Больше не надо» человек говорит про напоминания, а не про то, что
 * дела не было. Отменить запись значило бы стереть и историю: садик
 * оплачивался год, и это правда, даже если больше не оплачивается.
 */
export function isRecurring(item: Pick<Item, 'recurrenceRule'>): boolean {
  return ruleOf(item) !== undefined;
}
