/**
 * Дни недели из фразы повтора — «каждый вторник и четверг», «по
 * понедельникам, средам и пятницам» (Р4 шаг 3, стенд 27.09.2026,
 * `voice-27-07`).
 *
 * Модель на такие фразы отвечает «не поняла» — набор правил их не знал.
 * Промпт не трогаем; дни достаёт код, и узко: **в фразе только слова из
 * закрытого списка** — «каждый», «по», «и», «неделю», дни недели. Любое
 * другое слово — «раз», «через», «или», «кроме», число, «вторую», чужое
 * «у Сони бассейн» — значит правила нет, как было: выдумать повтор, которого
 * человек не называл, хуже, чем оставить его слова без правила.
 *
 * И обязательно «каждый» или «по …-ам»: «вторник и четверг» без них может
 * быть и разовым. Один день — прежний путь «раз в неделю», не этот.
 */

/** Формы дней недели; понедельник — 1, воскресенье — 7. */
const WEEKDAY_FORMS: ReadonlyMap<string, number> = new Map([
  ['понедельник', 1],
  ['понедельникам', 1],
  ['вторник', 2],
  ['вторникам', 2],
  ['среда', 3],
  ['среду', 3],
  ['средам', 3],
  ['четверг', 4],
  ['четвергам', 4],
  ['пятница', 5],
  ['пятницу', 5],
  ['пятницам', 5],
  ['суббота', 6],
  ['субботу', 6],
  ['субботам', 6],
  ['воскресенье', 7],
  ['воскресеньям', 7],
]);

/** «По вторникам» — повтор и без «каждый». */
const PLURAL = new Set([
  'понедельникам',
  'вторникам',
  'средам',
  'четвергам',
  'пятницам',
  'субботам',
  'воскресеньям',
]);

const EVERY = new Set(['каждый', 'каждую', 'каждое']);

/** Всё, что может стоять в фразе помимо дней. */
const ALLOWED = new Set([...EVERY, 'по', 'и', 'а', 'также', 'неделю']);

export function weekdaysOfPhrase(phrase: string): readonly number[] | undefined {
  const words = phrase
    .toLowerCase()
    .replace(/ё/gu, 'е')
    .split(/[^\p{L}\p{N}]+/u)
    .filter((word) => word.length > 0);
  if (words.length === 0) return undefined;

  if (!words.every((word) => ALLOWED.has(word) || WEEKDAY_FORMS.has(word))) return undefined;

  const repeats =
    words.some((word) => EVERY.has(word)) ||
    (words.includes('по') && words.some((word) => PLURAL.has(word)));
  if (!repeats) return undefined;

  const days = [
    ...new Set(
      words.flatMap((word) => {
        const day = WEEKDAY_FORMS.get(word);
        return day === undefined ? [] : [day];
      }),
    ),
  ].sort((one, other) => one - other);

  return days.length >= 2 ? days : undefined;
}
