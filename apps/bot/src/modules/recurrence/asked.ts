import type { RecurrenceSource } from './recurrence.js';

/**
 * Просьба запомнить (§ запрос на изменение №1, способ второй, задача 3.8б).
 *
 * «Запомни, садик оплачивается пятого числа» — это обычная выгрузка с
 * прямо названной регулярностью. Нового намерения не нужно: разбор её
 * уже умеет. Единственное, что обязано не потеряться, — **то, что
 * человек попросил запомнить сам**, а не бот догадался.
 *
 * Различие не косметическое. Четыре способа появления регулярности
 * (`stated`, `asked`, `noticed`, `history`) — это четыре разных уровня
 * права бота на инициативу. Правило, о котором попросили, менять без
 * спроса нельзя; правило, которое бот заметил сам, — можно предложить
 * убрать. Слить их в одно значило бы потерять это различие навсегда:
 * задним числом источник не восстановить.
 *
 * **Определяется словарём, а не моделью.** «Запомни» — литеральное
 * слово, и спрашивать про него модель значит платить за то, что видно
 * глазом. Промпт при этом не меняется, а значит не нужен и прогон
 * контрольного набора.
 */

/** Формы, в которых звучит просьба запомнить. */
const ASKED = [
  'запомни',
  'запомните',
  'запиши себе',
  'держи в голове',
  'не забывай',
  'напоминай',
  'напоминай мне',
];

/**
 * Слова текста без знаков, в нижнем регистре, «ё» приравнена к «е».
 *
 * Разбиением, а не поиском подстроки: «запомнить» внутри «запомнилось»
 * границами `\b` не отсечь — они определены через латиницу.
 */
function wordsOf(text: string): readonly string[] {
  return text
    .toLowerCase()
    .replace(/ё/gu, 'е')
    .split(/[^\p{L}]+/u)
    .filter((word) => word.length > 0);
}

function hasPhrase(words: readonly string[], phrase: string): boolean {
  const parts = phrase.split(' ');
  return words.some((_unused, index) =>
    parts.every((part, shift) => words[index + shift] === part),
  );
}

/** Человек попросил запомнить — или просто назвал регулярность. */
export function askedToRemember(text: string): boolean {
  const words = wordsOf(text);
  return ASKED.some((phrase) => hasPhrase(words, phrase));
}

/**
 * Откуда взялась регулярность у этой записи.
 *
 * Разбор выгрузки всегда возвращает `stated`: он видит правило, но не
 * видит, просили его запомнить или назвали мимоходом. Здесь это
 * уточняется по сказанному.
 */
export function sourceOf(text: string, fallback: RecurrenceSource = 'stated'): RecurrenceSource {
  return askedToRemember(text) ? 'asked' : fallback;
}
