import { describe, expect, it } from 'vitest';

import { weekdaysOfPhrase } from './weekdays-phrase.js';

/**
 * Дни недели из фразы повтора (Р4 шаг 3, стенд 27.09.2026, voice-27-07).
 *
 * На «Каждый вторник и четверг» модель отвечает «не поняла» — набор
 * правил такого не знал. Дни достаёт код, и узко: в фразе только слова
 * из закрытого списка. Любое другое — «раз», «через», «или», «кроме»,
 * число, «вторую» — значит правила нет, как было.
 */

describe('фраза даёт дни', () => {
  it.each([
    ['Каждый вторник и четверг', [2, 4]],
    ['каждый вторник и четверг', [2, 4]],
    ['по вторникам и четвергам', [2, 4]],
    ['Каждую среду и пятницу', [3, 5]],
    ['по понедельникам, средам и пятницам', [1, 3, 5]],
    ['каждый понедельник, среду и пятницу', [1, 3, 5]],
    ['каждую субботу и воскресенье', [6, 7]],
    ['каждую неделю по вторникам и четвергам', [2, 4]],
    ['Каждый четверг и вторник', [2, 4]],
  ])('«%s» → %j', (phrase, days) => {
    expect(weekdaysOfPhrase(phrase)).toEqual(days);
  });
});

describe('фраза не даёт ничего — правило не строится', () => {
  it.each([
    ['один день — прежний путь «раз в неделю»', 'каждый вторник'],
    ['через неделю', 'раз в две недели по вторникам и четвергам'],
    ['«через»', 'через вторник и четверг'],
    ['выбор', 'каждый вторник или четверг'],
    ['исключение', 'каждый день кроме вторника и четверга'],
    ['число', 'каждый вторник и четверг 2 раза'],
    ['«вторую»', 'каждую вторую среду и пятницу'],
    ['без «каждый» и «по» — может быть разово', 'вторник и четверг'],
    ['по будням — свой вид', 'по будням'],
    ['чужие слова рядом', 'каждый вторник и четверг у Сони бассейн'],
    ['пусто', ''],
  ])('%s: «%s»', (_why, phrase) => {
    expect(weekdaysOfPhrase(phrase)).toBeUndefined();
  });
});
