import { describe, expect, it } from 'vitest';
import { onlyAgreementAck } from './acknowledgement.js';

describe('согласие целиком, без нового дела', () => {
  it.each([
    'Ок',
    'Да, поняла',
    'Ага, понятно',
    'Всё поняла',
    'Я поняла',
    'Хорошо, договорились',
    'Супер',
    'Отлично!',
    'Ну хорошо',
    'Ясно, понятно',
  ])('«%s» — согласие', (text) => {
    expect(onlyAgreementAck(text)).toBe(true);
  });
  it.each([
    'Да',
    'Давай',
    'Согласна',
    'Готово',
    'Сделала',
    'Сделаю завтра',
    'Завтра',
    'Не поняла',
    'Хорошо бы выспаться',
    'Всё надо сделать',
    'Я поняла, надо купить хлеб',
    'Хорошо?',
    'Ок 2',
    '«Супер»',
    'Купить книгу «Всё поняла»',
    '',
  ])('«%s» — прежний сценарий или конкретное содержание', (text) => {
    expect(onlyAgreementAck(text)).toBe(false);
  });
});
