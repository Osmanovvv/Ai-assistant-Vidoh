import { describe, expect, it } from 'vitest';

import { pastFormsOf } from './past-forms.js';

/**
 * Прошедшее время глагола дела (живая проверка Никиты 24.09.2026): по нему
 * страж узнаёт, что модель назвала открытое дело сделанным — «ты отвела
 * сельди на автостанцию, забрала посылку».
 */
describe('прошедшее время глагола дела', () => {
  it.each<[string, readonly string[]]>([
    ['забрать', ['забрал', 'забрала', 'забрали', 'забрало']],
    ['позвонить', ['позвонил', 'позвонила', 'позвонили', 'позвонило']],
    ['поехать', ['поехал', 'поехала', 'поехали', 'поехало']],
    ['записаться', ['записался', 'записалась', 'записались', 'записалось']],
    ['отвести', ['отвел', 'отвела', 'отвели', 'отвело']],
    ['отнести', ['отнес', 'отнесла', 'отнесли', 'отнесло']],
    ['привезти', ['привез', 'привезла', 'привезли', 'привезло']],
    ['пойти', ['пошел', 'пошла', 'пошли', 'пошло']],
    ['прийти', ['пришел', 'пришла', 'пришли', 'пришло']],
    ['испечь', ['испек', 'испекла', 'испекли', 'испекло']],
    ['помочь', ['помог', 'помогла', 'помогли', 'помогло']],
    ['подстричься', ['подстригся', 'подстриглась', 'подстриглись', 'подстриглось']],
    ['сесть', ['сел', 'села', 'сели', 'село']],
    ['запереть', ['запер', 'заперла', 'заперли', 'заперло']],
    ['Забрать', ['забрал', 'забрала', 'забрали', 'забрало']],
  ])('«%s»', (infinitive, forms) => {
    expect(pastFormsOf(infinitive)).toEqual(forms);
  });

  it.each(['посылку', 'надо', 'хочу', 'сегодня', 'купи', ''])(
    '«%s» — не инфинитив, форм нет',
    (word) => {
      expect(pastFormsOf(word)).toEqual([]);
    },
  );
});
