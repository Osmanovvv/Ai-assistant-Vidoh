/**
 * Сила эмоции — по словам человека (заказчица, 16.09.2026, «про
 * эмоции»).
 *
 * «Если эмоция лёгкая, бытовая — устала, бесит, надоело, всё навалилось —
 * можно отвечать тепло и иногда с лёгким юмором. Если эмоция сильная — „я
 * в панике", „я плачу", „всё разваливается" — юмор выключаем. Тон
 * становится спокойным и бережным. Чем сильнее эмоция — тем спокойнее и
 * проще ответ.»
 *
 * **Слово, а не решение модели.** Классификатор отдаёт единицы EMOTION, но
 * короткую фразу о состоянии он может и пропустить, а маршрутизатор —
 * счесть болтовнёй; человек при этом сказал «устала» буквально. Тон
 * выбирается по сказанному: правило по закрытому списку, а не догадка.
 * Список короткий намеренно: слово вне списка даёт прежний спокойный
 * ответ, а не неуместную улыбку — так ошибка дешевле.
 *
 * **Порядок — сильная, усталость, досада.** В одном тексте побеждает
 * сильная («устала так, что плачу» — без шуток), а между лёгкими —
 * усталость: она про неё саму, досада — про повод.
 *
 * Кризис (§13.7) — отдельный контур в `safety/crisis.ts`, он срабатывает
 * раньше и сюда не доходит.
 */
export type Mood = 'heavy' | 'tired' | 'annoyed';

/** Слово по корню: «устал» — «устала», «усталость», «устали». */
const stem = (root: string): RegExp => new RegExp(String.raw`(?<!\p{L})${root}`, 'u');
/** Слово целиком: «достало» — но не «достала посылку». */
const word = (text: string): RegExp => new RegExp(String.raw`(?<!\p{L})${text}(?!\p{L})`, 'u');

/** Сильная — её примеры и ближайшие к ним формы. */
const HEAVY: readonly RegExp[] = [
  stem('паник'),
  // «Плачу» — ещё и «плачу за садик»: платёж в выгрузке обычнее слёз.
  new RegExp(String.raw`(?<!\p{L})плачу(?!\p{L})(?!\s+за(?!\p{L}))`, 'u'),
  stem('плакала'),
  stem('расплакал'),
  stem('разрыдал'),
  stem('рыда'),
  word('реву'),
  stem('развалива'),
  word('больше не могу'),
  word('не могу больше'),
  word('не выдерживаю'),
  word('не справляюсь'),
  stem('истерик'),
];

/** Лёгкая усталость — «устала», «всё навалилось», «на нуле» (§13.7). */
const TIRED: readonly RegExp[] = [
  stem('устал'),
  stem('вымотал'),
  stem('измотал'),
  stem('выдохл'),
  stem('задолбал'),
  stem('заколебал'),
  stem('замучил'),
  word('нет сил'),
  word('сил нет'),
  word('без сил'),
  word('на нуле'),
  /**
   * Расшифровка речи пишет числительные цифрами (прогон 17.09.2026,
   * шаг 28): «я на нуле совсем» пришло как «Я на 0 совсем», и тон ушёл
   * ровным. Ноль — только в связке с «на» или «сил»: «на 0 этаже» и
   * «0,5 литра» — числа, а не состояние.
   */
  new RegExp(String.raw`(?<!\p{L})на 0(?!\s*(?:этаж|\d))`, 'u'),
  new RegExp(String.raw`(?<!\p{L})сил(?:\s+\p{L}+)?\s+0(?![\d])`, 'u'),
  stem('навалил'),
];

/** Лёгкая досада — «бесит», «надоело». */
const ANNOYED: readonly RegExp[] = [
  word('бесит'),
  word('бесят'),
  stem('взбесил'),
  word('злит'),
  word('злюсь'),
  stem('разозлил'),
  stem('раздража'),
  stem('надоел'),
  word('достало'),
];

/** «Ё» приравнивается к «е», знаки — к пробелу: живая речь даёт всякое. */
function normalize(text: string): string {
  return text
    .toLowerCase()
    .replace(/ё/gu, 'е')
    .replace(/[^\p{L}\p{N}]+/gu, ' ')
    .trim();
}

export function moodOf(speech: string): Mood | undefined {
  const said = normalize(speech);
  if (said === '') return undefined;

  const has = (list: readonly RegExp[]): boolean => list.some((pattern) => pattern.test(said));

  if (has(HEAVY)) return 'heavy';
  if (has(TIRED)) return 'tired';
  if (has(ANNOYED)) return 'annoyed';

  return undefined;
}
