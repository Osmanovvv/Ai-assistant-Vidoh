/**
 * Быстрое добавление (§13.3 ТЗ, задача 3.9).
 *
 * «Добавь ещё купить витамины» — ответ «Добавила.» и всё: без выдачи
 * действий, без вопроса, без открытия разбора. Женщина вспомнила
 * что-то на ходу; предлагать ей в этот момент три дела на сегодня —
 * значит превратить полсекунды в разговор.
 *
 * **Это режим ответа, а не намерение.** От обычной выгрузки быстрое
 * добавление отличается только формой реплики: запись создаётся так же,
 * в ту же тему, с тем же приоритетом. Заводить ради формы ответа седьмое
 * намерение значило бы платить маршрутизатору за то, что видно по трём
 * словам.
 *
 * **Правило в коде, а не в промпте.** В промпте оно плавало бы от версии
 * к версии, и «Добавила.» приходило бы через раз — а человек привыкает к
 * форме ответа быстрее, чем к чему бы то ни было ещё.
 */

/** Слова, которыми люди дописывают одно дело к списку. */
const MARKERS = [
  'добавь',
  'добавить',
  'запиши',
  'записать',
  'ещё',
  'еще',
  'кстати',
  'вспомнила',
  'вспомнил',
  'не забыть',
];

/**
 * Слова текста без знаков, «ё» приравнена к «е».
 *
 * Разбиением, а не поиском подстроки: «ещё» внутри «ещёщё» — выдумка, а
 * вот «еще» внутри «утешение» вполне реально, и границы `\b` кириллицу
 * не видят.
 */
function wordsOf(text: string): readonly string[] {
  return text
    .toLowerCase()
    .replace(/ё/gu, 'е')
    .split(/[^\p{L}]+/u)
    .filter((word) => word.length > 0);
}

function hasPhrase(words: readonly string[], phrase: string): boolean {
  const parts = phrase.replace(/ё/gu, 'е').split(' ');
  return words.some((_unused, index) =>
    parts.every((part, shift) => words[index + shift] === part),
  );
}

export interface QuickAddCheck {
  /**
   * Сколько дел вышло из выгрузки — считая те, что у человека уже
   * были и повторно заводить их не пришлось.
   */
  readonly created: number;
  /** Сколько дел бот собирался предложить. */
  readonly hidden: number;
  /** Нужен ли уточняющий вопрос: он важнее короткого ответа. */
  readonly asked: boolean;
  /** Было ли в выгрузке высказанное состояние (§13.7). */
  readonly emotions: number;
  /** Сказанное человеком целиком. */
  readonly spoken: string;
}

/**
 * Подходит ли выгрузка под быстрое добавление.
 *
 * Условий четыре, и каждое отсекает свой случай:
 *
 * - **одна запись** — две уже поток, и человек ждёт разбора;
 * - **вопроса не потребовалось** — вопрос важнее короткой реплики;
 * - **состояния не было** — §13.7 требует признать сказанное, а
 *   «Добавила.» в ответ на «сил нет» звучит глухо;
 * - **есть маркер добавления** — без него «купить витамины» это обычная
 *   мысль, и отвечать на неё односложно значит промолчать.
 */
export function isQuickAdd(check: QuickAddCheck): boolean {
  if (check.created !== 1) return false;
  if (check.asked) return false;
  if (check.emotions > 0) return false;

  return hasMarker(check.spoken);
}

export function hasMarker(text: string): boolean {
  const words = wordsOf(text);
  return MARKERS.some((marker) => hasPhrase(words, marker));
}
