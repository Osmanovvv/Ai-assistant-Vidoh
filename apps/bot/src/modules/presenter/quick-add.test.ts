import { describe, expect, it } from 'vitest';

import { hasMarker, isQuickAdd, type QuickAddCheck } from './quick-add.js';

/**
 * Быстрое добавление (§13.3 ТЗ, задача 3.9).
 *
 * Женщина вспомнила одно дело на ходу. Предлагать ей в этот момент три
 * дела на сегодня значит превратить полсекунды в разговор.
 *
 * Условий четыре, и каждое отсекает свой случай. Проверять надо оба
 * направления: и что короткое добавление узнаётся, и что обычная
 * выгрузка под него не попадает — иначе бот перестанет отвечать
 * по существу там, где человек этого ждёт.
 */

function check(overrides: Partial<QuickAddCheck> = {}): QuickAddCheck {
  return {
    created: 1,
    hidden: 4,
    asked: false,
    emotions: 0,
    spoken: 'добавь ещё купить витамины',
    ...overrides,
  };
}

describe('примеры из §13.3', () => {
  it('«Добавь ещё купить витамины»', () => {
    expect(isQuickAdd(check())).toBe(true);
  });

  it('«А, ещё надо записать ребёнка на плавание»', () => {
    expect(isQuickAdd(check({ spoken: 'а, ещё надо записать ребёнка на плавание' }))).toBe(true);
  });
});

describe('когда режим не включается', () => {
  it('две записи — это уже поток, и человек ждёт разбора', () => {
    expect(isQuickAdd(check({ created: 2 }))).toBe(false);
  });

  it('ни одной записи — отвечать «записала» не о чем', () => {
    expect(isQuickAdd(check({ created: 0 }))).toBe(false);
  });

  it('вопрос важнее короткой реплики', () => {
    expect(isQuickAdd(check({ asked: true }))).toBe(false);
  });

  it('высказанное состояние важнее (§13.7)', () => {
    // «Сил нет, добавь ещё витамины» — ответить «Записала» значит
    // услышать половину сказанного.
    expect(isQuickAdd(check({ emotions: 1 }))).toBe(false);
  });

  it('без маркера добавления это обычная мысль', () => {
    // «Купить витамины» само по себе — выгрузка, и односложный ответ на
    // неё читается как «бот не понял».
    expect(isQuickAdd(check({ spoken: 'купить витамины' }))).toBe(false);
  });
});

describe('маркер добавления', () => {
  it('узнаётся в разных формах', () => {
    for (const text of ['добавь молоко', 'запиши, что надо к врачу', 'кстати, надо в банк']) {
      expect(hasMarker(text), text).toBe(true);
    }
  });

  it('«ещё» с «ё» и без — одно слово', () => {
    expect(hasMarker('а ещё надо в банк')).toBe(true);
    expect(hasMarker('а еще надо в банк')).toBe(true);
  });

  it('маркер внутри другого слова не считается', () => {
    // «Утешение» содержит «еще», «добавка» — «добав».
    for (const text of ['нужно утешение', 'купить добавки к чаю']) {
      expect(hasMarker(text), text).toBe(false);
    }
  });
});

describe('неразобранное отменяет короткий ответ', () => {
  /**
   * Найдено живым прогоном через Telegram 02.09.2026 (задача 3.32).
   *
   * Человек повторил выгрузку целиком. Одно дело узналось как уже
   * имеющееся, поправка к нему ушла в черновик — осталась одна запись и
   * маркер «ещё» в тексте. Бот ответил «Записала.» на то, чего не
   * записывал, и промолчал о неразобранном.
   */
  it('черновик в выгрузке отменяет быстрое добавление', () => {
    expect(isQuickAdd(check({ parked: true }))).toBe(false);
  });

  it('без черновика правило работает как прежде', () => {
    expect(isQuickAdd(check())).toBe(true);
    expect(isQuickAdd(check({ parked: false }))).toBe(true);
  });
});
