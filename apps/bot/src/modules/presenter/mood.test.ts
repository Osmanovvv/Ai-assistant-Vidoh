import { describe, expect, it } from 'vitest';

import { moodOf } from './mood.js';

/**
 * Сила эмоции — по словам человека (заказчица, 16.09.2026, «про
 * эмоции»): лёгкая бытовая — тепло и с лёгкой улыбкой; сильная — спокойно
 * и без юмора; нет слов — нет и тона. Правило, а не догадка: слово либо
 * есть в закрытом списке, либо нет.
 */
describe('moodOf — сила эмоции по её примерам', () => {
  it('лёгкая усталость: «устала», «навалилось», «вымоталась», «на нуле»', () => {
    expect(moodOf('Я ужасно устала, ещё надо забрать заказ и написать учительнице')).toBe('tired');
    expect(moodOf('Я сегодня вообще вымоталась')).toBe('tired');
    expect(moodOf('и как-то всё навалилось')).toBe('tired');
    expect(moodOf('Я на нуле совсем. Ещё надо оплатить садик')).toBe('tired');
    expect(moodOf('Задолбалась всё это в голове держать')).toBe('tired');
  });

  it('расшифровка пишет цифрой: «на 0 совсем», «сил 0» — та же усталость (прогон 17.09.2026, шаг 28)', () => {
    // Бой: Никита сказал «я на нуле совсем», SpeechKit записал «Я на 0
    // совсем» — слово из списка не совпало, и тон ушёл ровным.
    expect(moodOf('Я на 0 совсем еще надо забрать ботинки из ремонта')).toBe('tired');
    expect(moodOf('сил 0, ничего не хочу')).toBe('tired');
    expect(moodOf('сил вообще 0')).toBe('tired');
    // Число как число — не состояние.
    expect(moodOf('купить 0 5 литра молока и на 0 этаже забрать посылку')).toBeUndefined();
    expect(moodOf('счёт 0 0, ничья')).toBeUndefined();
  });

  it('лёгкая досада: «бесит», «надоело», «раздражает»', () => {
    expect(moodOf('Меня бесит, что я опять забыла записаться к стоматологу')).toBe('annoyed');
    expect(moodOf('Надоело каждый день одно и то же')).toBe('annoyed');
    expect(moodOf('Раздражает, что садик опять поменял расписание')).toBe('annoyed');
  });

  it('сильная: «в панике», «плачу», «всё разваливается» — юмор выключается', () => {
    expect(moodOf('Я в панике, завтра сдавать отчёт')).toBe('heavy');
    expect(moodOf('я плачу и не знаю, с чего начать')).toBe('heavy');
    expect(moodOf('Всё разваливается')).toBe('heavy');
    expect(moodOf('Я больше не могу')).toBe('heavy');
  });

  it('сильная перевешивает лёгкую в одном тексте', () => {
    expect(moodOf('Устала так, что плачу')).toBe('heavy');
    expect(moodOf('Бесит всё, я в панике')).toBe('heavy');
  });

  it('усталость перевешивает досаду: тон один, и он про неё, а не про повод', () => {
    expect(moodOf('Устала, и бесит, что опять забыла')).toBe('tired');
  });

  it('без слов о состоянии тона нет — обычная выгрузка', () => {
    expect(moodOf('В пятницу забрать справку и позвонить в банк')).toBeUndefined();
    expect(moodOf('')).toBeUndefined();
  });

  it('усилитель «ужасно» и чужие слёзы — не сильная эмоция', () => {
    expect(moodOf('Ужасно устала')).toBe('tired');
    expect(moodOf('Ребёнок плачет по ночам, записаться к неврологу')).toBeUndefined();
  });

  it('«достала посылку» — не досада: слово целиком, а не корень', () => {
    expect(moodOf('Достала посылку с почты')).toBeUndefined();
    expect(moodOf('Достало уже всё')).toBe('annoyed');
  });

  it('регистр и «ё» не мешают', () => {
    expect(moodOf('УСТАЛА')).toBe('tired');
    expect(moodOf('всё разваливается')).toBe('heavy');
    expect(moodOf('все разваливается')).toBe('heavy');
  });
});
