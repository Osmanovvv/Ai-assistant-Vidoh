import { describe, expect, it } from 'vitest';

import { onlyThanks, saysThanks } from './thanks.js';

/**
 * «Спасибо» узнаётся по закрытому списку слов, целыми словами (заказчица,
 * 16.09.2026: «женщина поблагодарила бота» — одна из немногих ситуаций для
 * фирменного 🤍). Это правило, а не догадка: слово либо есть, либо нет.
 */
describe('saysThanks', () => {
  it('узнаёт благодарность целым словом, в любом регистре и с знаками', () => {
    expect(saysThanks('спасибо')).toBe(true);
    expect(saysThanks('Спасибо большое!')).toBe(true);
    expect(saysThanks('благодарю тебя')).toBe(true);
    expect(saysThanks('ой, спасибо, ты очень помогла')).toBe(true);
  });

  it('не узнаёт по обрывку и в чужих словах', () => {
    expect(saysThanks('привет')).toBe(false);
    expect(saysThanks('спасибочки')).toBe(false);
    expect(saysThanks('надо купить хлеб')).toBe(false);
    expect(saysThanks('')).toBe(false);
  });
});

describe('onlyThanks — чистая благодарность, без другого дела (Никита, 27.09.2026)', () => {
  /**
   * На чистую благодарность бот отвечает сразу, без ожидания тишины и
   * без модели. Поэтому список закрытый: всё, что сверх благодарности,
   * — в разбор, как раньше.
   */
  it.each([
    'Спасибо',
    'спасибо!',
    'Спасибо тебе',
    'Спасибо тебе большое 🤍',
    'Спасибо большое!!!',
    'Благодарю',
    'Огромное спасибо',
    'Спасибо, ты очень помогла',
    'Спасибо за всё',
    'Спасибо за помощь',
    'Спасибо, поняла',
    'Хорошо, спасибо',
    'Супер, спасибо',
    'Спасибо, всё понятно',
    'Да, спасибо, я поняла',
    'Ага, спасибо тебе большое',
  ])('«%s» — да', (text) => {
    expect(onlyThanks(text)).toBe(true);
  });

  it.each([
    'Спасибо, и купи хлеб',
    'спасибо, а что у меня завтра?',
    'Спасибо, перенеси на пятницу',
    'Спасибо, поняла, ещё надо позвонить маме',
    'Спасибо, готово',
    'Спасибо, сделала',
    'Спасибо, сделаю завтра',
    'Спасибо, на сегодня всё',
    'Спасибо?',
    'Спасибо 2',
    'Купить книгу «Спасибо, поняла»',
    '«Спасибо, поняла»',
    'спасибочки',
    'Большое',
    'тебе',
    '',
    '   ',
  ])('«%s» — нет', (text) => {
    expect(onlyThanks(text)).toBe(false);
  });

  it('без текста — нет (голосовое)', () => {
    expect(onlyThanks(undefined)).toBe(false);
  });
});
