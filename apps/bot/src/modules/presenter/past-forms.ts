/**
 * Прошедшее время глагола дела — «забрать» → «забрал, забрала, забрали,
 * забрало» (живая проверка Никиты 24.09.2026).
 *
 * На «Напомнишь ?» модель пересказала день и назвала открытые дела
 * сделанными: «ты отвела сельди на автостанцию, забрала посылку». Дела
 * начинаются с глагола в неопределённой форме — заголовки такими делает
 * код (`title.ts`), — и его прошедшее время в ответе значит «сделано».
 * Страж голоса по этим формам отличает открытое от сделанного.
 *
 * Правильные глаголы на «-ть» — отбрасыванием «-ть»; на «-ти» и «-чь» —
 * закрытым списком корней с приставками («отвести» → «отвёл», «пойти» →
 * «пошёл»). Незнакомый корень форм не даёт: страж тогда молчит, как и
 * прежде. «Ё» везде как «е» — так сравнивает страж.
 */

/** Корень, мужской род и основа остальных форм: «вести» → «вел», «вел-а». */
const IRREGULAR: readonly (readonly [root: string, masculine: string, stem: string])[] = [
  ['скрести', 'скреб', 'скребл'],
  ['плести', 'плел', 'плел'],
  ['цвести', 'цвел', 'цвел'],
  ['брести', 'брел', 'брел'],
  ['грести', 'греб', 'гребл'],
  ['трясти', 'тряс', 'трясл'],
  ['стричь', 'стриг', 'стригл'],
  ['переть', 'пер', 'перл'],
  ['тереть', 'тер', 'терл'],
  ['вести', 'вел', 'вел'],
  ['нести', 'нес', 'несл'],
  ['везти', 'вез', 'везл'],
  ['мести', 'мел', 'мел'],
  ['пасти', 'пас', 'пасл'],
  ['расти', 'рос', 'росл'],
  ['влечь', 'влек', 'влекл'],
  ['идти', 'шел', 'шл'],
  ['мочь', 'мог', 'могл'],
  ['лечь', 'лег', 'легл'],
  ['печь', 'пек', 'пекл'],
  ['речь', 'рег', 'регл'],
  ['жечь', 'жег', 'жгл'],
  ['сечь', 'сек', 'секл'],
  ['течь', 'тек', 'текл'],
  ['йти', 'шел', 'шл'],
];

const INFINITIVE = /^\p{L}+(?:ть|ти|чь)(?:ся|сь)?$/u;

export function pastFormsOf(infinitive: string): readonly string[] {
  const word = infinitive.toLowerCase().replace(/ё/gu, 'е');
  if (!INFINITIVE.test(word)) return [];

  const reflexive = /(?:ся|сь)$/u.test(word);
  const base = reflexive ? word.slice(0, -2) : word;

  let masculine: string;
  let stem: string;
  const irregular = IRREGULAR.find(([root]) => base.endsWith(root));
  if (irregular !== undefined) {
    const [root, ownMasculine, ownStem] = irregular;
    const prefix = base.slice(0, base.length - root.length);
    masculine = prefix + ownMasculine;
    stem = prefix + ownStem;
  } else if (base.endsWith('ть')) {
    // «сесть» → «сел», «упасть» → «упал»: «-сть» уходит целиком.
    const root = base.endsWith('сть') ? base.slice(0, -3) : base.slice(0, -2);
    masculine = `${root}л`;
    stem = `${root}л`;
  } else {
    return [];
  }

  const forms = [masculine, `${stem}а`, `${stem}и`, `${stem}о`];
  if (!reflexive) return forms;
  return [`${forms[0] ?? ''}ся`, ...forms.slice(1).map((form) => `${form}сь`)];
}
