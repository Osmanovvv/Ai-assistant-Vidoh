const of = (lines: readonly string[]): string => lines.join('\n');
const passes = (answer: string, lines: readonly string[]): void => {
  expect(siftAnswer(answer, of(lines)), answer).toEqual({ ok: true });
};
const fails = (answer: string, lines: readonly string[]): string => {
  const sifted = siftAnswer(answer, of(lines));
  expect(sifted.ok, answer).toBe(false);
  return sifted.ok ? '' : sifted.why;
};

describe('сито живого ответа: каждое слово — из фактов, её вопроса или словаря бота', () => {
  it('хорошие ответы стенда проходят', () => {
    passes(
      'Ты хотела сделать семейный альбом. Уже собрала фотографии с телефона, следующий шаг — выбрать первые фотографии, потом заказать печать.',
      facts.album,
    );
    passes(
      'Ресторан выбран, с сестрой договорились о подарке. Дальше — разослать приглашения, потом остаётся заказать торт.',
      facts.birthday,
    );
    passes('Цветы — у них срок завтра. Ковёр без срока, он подождёт.', facts.flowers);
    passes('Няню ты нашла — это закрыто.', facts.nanny);
    passes(
      'На сегодня у тебя два дела: позвонить сестре в 15:30 и сдать отчёт в 21:00. Справку из поликлиники надо было забрать 6 дней назад — она всё ещё ждёт. Остальное подождёт.',
      facts.manage,
    );
    passes('Про кота у меня ничего не записано. На сегодня — сдать отчёт в 21:00.', facts.cat);
    passes(
      'Да, ты хотела записаться к стоматологу — срок был 13.09, запись всё ещё не закрыта.',
      facts.dentist,
    );
    passes(
      'Забыла забрать справку из поликлиники — срок прошёл 6 дней назад. Ещё не написала учительнице — срок прошёл 4 дня назад. Ближайшее: купить хлеб 23.09.',
      facts.forgot,
    );
    passes('Забрать посылку с почты поручено мужу.', facts.parcel);
    passes('Ремонт в спальне — большая цель, шаги ещё не разложены.', facts.repair);
    passes(
      'Сегодня надо купить молоко. Обои пока подождут, их срок 27.09. О заказе воды помню, но у него нет срока.',
      facts.buy,
    );
    passes('Ты нашла няню и купила обои. Звонок в агентство отменён.', facts.closed);
    passes('Учить испанский ты отложила на потом.', facts.spanish);
  });

  it('выдуманная оценка или подробность — слова нет ни в фактах, ни в словаре', () => {
    expect(fails('Цветы — отличный выбор для гостиной.', facts.flowers)).toMatch(
      /^слово не из фактов/u,
    );
    expect(fails('Ковёр подождёт до выходных.', facts.flowers)).toMatch(/^слово не из фактов/u);
    expect(fails('Посылку заберёт муж, всё в порядке.', facts.parcel)).toMatch(
      /^слово не из фактов/u,
    );
    expect(fails('Ремонт — большое дело, ты справишься.', facts.repair)).toMatch(
      /^слово не из фактов/u,
    );
  });

  it('о сделанном — только если в фактах есть сделанное; «не закрыта» — всегда', () => {
    expect(fails('Стоматолог закрыт.', facts.dentist)).toMatch(/^слово не из фактов: закрыт/u);
    passes('Про стоматолога помню — запись всё ещё не закрыта.', facts.dentist);
    passes('Няню ты нашла — это закрыто.', facts.nanny);
  });

  it('«открыта» — только если в фактах есть незакрытое дело (интеграционный тест 22.09.2026)', () => {
    passes('Ты хотела записаться к стоматологу — запись всё ещё открыта.', facts.dentist);
    expect(fails('Няня — вопрос открыт.', facts.nanny)).toMatch(/^слово не из фактов: открыт/u);
  });

  it('«отложила», «поручила», «отменила» — только при таком состоянии в фактах', () => {
    passes('Учить испанский ты отложила на потом.', facts.spanish);
    expect(fails('Учить испанский ты отменила.', facts.spanish)).toMatch(
      /^слово не из фактов: отменила/u,
    );
    expect(fails('Посылку ты отложила.', facts.parcel)).toMatch(/^слово не из фактов: отложила/u);
  });
});
