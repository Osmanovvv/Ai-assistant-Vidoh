const of = (lines: readonly string[]): string => lines.join('\n');
const passes = (answer: string, lines: readonly string[]): void => {
  expect(siftAnswer(answer, of(lines)), answer).toEqual({ ok: true });
};
const fails = (answer: string, lines: readonly string[]): string => {
  const sifted = siftAnswer(answer, of(lines));
  expect(sifted.ok, answer).toBe(false);
  return sifted.ok ? '' : sifted.why;
};

describe('сито живого ответа: каждое слово — из фактов, её вопроса или словаря бота', () => {
  it('хорошие ответы стенда проходят', () => {
    passes(
      'Ты хотела сделать семейный альбом. Уже собрала фотографии с телефона, следующий шаг — выбрать первые фотографии, потом заказать печать.',
      facts.album,
    );
    passes(
      'Ресторан выбран, с сестрой договорились о подарке. Дальше — разослать приглашения, потом остаётся заказать торт.',
      facts.birthday,
    );
    passes('Цветы — у них срок завтра. Ковёр без срока, он подождёт.', facts.flowers);
    passes('Няню ты нашла — это закрыто.', facts.nanny);
    passes(
      'На сегодня у тебя два дела: позвонить сестре в 15:30 и сдать отчёт в 21:00. Справку из поликлиники надо было забрать 6 дней назад — она всё ещё ждёт. Остальное подождёт.',
      facts.manage,
    );
    passes('Про кота у меня ничего не записано. На сегодня — сдать отчёт в 21:00.', facts.cat);
    passes(
      'Да, ты хотела записаться к стоматологу — срок был 13.09, запись всё ещё не закрыта.',
      facts.dentist,
    );
    passes(
      'Забыла забрать справку из поликлиники — срок прошёл 6 дней назад. Ещё не написала учительнице — срок прошёл 4 дня назад. Ближайшее: купить хлеб 23.09.',
      facts.forgot,
    );
    passes('Забрать посылку с почты поручено мужу.', facts.parcel);
    passes('Ремонт в спальне — большая цель, шаги ещё не разложены.', facts.repair);
    passes(
      'Сегодня надо купить молоко. Обои пока подождут, их срок 27.09. О заказе воды помню, но у него нет срока.',
      facts.buy,
    );
    passes('Ты нашла няню и купила обои. Звонок в агентство отменён.', facts.closed);
    passes('Учить испанский ты отложила на потом.', facts.spanish);
  });

  it('выдуманная оценка или подробность — слова нет ни в фактах, ни в словаре', () => {
    expect(fails('Цветы — отличный выбор для гостиной.', facts.flowers)).toMatch(
      /^слово не из фактов/u,
    );
    expect(fails('Ковёр подождёт до выходных.', facts.flowers)).toMatch(/^слово не из фактов/u);
    expect(fails('Посылку заберёт муж, всё в порядке.', facts.parcel)).toMatch(
      /^слово не из фактов/u,
    );
    expect(fails('Ремонт — большое дело, ты справишься.', facts.repair)).toMatch(
      /^слово не из фактов/u,
    );
  });

  it('о сделанном — только если в фактах есть сделанное; «не закрыта» — всегда', () => {
    expect(fails('Стоматолог закрыт.', facts.dentist)).toMatch(/^слово не из фактов: закрыт/u);
    passes('Про стоматолога помню — запись всё ещё не закрыта.', facts.dentist);
    passes('Няню ты нашла — это закрыто.', facts.nanny);
  });

  it('«открыта» — только если в фактах есть незакрытое дело (интеграционный тест 22.09.2026)', () => {
    passes('Ты хотела записаться к стоматологу — запись всё ещё открыта.', facts.dentist);
    expect(fails('Няня — вопрос открыт.', facts.nanny)).toMatch(/^слово не из фактов: открыт/u);
  });

  it('«срок был» о сроке, который впереди, — неправда (бой 25.09.2026, 17:12)', () => {
    // Стоматолог перенесён на 27.09, 19:00 — послезавтра; модель: «срок был».
    const ahead = [
      'Вопрос: Что там со стоматологом?',
      'Сейчас: вечер',
      'Найдено по вопросу:',
      '— Записаться к стоматологу (здоровье), срок: послезавтра, 27.09, 19:00',
    ];
    expect(
      fails(
        'Ты хотела записаться к стоматологу — срок был 27.09, 19:00, запись всё ещё открыта.',
        ahead,
      ),
    ).toBe('срок назван прошедшим, а он впереди');
    expect(fails('Срок уже прошёл, запись открыта.', ahead)).toBe(
      'срок назван прошедшим, а он впереди',
    );
    passes('Ты хотела записаться к стоматологу — срок 27.09, 19:00, запись открыта.', ahead);
    // Будущее словами фактов (25.09.2026, Н1) — «послезавтра», «через N дней».
    passes('Записаться к стоматологу — послезавтра, 27.09 в 19:00.', ahead);
    passes('Обои подождут — их срок 27.09, через 5 дней.', facts.buy);
    // Срок действительно прошёл — «срок был» правда.
    passes(
      'Да, ты хотела записаться к стоматологу — срок был 13.09, запись всё ещё не закрыта.',
      facts.dentist,
    );
  });

  it('сроки вперемешку — сверяется дата из ответа: прошедший «был», будущий — нет', () => {
    const mixed = [
      'Вопрос: что у меня по здоровью?',
      'Сейчас: день',
      'Найдено по вопросу:',
      '— Записаться к стоматологу (здоровье), срок прошёл: 13.09, 9 дней назад',
      '— Сдать анализы (здоровье), срок: 27.09, 19:00, через 5 дней',
    ];
    passes('У стоматолога срок был 13.09 — запись всё ещё открыта.', mixed);
    expect(fails('У анализов срок был 27.09.', mixed)).toBe('срок назван прошедшим, а он впереди');
    // Порядок слов и слова между «срок» и «был» — то же самое.
    expect(fails('Был срок 27.09 у анализов.', mixed)).toBe('срок назван прошедшим, а он впереди');
    expect(fails('Срок у анализов был 27.09.', mixed)).toBe('срок назван прошедшим, а он впереди');
    // Без даты в ответе — как раньше: прошедший срок в фактах есть, значит можно.
    passes('У стоматолога срок уже прошёл, запись открыта.', mixed);
    // Дата перед фразой, а не после: «27.09, срок был» — тоже сверяется.
    expect(fails('Анализы — 27.09, срок был.', mixed)).toBe('срок назван прошедшим, а он впереди');
    passes('Стоматолог — 13.09, срок уже прошёл.', mixed);
  });

  it('день одной цифрой — «5.10» в ответе то же, что «05.10» в фактах', () => {
    const october = [
      'Вопрос: что с поликлиникой?',
      'Сейчас: день',
      'Найдено по вопросу:',
      '— Сдать анализы (здоровье), срок прошёл: 05.10, 2 дня назад',
      '— Записаться к стоматологу (здоровье), срок: послезавтра, 09.10',
    ];
    passes('У анализов срок был 5.10 — запись открыта.', october);
    expect(fails('У стоматолога срок был 9.10.', october)).toBe(
      'срок назван прошедшим, а он впереди',
    );
  });

  it('ближайшие дни в обзоре — тоже будущее: «срок был 23.09» о хлебе — неправда', () => {
    expect(fails('У хлеба срок был 23.09.', facts.manage)).toBe(
      'срок назван прошедшим, а он впереди',
    );
    passes('Справку надо было забрать 6 дней назад — срок прошёл.', facts.manage);
  });

  /** Обзор, как на бою 25.09.2026 в 20:24: на сегодня пусто, ближайшие дни — четыре дела. */
  const evening = [
    'Вопрос: На когад На когда',
    'Сейчас: вечер',
    'По вопросу ничего не найдено',
    'Ближайшие дни: Купить хлеб и молоко — 26.09; Забрать ребёнка из школы — 26.09; Записаться к стоматологу — 27.09; Позвонить маме — 27.09',
    'Открытых дел всего: 6',
  ];

  it('«ничего не назначено» — речь бота: верный ответ по обзору проходит (проверка 25.09.2026, 20:24)', () => {
    // Сито отвергло его из-за одного слова: «назначено» не было в словаре,
    // а это фраза самого бота — «На вторник ничего не назначено.»
    passes(
      'На сегодня ничего не назначено. Завтра — купить хлеб и молоко, забрать ребёнка из школы. Послезавтра — позвонить маме и записаться к стоматологу.',
      evening,
    );
  });

  it('«назначен», «назначено» без «не» — нет: это уже запись к врачу, а у неё дело «записаться»', () => {
    expect(fails('Стоматолог назначен на 27.09.', evening)).toBe('слово не из фактов: назначен');
    expect(fails('Запись к стоматологу назначено на 27.09.', evening)).toBe(
      'слово не из фактов: назначено',
    );
  });

  it('«на сегодня ничего не назначено» при делах на сегодня — неправда; «больше ничего» — правда', () => {
    const why = 'на сегодня дела есть, а сказано «ничего»';
    expect(fails('На сегодня ничего не назначено.', facts.cat)).toBe(why);
    // То же словами, которые словарь знал и раньше.
    expect(fails('На сегодня ничего не записано.', facts.cat)).toBe(why);
    expect(fails('Сегодня ничего не записано.', facts.buy)).toBe(why);
    const todayWithHour = [
      'Вопрос: что там с ребёнком?',
      'Сейчас: день',
      'Найдено по вопросу:',
      '— Забрать ребёнка из школы (семья), срок: сегодня, 16:00',
    ];
    expect(fails('На сегодня ничего не назначено.', todayWithHour)).toBe(why);
    passes('На сегодня — сдать отчёт в 21:00, больше ничего не назначено.', facts.cat);
    passes('Про кота ничего не записано.', facts.cat);
  });

  it('«отложила», «поручила», «отменила» — только при таком состоянии в фактах', () => {
    passes('Учить испанский ты отложила на потом.', facts.spanish);
    expect(fails('Учить испанский ты отменила.', facts.spanish)).toMatch(
      /^слово не из фактов: отменила/u,
    );
    expect(fails('Посылку ты отложила.', facts.parcel)).toMatch(/^слово не из фактов: отложила/u);
  });
});
