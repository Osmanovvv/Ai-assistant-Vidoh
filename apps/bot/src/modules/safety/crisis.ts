/**
 * Контур острого кризиса (задача 2.12).
 *
 * §13.7 ТЗ описывает этот случай мягче остальных требований, а цена
 * ошибки здесь выше денег. Поэтому реализация жёсткая:
 *
 * 1. **Два контура.** Список маркеров в коде и признак от модели.
 *    Срабатывание любого включает безопасный ответ. Модель может
 *    промолчать — тогда сработают маркеры; человек может сказать так, как
 *    в списке не написано — тогда сработает модель.
 * 2. **Ответ из словаря, и только из словаря.** Модель его не генерирует
 *    и не переписывает.
 * 3. **Разбор прекращается.** Ни записей, ни черновиков, ни уточняющих
 *    вопросов. Текст человека при этом на месте: он сохранён в
 *    `messages_raw` до всякого разбора (инвариант 1).
 * 4. **В журнал идёт факт, а не содержание.** Частоту ложных
 *    срабатываний оценить надо, читать чужую беду в логах — нет.
 *
 * **Маркеры — фразы, а не слова.** «Умереть» встречается в «умереть можно
 * от этой жары», и запрет по словам сработал бы там, где никакого
 * кризиса нет. Ложное срабатывание здесь не безобидно: человек вместо
 * своего списка дел получает реплику про специалиста.
 *
 * **Первый контур считается до обращения к модели.** Он ничего не стоит,
 * а значит на настоящем кризисе разбор останавливается до первой
 * потраченной копейки.
 *
 * ---
 *
 * **Требование заказчицы 27.08.2026.** Бытовая гипербола про нагрузку —
 * «я задолбалась», «я больше не могу», «убейте меня с этими делами» —
 * кризисом считаться не должна. Это не придирка: женщина приходит к боту
 * именно тогда, когда её накрыло, и говорит о своих делах резко. Если в
 * ответ на «убейте меня с этими делами» она получает реплику про
 * специалиста вместо списка дел, продукт не работает.
 *
 * Замер 27.08.2026 на живой лёгкой модели показал четыре ложных
 * срабатывания из двенадцати, все от модели. Промпт `router@3` снял
 * половину, две остались — и их правило переехало сюда, в код. Тот же
 * порядок, что со сроками на 2.7: сначала просим, потом проверяем.
 */

/**
 * Признаки острого кризиса.
 *
 * Список закрытый и намеренно узкий: сигналы прямой угрозы жизни и
 * самоповреждения. Всё остальное — тяжёлое состояние, а не кризис, и с
 * ним работает обычное правило эмоций §13.7: признание одной строкой и
 * сокращённая выдача.
 */
const MARKERS: readonly string[] = [
  'не хочу жить',
  'не хочется жить',
  'жить не хочу',
  'жить не хочется',
  'хочу умереть',
  'хочется умереть',
  'лучше бы меня не было',
  'лучше бы я не жила',
  'покончить с собой',
  'покончу с собой',
  'убить себя',
  'убью себя',
  'свести счеты с жизнью',
  'сведу счеты с жизнью',
  'резать себя',
  'режу себя',
  'сделать себе больно',
  'причинить себе вред',
  'выйти в окно',
  'шагнуть с балкона',
  'наглотаться таблеток',
];

/**
 * Обороты, которыми по-русски говорят про досаду и усталость, а не про
 * смерть.
 *
 * Работают в двух ролях:
 *
 * 1. **Гасят маркер, который сами и содержат.** «Хочется убить себя за
 *    то, что забыла» — здесь маркер «убить себя» есть, а кризиса нет.
 * 2. **Отменяют признак модели**, если модель отреагировала именно на
 *    оборот и больше ни на что (см. `modelReactedToIdiom`).
 */
const HYPERBOLE: readonly string[] = [
  // Про смерть на словах — самые опасные для проверки: в них есть и
  // глагол, и «себя», поэтому на них клюют и маркеры, и модель.
  'убейте меня',
  'убей меня',
  'убила бы себя',
  'убил бы себя',
  'готова себя убить',
  'готова убить себя',
  'хочется убить себя за',
  'убить себя за то',
  'убить себя за это',
  'хоть убей',
  'умереть можно',
  'сдохнуть можно',
  'это убивает',

  // Про нагрузку. Их назвала заказчица, и они же стоят отрицательными
  // примерами в промпте router@3. Держать их здесь безопасно ровно
  // потому, что признак отменяет не список, а пустой остаток после
  // вырезания: «я больше не могу так жить» оборот не спасёт — в остатке
  // останется «так жить».
  'задолбал',
  'больше не могу',
  'сил моих больше нет',
  'на пределе',
  'ничего не успеваю',
  'я на нуле',
  'валится из рук',
  'плохая мать',
  'хоть плачь',
  'я в аду',
];

/**
 * Слова, которые сами по себе говорят о жизни, смерти и вреде себе.
 *
 * Нужны, чтобы отличить «модель отреагировала на оборот» от «модель
 * увидела что-то ещё». Оборот из текста вырезается, и если после этого не
 * осталось ни одного такого слова — значит признак модели держался на
 * обороте, и его можно не принимать. Осталось хоть одно — модели верим.
 *
 * Это важнее, чем кажется. Без такой проверки любой оборот в длинной
 * выгрузке глушил бы признак модели целиком: «хоть убей не помню, что
 * купить… и я хочу исчезнуть навсегда» осталось бы без ответа.
 */
const RISK_WORDS: readonly string[] = [
  'жить',
  'жизн',
  'умер',
  'умру',
  'смерт',
  'убь',
  'убит',
  'убива',
  'самоубий',
  'резать',
  'порезать',
  'вены',
  'таблеток',
  'из окна',
  'с балкона',
  'исчезн',
  'покончить',
  'не было меня',
  'меня не было',
  'меня не станет',
  'меня не стало',
  'не проснуться',
  'все закончить',
  'закончить все',
  'уйти навсегда',
  'больно себе',
  'себе больно',
  'себе вред',
];

/** «Ё» приравнивается к «е»: расшифровка даёт и то и другое. */
function normalize(text: string): string {
  return text.toLowerCase().replace(/ё/gu, 'е');
}

export type CrisisContour = 'markers' | 'model';

export interface CrisisOutcome {
  readonly detected: boolean;
  /** Каким контуром. Нужно журналу: по нему видно, кто из двух работает. */
  readonly contour?: CrisisContour | undefined;
  /**
   * Какой именно маркер сработал.
   *
   * Идёт в журнал вместо текста сообщения: по маркеру видно, не он ли
   * даёт ложные срабатывания, а самого сказанного в журнале нет.
   */
  readonly marker?: string | undefined;
  /**
   * Оборот, из-за которого признак не принят.
   *
   * Тоже для журнала: по нему видно, не глушим ли мы лишнего. Без этого
   * поля отмена признака была бы невидимой, а это самое опасное место
   * во всём модуле.
   */
  readonly hyperbole?: string | undefined;
}

const NO_CRISIS: CrisisOutcome = { detected: false };

interface Occurrence {
  readonly phrase: string;
  readonly from: number;
  readonly to: number;
}

/** Все вхождения любой из фраз, с позициями. */
function occurrences(text: string, phrases: readonly string[]): Occurrence[] {
  const found: Occurrence[] = [];

  for (const phrase of phrases) {
    let at = text.indexOf(phrase);
    while (at !== -1) {
      found.push({ phrase, from: at, to: at + phrase.length });
      at = text.indexOf(phrase, at + 1);
    }
  }

  return found;
}

/**
 * Первый контур: маркеры в коде, без обращения к модели.
 *
 * **Оборот гасит только тот маркер, который сам содержит.** Раньше
 * проверка была проще: нашёлся маркер, нашёлся любой оборот где-нибудь в
 * тексте — признака нет. Аудит 28.08.2026 показал, чем это кончается:
 * «хоть убей не помню, что надо было купить, ещё садик и химчистка. и
 * вообще я не хочу жить» проходило как обычная выгрузка. Оборот из одной
 * части гасил настоящий признак из другой — то есть ошибка была в
 * сторону пропуска, а здесь это худшая из двух.
 */
export function detectByMarkers(text: string): CrisisOutcome {
  const normalized = normalize(text);

  const markers = occurrences(normalized, MARKERS);
  if (markers.length === 0) return NO_CRISIS;

  const idioms = occurrences(normalized, HYPERBOLE);
  let cover: string | undefined;

  for (const marker of markers) {
    const covered = idioms.find((idiom) => idiom.from <= marker.from && idiom.to >= marker.to);
    if (covered === undefined) return { detected: true, contour: 'markers', marker: marker.phrase };
    cover ??= covered.phrase;
  }

  // Все маркеры оказались внутри оборотов. В журнал идёт именно тот
  // оборот, который накрыл маркер, — иначе по логу не понять, что
  // произошло.
  return { detected: false, hyperbole: cover };
}

/**
 * Держался ли признак модели на речевом обороте и больше ни на чём.
 *
 * Оборот вырезается из текста, и в остатке ищутся слова о жизни, смерти и
 * вреде себе. Нет ни одного — значит модель отреагировала на оборот.
 */
function modelReactedToIdiom(normalized: string): string | undefined {
  const idioms = HYPERBOLE.filter((phrase) => normalized.includes(phrase));
  if (idioms.length === 0) return undefined;

  let rest = normalized;
  for (const idiom of idioms) rest = rest.split(idiom).join(' ');

  return RISK_WORDS.some((word) => rest.includes(word)) ? undefined : idioms[0];
}

/**
 * Оба контура вместе.
 *
 * Признак модели приходит от маршрутизатора намерений: он первый видит
 * весь текст и работает на лёгкой модели, то есть стоит дешевле любого
 * отдельного вызова.
 *
 * **Порядок важен.** Маркеры считаются первыми и отмене не подлежат:
 * если человек сказал прямо, никакая гипербола рядом этого не отменяет.
 * И только потом, когда прямого не сказано, признак модели проверяется
 * на то, не держится ли он на речевом обороте.
 */
export function detectCrisis(text: string, modelFlag: boolean | undefined): CrisisOutcome {
  const byMarkers = detectByMarkers(text);
  if (byMarkers.detected) return byMarkers;

  if (modelFlag !== true) return NO_CRISIS;

  const normalized = normalize(text);
  const idiom = modelReactedToIdiom(normalized);
  if (idiom !== undefined) return { detected: false, hyperbole: idiom };

  return { detected: true, contour: 'model' };
}
