/**
 * Контур острого кризиса (задача 2.12).
 *
 * §13.7 ТЗ описывает этот случай мягче остальных требований, а цена
 * ошибки здесь выше денег. Поэтому реализация жёсткая:
 *
 * 1. **Два контура.** Список маркеров в коде и признак от модели.
 *    Срабатывание любого включает безопасный ответ. Модель может
 *    промолчать — тогда сработают маркеры; человек может сказать так, как
 *    в списке не написано — тогда сработает модель.
 * 2. **Ответ из словаря, и только из словаря.** Модель его не генерирует
 *    и не переписывает. Формулировка согласуется с заказчиком отдельно.
 * 3. **Разбор прекращается.** Ни записей, ни черновиков, ни уточняющих
 *    вопросов. Текст человека при этом на месте: он сохранён в
 *    `messages_raw` до всякого разбора (инвариант 1).
 * 4. **В журнал идёт факт, а не содержание.** Частоту ложных
 *    срабатываний оценить надо, читать чужую беду в логах — нет.
 *
 * **Маркеры — фразы, а не слова.** «Умереть» встречается в «умереть можно
 * от этой жары», и запрет по словам сработал бы там, где никакого
 * кризиса нет. Ложное срабатывание здесь не безобидно: человек вместо
 * своего списка дел получает реплику про специалиста.
 *
 * **Первый контур считается до обращения к модели.** Он ничего не стоит,
 * а значит на настоящем кризисе разбор останавливается до первой
 * потраченной копейки.
 */

/**
 * Признаки острого кризиса.
 *
 * Список закрытый и намеренно узкий: сигналы прямой угрозы жизни и
 * самоповреждения. Всё остальное — тяжёлое состояние, а не кризис, и с
 * ним работает обычное правило эмоций §13.7: признание одной строкой и
 * сокращённая выдача.
 */
const MARKERS: readonly string[] = [
  'не хочу жить',
  'не хочется жить',
  'жить не хочу',
  'жить не хочется',
  'хочу умереть',
  'хочется умереть',
  'лучше бы меня не было',
  'лучше бы я не жила',
  'покончить с собой',
  'покончу с собой',
  'убить себя',
  'убью себя',
  'свести счеты с жизнью',
  'сведу счеты с жизнью',
  'резать себя',
  'режу себя',
  'сделать себе больно',
  'причинить себе вред',
  'выйти в окно',
  'шагнуть с балкона',
  'наглотаться таблеток',
];

/**
 * Обороты, при которых маркер означает не кризис, а речевой оборот.
 *
 * «Готова себя убить, что забыла» — так говорят про досаду. Проверяются
 * только вместе с маркером: сам по себе такой оборот ничего не значит.
 */
const HYPERBOLE: readonly string[] = [
  'готова себя убить',
  'готова убить себя',
  'хоть убей',
  'убить себя за то',
  'убить себя за это',
];

/** «Ё» приравнивается к «е»: расшифровка даёт и то и другое. */
function normalize(text: string): string {
  return text.toLowerCase().replace(/ё/gu, 'е');
}

export type CrisisContour = 'markers' | 'model';

export interface CrisisOutcome {
  readonly detected: boolean;
  /** Каким контуром. Нужно журналу: по нему видно, кто из двух работает. */
  readonly contour?: CrisisContour | undefined;
  /**
   * Какой именно маркер сработал.
   *
   * Идёт в журнал вместо текста сообщения: по маркеру видно, не он ли
   * даёт ложные срабатывания, а самого сказанного в журнале нет.
   */
  readonly marker?: string | undefined;
}

const NO_CRISIS: CrisisOutcome = { detected: false };

/** Первый контур: маркеры в коде, без обращения к модели. */
export function detectByMarkers(text: string): CrisisOutcome {
  const normalized = normalize(text);

  const found = MARKERS.find((marker) => normalized.includes(marker));
  if (found === undefined) return NO_CRISIS;

  // Речевой оборот вокруг маркера снимает срабатывание. Проверяется
  // после маркера, а не вместо: список оборотов короткий и точный.
  if (HYPERBOLE.some((phrase) => normalized.includes(phrase))) return NO_CRISIS;

  return { detected: true, contour: 'markers', marker: found };
}

/**
 * Оба контура вместе.
 *
 * Признак модели приходит от маршрутизатора намерений: он первый видит
 * весь текст и работает на лёгкой модели, то есть стоит дешевле любого
 * отдельного вызова. Если лёгкая модель окажется на контрольном наборе
 * ненадёжной, признак переедет на полную — интерфейс от этого не меняется.
 */
export function detectCrisis(text: string, modelFlag: boolean | undefined): CrisisOutcome {
  const byMarkers = detectByMarkers(text);
  if (byMarkers.detected) return byMarkers;

  return modelFlag === true ? { detected: true, contour: 'model' } : NO_CRISIS;
}
