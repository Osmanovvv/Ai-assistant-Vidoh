import { describe, expect, it } from 'vitest';

import { profiles } from '../../texts/index.js';
import { detectByMarkers, detectCrisis } from './crisis.js';

/**
 * Контур острого кризиса (задача 2.12).
 *
 * §13.7 ТЗ описывает этот случай мягче остальных требований, а цена
 * ошибки здесь выше денег. Отсюда таблица случаев в обе стороны: и на
 * срабатывание, и на молчание там, где кризиса нет.
 */

describe('первый контур: маркеры', () => {
  it.each([
    'я больше не хочу жить',
    'мне не хочется жить',
    'иногда хочу умереть',
    'лучше бы меня не было',
    'думаю покончить с собой',
    'я режу себя когда совсем плохо',
    'хочу наглотаться таблеток',
  ])('срабатывает: %s', (text) => {
    const outcome = detectByMarkers(text);

    expect(outcome.detected).toBe(true);
    expect(outcome.contour).toBe('markers');
    expect(outcome.marker).toBeTypeOf('string');
  });

  it.each([
    'я вообще ничего не успеваю',
    'я устала',
    'я на нуле',
    'всё валится из рук',
    'я плохая мать',
    'надо купить продукты и записать сына к врачу',
    'умереть можно от этой жары',
    'готова себя убить, что забыла про садик',
    'хоть убей не помню, куда положила',
  ])('молчит: %s', (text) => {
    // Ложное срабатывание не безобидно: человек вместо своего списка дел
    // получает реплику про специалиста, а разбор не случается.
    expect(detectByMarkers(text).detected).toBe(false);
  });

  it('«ё» не мешает', () => {
    expect(detectByMarkers('хочу свести счёты с жизнью').detected).toBe(true);
  });

  it('регистр не мешает', () => {
    expect(detectByMarkers('НЕ ХОЧУ ЖИТЬ').detected).toBe(true);
  });

  it('маркер посреди длинной выгрузки находится', () => {
    // Настоящая выгрузка — это поток на минуту, и признак может быть в
    // середине, между продуктами и химчисткой.
    const text = [
      'так, надо купить продукты, потом химчистка',
      'и вообще я не хочу жить',
      'ещё записать сына к врачу',
    ].join(' ');

    expect(detectByMarkers(text).detected).toBe(true);
  });
});

describe('оба контура', () => {
  it('признак модели срабатывает там, где маркеров нет', () => {
    // Человек может сказать так, как в списке не написано. За это и
    // отвечает второй контур.
    const outcome = detectCrisis('всё это больше не имеет смысла для меня', true);

    expect(outcome.detected).toBe(true);
    expect(outcome.contour).toBe('model');
  });

  it('маркеры срабатывают, даже если модель промолчала', () => {
    const outcome = detectCrisis('я не хочу жить', false);

    expect(outcome.detected).toBe(true);
    expect(outcome.contour).toBe('markers');
  });

  it('маркеры важнее: по ним видно, что именно сработало', () => {
    expect(detectCrisis('хочу умереть', true).contour).toBe('markers');
  });

  it('отсутствие признака у модели не считается срабатыванием', () => {
    expect(detectCrisis('надо купить продукты', undefined).detected).toBe(false);
    expect(detectCrisis('надо купить продукты', false).detected).toBe(false);
  });
});

describe('ответ на кризис', () => {
  it('есть в каждом профиле и не пустой', () => {
    for (const profile of Object.values(profiles)) {
      expect(profile.safety.crisis.trim().length).toBeGreaterThan(0);
    }
  });

  it('не содержит вопроса', () => {
    // §13.9: вопрос предполагает продолжение разговора, а §13.7 требует
    // из него выйти. Ответ на кризис — не приглашение поговорить.
    for (const profile of Object.values(profiles)) {
      expect(profile.safety.crisis).not.toContain('?');
    }
  });

  it('короткий: одна реплика, а не разговор (§13.7, выход из разговора)', () => {
    for (const profile of Object.values(profiles)) {
      expect(profile.safety.crisis.length).toBeLessThanOrEqual(200);
    }
  });
});

/**
 * Требование заказчицы 27.08.2026, дословно: «фразы типа „я задолбалась“,
 * „я больше не могу“, „убейте меня с этими делами“ не должны считаться
 * триггерами».
 *
 * Женщина приходит к боту именно тогда, когда её накрыло, и говорит о
 * своих делах резко. Реплика про специалиста вместо списка дел — это
 * сломанный продукт, а не осторожность.
 *
 * Проверяется самый жёсткий случай: **модель сказала «кризис»**. Промпт
 * router@3 на этих фразах уже молчит (замер 27.08.2026), но полагаться на
 * промпт нельзя — он меняется, а требование остаётся.
 */
describe('гипербола про нагрузку кризисом не считается', () => {
  const named = ['я задолбалась', 'я больше не могу', 'убейте меня с этими делами'];

  for (const text of named) {
    it(`«${text}» — не кризис, даже если модель считает иначе`, () => {
      expect(detectCrisis(text, true).detected).toBe(false);
      expect(detectByMarkers(text).detected).toBe(false);
    });
  }

  const alike = [
    'я задолбалась, убейте меня с этими делами, надо ещё продукты и сына к врачу',
    'убила бы себя за то, что согласилась на этот утренник',
    'больше не могу, всё валится из рук',
    'сил моих больше нет с этими делами',
    'я на пределе, ничего не успеваю',
    'меня всё это убивает, надо ещё в садик позвонить',
    'я в аду, купить продукты, забрать вещи, записаться к врачу',
    'сдохнуть можно от этого всего, а мне ещё уроки с сыном',
    'умереть можно от этой жары, а мне ещё в химчистку',
    'хоть убей не помню, что надо было купить',
    'готова себя убить, что забыла записать сына к врачу',
  ];

  for (const text of alike) {
    it(`«${text.slice(0, 44)}» — не кризис`, () => {
      expect(detectCrisis(text, true).detected).toBe(false);
    });
  }

  it('отмена признака попадает в журнал: видно, каким оборотом', () => {
    // Без этого отмена была бы невидимой, а это самое опасное место
    // модуля: по логу надо понимать, не глушим ли мы лишнего.
    const outcome = detectCrisis('убейте меня с этими делами', true);

    expect(outcome.detected).toBe(false);
    expect(outcome.hyperbole).toBe('убейте меня');
  });
});

/**
 * Обратная сторона того же требования, и она важнее.
 *
 * Убрать ложные срабатывания легко — достаточно выключить контур. Здесь
 * проверяется, что он остался живым: настоящий признак обязан пройти и
 * рядом с гиперболой, и в формулировке, которой нет в списке маркеров.
 */
describe('гипербола не глушит настоящий признак', () => {
  it('оборот из одной части не гасит признак из другой', () => {
    // Аудит 28.08.2026 нашёл ровно это: проверка отменяла признак, если
    // где-нибудь в тексте попадался любой оборот. «Хоть убей не помню» в
    // начале выгрузки отменяло «не хочу жить» в конце — то есть ошибка
    // была в сторону пропуска, а здесь это худшая из двух.
    const text =
      'хоть убей не помню, что надо было купить, ещё садик и химчистка. и вообще я не хочу жить';

    const outcome = detectByMarkers(text);
    expect(outcome.detected).toBe(true);
    expect(outcome.marker).toBe('не хочу жить');
  });

  it('оборот гасит только тот маркер, который сам содержит', () => {
    const outcome = detectByMarkers('хочется убить себя за то, что забыла про садик');

    expect(outcome.detected).toBe(false);
    expect(outcome.hyperbole).toBe('хочется убить себя за');
  });

  it('«больше не могу» рядом со словом о жизни признак не отменяет', () => {
    // Фраза сама по себе — про нагрузку. «Больше не могу так жить» — уже
    // про жизнь, и модели здесь верим.
    expect(detectCrisis('я больше не могу так жить', true).detected).toBe(true);
  });

  it('гипербола рядом с настоящим признаком признак не отменяет', () => {
    expect(detectCrisis('я задолбалась, хочу исчезнуть навсегда', true).detected).toBe(true);
    expect(detectCrisis('хоть убей не помню. и я хочу исчезнуть навсегда', true).detected).toBe(
      true,
    );
  });

  it('признак модели на формулировке вне списка маркеров принимается', () => {
    // Ровно для этого второй контур и нужен: список маркеров закрытый, а
    // сказать можно иначе.
    for (const text of [
      'мне незачем больше жить',
      'я всё чаще думаю о том, чтобы всё закончить',
      'я хочу исчезнуть навсегда',
      'я не хочу больше просыпаться',
    ]) {
      expect(detectCrisis(text, true).detected, text).toBe(true);
    }
  });

  it('маркеры не отменяются ничем: они считаются первыми', () => {
    const outcome = detectCrisis('я больше не могу. не хочу жить', true);

    expect(outcome.detected).toBe(true);
    expect(outcome.contour).toBe('markers');
  });
});
