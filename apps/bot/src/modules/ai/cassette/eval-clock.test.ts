import { describe, expect, it } from 'vitest';

import type { CompletionRequest, LlmProvider } from '../providers/types.js';
import { RecordingLlmProvider, ReplayLlmProvider } from './provider.js';
import { CassettePlayer, CassetteRecorder } from './store.js';

/**
 * Запись ответов для **контрольного набора**: часы берутся от дня
 * записи, а не от сегодня (находка 10.09.2026).
 *
 * **Зачем запись вообще понадобилась набору.** Обе находки того дня
 * требуют сравнения «до» и «после». Сравнивать два платных прогона —
 * значит платить дважды и всё равно не получить ответа: между прогонами
 * меняется не только наше дерево, но и модель за веткой `latest`. Запись
 * снимает оба возражения разом: ответы модели спрашиваются **один раз**,
 * а сочетаний флагов по ним можно прогнать сколько угодно и бесплатно.
 *
 * **Но у сквозного прогона и у набора разное «сегодня», и в этом ловушка.**
 * Сквозной живёт в настоящем времени, поэтому запись разворачивает даты
 * относительно сегодняшнего дня — иначе она жила бы одни сутки. У набора
 * же «сегодня» задано в самом случае (`now` в файле набора) и не
 * двигается никогда: его случаи стоят на 26 августа 2026 и будут стоять
 * там всегда.
 *
 * Разверни ответ модели по сегодняшнему дню — и записанный срок
 * «2026-09-01» на следующие сутки станет вторым сентября. Ожидание в
 * наборе при этом останется первым, и прогон покажет промах по дате,
 * которого не было. Это ровно тот случай, которого проект боится больше
 * всего: стенд, мерящий не то, что происходит.
 *
 * Поэтому воспроизведение для набора разворачивает даты **днём записи**:
 * ответ возвращается таким, каким его дала модель, буква в букву.
 */

const RECORDED = new Date('2026-09-10T12:00:00.000Z');
/** Трое суток спустя: столько живёт разбор находок между прогонами. */
const LATER = new Date('2026-09-13T12:00:00.000Z');

/** Случай набора `recurrence`: «сегодня» у него 26 августа 2026. */
const REQUEST: CompletionRequest = {
  prompt: 'Сегодня среда, 26 августа 2026 г., часовой пояс Europe/Moscow.',
  input: 'Каждый вторник вожу сына на плавание.',
  jsonSchema: { title: 'classifier', type: 'object' },
};

/** Ответ модели: ближайший вторник от 26 августа — первое сентября. */
const ANSWER = '{"deadline":"2026-09-01","recurrenceKind":"weekly"}';

async function play(now: (player: CassettePlayer) => Date): Promise<string> {
  const live: LlmProvider = {
    name: 'yandex:yandexgpt/latest',
    complete: () =>
      Promise.resolve({
        text: ANSWER,
        model: 'yandex:yandexgpt/latest',
        tokensIn: 9,
        tokensOut: 9,
      }),
  };

  const recorder = new CassetteRecorder(RECORDED, 'yandex:yandexgpt/latest');
  await new RecordingLlmProvider({ live, recorder, recordedAt: RECORDED }).complete(REQUEST);

  const player = new CassettePlayer(recorder.toFile());
  const replay = new ReplayLlmProvider(player, () => now(player));

  return (await replay.complete(REQUEST)).text;
}

describe('воспроизведение записи для контрольного набора', () => {
  it('по дню записи ответ возвращается буква в букву', async () => {
    expect(await play((player) => player.recordedAt)).toBe(ANSWER);
  });

  it('по сегодняшнему дню записанный срок уезжает — этого набору нельзя', async () => {
    /**
     * Здесь названа сама опасность, а не только защита от неё. Трое
     * суток спустя «2026-09-01» превращается в «2026-09-04»: ожидание
     * набора остаётся прежним, и прогон покажет промах по дате, которого
     * не было.
     */
    expect(await play(() => LATER)).toContain('2026-09-04');
  });

  it('ключ запроса от дня воспроизведения не зависит', async () => {
    // Ключ обе стороны считают по дню записи, поэтому промаха нет и
    // «завтра». Без этого свойства запись пришлось бы переписывать за
    // деньги каждые сутки, а вся затея была ради бесплатного прогона.
    expect(await play(() => LATER)).not.toBe('');
  });
});
