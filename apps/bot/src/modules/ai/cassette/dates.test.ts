import { describe, expect, it } from 'vitest';

import { expand, hasMarks, relativise } from './dates.js';

/**
 * Даты в записи ответов модели (задача 3.80).
 *
 * **Половина проверок ниже — про то, чего заменять нельзя.** Испорченная
 * запись хуже отсутствующей: на ней сквозной прогон зелёный, а бот
 * сломан. Поэтому заменяется только то, что похоже на дату **и** попало
 * в окно вокруг дня записи.
 */

const RECORDED = new Date('2026-09-06T12:00:00.000Z');

describe('relativise', () => {
  it('дата записи становится «сегодня»', () => {
    expect(relativise('срок 2026-09-06', RECORDED)).toBe('срок {{день+0|iso}}');
  });

  it('завтра и вчера считаются днями', () => {
    expect(relativise('2026-09-07', RECORDED)).toBe('{{день+1|iso}}');
    expect(relativise('2026-09-05', RECORDED)).toBe('{{день-1|iso}}');
  });

  it('человеческая дата помнит свой вид', () => {
    /**
     * Вид записан в метке, и это не мелочь: ответ модели проверяется по
     * образцу ГГГГ-ММ-ДД, а в переписке человека дата стоит как «08.09».
     * Первая версия писала обеим одну метку, и развернуть их одинаково
     * значило бы отдать §2.7 дату в чужом формате.
     */
    expect(relativise('Перенесла на 08.09', RECORDED)).toBe('Перенесла на {{день+2|дм}}');
    expect(relativise('срок 08.09.2026', RECORDED)).toBe('срок {{день+2|дмг}}');
  });

  it('весь ответ модели разом', () => {
    const answer = '{"deadline":"2026-09-07","note":"перенесла на 07.09"}';

    expect(relativise(answer, RECORDED)).toBe(
      '{"deadline":"{{день+1|iso}}","note":"перенесла на {{день+1|дм}}"}',
    );
  });

  describe('чего заменять нельзя', () => {
    it('дата вне окна остаётся дословно', () => {
      // Год вперёд — это уже не «относительно записи», а чужая дата.
      expect(relativise('2028-01-01', RECORDED)).toBe('2028-01-01');
      expect(relativise('2020-05-05', RECORDED)).toBe('2020-05-05');
    });

    it('числа, которые не про календарь', () => {
      for (const text of [
        'нахаживать 10 000 шагов',
        'дочитать книгу до 120 страницы',
        'позвонить в 9 30',
        'сумма 1500.50 рублей',
        'версия 1.2.3',
      ]) {
        expect(relativise(text, RECORDED), text).toBe(text);
      }
    });

    it('слова человека о дне не трогаются', () => {
      // «Завтра» остаётся словом: относительной его делает не запись, а
      // разбор, и подменять сказанное нельзя.
      const said = 'Завтра надо купить собаке новый ошейник';
      expect(relativise(said, RECORDED)).toBe(said);
    });

    it('пустое и без дат не ломается', () => {
      expect(relativise('', RECORDED)).toBe('');
      expect(relativise('никаких дат', RECORDED)).toBe('никаких дат');
    });
  });
});

describe('expand', () => {
  it('разворачивает относительно нового дня', () => {
    const later = new Date('2026-12-25T08:00:00.000Z');

    expect(expand('{{день+0|iso}}', later)).toBe('2026-12-25');
    expect(expand('{{день+1|iso}}', later)).toBe('2026-12-26');
    expect(expand('{{день-1|iso}}', later)).toBe('2026-12-24');
  });

  it('возвращает тот вид, каким записали', () => {
    const later = new Date('2027-03-02T08:00:00.000Z');

    expect(expand('{{день+0|дм}}', later)).toBe('02.03');
    expect(expand('{{день+0|дмг}}', later)).toBe('02.03.2027');
  });

  it('через границу месяца и года считает верно', () => {
    expect(expand('{{день+1|iso}}', new Date('2026-12-31T12:00:00.000Z'))).toBe('2027-01-01');
    expect(expand('{{день-1|iso}}', new Date('2027-01-01T12:00:00.000Z'))).toBe('2026-12-31');
  });

  it('текст без меток не меняет', () => {
    expect(expand('срок 2026-09-07', RECORDED)).toBe('срок 2026-09-07');
  });
});

describe('туда и обратно', () => {
  it('в день записи ответ восстанавливается знак в знак', () => {
    /**
     * Главное свойство: запись и воспроизведение в один день обязаны
     * дать ровно то же. Иначе первый же прогон после записи покраснел бы,
     * и доверять записи стало бы нельзя.
     */
    const answer =
      '{"action":"update","changes":{"deadline":"2026-09-08","note":"перенесла на 08.09.2026"}}';

    expect(expand(relativise(answer, RECORDED), RECORDED)).toBe(answer);
  });

  it('через три месяца сдвигается ровно на столько же дней', () => {
    const answer = '{"deadline":"2026-09-08"}';
    const later = new Date('2026-12-06T12:00:00.000Z');

    expect(expand(relativise(answer, RECORDED), later)).toBe('{"deadline":"2026-12-08"}');
  });
});

describe('hasMarks', () => {
  it('находит метки и не находит их там, где нет', () => {
    expect(hasMarks('срок {{день+1|iso}}')).toBe(true);
    expect(hasMarks('срок 2026-09-07')).toBe(false);
    // Похожее, но не метка: разворачивать нечего.
    expect(hasMarks('{{день}}')).toBe(false);
  });
});
