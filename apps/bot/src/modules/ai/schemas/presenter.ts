import { z } from 'zod';

/**
 * Схема ответа представления (задачи 2.2 и 2.11).
 *
 * У модели здесь одна работа — признание из §13.2: одна фраза, которая
 * называет состав выгрузки, а не пересказывает её. Всё остальное в ответе
 * собирается кодом: список действий даёт фильтр выдачи (2.10), а вопрос,
 * кнопки и фраза о сохранённом лежат в словаре.
 *
 * Так сделано не из экономии. Список действий, собранный моделью, плавал
 * бы между запусками, и критерии приёмки 1 и 7 стали бы непроверяемыми —
 * ровно по той же причине, по которой фильтр выдачи не модель, а код.
 * А вопрос, придуманный моделью, рано или поздно окажется вторым в
 * реплике, что запрещает §13.9.
 */

export const PRESENTER_SCHEMA_NAME = 'presenter.v1';

/**
 * Потолок длины. §13.2 требует одной фразы, §13.9 — одной-двух
 * на реплику вне выдачи. Двести знаков — это примерно две строки;
 * всё, что длиннее, признанием уже не является.
 */
const MAX_ACKNOWLEDGEMENT = 200;

export const presenterSchema = z.object({
  /**
   * Признание. Без вопроса, без переноса строки, без советов — правила
   * §13.7 и §13.9 проверяются в коде, потому что схема их выразить не
   * может, а промпт — это просьба, а не гарантия.
   */
  acknowledgement: z.string().min(1).max(MAX_ACKNOWLEDGEMENT),
});

export type PresenterAcknowledgement = z.infer<typeof presenterSchema>;
