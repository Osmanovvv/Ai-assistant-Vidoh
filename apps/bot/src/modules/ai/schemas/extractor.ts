import { z } from 'zod';

/**
 * Схема ответа извлечения атомарных единиц (задачи 2.2 и 2.5).
 *
 * §6.1 ТЗ: перечисление разбивается на отдельные единицы, составная цель
 * помечается признаком проекта и не разбивается, повторы схлопываются,
 * оценочные реплики выделяются как эмоция, обращения к боту в единицы
 * не попадают.
 *
 * Тип, приоритет, тема и срок здесь не запрашиваются намеренно: это дело
 * классификации (задача 2.6). §10.1 разрешает объединить оба шага в один
 * вызов ради экономии, но только после того, как контрольный набор
 * покажет, что качество не падает. Сначала два вызова.
 */

/** Верхний предел на всякий случай: столько дел за одну выгрузку не бывает. */
const MAX_UNITS = 60;

export const EXTRACTOR_SCHEMA_NAME = 'extractor.v1';

export const extractorSchema = z.object({
  units: z
    .array(
      z.object({
        /**
         * Самостоятельная формулировка единицы. Не цитата: человек говорит
         * обрывками, и «к врачу в четверг» должно стать понятным делом,
         * а не остаться куском фразы.
         */
        text: z.string().min(1).max(500),

        /**
         * Составная цель вроде «день рождения сына»: внутри много дел,
         * но дробить её нельзя — человек думает о ней как об одном.
         */
        isProject: z.boolean(),

        /**
         * Оценочная реплика: «я вообще ничего не успеваю». §6.3 ТЗ
         * запрещает превращать такое в задачу, и отметить это надо уже
         * при извлечении — иначе классификация получит на вход дело,
         * которого человек не называл.
         */
        isEmotion: z.boolean(),
      }),
    )
    .max(MAX_UNITS),
});

export type ExtractedUnits = z.infer<typeof extractorSchema>;
