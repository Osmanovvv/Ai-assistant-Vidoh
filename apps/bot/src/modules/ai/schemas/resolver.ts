import { z } from 'zod';

import { RECURRENCE_KINDS } from '../../recurrence/recurrence.js';
import { DEADLINE_ACCURACY } from './classifier.js';

/**
 * Схема ответа резолвера (§7.3 ТЗ, задача 3.2).
 *
 * §7.3 перечисляет состав прямо: «модель возвращает структуру: действие,
 * идентификатор целевой записи, уверенность, набор изменяемых полей,
 * краткое обоснование».
 *
 * **Решение принимает не модель, а пороговая логика.** Здесь только её
 * входные данные. Модель не знает ни порогов, ни того, что случится с её
 * ответом: попросить её саму решать «применять или спросить» значило бы
 * отдать ей вопрос доверия, который §7.3 оставляет за продуктом.
 *
 * **Версия вторая: дополнение против замены (§7.4, задача 3.7).**
 * Добавлены `mode` и `changes.note`. Разница не косметическая: «а ещё
 * туда надо взять карту прививок» не заменяет дело и не двигает срок, а
 * прежняя схема умела только заменять — и переписала бы заголовок.
 *
 * **Версия третья: правка регулярности (задача 3.8б).** «Запомни, это у
 * меня каждый месяц» про существующее дело — это правка правила, и вести
 * себя она обязана как правка срока: с показом изменения и откатом в
 * один тап. Без этих полей она стала бы второй записью.
 */

export const RESOLVER_SCHEMA_NAME = 'resolver.v3';

/**
 * Первая версия остаётся в коде, хотя её больше никто не заливает.
 *
 * Версия промпта хранит имя своей схемы, и `resolver@1` продолжает
 * ссылаться на первую. Выкинуть её значит сломать и откат к прежнему
 * промпту, и ту минуту между выкладкой кода и заливкой промптов, когда в
 * базе ещё активна старая версия. Схема — не код, который стал не нужен,
 * а запись о том, что мы однажды пообещали.
 */
export const RESOLVER_V1_SCHEMA_NAME = 'resolver.v1';

/** Вторая версия: тоже остаётся, пока может быть активна или откачена. */
export const RESOLVER_V2_SCHEMA_NAME = 'resolver.v2';

/**
 * Что человек хочет сделать с найденной записью.
 *
 * Намерение сегмента уже известно от маршрутизатора, и всё же действие
 * спрашивается снова: маршрутизатор смотрел на текст, не видя записей, а
 * здесь у модели перед глазами список кандидатов. «Продукты купила»
 * маршрутизатор пометит `COMPLETE`, но если подходящей записи нет,
 * честный ответ резолвера — `new`, а не «закрыть хоть что-нибудь».
 */
export const RESOLVER_ACTIONS = [
  /** Поправить поля существующей записи. */
  'update',
  /** Отметить сделанным. */
  'complete',
  /** Отменить: §13.5 переводит запись в отменённые, а не удаляет. */
  'cancel',
  /** Подходящей записи нет — это новая мысль. */
  'new',
] as const;

/**
 * Правит поля или расширяет подробности (§7.4 ТЗ).
 *
 * Выбор спрашивается прямо, а не выводится из заполненных полей. Модель,
 * от которой ждут догадки «раз заполнил note — значит дополнение»,
 * заполняет и то, и другое. А различение здесь важнее аккуратности: при
 * замене переписывается заголовок дела человека.
 */
export const RESOLVER_MODES = [
  /** Человек называет дело или срок заново: правим поля. */
  'replace',
  /** Человек добавляет подробность: заголовок и срок не трогаем. */
  'append',
] as const;

/** Схема первой версии: без различения дополнения и замены. */
export const resolverV1Schema = z.object({
  action: z.enum(RESOLVER_ACTIONS),
  itemId: z.string().max(64),
  confidence: z.number().min(0).max(1),
  changes: z.object({
    text: z.string().max(500),
    deadline: z.string().max(10),
    deadlineAccuracy: z.enum(DEADLINE_ACCURACY),
  }),
  reason: z.string().max(300),
});

/** Схема второй версии: дополнение против замены, но без регулярности. */
export const resolverV2Schema = z.object({
  action: z.enum(RESOLVER_ACTIONS),
  mode: z.enum(RESOLVER_MODES),
  itemId: z.string().max(64),
  confidence: z.number().min(0).max(1),
  changes: z.object({
    note: z.string().max(500),
    text: z.string().max(500),
    deadline: z.string().max(10),
    deadlineAccuracy: z.enum(DEADLINE_ACCURACY),
  }),
  reason: z.string().max(300),
});

export const resolverSchema = z.object({
  action: z.enum(RESOLVER_ACTIONS),
  mode: z.enum(RESOLVER_MODES),

  /**
   * Идентификатор из списка кандидатов. Пустая строка — записи нет.
   *
   * Пустая строка, а не необязательное поле: у моделей обязательные поля
   * с явным «ничего» получаются надёжнее, чем пропущенные ключи. Тот же
   * приём в схеме классификации у срока.
   */
  itemId: z.string().max(64),

  /**
   * Насколько модель уверена, что речь именно об этой записи.
   *
   * Самооценка у языковых моделей плохо калибрована и завышена, поэтому
   * одного этого числа для применения изменения мало — порог требует
   * второго, независимого от модели подтверждения (см. decision.ts).
   */
  confidence: z.number().min(0).max(1),

  /**
   * Что именно меняется. Пустые значения означают «не трогать».
   *
   * Полный текст записи модель не переписывает по своему усмотрению:
   * заголовок заменяется, только если человек его действительно назвал
   * заново. Иначе «нет, в пятницу» переписало бы «Записать сына к врачу»
   * во что-нибудь своё.
   */
  changes: z.object({
    /**
     * Подробность, которую надо дописать к делу. Пусто — дописывать
     * нечего.
     *
     * Заполняется только при `append`. При замене остаётся пустой:
     * подробность и новая формулировка — разные вещи, и складывать их в
     * одно поле значило бы однажды перепутать.
     */
    note: z.string().max(500),
    text: z.string().max(500),
    /** Дата в виде ГГГГ-ММ-ДД, как в классификации. */
    deadline: z.string().max(10),
    deadlineAccuracy: z.enum(DEADLINE_ACCURACY),

    /**
     * Новое правило повторения (задача 3.8б).
     *
     * `none` — правило не меняется. Поля названы как в классификации:
     * одно и то же понятие в двух схемах должно называться одинаково,
     * иначе перенос значений между ними станет местом для ошибки.
     */
    recurrenceKind: z.enum(RECURRENCE_KINDS),
    recurrenceInterval: z.number().int().min(0).max(99),
    /** Как человек это сказал, дословно: «каждый месяц». */
    recurrenceText: z.string().max(200),
  }),

  /**
   * Краткое обоснование — для журнала и разбора жалоб, не для человека.
   *
   * Реплику человеку собирает представление (§13). Показывать
   * рассуждения модели продукт не станет: §12.3 требует говорить
   * по-человечески, а не отчитываться о работе.
   */
  reason: z.string().max(300),
});

export type ResolverAnswer = z.infer<typeof resolverSchema>;
export type ResolverAction = (typeof RESOLVER_ACTIONS)[number];
export type ResolverMode = (typeof RESOLVER_MODES)[number];
