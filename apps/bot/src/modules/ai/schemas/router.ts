import { z } from 'zod';

/**
 * Схема ответа маршрутизатора намерений (задачи 2.2 и 2.4).
 *
 * §7.1 ТЗ перечисляет шесть намерений. Седьмое, `ANSWER`, добавлено нами:
 * человек может ответить на уточняющий вопрос бота голосом или текстом,
 * а не кнопкой. Без этого намерения такой ответ уйдёт в `DUMP` и создаст
 * мусорную запись вроде «в четверг» — задачу без задачи.
 *
 * Одна выгрузка даёт массив сегментов. Порядок в ТЗ не задан, а без него
 * фраза «записать сына к врачу в четверг… хотя нет, в пятницу» внутри
 * одного голосового создаст две записи вместо одной исправленной.
 * Поэтому порядок — строго по тексту, и он проверяется отдельно от модели.
 */

export const ROUTER_SCHEMA_NAME = 'router.v1';

export const INTENTS = [
  /** Новая мысль: выгрузка, из которой рождаются записи. */
  'DUMP',
  /** Правка ранее сказанного: «хотя нет, в пятницу». */
  'PATCH',
  /** Дело сделано. */
  'COMPLETE',
  /** Дело отменяется. */
  'CANCEL',
  /** Вопрос к боту о своих записях. */
  'QUERY',
  /** Разговор ни о чём: «привет», «спасибо». */
  'SMALLTALK',
  /** Ответ на уточняющий вопрос бота. Проверяется первым, если вопрос открыт. */
  'ANSWER',
] as const;

export type Intent = (typeof INTENTS)[number];

/**
 * Верхний предел на число сегментов. Двадцать намерений в одной выгрузке
 * означают, что модель сорвалась в дробление, а не что человек столько
 * наговорил.
 */
const MAX_SEGMENTS = 20;

export const routerSchema = z.object({
  segments: z
    .array(
      z.object({
        intent: z.enum(INTENTS),
        /**
         * Часть выгрузки, к которой относится намерение. Дословно или
         * почти дословно: по этому тексту проверяется порядок сегментов,
         * и вольный пересказ ломает проверку.
         */
        text: z.string().min(1).max(2000),
      }),
    )
    .max(MAX_SEGMENTS),
});

export type RoutedSegments = z.infer<typeof routerSchema>;
