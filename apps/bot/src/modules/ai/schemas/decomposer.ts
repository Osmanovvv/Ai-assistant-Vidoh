import { z } from 'zod';

/**
 * Схема разложения большой цели на шаги (§5 ТЗ, задача 3.12).
 *
 * «День рождения сына» — внутри десяток дел, и человек думает о нём как
 * об одном. Разложение нужно, чтобы показать ему **один посильный шаг**,
 * а не всю гору сразу.
 *
 * **Шагов немного, и это ограничение продуктовое.** Модель, которой не
 * сказать предела, разложит день рождения на двадцать три пункта вместе
 * с «выбрать салфетки». Список, который страшно открыть, — ровно то, от
 * чего продукт избавляет.
 */

export const DECOMPOSER_SCHEMA_NAME = 'decomposer.v1';

export const decomposerSchema = z.object({
  steps: z
    .array(
      /**
       * Шаг — это действие, а не рубрика. «Определиться с местом» —
       * шаг, «Место» — заголовок в чьём-то плане.
       */
      z.string().min(3).max(200),
    )
    .max(7),
});

export type DecomposedSteps = z.infer<typeof decomposerSchema>;
