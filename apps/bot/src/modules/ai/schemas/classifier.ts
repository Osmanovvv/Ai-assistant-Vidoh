import { z } from 'zod';

/**
 * Схема ответа классификации (задачи 2.2, 2.6 и 2.7).
 *
 * §5.1 ТЗ задаёт справочники типов и приоритетов, §6.2 — признаки типов,
 * §6.3 — правило приоритета по умолчанию.
 *
 * Тема — свободная строка, а не перечисление. Темы у каждого человека
 * свои: §6.4 создаёт их на онбординге по его ответам. Список допустимых
 * тем передаётся в промпт параметром, а ответ сверяется с ним в коде и
 * при непопадании уходит в тему по умолчанию — так и требует §6.4.
 * Зашей мы перечисление в схему, его пришлось бы переделывать на 2.15.
 *
 * Пустых значений и null здесь нет намеренно. Строгие схемы у разных
 * провайдеров по-разному переносят необязательные поля и объединения
 * типов, и «нет срока» надёжнее выразить пустой строкой, чем
 * отсутствующим полем.
 */

/** §5.1 ТЗ, справочник type. */
export const ITEM_TYPES = ['TASK', 'DESIRE', 'IDEA', 'INFO', 'EMOTION'] as const;

/** §5.1 ТЗ, справочник priority. */
export const PRIORITIES = ['NOW', 'SOON', 'LATER', 'NONE'] as const;

/**
 * Точность срока (§2.7 плана).
 *
 * «В четверг» — это `day`, «на следующей неделе» — `week`, «в сентябре» —
 * `month`. Без точности напоминание про «следующую неделю» сработало бы
 * в конкретный день и не в тот.
 */
export const DEADLINE_ACCURACY = ['day', 'week', 'month', 'none'] as const;

export type ItemType = (typeof ITEM_TYPES)[number];
export type Priority = (typeof PRIORITIES)[number];
export type DeadlineAccuracy = (typeof DEADLINE_ACCURACY)[number];

export const CLASSIFIER_SCHEMA_NAME = 'classifier.v1';

/** Столько записей за одну выгрузку не бывает — это модель сорвалась. */
const MAX_ITEMS = 60;

export const classifierSchema = z.object({
  items: z
    .array(
      z.object({
        /** Формулировка записи. Может быть чуть аккуратнее исходной. */
        text: z.string().min(1).max(500),

        type: z.enum(ITEM_TYPES),

        /**
         * §6.3 ТЗ: желание, идея, информация и эмоция получают `NONE` и в
         * выдачу не попадают. Проверяется отдельно от модели — см. 2.6.
         */
        priority: z.enum(PRIORITIES),

        /** Название темы из переданного списка. Сверяется в коде. */
        topic: z.string().min(1).max(64),

        /**
         * §5.1 ТЗ: проект — это поле у записи типа TASK, а не отдельный
         * тип. Так задача может дорасти до проекта без миграции сущности.
         */
        isProject: z.boolean(),

        /**
         * Абсолютная дата в виде ГГГГ-ММ-ДД или пустая строка, если срока
         * нет. Именно абсолютная: «в четверг» — самый частый источник
         * тихих ошибок, и превращать его в дату должна модель, которой
         * передали сегодняшнее число, а не мы догадками потом.
         */
        deadline: z.string().max(10),

        deadlineAccuracy: z.enum(DEADLINE_ACCURACY),
      }),
    )
    .max(MAX_ITEMS),
});

export type ClassifiedItems = z.infer<typeof classifierSchema>;
