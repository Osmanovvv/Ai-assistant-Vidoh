import type { AiStage } from '../../db/schema.js';

/**
 * Температура вызовов по этапам (задача 3.23).
 *
 * §10.2 ТЗ: «Температура для структурных этапов минимальная. Для этапа
 * представления допустимо выше». Минимальная — это ноль, а в бою стояла
 * `0.1`: провайдер подставлял её по умолчанию, а ни один этап своей не
 * задавал.
 *
 * **Хуже того, контрольный набор мерил при нуле.** `eval/merged.ts`
 * передавал `temperature: 0` прямо в вызов, минуя общий путь. То есть
 * страж §10.3 — «выкладка только при отсутствии ухудшения на наборе» —
 * проверял поведение, которого в бою не было. Расхождение прожило
 * незамеченным именно потому, что число стояло в двух местах.
 *
 * Теперь оно стоит в одном, и его берут оба: и конвейер, и стенд.
 *
 * **Представление намеренно оставлено выше нуля.** Признание — та
 * единственная фраза, которую пишет модель, и одинаковая формулировка
 * каждый раз читалась бы как автоответчик. §10.2 это прямо разрешает.
 */

/** Ноль — для всего, что должно давать один и тот же разбор. */
const STRUCTURAL = 0;

/** Признание в ответе на выгрузку: разнообразие здесь к месту. */
const PRESENTER = 0.1;

const BY_STAGE: Readonly<Partial<Record<AiStage, number>>> = {
  router: STRUCTURAL,
  extractor: STRUCTURAL,
  classifier: STRUCTURAL,
  resolver: STRUCTURAL,
  decomposer: STRUCTURAL,
  presenter: PRESENTER,
};

/**
 * Температура этапа.
 *
 * Неизвестный этап получает ноль, а не значение провайдера: новый
 * структурный этап должен быть предсказуемым по умолчанию, а не
 * дребезжать до тех пор, пока кто-нибудь не вспомнит про эту таблицу.
 */
export function temperatureFor(stage: AiStage): number {
  return BY_STAGE[stage] ?? STRUCTURAL;
}
