/**
 * Правки, которые нельзя ставить без замера на контрольном наборе
 * (находки 10.09.2026).
 *
 * **Зачем такой модуль вообще.** Обе правки ниже меняют не оформление, а
 * то, **что бот примет за срок и за правило повторения**. Цену такого
 * решения этот проект уже дважды платил вслепую, и оба раза дорого:
 * широкий список слов о времени дал десять выдуманных сроков из сорока
 * трёх дел (27.08.2026), а строгость к цитате отняла шесть верных дат за
 * сутки (02.09.2026). Правило проекта с тех пор простое: сперва научи
 * набор мерить вред, потом правь.
 *
 * **Почему переменная окружения, а не правка в коде.** Прогон набора
 * стоит денег, а сравнивать надо одно и то же дерево при одинаковых
 * ответах модели. Переключатель снаружи даёт это одной командой: записал
 * ответы модели один раз — и гоняй по ним хоть четыре сочетания флагов
 * бесплатно. Правка же в коде между прогонами означает, что сравниваются
 * два разных дерева, и объяснить разницу будет нечем.
 *
 * **Флаги временные.** Как только число известно, правка либо становится
 * безусловной, либо не ставится вовсе, а этот модуль удаляется целиком.
 * Долгоживущий флаг — это два бота вместо одного, и проверять тогда
 * пришлось бы оба.
 *
 * По умолчанию **выключено**: без замера боевое поведение не меняется.
 */

/**
 * Имена переменных. Отдельно от значений, потому что их надо называть и
 * тестам, и скриптам прогона: строка, повторённая в трёх местах,
 * рано или поздно разъедется в одном из них.
 */
export const PENDING_FIX_ENV = {
  /** Корень «будни» → «будн»: словоформы «по будням», «в буднях». */
  weekdayRoot: 'VYDOH_FIX_WEEKDAY_ROOT',
  /** Якорь правила повторения только из проверенного срока. */
  strictRecurrenceAnchor: 'VYDOH_FIX_STRICT_ANCHOR',
} as const;

/**
 * Включено — это ровно «1».
 *
 * Не `!== undefined` и не «любая непустая строка»: пустое значение в
 * окружении встречается само собой (`VAR=` в скрипте, пустая строка из
 * docker compose), и читать его как «включено» значило бы включать
 * правку случайно. Ошибка такого рода стоит целого прогона.
 */
function on(name: string): boolean {
  return process.env[name] === '1';
}

/**
 * Состояние флагов на момент запуска процесса.
 *
 * Читается один раз при загрузке модуля намеренно: разбор одной выгрузки
 * не должен на середине сменить правила, по которым принимает сроки.
 */
export const PENDING_FIXES = {
  weekdayRoot: on(PENDING_FIX_ENV.weekdayRoot),
  strictRecurrenceAnchor: on(PENDING_FIX_ENV.strictRecurrenceAnchor),
} as const;

/** Какие правки включены — строкой для отчёта прогона. */
export function pendingFixesLine(): string {
  const on = Object.entries(PENDING_FIXES)
    .filter(([, value]) => value)
    .map(([name]) => name);

  return on.length === 0 ? 'ни одной (поведение как в бою)' : on.join(', ');
}
