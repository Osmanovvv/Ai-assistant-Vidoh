import type { TextProfile } from './types.js';

/**
 * §13 как проверяемые правила, а не как абзац в документе.
 *
 * **Почему это продуктовый код, а не тест.** До редактора текстов правки
 * словаря приезжали выкладкой — то есть через прогон и чужой взгляд.
 * §13.9 требует менять тексты **без выкладки**, и с редактором в панели
 * правка попадает людям сразу: ни прогона, ни ревью. Значит правило
 * обязано стоять на записи, а не только в наборе тестов, — иначе реплика
 * с двумя вопросами уйдёт человеку молча.
 *
 * Правило одно на всех, кто про него спрашивает: сохранение в панели,
 * ответ модели и проверка словаря целиком. Раздваивать нельзя — в этом
 * проекте два способа ответить на один вопрос уже расходились молча.
 */

/**
 * Фразы, которых §13.7 запрещает боту говорить.
 *
 * Список закрытый и составлен по самому §13.7: советы отдохнуть и
 * подышать, рассуждения про ресурс и выгорание, похвала без повода,
 * благодарность за то, что человек поделился. Это фразы, а не отдельные
 * слова, — «ванна» в деле «купить ванну» законна, а «прими ванну» нет.
 *
 * Жил в `presenter.service.ts`, где проверялся ответ модели. Переехал
 * сюда вместе с редактором текстов: у правила §13 один дом, и это дом
 * словаря.
 */
export const FORBIDDEN = [
  'отдохни',
  'отдохнуть',
  'подыши',
  'подышать',
  'прими ванну',
  'полежи',
  'побудь с собой',
  'выгорание',
  'выгораешь',
  'твой ресурс',
  'ресурсное состояние',
  'слишком много на себя',
  'расскажи подробнее',
  'как ты себя чувствуешь',
  'спасибо, что поделилась',
  'спасибо что поделилась',
  'ты молодец',
  'ты справишься',
  'все будет хорошо',
  'не переживай',
  'береги себя',
] as const;

/** «Ё» приравнивается к «е»: живая расшифровка даёт и то и другое. */
function normalize(text: string): string {
  return text.toLowerCase().replace(/ё/gu, 'е');
}

/** Какая из запрещённых §13.7 фраз встретилась. */
export function forbiddenPhraseIn(text: string): string | undefined {
  const normalized = normalize(text);

  return FORBIDDEN.find((phrase) => normalized.includes(phrase));
}

/**
 * Эмодзи, которым §13.9 разрешает быть в реплике.
 *
 * «Только как маркеры приоритета и статуса». Звезда — обозначение
 * валюты Telegram. Отмеченный квадрат — состояние согласия на
 * автосписания на экране оплаты (§14, требование Робокассы к чекбоксу):
 * это маркер статуса в самом прямом смысле, пустой квадрат рядом с ним
 * пиктограммой не считается. Маркеры тем живут в коде, а не в словаре, и
 * сюда не попадают. Всё украшательское отказывается.
 */
export const ALLOWED_EMOJI = new Set(['⭐', '☑']);

/** Предел Telegram на одно сообщение. Длиннее просто не уедет. */
const MESSAGE_LIMIT = 4_096;

/** Подстановка в реплике: `{1}` — первый аргумент, `{2}` — второй. */
const PLACEHOLDER = /\{(\d+)\}/gu;

/** Одна реплика словаря: где лежит и что человек прочтёт. */
export interface Reply {
  readonly path: string;
  readonly said: string;
  /** Сколько значений подставляется. Ноль — простая реплика. */
  readonly places: number;
}

/**
 * Слова параметризованной реплики — из её же исходника.
 *
 * **Почему не вызовом.** Таких реплик в словаре пятьдесят одна, у каждой
 * свои аргументы; звать их наугад значит либо уронить проверку, либо
 * подсунуть выдумку вместо текста. А правила §13 — про наши слова, и
 * слова эти лежат в литерале.
 *
 * Подставляемое (`${…}`) выбрасывается нарочно: там данные человека, а
 * не наш текст. Заодно это снимает ложную тревогу от тернарника внутри
 * подстановки — его «?» не вопрос, а код.
 *
 * **Раскодирование — страховка от сборщика, и она снята с опыта.** Под
 * vitest исходник функции отдаёт кириллицу как есть; под `tsx` тот же
 * вызов даёт escape-последовательности вместо букв. Зависеть от того,
 * кто собирает, правило не должно: иначе однажды оно ослепнет на всех
 * параметризованных репликах и промолчит.
 */
export function saidBy(source: string): string {
  // Обратная кавычка через код: вставить её литералом внутрь шаблонной
  // строки нельзя, а искать надо и шаблоны, и обычные строки —
  // составные реплики собираются из одиночных кавычек.
  const tick = String.fromCharCode(96);
  const literal = new RegExp(`${tick}[^${tick}]*${tick}|'[^']*'|"[^"]*"`, 'gsu');

  return (source.match(literal) ?? [])
    .map((one) => one.slice(1, -1))
    .join(' ')
    .replaceAll(/\$\{[^}]*\}/gu, ' ')
    .replaceAll(/\\u([0-9a-fA-F]{4})/gu, (_whole, code: string) =>
      String.fromCharCode(Number.parseInt(code, 16)),
    )
    .replaceAll(/\\x([0-9a-fA-F]{2})/gu, (_whole, code: string) =>
      String.fromCharCode(Number.parseInt(code, 16)),
    );
}

/**
 * Весь словарь одним списком: и простые реплики, и параметризованные.
 *
 * Разделять их нельзя — правила §13 не различают, из чего собрана фраза,
 * а редактору нужны обе: без параметризованных «все тексты» из §13.9
 * оказались бы четвертью словаря меньше.
 */
export function repliesOf(profile: TextProfile): readonly Reply[] {
  const found: Reply[] = [];

  const walk = (value: unknown, path: string): void => {
    if (typeof value === 'string') {
      found.push({ path, said: value, places: 0 });
      return;
    }

    if (typeof value === 'function') {
      found.push({ path, said: saidBy(String(value)), places: value.length });
      return;
    }

    if (typeof value === 'object' && value !== null) {
      for (const [key, nested] of Object.entries(value)) {
        walk(nested, path === '' ? key : `${path}.${key}`);
      }
    }
  };

  walk(profile, '');

  return found;
}

/**
 * Реплики, которых редактор не показывает, — и почему именно.
 *
 * Список закрытый и с причиной у каждой записи: «почему нельзя» должно
 * читаться, а не угадываться. Пустой список тоже был бы решением, и его
 * пришлось бы объяснять.
 *
 * Пока запись одна. `card.statusName` не фраза, а **таблица**: она
 * превращает состояние записи в слово («done» → «выполнено»), и слова
 * лежат в коде рядом, вне самой функции. Заменить её одной строкой с
 * подстановкой значило бы показать человеку сырое состояние вместо
 * слова. Понадобится править эти слова — они правятся как словарь
 * состояний, отдельной задачей.
 */
export const NOT_EDITABLE = new Map<string, string>([
  [
    'card.statusName',
    'это не фраза, а таблица состояний: она превращает «done» в «выполнено», и слова лежат в коде рядом с ней',
  ],
]);

/**
 * Реплики, которые редактор показывает и разрешает править.
 *
 * Отдельно от `repliesOf`, потому что вопросы разные: та отвечает «что
 * вообще есть в словаре» и нужна проверкам, а эта — «что можно отдать
 * человеку в панель».
 */
export function editableReplies(profile: TextProfile): readonly Reply[] {
  return repliesOf(profile).filter((one) => !NOT_EDITABLE.has(one.path));
}

/**
 * Нарушает ли текст §13 **по содержанию**. Отказ — словами, а не «нет».
 *
 * Отказ читает человек, который только что печатал: «в реплике не бывает
 * двух вопросов» он исправит, «не удалось сохранить» — не исправит
 * ничего. Поэтому у каждого правила своя фраза с числом или знаком,
 * который его нарушил.
 *
 * **Отдельно от правила подстановок, и это не дробление ради красоты.**
 * Правила содержания годятся для любого текста: и для правки из панели,
 * и для реплики из кода, и для ответа модели. А подстановки в правке
 * пишутся числами (`{1}`), а в коде — своим синтаксисом, и требовать
 * `{1}` от кодовой реплики значило бы краснеть на всех пятидесяти одной
 * параметризованной. Эта ошибка была сделана здесь же и поймана тестом.
 */
export function contentRefusal(said: string): string | undefined {
  const trimmed = said.trim();

  if (trimmed === '') {
    return 'Реплика не может быть пустой: в этом месте бот промолчит, а молчание человек читает как поломку.';
  }

  if (said.length > MESSAGE_LIMIT) {
    return `Слишком длинно: ${String(said.length)} знаков, Telegram принимает ${String(MESSAGE_LIMIT)}.`;
  }

  const questions = (said.match(/\?/gu) ?? []).length;

  if (questions > 1) {
    return `В одной реплике не бывает двух вопросов (§13.2), а здесь их ${String(questions)}. Оставьте один.`;
  }

  if (/!{2,}/u.test(said)) {
    return 'Восклицательные знаки не идут сериями (§13.9). Оставьте один.';
  }

  const forbidden = forbiddenPhraseIn(said);

  if (forbidden !== undefined) {
    return `§13.7 не разрешает боту такое: «${forbidden}». Бот признаёт состояние одной строкой и возвращает к делу, а не советует и не подбадривает.`;
  }

  const decoration = (said.match(/\p{Extended_Pictographic}/gu) ?? []).find(
    (symbol) => !ALLOWED_EMOJI.has(symbol),
  );

  if (decoration !== undefined) {
    return `Эмодзи только как маркеры приоритета и статуса (§13.9), а «${decoration}» — украшение.`;
  }

  return undefined;
}

/**
 * Реплики, которые уходят человеку в **одном ответе** с вопросом бота.
 *
 * Ответ на выгрузку §13.2 собирается из нескольких реплик словаря:
 * признание (или его словарная замена), подводка к списку, маркер
 * пункта, фраза о сохранённом — и следом вопрос «С чего начнём?» либо
 * «Разобрать что-нибудь из дел или на сегодня хватит?». Человек читает
 * склейку, а не реплику, и §13.2 говорит о ней: «Двух вопросов в реплике
 * не бывает». Значит у этих реплик своего вопроса быть не может — он в
 * ответе уже есть.
 *
 * **Почему список, а не пересчёт склейки.** Правило общего содержания
 * разрешает реплике один «?» — и для одиночной реплики это верно. Правка
 * «Остальное никуда не убежит, хорошо?» проходила запись и давала
 * человеку два вопроса; найдено ревизией второго этапа. Считать вопросы
 * у собранного текста на записи нельзя — сборка зависит от выгрузки, а
 * выбрасывать свой вопрос при сборке значило бы молча менять ответ.
 * Список сверяется с самой сборкой перебором в проверках презентера:
 * реплика, которую сборка ставит рядом с вопросом, обязана быть здесь.
 *
 * `closingTired` сюда не входит: при усталости вопроса в ответе нет
 * (§13.7), и второго вопроса из него не выйдет.
 */
export const BESIDE_QUESTION = [
  'answer.acknowledgementFallback',
  'answer.acknowledgementTiredFallback',
  'answer.actionsLead',
  'answer.actionsLeadSingle',
  'answer.bullet',
  'answer.restSaved',
  'answer.nothingHidden',
  'answer.nothingUrgent',
] as const;

/** Чего §13.2 требует от реплики, стоящей рядом с вопросом. Отказ — словами. */
export function besideQuestionRefusal(said: string): string | undefined {
  if (said.includes('?')) {
    return 'Эта реплика уходит человеку в одном ответе с вопросом бота, а двух вопросов в ответе не бывает (§13.2). Уберите «?» — свой вопрос в этом ответе уже есть.';
  }

  return undefined;
}

/**
 * Правила, которые держатся не на общем содержании, а на **роли** реплики.
 *
 * Две роли. Первая — самая ответственная в продукте: реплика острого
 * кризиса (§13.7, задача 2.12) обязана назвать конкретный контакт
 * цифрами — человеку в таком состоянии не следует искать телефон самому;
 * обещать, что сказанное не потеряно, иначе он решит, что его слова
 * пропали; не задавать вопроса — §13.7 требует из разговора выйти, а не
 * приглашать продолжить; и уложиться в двести знаков. Вторая — реплики,
 * стоящие в одном ответе с вопросом (`BESIDE_QUESTION`): им свой вопрос
 * не положен.
 *
 * **Почему правило живёт здесь, а не только в проверках.** До редактора
 * текстов свойства кризисной реплики стерегли два теста по словарю **из
 * кода**. Редактор §13.9 сделал реплику правимой, и правка идёт в бой,
 * минуя их: заказчица могла нечаянно снести контакт из самой
 * ответственной реплики продукта, и ни одна проверка не покраснела бы.
 * Найдено ревизией второго этапа. Теперь правило одно на всех, и стоит
 * оно на записи.
 */
const ROLE_RULES = new Map<string, (said: string) => string | undefined>([
  ['safety.crisis', crisisRefusal],
  ...BESIDE_QUESTION.map((path): [string, (said: string) => string | undefined] => [
    path,
    besideQuestionRefusal,
  ]),
]);

/** Чего требует §13.7 от реплики острого кризиса. Отказ — словами. */
export function crisisRefusal(said: string): string | undefined {
  if (!/\d{3}[\s-]?\d{2}[\s-]?\d{2}/u.test(said)) {
    return 'В реплике про острый кризис обязан быть конкретный контакт цифрами (§13.7): человеку в таком состоянии не следует искать телефон самому.';
  }

  if (!/сохранил|не потеря/iu.test(said)) {
    return 'Реплика про острый кризис обязана сказать, что сказанное не потеряно: разбор остановлен, и без этой мысли человек решит, что его слова пропали.';
  }

  if (said.includes('?')) {
    return 'В реплике про острый кризис не бывает вопроса (§13.7): вопрос приглашает продолжить разговор, а из него надо выйти.';
  }

  if (said.length > CRISIS_LIMIT) {
    return `Реплика про острый кризис короткая: ${String(said.length)} знаков, а можно не больше ${String(CRISIS_LIMIT)}. Это одна реплика, а не разговор.`;
  }

  return undefined;
}

/** Предел длины кризисной реплики: одна реплика, а не разговор. */
export const CRISIS_LIMIT = 200;

/**
 * Годится ли правка из панели: по содержанию, по роли и по подстановкам.
 *
 * `places` — сколько значений подставляет исходная реплика. Все они
 * обязаны остаться: реплика без подстановки потеряет название дела или
 * дату, и человек прочтёт обрубок вместо ответа.
 *
 * `path` нужен правилам по роли: у кризисной реплики требования свои, и
 * проверить их можно только зная, какую реплику правят. Необязателен,
 * потому что правила содержания и подстановок проверяются и без роли.
 * Ответ модели сюда не заходит: у него ни роли, ни подстановок, и
 * презентер зовёт `contentRefusal` напрямую, а сверху добавляет своё,
 * более строгое.
 */
export function refusalFor(said: string, places: number, path?: string): string | undefined {
  const byRole = path === undefined ? undefined : ROLE_RULES.get(path);

  return contentRefusal(said) ?? byRole?.(said) ?? placeholderRefusal(said, places);
}

/** Все подстановки исходной реплики обязаны остаться — и никаких лишних. */
function placeholderRefusal(said: string, places: number): string | undefined {
  const used = new Set<number>();

  for (const found of said.matchAll(PLACEHOLDER)) {
    used.add(Number(found[1]));
  }

  const wanted = Array.from({ length: places }, (_unused, index) => index + 1);
  const missing = wanted.filter((one) => !used.has(one));
  const extra = [...used].filter((one) => one < 1 || one > places).sort((a, b) => a - b);

  if (missing.length > 0) {
    const names = missing.map((one) => `{${String(one)}}`).join(', ');

    return places === 1
      ? `Здесь подставляется значение — оставьте ${names} там, где оно должно стоять. Без него человек прочтёт обрубок.`
      : `Здесь подставляются значения, и все должны остаться. Не хватает: ${names}.`;
  }

  if (extra.length > 0) {
    const names = extra.map((one) => `{${String(one)}}`).join(', ');

    return places === 0
      ? `В этой реплике нечего подставлять, а ${names} останется на экране как есть.`
      : `Подставляется ${String(places)} значения, поэтому ${names} заполнить нечем.`;
  }

  return undefined;
}

/**
 * Реплика с подставленными значениями.
 *
 * **Пустота вместо «undefined» и вместо «[object Object]».** Дырка в
 * тексте читается хуже, но не врёт, а служебное слово на экране человек
 * примет за поломку бота — и будет прав, только починить это он не
 * сможет. Реплики подставляют слова, числа и даты; объект здесь означал
 * бы ошибку в вызывающем коде, и показывать её человеку незачем.
 */
export function render(template: string, values: readonly unknown[]): string {
  return template.replaceAll(PLACEHOLDER, (_whole, index: string) => {
    const value = values[Number(index) - 1];

    if (typeof value === 'string') return value;
    if (typeof value === 'number' || typeof value === 'bigint') return String(value);
    if (value instanceof Date) return value.toISOString();

    return '';
  });
}
