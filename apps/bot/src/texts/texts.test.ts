describe('первый экран и конец знакомства (правки заказчицы 30.09.2026)', () => {
  it('первый экран — её текст: 🤍 и «Не надо…» с новой строки', () => {
    expect(defaultTexts.consent.screen('https://p', 'https://c')).toBe(
      [
        '*Привет. Я ВЫДОХ 🤍*',
        '',
        'Можешь просто рассказать мне всё, что сейчас крутится в голове — голосом или текстом.',
        'Не надо структурировать, красиво формулировать или сортировать.',
        '*Я помогу собрать мысли, дела и всё, что важно не забыть.*',
        '',
        'Чтобы я могла работать с тем, что ты скажешь, нужно твоё согласие на обработку данных — ' +
          'вот [политика конфиденциальности](https://p) и [согласие на обработку данных](https://c). ' +
          'ВЫДОХ — для тех, кому есть 18.',
      ].join('\n'),
    );
  });

  it('конец опроса — приглашение её словами, со второй строки', () => {
    expect(defaultTexts.onboarding.finished).toBe(
      'Всё, больше не спрашиваю.\n' +
        'Дальше просто напиши или наговори всё, что сейчас держишь в голове. Можно как есть.',
    );
  });
});

