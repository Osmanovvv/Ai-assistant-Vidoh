import { describe, expect, it } from 'vitest';

import { defaultTexts } from './index.js';
import { forbiddenPhraseIn, repliesOf, saidBy, type Reply } from './rules.js';

/**
 * Обход словаря и добыча слов живут в `rules.ts` — вместе с правилами.
 *
 * Здесь их копии быть не должно: правило §13 проверяется и на записи из
 * панели, и на словаре целиком, и если обходов станет два, они разойдутся
 * молча — ровно тот случай, против которого написан инвариант проекта.
 */

/** Кто нарушил правило — путём и словами, чтобы правка была очевидна. */
function blame(broken: readonly Reply[]): readonly string[] {
  return broken.map(
    (one) =>
      `${one.path} [${one.places > 0 ? 'с подстановкой' : 'простая'}]: ${one.said.replaceAll(String.fromCharCode(10), ' / ')}`,
  );
}

const replies = (): readonly Reply[] => repliesOf(defaultTexts);

describe('реплика на острый кризис (§17, задача 2.12)', () => {
  const crisis = defaultTexts.safety.crisis;

  it('предлагает конкретный контакт, а не «обратись к специалисту»', () => {
    // Человеку в таком состоянии не следует искать телефон самому.
    // Цифры в реплике — признак того, что контакт назван.
    expect(crisis).toMatch(/\d{3}[\s-]?\d{2}[\s-]?\d{2}/u);
  });

  it('обещает, что сказанное не потеряно', () => {
    // Разбор остановлен. Без этой мысли человек решит, что его слова
    // пропали, — а они сохранены до всякого разбора (инвариант 1).
    expect(crisis).toMatch(/сохранил|не потеря/iu);
  });

  it('не рассуждает про ресурс и выгорание', () => {
    // §13.8 и прямое требование заказчика. Проверяется тем же списком
    // запрещённых фраз, которым проверяется ответ модели: правило одно,
    // и раздваивать его нельзя.
    expect(forbiddenPhraseIn(crisis)).toBeUndefined();
  });
});

describe('словарь целиком', () => {
  it('ни одна реплика не пустая', () => {
    // Пустая строка в словаре — это молчание бота там, где он должен
    // ответить. Заметить это в бою можно только по жалобе человека.
    //
    // Правило про пустоту — только для простых реплик: у
    // параметризованной законно почти нет своих слов («— ${title}»), и
    // требовать их значило бы краснеть на верном коде.
    const empty = replies().filter((one) => one.places === 0 && one.said.trim() === '');

    expect(blame(empty)).toEqual([]);
  });
});

/**
 * Запрещённые шаблоны словаря (§13, задача 4.13).
 *
 * Словарь вычитывает заказчица, и правки будут её словами. Проверка не
 * судит формулировку — она держит те требования §13, которые
 * формулировка обязана соблюдать, как бы её ни переписали. Поэтому здесь
 * не «нравится ли текст», а «не нарушает ли он правило».
 *
 * Все реплики словаря проходят через один обход: и простые, и
 * параметризованные. Разделять их нельзя — правила §13 не различают, из
 * чего собрана фраза.
 */
describe('запрещённые шаблоны словаря (§13, задача 4.13)', () => {
  it('обход видит и простые реплики, и параметризованные', () => {
    /**
     * **Страж стража, и он здесь не формальность.**
     *
     * Первая версия добычи слов возвращала «\u0414\u043E\u0431…»:
     * сборка экранирует кириллицу, и все проверки ниже проходили по
     * пустому месту — зелёные при любом тексте. Поэтому проверяется
     * само добывание: у известной параметризованной реплики обязаны
     * найтись настоящие русские слова.
     */
    const all = replies();
    const parameterized = all.filter((one) => one.places > 0);

    expect(all.length).toBeGreaterThan(200);
    expect(parameterized.length).toBeGreaterThan(40);

    // Русские буквы, а не escape-последовательности.
    expect(saidBy(String(defaultTexts.resolver.noted))).toMatch(/[а-яё]{4,}/iu);
    expect(parameterized.filter((one) => /[а-яё]{4,}/iu.test(one.said)).length).toBeGreaterThan(30);
  });

  it('двух вопросов в одной реплике не бывает', () => {
    /**
     * §13.2: «Вопрос — ровно один. Двух вопросов в реплике не бывает».
     * §13.9 повторяет это общим правилом.
     *
     * Причина не в стилистике: два вопроса подряд человек читает как
     * «да/нет» и отвечает на один, а бот теряет содержание — этот случай
     * в проекте уже был, и стоил ответа поверх открытого вопроса.
     */
    const twoQuestions = replies().filter((one) => (one.said.match(/\?/gu) ?? []).length > 1);

    expect(blame(twoQuestions)).toEqual([]);
  });

  it('восклицательные знаки не идут сериями', () => {
    // §13.9. Сдержанный тон — не украшение: продукт разгружает голову,
    // а серия восклицательных читается как бодрость, о которой не просили.
    const shouting = replies().filter((one) => /!{2,}/u.test(one.said));

    expect(blame(shouting)).toEqual([]);
  });

  it('ни одной фразы из списка запретов §13.7', () => {
    /**
     * Тем же списком, которым проверяется ответ модели: правило одно, и
     * раздваивать его нельзя. Список закрытый и составлен по самому
     * §13.7 — советы отдохнуть и подышать, рассуждения про ресурс и
     * выгорание, похвала без повода, благодарность за то, что человек
     * поделился.
     */
    const preachy = replies().filter((one) => forbiddenPhraseIn(one.said) !== undefined);

    expect(preachy.map((one) => `${one.path}: «${String(forbiddenPhraseIn(one.said))}»`)).toEqual(
      [],
    );
  });

  it('эмодзи — только маркеры приоритета и статуса', () => {
    /**
     * §13.9: «эмодзи только как маркеры приоритета и статуса».
     *
     * Сегодня в словаре нет ни одного: маркеры тем и звезда тарифа
     * живут в коде, а не в тексте. Список разрешённых всё равно нужен —
     * звезда Telegram законна как обозначение валюты и однажды может
     * переехать сюда. Всё украшательское краснеет.
     */
    const ALLOWED = new Set(['⭐']);
    const decorated: string[] = [];

    for (const one of replies()) {
      for (const symbol of one.said.match(/\p{Extended_Pictographic}/gu) ?? []) {
        if (!ALLOWED.has(symbol)) decorated.push(`${one.path}: ${symbol}`);
      }
    }

    expect(decorated).toEqual([]);
  });
});
