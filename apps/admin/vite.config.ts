import react from '@vitejs/plugin-react';
import { defineConfig } from 'vite';

/**
 * Сборка админ-панели (§15 ТЗ, задача 4.5).
 *
 * **`base: '/admin/'`**, потому что панель живёт не в корне: бот отдаёт
 * её раздел по этому пути, и без базы собранные ссылки на скрипты вели
 * бы в корень домена, где ничего нет.
 *
 * **Прокси на бота в разработке.** Печенье пропуска помечено
 * `SameSite=Strict` и путём `/admin` — то есть браузер отдаёт его только
 * на тот же адрес. Если бы панель в разработке ходила на другой порт
 * напрямую, вход не работал бы именно там, где его отлаживают, и
 * разница с боем всплыла бы на приёмке.
 */
const BOT = process.env.ADMIN_API_ORIGIN ?? 'http://127.0.0.1:3000';

export default defineConfig({
  base: '/admin/',
  plugins: [react()],
  server: {
    port: 5173,
    proxy: {
      '/admin/api': { target: BOT, changeOrigin: false },
    },
  },
  build: {
    outDir: 'dist',
    // Панель показывает чужие выгрузки: карты исходников на боевом дают
    // читателю больше, чем нам.
    sourcemap: false,
  },
});
