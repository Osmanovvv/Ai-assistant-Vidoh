#!/usr/bin/env bash
# Внешний пульс бота (§18 ТЗ).
#
# §18 требует оповещения «при росте ошибок, недоступности модели и падении
# сервиса». Первые два были: мониторинг считает долю ошибок и шлёт
# сообщение в чат. А третьего не было вовсе — и не могло быть: счётчик
# ошибок живёт внутри того же процесса, который умирает. Мёртвый бот
# молчал бы ровно так же, как исправный в спокойный день.
#
# Найдено сверкой с ТЗ 28.08.2026.
#
# Проверяется готовность, а не просто живость: /health/ready отвечает 503,
# если отвалилась база или Redis, — а бот, который поднялся и не может
# работать, для человека ничем не лучше упавшего.
#
# Запускается cron на сервере каждые десять минут.
set -euo pipefail

. "$(dirname "$0")/notify.sh"
trap 'notify_failure "пульс бота"' ERR

COMPOSE="${COMPOSE:-docker compose -f docker-compose.prod.yml}"
STATE="${HEARTBEAT_STATE:-/var/lib/vydoh-heartbeat}"

# Сколько неудач подряд до оповещения.
#
# Одной мало: выкладка перезапускает контейнер, и попасть проверкой в эту
# секунду — обычное дело. Двух хватает: между ними десять минут, а выкладка
# укладывается в одну.
LIMIT="${HEARTBEAT_LIMIT:-2}"

mkdir -p "$(dirname "$STATE")"
[ -f "$STATE" ] || echo 0 > "$STATE"
FAILS="$(cat "$STATE")"

# `exec` падает и когда контейнера нет вовсе — это тот самый случай, ради
# которого пульс и нужен.
if $COMPOSE exec -T bot node -e \
    "fetch('http://localhost:3000/health/ready').then(r=>process.exit(r.ok?0:1)).catch(()=>process.exit(1))" \
    >/dev/null 2>&1; then
  # Вернулся после оповещения — об этом надо сказать. Иначе человек знает
  # только про поломку и не знает, что она кончилась.
  if [ "$FAILS" -ge "$LIMIT" ]; then
    notify "✅ бот снова отвечает"
  fi

  echo 0 > "$STATE"
  echo "бот отвечает"
  exit 0
fi

FAILS=$((FAILS + 1))
echo "$FAILS" > "$STATE"

if [ "$FAILS" -lt "$LIMIT" ]; then
  echo "не ответил ($FAILS из $LIMIT) — жду следующей проверки" >&2
  exit 0
fi

# Оповещение шлётся один раз, а не каждые десять минут: молчание после
# первого сообщения лучше, чем поток одинаковых.
if [ "$FAILS" -eq "$LIMIT" ]; then
  notify "⚠️ бот не отвечает на проверку готовности ${LIMIT} раза подряд. Смотри: docker compose -f docker-compose.prod.yml logs --tail=50 bot"
fi

echo "бот не отвечает ($FAILS)" >&2
exit 1
